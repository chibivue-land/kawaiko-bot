export interface 偽のチャット extends チャット {
  readonly 投稿済み: 配列<{ チャンネルid: 文字列; 本文: 文字列; 返信先?: 文字列 }>;
  履歴: 配列<発言>;
}

export function 偽のチャットを作る(履歴: 配列<発言> = []): 偽のチャット {
  const 投稿済み: 偽のチャット["投稿済み"] = [];

  return {
    投稿済み,
    履歴,

    async 投稿する(チャンネルid, 本文, 返信先) {
      投稿済み.push({ チャンネルid, 本文, 返信先 });
    },

    async 直近の発言() {
      return this.履歴;
    },

    async サーバーを引く() {
      return "サーバー-1";
    },

    入力中にする: (_チャンネルid, 処理) => 処理(),
  };
}

export interface 偽の発話器 extends 発話器 {
  readonly 受け取った指示文: 配列<文字列>;
}

/** 渡した返事を順に返し，尽きたら最後のものを繰り返す． */
export function 偽の発話器を作る(返事一覧: 配列<文字列>): 偽の発話器 {
  const 受け取った指示文: 配列<文字列> = [];
  let 番号 = 0;

  return {
    受け取った指示文,

    async 発話する(依頼): 約束<発話の結果> {
      受け取った指示文.push(依頼.指示文);
      const 本文 = 返事一覧[数学.min(番号, 返事一覧.length - 1)] ?? "";
      番号++;

      return { 本文, 費用ドル: 0.001, モデル: "偽のモデル" };
    },
  };
}

export interface 偽の記憶庫 extends 記憶庫 {
  readonly 観測済み: 配列<観測>;
  事実一覧: 配列<事実>;
  readonly 追記済み: 配列<{
    識別子: 文字列;
    事実一覧: 読み取り専用配列<学習した事実>;
    読んだ位置: 数値;
  }>;
  未学習の行: 配列<観測>;
}

export function 偽の記憶庫を作る(上書き?: { 使えるか?: 真偽; 事実一覧?: 配列<事実> }): 偽の記憶庫 {
  const 観測済み: 配列<観測> = [];
  const 追記済み: 偽の記憶庫["追記済み"] = [];

  return {
    使えるか: 上書き?.使えるか ?? 真,
    観測済み,
    追記済み,
    事実一覧: 上書き?.事実一覧 ?? [],
    未学習の行: [],

    async 観測する(行) {
      各要素に(行, (観測の行, 順番) => {
        末尾に足す(観測済み, {
          連番: 長さ(観測済み) + 順番 + 1,
          チャンネルid: 観測の行.チャンネルid,
          発言者id: 観測の行.発言者id,
          発言者名: 観測の行.発言者名,
          kawaikoの発言か: 観測の行.kawaikoの発言か,
          本文: 観測の行.本文,
          時刻: 観測の行.時刻,
        });
      });
    },

    async 生きている事実() {
      return this.事実一覧;
    },

    async 観測したサーバー() {
      return ["サーバー-1"];
    },

    async 学習の読み取り位置() {
      return 0;
    },

    async 未学習の観測() {
      return this.未学習の行;
    },

    async 学習を追記する(引数) {
      追記済み.push({
        識別子: 引数.識別子,
        事実一覧: 引数.事実一覧,
        読んだ位置: 引数.読んだ位置,
      });

      return { 学習: 引数.事実一覧.length, 更新: 0, 却下: 0 };
    },

    async 学習の履歴() {
      return [];
    },

    async 学習の回を取り消す() {
      return 真;
    },

    async 時点まで巻き戻す() {
      return 真;
    },
  };
}

