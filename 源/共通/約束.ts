import { 真, 偽, 未定義 } from "./型";
import type { 文字列, 不明, 無, 約束, 約束もどき, 読み取り専用配列 } from "./型";

/**
 * 約束の続きを日本語で書けるようにする．
 *
 * `await` は予約語で別名を付けられないが，`then` はただのメソッドなので，同じ
 * ものに日本語の名前を足せる．おかげで続きが左から右へ読める:
 *
 *   直近の発言(部屋).んで((発言一覧) => 会話ログを組み立てる(発言一覧, 設定))
 *
 * 実体は `Promise.prototype.then` / `catch` / `finally` そのもので，包み直しては
 * いない．挙動もコストも変わらず，増えるのは呼び名だけ．
 *
 * 組み込みのプロトタイプに足すので，**使う前に一度だけ読み込まれている必要が
 * ある**．本番は 入口.ts が先頭で読み込み，試験は vite.config.ts の
 * `test.setupFiles` が読み込む．それ以外の入口を増やすときは同じことをする．
 */

declare global {
  interface Promise<T> {
    /** then — 続き． */
    んで<結果>(次: (値: T) => 結果 | 約束もどき<結果>): 約束<結果>;

    /** catch — 転んだときの拾い方． */
    しくじったら<結果>(拾う: (躓き: 不明) => 結果 | 約束もどき<結果>): 約束<T | 結果>;

    /** finally — 転んでも転ばなくても片付ける． */
    ともかく(始末: () => 無): 約束<T>;
  }
}

const 足す = (名前: 文字列, 元: 不明): 無 => {
  Object.defineProperty(Promise.prototype, 名前, {
    value: 元,
    writable: 真,
    configurable: 真,
    enumerable: 偽,
  });
};

足す("んで", Promise.prototype.then);
足す("しくじったら", Promise.prototype.catch);
足す("ともかく", Promise.prototype.finally);

/**
 * 何もしない約束．
 *
 * もし や 場合分け の枝は式なので，「この枝ではやることが無い」も値で言う必要が
 * ある．`async () => {}` と書くより，何もしないと名前で言ったほうが読める．
 */
export function 何もしない(): 約束<無> {
  return すぐ返す(未定義);
}

/**
 * Promise.resolve — もう出来ている約束にして，すぐ返す．
 *
 * もし や 場合分け の枝で，片方だけが実際に待つときに使う．待たない側も同じ形で
 * 返さないと，枝の型が揃わない．
 */
export function すぐ返す<値>(値候補: 値): 約束<値> {
  return Promise.resolve(値候補);
}

/**
 * Promise.resolve — 約束もどきを，本物の約束に均す．
 *
 * 世の中には「then は持つが約束ではない」ものがある．Drizzle のクエリビルダと，
 * **Cloudflare の束縛が返すもの全部**がそれ．後者は知らないプロパティを
 * 「向こう側のメソッド呼び出し」として解釈するので，均さずに `.んで` と書くと
 * «んで» という名前のメソッドを探しにいって落ちる．
 *
 * 永続体 (Durable Object) で 1 度，ブラウザ (Browser Run) でもう 1 度，同じ形で
 * 本番を落とした．**束縛を呼んだ戻り値は，例外なくここを通す**こと — 見た目は
 * 普通の約束なので，通っていないことは型では気づけない．
 */
export function 約束に均す<値>(もどき: 値 | 約束もどき<値>): 約束<値> {
  return Promise.resolve(もどき);
}

/**
 * Promise.all — 全部が揃うまで．
 *
 * 渡したものは互いを待たない．いちばん遅い 1 つぶんの時間で全部そろう代わりに，
 * どれか 1 つでも転べば全体が転ぶ．転んでほしくないものは，渡す前にそれぞれ
 * `.しくじったら` で拾っておくこと．
 */
export function 揃える<一覧 extends 読み取り専用配列<不明>>(
  // 変長タプルで受けると，並びごとの型が保たれる — 分配して受け取れるように．
  約束一覧: readonly [...一覧],
): 約束<揃った<一覧>> {
  return Promise.all(約束一覧) as 約束<揃った<一覧>>;
}

/** 揃ったあとの並び．約束は中身に，それ以外はそのまま． */
type 揃った<一覧> = { -readonly [鍵 in keyof 一覧]: Awaited<一覧[鍵]> };

/**
 * Promise.reject — 待つまでもなく，もう転んでいる約束．
 *
 * すぐ返す の裏返し．式の中で「ここは失敗した」と言うためのもので，その場で
 * 投げてしまう しくじる (構文.ts) とは，投げるか約束に包むかだけが違う．
 */
export function すぐしくじる<値 = 無>(躓き: 不明): 約束<値> {
  return Promise.reject(躓き);
}
