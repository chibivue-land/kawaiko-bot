import { 仕様, 検証, 期待 } from "../試験/言葉";
import { しくじる } from "./構文";
import { 数値, 文字列, 新しい例外, 真, 偽 } from "./型";
import type { 不明, 約束もどき } from "./型";
import { すぐしくじる, すぐ返す, 約束に均す } from "./約束";

仕様("んで", () => {
  検証("then と同じものを指す", () => {
    期待(Promise.prototype.んで).である(Promise.prototype.then);
  });

  検証("続きを左から右へ書ける", () =>
    すぐ返す(2)
      .んで((値) => 値 * 3)
      .んで((値) => 期待(値).である(6)),
  );

  検証("続きの中で約束を返せば待つ", () =>
    すぐ返す("あ")
      .んで((値) => すぐ返す(`${値}い`))
      .んで((値) => 期待(値).である("あい")),
  );
});

仕様("しくじったら", () => {
  検証("catch と同じものを指す", () => {
    期待(Promise.prototype.しくじったら).である(Promise.prototype.catch);
  });

  検証("転んだら拾える", () =>
    すぐしくじる(新しい例外("転んだ"))
      .しくじったら((躓き) => (躓き as Error).message)
      .んで((値) => 期待(値).である("転んだ")),
  );
});

仕様("ともかく", () => {
  検証("finally と同じものを指す", () => {
    期待(Promise.prototype.ともかく).である(Promise.prototype.finally);
  });

  検証("転んでも片付けが走る", () => {
    let 片付けた = 偽;

    return すぐしくじる(新しい例外("転んだ"))
      .ともかく(() => {
        片付けた = 真;
      })
      .しくじったら(() => 期待(片付けた).である(真));
  });
});

仕様("しくじる", () => {
  検証("もし の枝から投げられる", () => {
    const 拾った = (() => {
      try {
        return しくじる(新しい例外("枝から"));
      } catch (躓き) {
        return (躓き as Error).message;
      }
    })();

    期待(拾った).である("枝から");
  });
});

仕様("約束に均す", () => {
  検証("素の値はそのまま約束になる", () => {
    return 約束に均す(1).んで((値) => {
      期待(値).である(1);
    });
  });

  検証("約束もどきを本物の約束にする", () => {
    // then しか持たない — Drizzle のクエリビルダや，永続体の RPC がこれ．
    // oxlint-disable-next-line unicorn/no-thenable
    const もどき: 約束もどき<文字列> = { then: (次) => 次!("中身") as 不明 as 約束もどき<never> };

    return 約束に均す(もどき).んで((値) => {
      期待(値).である("中身");
    });
  });

  検証("均したあとは `.んで` が生えている", () => {
    // oxlint-disable-next-line unicorn/no-thenable
    const もどき: 約束もどき<数値> = { then: (次) => 次!(1) as 不明 as 約束もどき<never> };

    期待(typeof (もどき as 不明 as { んで?: 不明 }).んで).である("undefined");
    期待(typeof 約束に均す(もどき).んで).である("function");
  });
});
