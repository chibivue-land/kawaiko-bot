import { 仕様, 検証, 期待 } from "../試験/言葉";
import { しくじる } from "./構文";
import { 新しい例外, 真, 偽 } from "./型";
import { しくじった約束, 約束にする } from "./約束";

仕様("んで", () => {
  検証("then と同じものを指す", () => {
    期待(Promise.prototype.んで).である(Promise.prototype.then);
  });

  検証("続きを左から右へ書ける", () =>
    約束にする(2)
      .んで((値) => 値 * 3)
      .んで((値) => 期待(値).である(6)),
  );

  検証("続きの中で約束を返せば待つ", () =>
    約束にする("あ")
      .んで((値) => 約束にする(`${値}い`))
      .んで((値) => 期待(値).である("あい")),
  );
});

仕様("しくじったら", () => {
  検証("catch と同じものを指す", () => {
    期待(Promise.prototype.しくじったら).である(Promise.prototype.catch);
  });

  検証("転んだら拾える", () =>
    しくじった約束(新しい例外("転んだ"))
      .しくじったら((躓き) => (躓き as Error).message)
      .んで((値) => 期待(値).である("転んだ")),
  );
});

仕様("ともかく", () => {
  検証("finally と同じものを指す", () => {
    期待(Promise.prototype.ともかく).である(Promise.prototype.finally);
  });

  検証("転んでも片付けが走る", () => {
    let 片付けた = 偽;

    return しくじった約束(新しい例外("転んだ"))
      .ともかく(() => {
        片付けた = 真;
      })
      .しくじったら(() => 期待(片付けた).である(真));
  });
});

仕様("しくじる", () => {
  検証("もし の枝から投げられる", () => {
    const 拾った = (() => {
      try {
        return しくじる(新しい例外("枝から"));
      } catch (躓き) {
        return (躓き as Error).message;
      }
    })();

    期待(拾った).である("枝から");
  });
});
