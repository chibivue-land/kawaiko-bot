/**
 * 制御構文の日本語版．
 *
 * `if` `switch` `try` は予約語なので別名は付けられないが，同じ形を関数で作れる．
 * 枝はラベル付きの引数で受け取るので，読み下すとそのまま日本語になる:
 *
 *   もし(反復しているか(本文, 直近), {
 *     であれば: () => 言い直す(),
 *     でなければ: () => 本文,
 *   })
 *
 * 枝を関数で受けるのは，両方が先に評価されてしまわないようにするため．呼ばれる
 * のは選ばれた側だけで，元の `if` と同じく短絡する．
 *
 * ただし枝の中から外側の関数を `return` で抜けることはできない (別の関数の中
 * だから)．番兵節のように「途中で抜ける」書き方が要る場所は，素の `if` で書く
 * ほうが正しい．ここにあるのは値を選ぶための道具であって，`if` の全面的な
 * 置き換えではない．
 */
import type { 不明, 省略可, 約束, 読み取り専用配列 } from "./型";

/** 条件で値を選ぶ．`でなければ` を省くと，偽のとき undefined． */
export function もし<結果>(条件: 不明, 枝: { であれば: () => 結果; でなければ: () => 結果 }): 結果;
export function もし<結果>(条件: 不明, 枝: { であれば: () => 結果 }): 省略可<結果>;
export function もし<結果>(
  条件: 不明,
  枝: { であれば: () => 結果; でなければ?: () => 結果 },
): 省略可<結果> {
  return 条件 ? 枝.であれば() : 枝.でなければ?.();
}

/** `switch` の関数版．該当が無ければ `それ以外` へ． */
export function 場合分け<鍵 extends string, 結果>(
  値: 鍵,
  枝: { [K in 鍵]?: () => 結果 } & { それ以外?: () => 結果 },
): 省略可<結果> {
  const 該当 = 枝[値] as 省略可<() => 結果>;
  return 該当 ? 該当() : 枝.それ以外?.();
}

/**
 * 番兵節の連なり．上から順に条件を見て，最初に当てはまった枝の値を返す．
 *
 * `if (だめな条件) return 断る;` を何度も積む書き方は，外側の関数を抜ける必要が
 * あるので もし では書けない．代わりに「どれに当てはまるか」を値として表す．
 */
export async function 振り分ける<結果>(
  枝一覧: 読み取り専用配列<{ 条件: () => 不明 | 約束<不明>; ならば: () => 結果 | 約束<結果> }>,
  最後: { どれでもなければ: () => 結果 | 約束<結果> },
): 約束<結果> {
  for (const 枝 of 枝一覧) {
    if (await 枝.条件()) return await 枝.ならば();
  }

  return await 最後.どれでもなければ();
}

/** `try`/`catch` の関数版． */
export function 試す<結果>(枝: { 実行: () => 結果; しくじったら: (異常: 不明) => 結果 }): 結果 {
  try {
    return 枝.実行();
  } catch (躓き) {
    return 枝.しくじったら(躓き);
  }
}

/** 非同期版の `try`/`catch`． */
export async function 試みる<結果>(枝: {
  実行: () => 約束<結果>;
  しくじったら: (躓き: 不明) => 結果 | 約束<結果>;
}): 約束<結果> {
  try {
    return await 枝.実行();
  } catch (躓き) {
    return await 枝.しくじったら(躓き);
  }
}
