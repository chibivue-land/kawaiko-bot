/**
 * 演算子の日本語版。
 *
 * `+` や `===` のような記号そのものは JavaScript では再定義できない (演算子
 * オーバーロードが無い) ので、同じ働きをする関数として置いてある。
 *
 * 短絡する演算子 — `&&` `||` `?:` — は右辺を関数で受け取る。素直に値で受けると
 * 引数が先に評価されてしまい、短絡でなくなるため。`かつ(条件, () => 重い処理())`
 * と書けば、元の `条件 && 重い処理()` と同じく重い処理は必要なときだけ動く。
 */
import type { 数値, 真偽, 不明, 省略可 } from "./型";

// ---- 算術 ----
export const 足す = (左: 数値, 右: 数値): 数値 => 左 + 右;
export const 引く = (左: 数値, 右: 数値): 数値 => 左 - 右;
export const 掛ける = (左: 数値, 右: 数値): 数値 => 左 * 右;
export const 割る = (左: 数値, 右: 数値): 数値 => 左 / 右;
export const 余り = (左: 数値, 右: 数値): 数値 => 左 % 右;

// ---- 比較 ----
export const 等しい = <値>(左: 値, 右: 値): 真偽 => 左 === 右;
export const 等しくない = <値>(左: 値, 右: 値): 真偽 => 左 !== 右;
export const より大きい = (左: 数値, 右: 数値): 真偽 => 左 > 右;
export const 以上 = (左: 数値, 右: 数値): 真偽 => 左 >= 右;
export const より小さい = (左: 数値, 右: 数値): 真偽 => 左 < 右;
export const 以下 = (左: 数値, 右: 数値): 真偽 => 左 <= 右;

// ---- 論理 (右辺は短絡のため関数で受ける) ----
export const 否定 = (値: 不明): 真偽 => !値;

export function かつ<値>(左: 不明, 右: () => 値): 省略可<値> {
  return 左 ? 右() : undefined;
}

export function または<値>(左: 省略可<値>, 右: () => 値): 値 {
  return 左 ?? 右();
}

/** `?:` の関数版。両辺とも必要になったときだけ評価される。 */
export function 条件<値>(判定: 不明, 真のとき: () => 値, 偽のとき: () => 値): 値 {
  return 判定 ? 真のとき() : 偽のとき();
}

/** `??` の関数版。null と undefined のときだけ既定値へ倒れる。 */
export function 既定値<値>(値候補: 省略可<値> | null, 既定: 値): 値 {
  return 値候補 ?? 既定;
}
