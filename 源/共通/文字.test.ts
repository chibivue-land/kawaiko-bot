import { 未定義, 空, 真 } from "./型";
import { 空文字, 空行, 改行, 空白, タブ } from "./文字";

import { 仕様, 検証, 期待 } from "../試験/言葉";

仕様("制御文字の定数", () => {
  検証("素のエスケープと同じものを指す", () => {
    期待(改行).である("\n");
    期待(空行).である("\n\n");
    期待(タブ).である("\t");
    期待(空白).である(" ");
    期待(空文字).である("");
  });

  検証("繋ぐ の区切りとして読める", () => {
    期待(["一", "二"].join(改行)).である("一\n二");
  });
});

仕様("未定義 と 空", () => {
  検証("素の 未定義 / 空 と同一である", () => {
    期待(未定義).が未定義();
    期待(空).が空();
    期待(未定義 === 未定義).である(真);
    期待(空 === 空).である(真);
  });
});
