/**
 * 繰り返しの日本語版．
 *
 * `for` は予約語で別名を付けられないが，このリポジトリの繰り返しはどれも
 * 高階関数で書き直せる形をしている．`for (const x of 一覧)` は
 * `各要素に(一覧, (x) => ...)`，添字回しは `回数だけ` / `範囲` で置き換える．
 *
 * ただし `break` と，外側の関数からの早期 `return` は，コールバックの中からは
 * 効かない．そういう場所は 絞る / いずれか / 探す のように「途中で止まる」
 * 意味を持つ関数へ書き換えること．
 */
import type { 数値, 真偽, 約束, 配列, 読み取り専用配列, 無 } from "./型";

const 呼ぶ = Function.prototype.call;

/** `for (const 要素 of 一覧)` の置き換え． */
export const 各要素に = 呼ぶ.bind(Array.prototype.forEach) as <要素>(
  一覧: 読み取り専用配列<要素>,
  処理: (要素: 要素, 添字: 数値) => 無,
) => 無;

/** `for (let i = 0; i < 回数; i++)` の置き換え． */
export function 回数だけ<結果>(回数: 数値, 処理: (添字: 数値) => 結果): 配列<結果> {
  return Array.from({ length: 回数 }, (_, 添字) => 処理(添字));
}

/**
 * 一覧を頭から 1 件ずつ，前の結果を持ち越しながら畳む (非同期)．
 * `for (const x of 一覧) { 積 = await f(積, x) }` の置き換え．
 */
export async function 順に畳む<要素, 積>(
  一覧: 読み取り専用配列<要素>,
  演算: (積: 積, 要素: 要素) => 約束<積>,
  初期値: 積,
): 約束<積> {
  let 積 = 初期値;

  for (const 要素 of 一覧) {
    積 = await 演算(積, 要素);
  }

  return 積;
}

/**
 * 打ち切りが立つまで，前の結果を持ち越しながら繰り返す (非同期)．
 * `while (回 < 上限 && !終わり)` の置き換え．
 */
export async function 打ち切るまで繰り返す<状態>(
  上限: 数値,
  状態: 状態,
  一回: (状態: 状態, 回: 数値) => 約束<{ 状態: 状態; 打ち切るか: 真偽 }>,
): 約束<状態> {
  let 今の状態 = 状態;

  for (let 回 = 0; 回 < 上限; 回++) {
    const 結果 = await 一回(今の状態, 回);
    今の状態 = 結果.状態;

    if (結果.打ち切るか) break;
  }

  return 今の状態;
}

/** `[開始, 終わり)` の整数列． */
export function 範囲(開始: 数値, 終わり: 数値): 配列<数値> {
  return Array.from({ length: Math.max(終わり - 開始, 0) }, (_, i) => 開始 + i);
}
