/**
 * 制御文字と、名前が無いと読めない文字の定数。
 *
 * `"\n"` や `""` はソースの中で意味が読み取れない。名前を付けておけば、
 * 繋ぐ(行, 改行) のように、何をしているかがそのまま文になる。
 */
import type { 文字列 } from "./型";

/** 改行。 */
export const 改行: 文字列 = "\n";
/** 段落の区切り (空行を 1 行はさむ)。 */
export const 空行: 文字列 = "\n\n";
/** 復帰。 */
export const 復帰: 文字列 = "\r";
/** 水平タブ。 */
export const タブ: 文字列 = "\t";
/** 半角空白。 */
export const 空白: 文字列 = " ";
/** 何も無い文字列。 */
export const 空文字: 文字列 = "";
