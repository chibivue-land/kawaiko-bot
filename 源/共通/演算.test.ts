import { 仕様, 検証, 期待, 偽装 } from "../試験/言葉";
import { かつ, または, 余り, 既定値, 条件, 等しい, 足す, 否定 } from "./演算";
import { 各要素に, 回数だけ, 範囲 } from "./反復";
import { 含む, 写す, 切り出す, 繋ぐ, 絞る } from "./関数";
import { 空, 未定義 } from "./型";
import type { 文字列 } from "./型";

仕様("算術と比較", () => {
  検証("記号の演算子と同じ結果になる", () => {
    期待(足す(2, 3)).である(5);
    期待(余り(7, 2)).である(1);
    期待(等しい("あ", "あ")).である(true);
    期待(否定(0)).である(true);
  });
});

仕様("論理", () => {
  検証("右辺を必要なときだけ評価する (短絡が保たれる)", () => {
    const 重い処理 = 偽装.fn(() => "実行された");
    期待(かつ(false, 重い処理)).が未定義();
    期待(重い処理).否.呼ばれた();

    期待(かつ(true, 重い処理)).である("実行された");
    期待(重い処理).一度だけ呼ばれた();
  });

  検証("または は左辺が空のときだけ右辺を見る", () => {
    const 代替 = 偽装.fn(() => "代替");
    期待(または("本命", 代替)).である("本命");
    期待(代替).否.呼ばれた();
    期待(または(未定義, 代替)).である("代替");
  });

  検証("条件 はどちらか一方しか評価しない", () => {
    const 真 = 偽装.fn(() => "真");
    const 偽 = 偽装.fn(() => "偽");
    期待(条件(1, 真, 偽)).である("真");
    期待(偽).否.呼ばれた();
  });

  検証("既定値 は 空 と 未定義 だけを拾う", () => {
    期待(既定値(0, 60)).である(0);
    期待(既定値(未定義, 60)).である(60);
    期待(既定値(空, 60)).である(60);
  });
});

仕様("繰り返し", () => {
  検証("各要素に が for-of の代わりになる", () => {
    const 集めた: 文字列[] = [];
    各要素に(["あ", "い"], (要素) => {
      集めた.push(要素);
    });
    期待(集めた).と等しい(["あ", "い"]);
  });

  検証("回数だけ と 範囲 が添字回しの代わりになる", () => {
    期待(回数だけ(3, (i) => i * 2)).と等しい([0, 2, 4]);
    期待(範囲(2, 5)).と等しい([2, 3, 4]);
    期待(範囲(5, 2)).と等しい([]);
  });
});

仕様("プロトタイプ移植", () => {
  検証("元のメソッドと同じ挙動になる", () => {
    期待(切り出す("かわいこ", 0, 2)).である("かわ");
    期待(
      繋ぐ(
        写す([1, 2, 3], (n) => n * 2),
        "-",
      ),
    ).である("2-4-6");
    期待(絞る([1, 2, 3], (n) => 等しい(余り(n, 2), 1))).と等しい([1, 3]);
    期待(含む("kawaiko", "wai")).である(true);
  });
});
