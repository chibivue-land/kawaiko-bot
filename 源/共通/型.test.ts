import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 数値, 文字列, 数学, 新しい応答, 新しい対応表, 真 } from "./型";

仕様("組み込み型の別名", () => {
  検証("型としても値としても使える", () => {
    const 秒: 数値 = 12;
    期待(数値.isFinite(秒)).である(真);
    期待(文字列(秒)).である("12");
  });

  検証("実行環境の別名がそのままコンストラクタとして働く", () => {
    期待(新しい応答("ok").status).である(200);
    期待(新しい対応表([["a", 1]]).get("a")).である(1);
    期待(数学.floor(1.9)).である(1);
  });
});
