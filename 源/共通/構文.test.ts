import { 仕様, 検証, 期待, 偽装 } from "../試験/言葉";
import { もし, 場合分け, 試す, 試みる } from "./構文";

仕様("もし", () => {
  検証("選ばれた枝だけを評価する", () => {
    const 真の枝 = 偽装.fn(() => "真");
    const 偽の枝 = 偽装.fn(() => "偽");

    期待(もし(1, { であれば: 真の枝, でなければ: 偽の枝 })).である("真");
    期待(偽の枝).否.呼ばれた();

    期待(もし(0, { であれば: 真の枝, でなければ: 偽の枝 })).である("偽");
    期待(真の枝).一度だけ呼ばれた();
  });

  検証("でなければ を省くと偽のとき undefined になる", () => {
    期待(もし(false, { であれば: () => "真" })).が未定義();
  });

  検証("素の if と同じ真偽の判定をする", () => {
    for (const 値 of [0, "", null, undefined, NaN]) {
      期待(もし(値, { であれば: () => "真", でなければ: () => "偽" }), String(値)).である("偽");
    }
    for (const 値 of [1, "あ", [], {}]) {
      期待(もし(値, { であれば: () => "真", でなければ: () => "偽" })).である("真");
    }
  });
});

仕様("場合分け", () => {
  const 担当を言葉にする = (担当: "独言" | "横槍" | "学習") =>
    場合分け(担当, {
      独言: () => "誰にも宛てずに呟く",
      横槍: () => "人の発言に絡む",
      それ以外: () => "観測を畳み込む",
    });

  検証("該当する枝を選ぶ", () => {
    期待(担当を言葉にする("独言")).である("誰にも宛てずに呟く");
    期待(担当を言葉にする("横槍")).である("人の発言に絡む");
  });

  検証("該当が無ければ それ以外 へ落ちる", () => {
    期待(担当を言葉にする("学習")).である("観測を畳み込む");
  });
});

仕様("試す", () => {
  検証("投げられなければ実行の結果を返す", () => {
    期待(試す({ 実行: () => "無事", しくじったら: () => "拾った" })).である("無事");
  });

  検証("投げられたら しくじったら へ渡す", () => {
    const 結果 = 試す({
      実行: () => {
        throw new Error("転んだ");
      },
      しくじったら: (異常) => (異常 as Error).message,
    });
    期待(結果).である("転んだ");
  });

  検証("非同期でも同じように拾える", async () => {
    const 結果 = await 試みる({
      実行: async () => {
        throw new Error("非同期で転んだ");
      },
      しくじったら: (異常) => (異常 as Error).message,
    });
    期待(結果).である("非同期で転んだ");
  });
});
