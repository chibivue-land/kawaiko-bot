import { 仕様, 検証, 期待 } from "../../試験/言葉";
import { 概算費用ドル, 月キー } from "./料金";
import { 文字数を収める } from "../Discord/通信";
import { Temporal } from "../../核/時刻";
import { 真 } from "../../共通/型";

仕様("概算費用ドル", () => {
  検証("思考トークンを出力の単価で数える", () => {
    const 費用 = 概算費用ドル("gemini-3.7-flash", {
      total_input_tokens: 1_000_000,
      total_output_tokens: 500_000,
      total_thought_tokens: 500_000,
    });

    // 入力 $0.75 + 出力 $3.75 (本文 0.5M + 思考 0.5M)
    期待(費用).とほぼ等しい(4.5, 5);
  });

  検証("前方一致がいちばん長いものを採る", () => {
    // -lite の単価 ($0.10)．3.5-flash の $1.50 ではない．
    期待(概算費用ドル("gemini-3.5-flash-lite", { total_input_tokens: 1_000_000 })).とほぼ等しい(
      0.1,
      5,
    );
  });

  検証("知らないモデルには保守的な単価を当てる", () => {
    期待(概算費用ドル("gemini-99-ultra", { total_input_tokens: 1_000_000 })).とほぼ等しい(2, 5);
  });

  検証("キャッシュ済み入力は割り引く", () => {
    const 費用 = 概算費用ドル("gemini-3.5-flash-lite", {
      total_input_tokens: 1_000_000,
      total_cached_tokens: 1_000_000,
    });

    期待(費用).とほぼ等しい(0.01, 5);
  });
});

仕様("月キー", () => {
  検証("UTC の月で束ねる", () => {
    期待(月キー(Temporal.Instant.from("2026-08-21T00:00:00Z"))).である("2026-08");
    期待(月キー(Temporal.Instant.from("2026-01-02T00:00:00Z"))).である("2026-01");
  });

  検証("日本時間の夜でも月を先に繰り上げない", () => {
    // 2026-08-31T23:00Z は東京ではもう 9 月．予算の束ねは UTC．
    期待(月キー(Temporal.Instant.from("2026-08-31T23:00:00Z"))).である("2026-08");
  });
});

仕様("文字数を収める", () => {
  検証("短い発言はそのまま", () => {
    期待(文字数を収める("短い")).である("短い");
  });

  検証("Discord の 2000 文字上限より内側へ収める", () => {
    const 収めた = 文字数を収める("あ".repeat(3000));

    期待(収めた.length).以下(2000);
    期待(収めた.endsWith("…")).である(真);
  });
});
