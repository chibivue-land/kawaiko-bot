import { Jevの判定器, 判定なし, 判定器の名前, 答えを読み取る, 線の上へ直す } from "./Jev";

import type { 提供者の休み, 提供者の記録 } from "../../振る舞い/接続口";

import type { 問い } from "../../核/判定";

import { 仕様, 検証, 期待, 偽装する } from "../../試験/言葉";

import { 文字列, 新しい例外, 真 } from "../../共通/型";
import type { 不明, 記録 } from "../../共通/型";

const 問い一覧: 記録<文字列, 問い> = {
  急ぎか: { 種別: "真偽", 指示: "急ぎか", 基準: { 真: "急ぎ", 偽: "急ぎでない" } },
  晩飯: { 種別: "選択", 指示: "晩飯", 基準: { ラーメン: "麺", カレー: "米" } },
  ヤバさ: { 種別: "段階", 指示: "ヤバさ", 基準: ["平和", "怪しい", "炎上"] },
};

/** 相手が返してくる形．鍵は線の上の札 (q0, o0…)． */
const 応答 = {
  model: "jev-1.13.0",
  answers: {
    q0: { type: "noul", noul: 0.93 },
    q1: { type: "choice", choice: "o1", confidence: 0.8, probabilities: { o0: 0.13, o1: 0.87 } },
    q2: { type: "score", score: 1.4, confidence: 0.6 },
  },
  usage: { input_tokens: 1_000_000, output_tokens: 12 },
};

function 記録係を作る(休み: 記録<文字列, 提供者の休み> = {}): 提供者の記録 & {
  休ませた: 記録<文字列, 提供者の休み>;
} {
  const 休ませた: 記録<文字列, 提供者の休み> = {};

  return {
    休ませた,
    休んでいる提供者: async () => 休み,
    休ませる: async (名前, 内容) => {
      休ませた[名前] = 内容;
    },
  };
}

function AIを作る(実行: (...引数: 不明[]) => Promise<不明>): Ai {
  return { run: 実行 } as unknown as Ai;
}

仕様("線の上へ直す", () => {
  検証("問いの形を相手の語彙へ写し，鍵は ASCII の札に付け替える", () => {
    const 対応 = 線の上へ直す(問い一覧);

    期待(対応.問い一覧).と等しい({
      q0: { type: "noul", instructions: "急ぎか", criteria: { true: "急ぎ", false: "急ぎでない" } },
      q1: { type: "choice", instructions: "晩飯", criteria: { o0: "麺", o1: "米" } },
      q2: { type: "score", instructions: "ヤバさ", criteria: ["平和", "怪しい", "炎上"] },
    });
    期待(対応.問いの名前).と等しい({ q0: "急ぎか", q1: "晩飯", q2: "ヤバさ" });
    期待(対応.選択肢の名前).と等しい({ q1: { o0: "ラーメン", o1: "カレー" } });
  });
});

仕様("答えを読み取る", () => {
  検証("札をこちらの名前へ戻しながら，3 つの形を読む", () => {
    期待(答えを読み取る(応答, 線の上へ直す(問い一覧))).と等しい({
      急ぎか: { 種別: "真偽", 確率: 0.93 },
      晩飯: { 種別: "選択", 選択: "カレー", 確信: 0.8, 確率: { ラーメン: 0.13, カレー: 0.87 } },
      ヤバさ: { 種別: "段階", 点数: 1.4, 確信: 0.6 },
    });
  });

  検証("読めない答えは一覧に載せない (= 分からなかった)", () => {
    const 壊れた = { answers: { q0: { type: "noul", noul: "高い" }, q2: {} } } as never;

    期待(答えを読み取る(壊れた, 線の上へ直す(問い一覧))).と等しい({});
  });
});

仕様("Jevの判定器", () => {
  検証("AI Gateway 越しに呼び，答えと費用を返す", () => {
    const 実行 = 偽装する(async () => 応答);

    return Jevの判定器(AIを作る(実行))
      .判定する({ 状態: "[発言]\nやあ", 問い一覧 })
      .んで((結果) => {
        期待(結果?.モデル).である("jev-1.13.0");
        期待(結果?.答え一覧["急ぎか"]).と等しい({ 種別: "真偽", 確率: 0.93 });
        // 入力 100 万トークンで $0.042．出力は課金されない．
        期待(結果?.費用ドル).とほぼ等しい(0.042, 6);

        const [モデル, 入力, 設定] = 実行.mock.calls[0] as unknown as [
          文字列,
          { state: 文字列 },
          { gateway: { id: 文字列 } },
        ];
        期待(モデル).である("typesafe/jev");
        期待(入力.state).である("[発言]\nやあ");
        // 第三者モデルはゲートウェイの指定が要る．"default" は勝手に作られる．
        期待(設定.gateway).と等しい({ id: "default" });
      });
  });

  検証("転んでも投げない．分からなかったことにして，しばらく休む", () => {
    // Unified Billing の残高が無いアカウントでは毎回こうなる．
    const 記録係 = 記録係を作る();
    const 実行 = 偽装する(async () => {
      throw 新しい例外("402: insufficient credits");
    });

    return Jevの判定器(AIを作る(実行), { 記録係 })
      .判定する({ 状態: "やあ", 問い一覧 })
      .んで((結果) => {
        期待(結果).が未定義();
        期待(記録係.休ませた[判定器の名前]?.理由).を含む("insufficient credits");
        期待(記録係.休ませた[判定器の名前]!.いつまで).より大きい(0);
      });
  });

  検証("休んでいるあいだは叩かない (確実に転ぶ往復を，返事のたびに払わない)", () => {
    const 実行 = 偽装する(async () => 応答);
    const 記録係 = 記録係を作る({
      [判定器の名前]: { いつまで: 9e15, 理由: "402", 休ませた時刻: 0 },
    });

    return Jevの判定器(AIを作る(実行), { 記録係 })
      .判定する({ 状態: "やあ", 問い一覧 })
      .んで((結果) => {
        期待(結果).が未定義();
        期待(実行).呼ばれた回数が(0);
      });
  });

  検証("名指しで頼まれたら休んでいても訊き，通ったら起こす", () => {
    const 実行 = 偽装する(async () => 応答);
    const 記録係 = 記録係を作る({
      [判定器の名前]: { いつまで: 9e15, 理由: "402", 休ませた時刻: 0 },
    });

    return Jevの判定器(AIを作る(実行), { 記録係 })
      .判定する({ 状態: "やあ", 問い一覧, 休みを無視するか: 真 })
      .んで((結果) => {
        期待(結果?.答え一覧["急ぎか"]).が真();
        期待(実行).一度だけ呼ばれた();
        // 期限切れの休みで上書きする = 次に読まれた時点で消える．
        期待(記録係.休ませた[判定器の名前]!.いつまで).である(0);
      });
  });

  検証("通ったのに読める答えが無ければ，形が変わったとみて休む", () => {
    const 記録係 = 記録係を作る();

    return Jevの判定器(
      AIを作る(async () => ({ result: "知らない形" })),
      { 記録係 },
    )
      .判定する({ 状態: "やあ", 問い一覧 })
      .んで((結果) => {
        期待(結果).が未定義();
        期待(記録係.休ませた[判定器の名前]?.理由).を含む("答えが読めない");
      });
  });

  検証("問いが無ければ訊かない", () => {
    const 実行 = 偽装する(async () => 応答);

    return Jevの判定器(AIを作る(実行))
      .判定する({ 状態: "やあ", 問い一覧: {} })
      .んで((結果) => {
        期待(結果).が未定義();
        期待(実行).呼ばれた回数が(0);
      });
  });

  検証("判定器を置かない設定なら，何を訊いても分からない", () => {
    return 判定なし.判定する({ 状態: "やあ", 問い一覧 }).んで((結果) => {
      期待(結果).が未定義();
    });
  });
});
