/** 既定の判定モデル． */
export const 既定の判定モデル = "typesafe/jev";

/** 休みの帳面に書く名前．発話の提供者 (workers-ai / gemini) と同じ帳面に並ぶ． */
export const 判定器の名前 = "jev";

/** 判定は 1 秒かからないのが売り．これだけ待って来ないなら，返事を待たせない． */
const 待てる時間 = 4000;

/** 相手が受け取る問いの形． */
type 線の上の問い =
  | { type: "noul"; instructions: 文字列; criteria?: 省略可<{ true: 文字列; false: 文字列 }> }
  | { type: "choice"; instructions: 文字列; criteria: 記録<文字列, 文字列> }
  | { type: "score"; instructions: 文字列; criteria: 読み取り専用配列<文字列> };

/** 相手が返す答えの形．知らない項目は読まない． */
interface 線の上の答え {
  type?: 省略可<文字列>;
  noul?: 省略可<数値>;
  choice?: 省略可<文字列>;
  score?: 省略可<数値>;
  confidence?: 省略可<数値>;
  probabilities?: 省略可<記録<文字列, 数値>>;
}

interface 線の上の応答 {
  model?: 省略可<文字列>;
  answers?: 省略可<記録<文字列, 線の上の答え>>;
  usage?: 省略可<{ input_tokens?: 省略可<数値>; output_tokens?: 省略可<数値> }>;
}

/** こちらの鍵と，線の上の札の対応． */
interface 付け替え {
  問い一覧: 記録<文字列, 線の上の問い>;

  /** 線の上の問いの札 -> こちらの問いの名前． */
  問いの名前: 記録<文字列, 文字列>;

  /** 線の上の問いの札 -> (線の上の選択肢の札 -> こちらの選択肢)． */
  選択肢の名前: 記録<文字列, 記録<文字列, 文字列>>;
}

/** こちらの問いを，線の上の形へ．鍵は札に付け替える． */
export function 線の上へ直す(問い一覧: 記録<文字列, 問い>): 付け替え {
  const 結果: 付け替え = { 問い一覧: {}, 問いの名前: {}, 選択肢の名前: {} };

  各要素に(Object.entries(問い一覧), ([名前, 問い], 位置) => {
    const 札 = `q${位置}`;
    結果.問いの名前[札] = 名前;

    // 判別可能ユニオンの絞り込みは，関数越しの型述語では効かない．ここは素の === で見る．
    結果.問い一覧[札] =
      問い.種別 === "真偽"
        ? {
            type: "noul",
            instructions: 問い.指示,
            criteria: 問い.基準 ? { true: 問い.基準.真, false: 問い.基準.偽 } : 未定義,
          }
        : 問い.種別 === "段階"
          ? { type: "score", instructions: 問い.指示, criteria: 問い.基準 }
          : 選択を直す(結果, 札, 問い.指示, 問い.基準);
  });

  return 結果;
}

function 選択を直す(
  結果: 付け替え,
  問いの札: 文字列,
  指示: 文字列,
  基準: 記録<文字列, 文字列>,
): 線の上の問い {
  const 札一覧 = 写す(Object.entries(基準), ([選択肢, 説明], 位置) => ({
    札: `o${位置}`,
    選択肢,
    説明,
  }));

  結果.選択肢の名前[問いの札] = Object.fromEntries(写す(札一覧, (項) => [項.札, 項.選択肢]));

  return {
    type: "choice",
    instructions: 指示,
    criteria: Object.fromEntries(写す(札一覧, (項) => [項.札, 項.説明])),
  };
}

/** 確率として読める数か． */
function 数か(値: 不明): 値 is 数値 {
  return 等しい(typeof 値, "number") && 数値.isFinite(値 as 数値);
}

/** 線の上の答え 1 つを，こちらの答えへ．形が合わなければ未定義 (= 答えが無かった)． */
function 答えを直す(生: 線の上の答え, 選択肢の名前: 省略可<記録<文字列, 文字列>>): 省略可<答え> {
  const 元の名前 = (札: 文字列) => 選択肢の名前?.[札] ?? 札;

  return 数か(生.noul)
    ? { 種別: "真偽", 確率: 生.noul }
    : 数か(生.score)
      ? { 種別: "段階", 点数: 生.score, 確信: 数か(生.confidence) ? 生.confidence : 0 }
      : 等しい(typeof 生.choice, "string")
        ? {
            種別: "選択",
            選択: 元の名前(生.choice!),
            確信: 数か(生.confidence) ? 生.confidence : 0,
            確率: Object.fromEntries(
              写す(
                絞る(Object.entries(生.probabilities ?? {}), ([, 値]) => 数か(値)),
                ([札, 値]) => [元の名前(札), 値],
              ),
            ),
          }
        : 未定義;
}

/** 線の上の応答を，こちらの答え一覧へ．読めなかった問いは一覧に載らない． */
export function 答えを読み取る(応答: 線の上の応答, 対応: 付け替え): 答え一覧 {
  return Object.fromEntries(
    絞る(
      写す(Object.entries(応答.answers ?? {}), ([札, 生]) => {
        const 答え = 答えを直す(生 ?? {}, 対応.選択肢の名前[札]);

        return [対応.問いの名前[札] ?? 札, 答え] as const;
      }),
      (組): 組 is readonly [文字列, 答え] => 等しくない(組[1], 未定義),
    ),
  );
}

export function Jevの判定器(
  ai: Ai,
  設定?: 省略可<{ モデル?: 省略可<文字列>; 記録係?: 省略可<提供者の記録> }>,
): 判定器 {
  const モデル = 設定?.モデル ?? 既定の判定モデル;
  const 記録係 = 設定?.記録係;
  // env.AI.run は組み込みモデル一覧で型が付いている．任意の id 用に広げる．
  const 実行 = ai.run.bind(ai) as unknown as (
    モデル: 文字列,
    入力: 記録<文字列, 不明>,
    設定: AiOptions,
  ) => 約束<線の上の応答>;

  const 休ませる = (理由: 文字列): 約束<無> => {
    const 現在 = 現在時刻().epochMilliseconds;

    return 約束に均す(
      記録係?.休ませる(判定器の名前, {
        いつまで: 足す(現在, 提供者を休ませる長さ),
        理由,
        休ませた時刻: 現在,
      }),
      // 休ませ損ねても先へ進む．次の回にまた叩くだけ．
    ).しくじったら(() => 未定義);
  };

  /** 休みを無視して訊いて通ったなら，もう休ませておく理由が無い．期限切れで上書きする． */
  const 起こす = (休んでいたか: 真偽): 約束<無> =>
    もし<約束<無>>(休んでいたか, {
      であれば: () =>
        約束に均す(
          記録係?.休ませる(判定器の名前, { いつまで: 0, 理由: "", 休ませた時刻: 0 }),
        ).しくじったら(() => 未定義),
      でなければ: () => すぐ返す(未定義),
    });

  const 実際に訊く = (依頼: 判定の依頼, 休んでいたか: 真偽): 約束<省略可<判定の結果>> => {
    const 対応 = 線の上へ直す(依頼.問い一覧);

    return 試みる<省略可<判定の結果>>({
      実行: () =>
        実行(
          モデル,
          { state: 依頼.状態, questions: 対応.問い一覧 },
          { gateway: { id: "default" }, signal: AbortSignal.timeout(待てる時間) },
        ).んで((応答) => {
          const 答え一覧 = 答えを読み取る(応答, 対応);

          return もし<約束<省略可<判定の結果>>>(空か(Object.keys(答え一覧)), {
            // 通ったが，読める答えが一つも無い．形が変わったか，こちらの読み違い．
            であれば: () =>
              休ませる(`答えが読めない: ${切り出す(JSON.stringify(応答) ?? "", 0, 200)}`).んで(
                () => 未定義,
              ),
            でなければ: () =>
              起こす(休んでいたか).んで(() => ({
                答え一覧,
                費用ドル: 概算費用ドル(モデル, {
                  total_input_tokens: 応答.usage?.input_tokens ?? 0,
                  total_output_tokens: 応答.usage?.output_tokens ?? 0,
                }),
                モデル: 応答.model ?? モデル,
              })),
          });
        }),
      しくじったら: (躓き) => {
        const 理由 = 失敗を要約する(躓き);
        注意(`Jev: 判定に失敗: ${理由}`);

        return 休ませる(理由).んで(() => 未定義);
      },
    });
  };

  return {
    判定する(依頼: 判定の依頼): 約束<省略可<判定の結果>> {
      return 約束に均す(記録係?.休んでいる提供者())
        .しくじったら(() => 未定義)
        .んで((休み) => {
          const 休んでいるか = 等しくない(休み?.[判定器の名前], 未定義);

          return 振り分ける<省略可<判定の結果>>(
            [
              {
                // 問いが無ければ訊くことも無い．
                条件: () => 空か(Object.keys(依頼.問い一覧)),
                ならば: () => 未定義,
              },
              {
                // 直前に転んだ．時間が経つまで叩かない (名指しで頼まれたときを除く)．
                条件: () => 休んでいるか && 否定(依頼.休みを無視するか),
                ならば: () => 未定義,
              },
            ],
            { どれでもなければ: () => 実際に訊く(依頼, 休んでいるか) },
          );
        });
    },
  };
}

/** 判定器を置かない (設定で切ってある) ときの身代わり．何を訊いても「分からない」． */
export const 判定なし: 判定器 = {
  判定する: () => すぐ返す(未定義),
};
