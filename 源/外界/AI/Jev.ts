/**
 * Jev — TypeSafe の判定モデル．文章は書かず，状態を型付きの問い (Noul / Choice /
 * Score) に照らして，確率つきの答えを返す．1 秒かからず，入力 100 万トークンで
 * $0.042，出力は無料．
 *
 * Cloudflare では第三者モデルとして AI Gateway 越しに呼ぶ:
 *
 *   env.AI.run("typesafe/jev", { state, questions }, { gateway: { id: "default" } })
 *
 * "default" のゲートウェイは最初の呼び出しで勝手に作られる．費用はアカウントの
 * Unified Billing の残高から引かれる — **残高が無いアカウントでは毎回転ぶ**．
 * それでも kawaiko は困らない: 判定はどれも上乗せで，取れなければ決定的な見立てへ
 * 落ちる．転んだ判定器は発話の提供者と同じ帳面で休ませるので，確実に転ぶ往復を
 * 返事のたびに払うこともない (理由は /status の「休んでいる提供者」に出る)．
 *
 * 線の上では鍵を ASCII に付け替える (q0, q1… / o0, o1…)．こちらの問いの名前も
 * jev 命令の選択肢も日本語で，相手がそれを鍵として受けるかは相手の都合なので，
 * 意味は説明文のほうに全部載せて，鍵はただの札にしておく．
 */
