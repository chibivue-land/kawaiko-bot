/**
 * 調べ物が要るかを決める道案内．
 *
 * いちばん安いモデルに一言で判断させる — 正規表現の当てはめより当たるし，
 * 「何で引くか」まで決めてくれる．3B のモデルは 4,625 neuron/M 入力トークンで，
 * 1 回あたり 1 neuron に届かない．無料枠 10,000/日 のうちでは無視できる．
 *
 * 人格指示書は渡さない．ここは会話ではなく判断で，会話向けの縛り
 * (「見出しも箇条書きも使うな」) はラベル付きの 2 行と喧嘩する．
 */
import type { 道案内 } from "../../振る舞い/接続口";

import { 調べ方の依頼を組み立てる, 調べ方を読み取る } from "../../核/調べ方";
import type { 調べ方 } from "../../核/調べ方";

import { 偽, 文字列, 未定義, 真 } from "../../共通/型";
import type { 不明, 省略可, 約束, 記録 } from "../../共通/型";
import { 試みる } from "../../共通/構文";
import { 注意 } from "../../共通/記録";
import { すぐ返す } from "../../共通/約束";

/**
 * 判断に使うモデル．
 *
 * 賢さより速さと安さ．ここで数百 ms 待たせると，返事全体がその分遅くなる．
 */
export const 道案内のモデル = "@cf/meta/llama-3.2-3b-instruct";

export function WorkersAIの道案内(ai: Ai): 道案内 {
  // env.AI.run は組み込みモデル一覧で型が付いている．任意の id 用に広げる．
  const 実行 = ai.run.bind(ai) as (モデル: 文字列, 入力: 記録<文字列, 不明>) => 約束<答えの形>;

  return {
    使えるか: 真,

    調べ方を決める(問いかけ: 文字列): 約束<省略可<調べ方>> {
      return 試みる<省略可<調べ方>>({
        実行: () =>
          実行(道案内のモデル, {
            messages: [{ role: "user", content: 調べ方の依頼を組み立てる(問いかけ) }],
            max_completion_tokens: 64,
          }).んで((答え) => 調べ方を読み取る(本文を取り出す(答え), 問いかけ)),
        しくじったら: (躓き) => {
          // 判断できなかっただけ．呼び出し側が当て推量へ落ちる．
          注意("道案内: 決められなかった:", 文字列(躓き));

          return 未定義;
        },
      });
    },
  };
}

function 本文を取り出す(答え: 答えの形): 文字列 {
  return 答え.choices?.[0]?.message?.content ?? 答え.response ?? "";
}

/** OpenAI 互換の応答．古い Workers AI のモデルは `response` を使う． */
interface 答えの形 {
  response?: 省略可<文字列>;
  choices?: 省略可<Array<{ message?: 省略可<{ content?: 省略可<文字列> }> }>>;
}

/** 道案内が繋がっていない構成のときの身代わり． */
export const 道案内なし: 道案内 = {
  使えるか: 偽,
  調べ方を決める: () => すぐ返す(未定義),
};
