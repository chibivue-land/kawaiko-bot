import type { モデル提供者 } from "./提供者";
import { 点呼する } from "./点呼";

import { 仕様, 検証, 期待 } from "../../試験/言葉";

import { 偽, 文字列, 新しい例外, 真 } from "../../共通/型";
import type { 約束 } from "../../共通/型";

function 提供者を作る(答え方: (モデル: 文字列) => 約束<文字列>): モデル提供者 {
  return {
    名前: "偽物",
    受け持つか: (モデル) => モデル.startsWith("@cf/"),
    画像を見られるか: () => 偽,
    実行する: (モデル) => 答え方(モデル).んで((本文) => ({ 本文, 費用ドル: 0.001, モデル })),
  };
}

仕様("点呼する", () => {
  検証("答えたモデルも転んだモデルも，並べた順に 1 行ずつ返す", () => {
    const 提供者 = 提供者を作る(async (モデル) => {
      if (モデル.endsWith("転ぶ")) throw 新しい例外("5007: No such model");

      return "はい";
    });

    return 点呼する([提供者], ["@cf/答える", "@cf/転ぶ"]).んで((結果) => {
      期待(結果[0]!.モデル).である("@cf/答える");
      期待(結果[0]!.答えたか).である(真);
      期待(結果[0]!.文字数).である(2);
      期待(結果[0]!.費用ドル).である(0.001);
      期待(結果[1]!.モデル).である("@cf/転ぶ");
      期待(結果[1]!.答えたか).である(偽);
      期待(結果[1]!.異常).を含む("5007");
    });
  });

  検証("空の返事は答えたうちに入れない", () => {
    // 引数の形が合わず，黙って空を返すモデルがいちばん見つけにくい．
    // 本番では「無言」の定型文に化けるだけで，転びもしない．
    return 点呼する([提供者を作る(async () => "   ")], ["@cf/黙る"]).んで((結果) => {
      期待(結果[0]!.答えたか).である(偽);
    });
  });

  検証("拒否も答えたうちに入れない", () => {
    const 拒む: モデル提供者 = {
      ...提供者を作る(async () => ""),
      実行する: async (モデル) => ({ 本文: "", 費用ドル: 0, モデル, 拒否された: 真 }),
    };

    return 点呼する([拒む], ["@cf/拒む"]).んで((結果) => {
      期待(結果[0]!.答えたか).である(偽);
      期待(結果[0]!.異常).である("拒否された");
    });
  });

  検証("受け持つ提供者が居ないモデルも，落ちずに 1 行として返す", () => {
    return 点呼する([提供者を作る(async () => "はい")], ["謎のモデル"]).んで((結果) => {
      期待(結果[0]!.答えたか).である(偽);
      期待(結果[0]!.異常).を含む("受け持つ提供者が無い");
    });
  });
});
