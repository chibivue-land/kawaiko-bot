/**
 * 失敗したモデルを休ませる長さ．
 *
 * 短すぎると無駄な往復が減らず，長すぎると一時的な不調で無料枠を取り逃す．
 * 30 分なら，1 日の無料枠が尽きたモデルを叩く回数が 1 日 48 回に収まり，
 * 枠が戻ってからも 30 分以内に自力で復帰する．
 */
export const モデルを休ませる長さ = 30 * 60_000;

export function 順に試す発話器(
  提供者一覧: 読み取り専用配列<モデル提供者>,
  モデル一覧: 読み取り専用配列<文字列>,
  記録係?: 省略可<提供者の記録>,
): 発話器 {
  return {
    発話する(生の依頼: 発話の依頼): 約束<発話の結果> {
      const 依頼 = 送れる形にする(生の依頼);
      const 並び = 試す順に並べる(モデル一覧, 提供者一覧, 依頼);

      return 約束に均す(記録係?.休んでいるモデル()).んで((休み) =>
        順に畳む<文字列, 試した記録>(
          並び,
          (これまで, モデル) =>
            一つ試す(
              {
                提供者一覧,
                モデル一覧: 並び,
                依頼,
                休み: 効かせる休み(並び, 提供者一覧, 休み ?? {}),
                記録係,
              },
              モデル,
              これまで,
            ),
          { 結果: 未定義, 躓き: 新しい例外("モデルが 1 つも設定されていない"), 順番: 0 },
        ).んで((結末) =>
          もし(等しくない(結末.結果, 未定義), {
            であれば: () => 結末.結果!,
            // どのモデルも駄目だった．最後の躓きをそのまま上へ渡す．
            でなければ: (): 発話の結果 => しくじる(結末.躓き),
          }),
        ),
      );
    },
  };
}

/**
 * この回に効かせる休み．
 *
 * 休みは「他に当てがあるなら，倒れているモデルを叩かない」ためのもの．全員が
 * 休んでいる回にまで守ると，試しもせずに失敗するだけになる — 1 回の発言で全員が
 * 倒れると，原因を直したあとも 30 分は誰にも返事ができなかった (2026-10)．
 * 叩ける相手が 1 つも残らない回は，休みを無かったことにして全員を試す．
 */
export function 効かせる休み(
  モデル一覧: 読み取り専用配列<文字列>,
  提供者一覧: 読み取り専用配列<モデル提供者>,
  休み: 記録<文字列, 提供者の休み>,
): 記録<文字列, 提供者の休み> {
  const 叩けるか = (モデル: 文字列) =>
    いずれか(提供者一覧, (提供者) => 提供者.受け持つか(モデル)) &&
    否定(Object.hasOwn(休み, モデル));

  return もし(いずれか(モデル一覧, 叩けるか) || 空か(Object.keys(休み)), {
    であれば: () => 休み,
    でなければ: () => {
      注意("選択: 全員が休み中なので，休みを無視して試す");

      return {};
    },
  });
}

/**
 * どの提供者にも断られない文字列にする．
 *
 * 会話ログや自分の直近発言は文字数で刈ってあり，刈り口が絵文字の真ん中だと
 * 代用符号の片割れが残る．それが 1 つ混ざるだけで，Workers AI は「8006: Invalid
 * data for body - reason must be valid JSON」，Gemini は「400 Invalid JSON
 * payload」と本文ごと断る．提供者の違いではなくこちらの文字列のせいなので，
 * 次のモデルへ手渡しても同じ理由で全員が倒れ，全員が休みに入る．その発言が
 * 直近の履歴から流れ出るまで，kawaiko は誰にも返事ができなかった (2026-10)．
 *
 * 刈る側を 1 つずつ直すのではなく，出口のここで均す．刈る場所は増えるので．
 */
export function 送れる形にする(依頼: 発話の依頼): 発話の依頼 {
  return { ...依頼, 指示書: 整った形にする(依頼.指示書), 指示文: 整った形にする(依頼.指示文) };
}

/**
 * どの順で試すか．
 *
 * 普段は設定どおりの順 — 先頭に無料枠のモデルが置いてあるので，並べ替えると
 * その枠を捨てることになる．画像が添えられているときだけ，見られる提供者を
 * 前に出す．見えないモデルに先に当たると，画像の話を画像抜きで返してしまう．
 * 前に出すだけで落としはしないので，目のある提供者が全部倒れても返事は出る．
 */
export function 試す順に並べる(
  モデル一覧: 読み取り専用配列<文字列>,
  提供者一覧: 読み取り専用配列<モデル提供者>,
  依頼: 発話の依頼,
): 読み取り専用配列<文字列> {
  return もし(空か(依頼.画像一覧 ?? []), {
    であれば: () => モデル一覧,
    でなければ: () => {
      const 見られるか = (モデル: 文字列) =>
        探す(提供者一覧, (提供者) => 提供者.受け持つか(モデル))?.画像を見られるか(モデル) ?? 偽;

      return [
        ...絞る(モデル一覧, (モデル) => 見られるか(モデル)),
        ...絞る(モデル一覧, (モデル) => 否定(見られるか(モデル))),
      ];
    },
  });
}

/** 1 回の生成のあいだ持ち回るもの． */
interface 選ぶ場 {
  提供者一覧: 読み取り専用配列<モデル提供者>;
  モデル一覧: 読み取り専用配列<文字列>;
  依頼: 発話の依頼;
  休み: 記録<文字列, 提供者の休み>;
  記録係: 省略可<提供者の記録>;
}

/** ここまでに何が返ってきたか． */
interface 試した記録 {
  結果: 省略可<発話の結果>;
  躓き: 不明;
  順番: 数値;
}

async function 一つ試す(場: 選ぶ場, モデル: 文字列, これまで: 試した記録): 約束<試した記録> {
  const 順番 = これまで.順番 + 1;

  return もし(等しくない(これまで.結果, 未定義), {
    // もう答えは出ている．残りのモデルには触らない．
    であれば: async () => これまで,
    でなければ: () => 提供者へ投げる(場, モデル, これまで, 順番),
  });
}

async function 提供者へ投げる(
  場: 選ぶ場,
  モデル: 文字列,
  これまで: 試した記録,
  順番: 数値,
): 約束<試した記録> {
  const 提供者 = 探す(場.提供者一覧, (提供者) => 提供者.受け持つか(モデル));
  const 休み中 = 場.休み[モデル];

  return 振り分ける<試した記録>(
    [
      {
        条件: () => 等しい(提供者, 未定義),
        ならば: () => {
          注意(`選択: 「${モデル}」を受け持つ提供者が無いので飛ばす`);

          return { ...これまで, 順番 };
        },
      },
      {
        // 直前に失敗したモデル．時間が経つまで叩かない．
        条件: () => 等しくない(休み中, 未定義),
        ならば: () => {
          注意(`選択: ${モデル} は休み中なので飛ばす (${休み中!.理由})`);

          return { ...これまで, 順番 };
        },
      },
    ],
    { どれでもなければ: () => 実際に投げる(場, 提供者!, モデル, これまで, 順番) },
  );
}

async function 実際に投げる(
  場: 選ぶ場,
  提供者: モデル提供者,
  モデル: 文字列,
  これまで: 試した記録,
  順番: 数値,
): 約束<試した記録> {
  return 試みる<試した記録>({
    実行: () =>
      提供者
        .実行する(モデル, 見えるなりの依頼(提供者, モデル, 場.依頼))
        .んで((結果) => ({ 結果, 躓き: これまで.躓き, 順番 })),
    しくじったら: (躓き) => {
      const 理由 = 失敗を要約する(躓き);
      注意(`選択: ${モデル} が失敗 (${順番}/${長さ(場.モデル一覧)}): ${理由}`);

      const 現在 = 現在時刻().epochMilliseconds;

      // 休ませ損ねても返事は続ける．次の回にまた叩くだけ．
      return 約束に均す(
        もし(画像を見せたか(提供者, モデル, 場.依頼), {
          // 画像を見せた回の失敗は，その画像のせい (形式・大きさ) かもしれない．
          // それでモデルを 30 分休ませると，画像が 1 枚貼られるたびに普段の雑談まで
          // 控えのモデルへ流れる．次の回に無駄な往復が 1 回増えるほうがまし．
          であれば: () => 未定義,
          でなければ: () =>
            場.記録係?.休ませる(モデル, {
              いつまで: 足す(現在, モデルを休ませる長さ),
              理由,
              休ませた時刻: 現在,
            }),
        }),
      ).んで(() => ({ 結果: 未定義, 躓き, 順番 }));
    },
  });
}

/** この回，そのモデルへ実際に画像を渡したか． */
function 画像を見せたか(提供者: モデル提供者, モデル: 文字列, 依頼: 発話の依頼): 真偽 {
  return 否定(空か(依頼.画像一覧 ?? [])) && 提供者.画像を見られるか(モデル);
}

/**
 * そのモデルに見えるものだけを渡す．
 *
 * 画像が添えられているのに目の無いモデルまで落ちてきたら，画像を外し，
 * 「今回は見えていない」と指示文に書き足す．黙って画像だけ落とすと，モデルは
 * ファイル名しか知らないまま見えたふりで語る — 「この画像を解説して」に
 * 無関係な話を返したのがそれ (2026-09-21)．
 */
export function 見えるなりの依頼(
  提供者: モデル提供者,
  モデル: 文字列,
  依頼: 発話の依頼,
): 発話の依頼 {
  return もし(空か(依頼.画像一覧 ?? []) || 提供者.画像を見られるか(モデル), {
    であれば: () => 依頼,
    でなければ: () => {
      注意(`選択: ${モデル} には目が無いので，画像抜きで「見えていない」と伝えて投げる`);

      return { ...依頼, 画像一覧: [], 指示文: `${依頼.指示文}\n\n${見えない画像の断り}` };
    },
  });
}

/**
 * Workers AI を先に (1 日の無料枠)，Gemini を控えに．どちらも無料の範囲だけ．
 *
 * Workers AI は全モデルで 1 日 10,000 neuron を分け合う．並べる数を増やしても枠は
 * 増えないが，あるモデルだけが転んだ (混んでいる・消えた) 回の逃げ道になる．
 * Gemini (と Gemma) は枠がモデルごとに別なので，並べたぶんだけ 1 日に答えられる数が
 * 増える．入れていないのは，有料の契約が要るもの (Workers AI の kimi・glm-5・
 * deepseek-v4，Gemini の Pro と 4) と，人格を演じきれない小さいモデル．Gemini 2.5 系は
 * 無料枠に載っているが，前から使っていたアカウントにしか開いておらず，このキーでは
 * 404 が返る (2026-10-20 の点呼)．
 *
 * Gemini 側は点呼で測った速さの順．3.8 Flash と Gemma 4 31B は賢いが，1 言に 30〜50 秒
 * 掛かったので後ろへ回してある．
 *
 * 視覚モデルは安いものより後ろに置いてある．普段の雑談に 27B は要らない．
 * 画像が添えられている回だけ，試す順に並べる が前へ出す．
 */
export const 既定のモデル一覧 =
  "@cf/google/gemma-4-26b-a4b-it,@cf/zai-org/glm-4.7-flash,@cf/qwen/qwen3.8-27b,@cf/openai/gpt-oss-120b,@cf/qwen/qwen3-30b-a3b-fp8,@cf/meta/llama-4-scout-17b-16e-instruct,@cf/mistralai/mistral-small-3.1-24b-instruct,@cf/nvidia/nemotron-3-120b-a12b,@cf/meta/llama-3.3-70b-instruct-fp8-fast,@cf/aisingapore/gemma-sea-lion-v4-27b-it,@cf/openai/gpt-oss-20b,gemini-3.5-flash-lite,gemini-3-flash-preview,gemini-3.6-flash,gemini-3.1-flash-lite,gemma-4-26b-a4b-it,gemini-3.8-flash,gemma-4-31b-it";

export function モデル一覧を読む(設定: 文字列 | 未定義): 配列<文字列> {
  return 絞る(
    写す(分ける(設定 || 既定のモデル一覧, ","), (モデル) => 前後の空白を落とす(モデル)),
    (モデル) => 否定(空か(モデル)),
  );
}
