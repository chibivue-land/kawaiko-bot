/**
 * モデルの優先順リストの上で動く発話器．
 *
 * どのモデルも順に試し，**どんな失敗でも**次へ手渡す．これは意図してそうしてある
 * し，痛い目を見て学んだ形でもある．以前は「再試行してよいエラー」の一覧に文面を
 * 突き合わせていて，Workers AI が「AiError: 4006: you have used up your daily
 * free allocation of 10,000 neurons」と答えた日に落ちた．その文面には一覧のどの
 * 語も入っていない．失敗の仕方は前もって数え上げられないので，致命なのは最後の
 * モデルの失敗だけにする．
 *
 * ただし「毎回同じ提供者が確実に失敗する」状態 (無料枠が尽きた，など) では，
 * 返事のたびに doomed な往復を払うことになる．そこで失敗した提供者を短い間だけ
 * 休ませる．順番を変えて無料枠を捨てるのではなく，しばらく飛ばしてまた試す．
 *
 * 休ませる判断に**エラーの文面は見ない**．4006 の一件で学んだとおり，失敗の
 * 種類は数え上げられない．だから「失敗したら一律で休ませ，時間で復帰させる」．
 * 一時的な不調なら休み時間ぶん無料枠を取り逃すだけで，自力で戻ってくる．
 */
import {
  失敗を要約する,
  type 提供者の休み,
  type 提供者の記録,
  type 発話の依頼,
  type 発話の結果,
  type 発話器,
} from "../../振る舞い/接続口";
import { 現在時刻 } from "../../核/時刻";
import type { モデル提供者 } from "./提供者";
import { 偽, 数値, 文字列, 新しい例外, 未定義 } from "../../共通/型";
import type { 不明, 省略可, 約束, 記録, 読み取り専用配列, 配列 } from "../../共通/型";
import {
  一覧に含む,
  写す,
  分ける,
  前後の空白を落とす,
  探す,
  空か,
  絞る,
  長さ,
} from "../../共通/関数";
import { 否定, 等しい, 等しくない, 足す } from "../../共通/演算";
import { しくじる, もし, 振り分ける, 試みる } from "../../共通/構文";
import { 順に畳む } from "../../共通/反復";
import { 注意 } from "../../共通/記録";
import { 約束に均す } from "../../共通/約束";

/**
 * 失敗した提供者を休ませる長さ．
 *
 * 短すぎると無駄な往復が減らず，長すぎると一時的な不調で無料枠を取り逃す．
 * 30 分なら，1 日の無料枠が尽きた提供者を叩く回数が 1 日 48 回に収まり，
 * 枠が戻ってからも 30 分以内に自力で復帰する．
 */
export const 提供者を休ませる長さ = 30 * 60_000;

export function 順に試す発話器(
  提供者一覧: 読み取り専用配列<モデル提供者>,
  モデル一覧: 読み取り専用配列<文字列>,
  記録係?: 省略可<提供者の記録>,
  熟考のモデル一覧: 読み取り専用配列<文字列> = [],
): 発話器 {
  return {
    発話する(依頼: 発話の依頼): 約束<発話の結果> {
      const 並び = 試す順に並べる(モデル一覧, 提供者一覧, 依頼, 熟考のモデル一覧);

      return 約束に均す(記録係?.休んでいる提供者()).んで((休み) =>
        順に畳む<文字列, 試した記録>(
          並び,
          (これまで, モデル) =>
            一つ試す(
              { 提供者一覧, モデル一覧: 並び, 熟考のモデル一覧, 依頼, 休み: 休み ?? {}, 記録係 },
              モデル,
              これまで,
            ),
          { 結果: 未定義, 躓き: 新しい例外("モデルが 1 つも設定されていない"), 順番: 0 },
        ).んで((結末) =>
          もし(等しくない(結末.結果, 未定義), {
            であれば: () => 結末.結果!,
            // どのモデルも駄目だった．最後の躓きをそのまま上へ渡す．
            でなければ: (): 発話の結果 => しくじる(結末.躓き),
          }),
        ),
      );
    },
  };
}

/**
 * どの順で試すか．
 *
 * 普段は設定どおりの順 — 先頭に無料枠のモデルが置いてあるので，並べ替えると
 * その枠を捨てることになる．例外は 2 つ:
 *
 * - 構えが「熟考」のとき，熟考のモデルを前に足す．正解のある問い (ゲームの一手・
 *   計算・コード) は小さいモデルでは外すので，そこだけ賢いモデルに先に当てる．
 *   見立て (核/見立て.ts) が熟考と言ったときにしか起きないので，雑談は今までどおり
 *   無料枠で回る
 * - 画像が添えられているとき，見られる提供者を前に出す．見えないモデルに先に
 *   当たると，画像の話を画像抜きで返してしまう
 *
 * どちらも前に出すだけで落としはしないので，前に出したものが全部倒れても返事は出る．
 */
export function 試す順に並べる(
  モデル一覧: 読み取り専用配列<文字列>,
  提供者一覧: 読み取り専用配列<モデル提供者>,
  依頼: 発話の依頼,
  熟考のモデル一覧: 読み取り専用配列<文字列> = [],
): 読み取り専用配列<文字列> {
  const 並び = もし(等しい(依頼.構え, "熟考"), {
    であれば: () => [
      ...熟考のモデル一覧,
      ...絞る(モデル一覧, (モデル) => 否定(一覧に含む(熟考のモデル一覧, モデル))),
    ],
    でなければ: () => モデル一覧,
  });

  return もし(空か(依頼.画像一覧 ?? []), {
    であれば: () => 並び,
    でなければ: () => {
      const 見られるか = (モデル: 文字列) =>
        探す(提供者一覧, (提供者) => 提供者.受け持つか(モデル))?.画像を見られるか(モデル) ?? 偽;

      return [
        ...絞る(並び, (モデル) => 見られるか(モデル)),
        ...絞る(並び, (モデル) => 否定(見られるか(モデル))),
      ];
    },
  });
}

/** 1 回の生成のあいだ持ち回るもの． */
interface 選ぶ場 {
  提供者一覧: 読み取り専用配列<モデル提供者>;
  モデル一覧: 読み取り専用配列<文字列>;
  熟考のモデル一覧: 読み取り専用配列<文字列>;
  依頼: 発話の依頼;
  休み: 記録<文字列, 提供者の休み>;
  記録係: 省略可<提供者の記録>;
}

/** ここまでに何が返ってきたか． */
interface 試した記録 {
  結果: 省略可<発話の結果>;
  躓き: 不明;
  順番: 数値;
}

/**
 * 休みの帳面に書く名前．
 *
 * 普段のモデルは提供者ごと休ませる — 尽きるのは提供者の無料枠なので，同じ提供者の
 * 別のモデルを叩いても同じところで転ぶ．熟考のモデルだけはモデル単位で休ませる．
 * あちらは普段の一覧の**前に足した**もので，それが転んだ巻き添えで，同じ提供者の
 * 控え (一覧の最後の砦) まで 30 分休ませては本末転倒．提供者ごと休んでいるときは，
 * 熟考のモデルも一緒に飛ばす．
 */
function 休みの名前(場: 選ぶ場, 提供者: モデル提供者, モデル: 文字列): 文字列 {
  return 一覧に含む(場.熟考のモデル一覧, モデル) ? `${提供者.名前}/${モデル}` : 提供者.名前;
}

async function 一つ試す(場: 選ぶ場, モデル: 文字列, これまで: 試した記録): 約束<試した記録> {
  const 順番 = これまで.順番 + 1;

  return もし(等しくない(これまで.結果, 未定義), {
    // もう答えは出ている．残りのモデルには触らない．
    であれば: async () => これまで,
    でなければ: () => 提供者へ投げる(場, モデル, これまで, 順番),
  });
}

async function 提供者へ投げる(
  場: 選ぶ場,
  モデル: 文字列,
  これまで: 試した記録,
  順番: 数値,
): 約束<試した記録> {
  const 提供者 = 探す(場.提供者一覧, (提供者) => 提供者.受け持つか(モデル));
  const 休み中 = 提供者
    ? (場.休み[提供者.名前] ?? 場.休み[休みの名前(場, 提供者, モデル)])
    : 未定義;

  return 振り分ける<試した記録>(
    [
      {
        条件: () => 等しい(提供者, 未定義),
        ならば: () => {
          注意(`選択: 「${モデル}」を受け持つ提供者が無いので飛ばす`);

          return { ...これまで, 順番 };
        },
      },
      {
        // 直前に失敗した提供者．時間が経つまで叩かない．
        条件: () => 等しくない(休み中, 未定義),
        ならば: () => {
          注意(`選択: 休み中なので ${モデル} を飛ばす (${休み中!.理由})`);

          return { ...これまで, 順番 };
        },
      },
    ],
    { どれでもなければ: () => 実際に投げる(場, 提供者!, モデル, これまで, 順番) },
  );
}

async function 実際に投げる(
  場: 選ぶ場,
  提供者: モデル提供者,
  モデル: 文字列,
  これまで: 試した記録,
  順番: 数値,
): 約束<試した記録> {
  return 試みる<試した記録>({
    実行: () =>
      提供者.実行する(モデル, 場.依頼).んで((結果) => ({ 結果, 躓き: これまで.躓き, 順番 })),
    しくじったら: (躓き) => {
      const 理由 = 失敗を要約する(躓き);
      注意(`選択: ${モデル} が失敗 (${順番}/${長さ(場.モデル一覧)}): ${理由}`);

      const 現在 = 現在時刻().epochMilliseconds;

      // 休ませ損ねても返事は続ける．次の回にまた叩くだけ．
      return 約束に均す(
        場.記録係?.休ませる(休みの名前(場, 提供者, モデル), {
          いつまで: 足す(現在, 提供者を休ませる長さ),
          理由,
          休ませた時刻: 現在,
        }),
      ).んで(() => ({ 結果: 未定義, 躓き, 順番 }));
    },
  });
}

/** Workers AI を先に (1 日の無料枠)，Gemini を控えに． */
export const 既定のモデル一覧 =
  "@cf/google/gemma-4-26b-a4b-it,@cf/zai-org/glm-4.7-flash,gemini-3.5-flash-lite";

/**
 * 正解のある問いに先に当てるモデル．
 *
 * Gemini の Flash は AI Studio の無料枠で動き，思考つきで回せる．Workers AI の
 * 大きいモデルを置かないのは，1 日の無料枠が雑談と共有で，数回の熟考で枯れるため
 * (枯れると workers-ai ごと 30 分休むので，雑談まで巻き添えになる)．
 */
export const 既定の熟考のモデル一覧 = "gemini-3.8-flash";

export function モデル一覧を読む(
  設定: 文字列 | 未定義,
  既定: 文字列 = 既定のモデル一覧,
): 配列<文字列> {
  return 絞る(
    写す(分ける(設定 || 既定, ","), (モデル) => 前後の空白を落とす(モデル)),
    (モデル) => 否定(空か(モデル)),
  );
}
