/**
 * モデルの優先順リストの上で動く発話器。
 *
 * どのモデルも順に試し、**どんな失敗でも**次へ手渡す。これは意図してそうしてある
 * し、痛い目を見て学んだ形でもある。以前は「再試行してよいエラー」の一覧に文面を
 * 突き合わせていて、Workers AI が「AiError: 4006: you have used up your daily
 * free allocation of 10,000 neurons」と答えた日に落ちた。その文面には一覧のどの
 * 語も入っていない。失敗の仕方は前もって数え上げられないので、致命なのは最後の
 * モデルの失敗だけにする。
 */
import {
  失敗を要約する,
  type 発話の依頼,
  type 発話の結果,
  type 発話器,
} from "../../振る舞い/接続口";
import type { モデル提供者 } from "./提供者";
import { 分ける, 前後の空白を落とす, 探す, 写す, 絞る } from "../../共通/関数";
import { 例外 } from "../../共通/型";
import type { 文字列, 約束, 配列, 読み取り専用配列, 不明 } from "../../共通/型";
import { 注意 } from "../../共通/記録";

export function 順に試す発話器(
  提供者一覧: 読み取り専用配列<モデル提供者>,
  モデル一覧: 読み取り専用配列<文字列>,
): 発話器 {
  return {
    async 発話する(依頼: 発話の依頼): 約束<発話の結果> {
      let 最後の躓き: 不明 = new 例外("モデルが 1 つも設定されていない");
      for (const [順番, モデル] of モデル一覧.entries()) {
        const 提供者 = 探す(提供者一覧, (提供者) => 提供者.受け持つか(モデル));
        if (!提供者) {
          注意(`選択: 「${モデル}」を受け持つ提供者が無いので飛ばす`);
          continue;
        }
        try {
          return await 提供者.実行する(モデル, 依頼);
        } catch (躓き) {
          最後の躓き = 躓き;
          注意(
            `選択: ${モデル} が失敗 (${順番 + 1}/${モデル一覧.length}): ${失敗を要約する(躓き)}`,
          );
        }
      }
      throw 最後の躓き;
    },
  };
}

/** Workers AI を先に (1 日の無料枠)、Gemini を控えに。 */
export const 既定のモデル一覧 =
  "@cf/google/gemma-4-26b-a4b-it,@cf/zai-org/glm-4.7-flash,gemini-3.5-flash-lite";

export function モデル一覧を読む(設定: 文字列 | undefined): 配列<文字列> {
  return 絞る(
    写す(分ける(設定 || 既定のモデル一覧, ","), (モデル) => 前後の空白を落とす(モデル)),
    (モデル) => モデル.length > 0,
  );
}
