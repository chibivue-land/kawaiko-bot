/**
 * 並べたモデルの点呼．どれが本当に答えるかを 1 つずつ確かめる．
 *
 * 順に試す発話器は失敗を黙って次へ渡すので，並べたモデルが 1 つ使えなくなって
 * いても外からは見えない — 返事はちゃんと出る．足したモデルが実際に動くか，
 * 渡している引数の形が合っているかは，こうして全部を叩かないと分からない．
 *
 * 休みは見ないし，付けもしない．調べるための口なので，普段の順番には触らない．
 */
import type { モデル提供者 } from "./提供者";

import { 失敗を要約する, type 発話の依頼, type 発話の結果 } from "../../振る舞い/接続口";

import { 現在時刻 } from "../../核/時刻";

import { 偽, 数値, 文字列, 新しい例外, 未定義 } from "../../共通/型";
import type { 省略可, 約束, 真偽, 読み取り専用配列, 配列 } from "../../共通/型";
import { 試みる } from "../../共通/構文";
import { 否定, 引く } from "../../共通/演算";
import { すぐしくじる, 揃える } from "../../共通/約束";
import { 写す, 前後の空白を落とす, 探す, 空か, 長さ } from "../../共通/関数";

export interface 点呼の結果 {
  モデル: 文字列;

  /** 中身のある返事が来たか．空の返事や拒否は，答えたうちに入れない． */
  答えたか: 真偽;

  ミリ秒: 数値;

  文字数: 数値;

  費用ドル: 数値;

  /** 転んだときの文面．提供者の異常の文面なので，公開の場へは出さないこと． */
  異常?: 省略可<文字列>;
}

/** 普段の返事と同じ引数の形で，いちばん短く答えられる問い． */
const 点呼の依頼: 発話の依頼 = {
  指示書: "点呼に答える係．",
  指示文: "点呼です．「はい」とだけ返してください．",
  深さ: "low",
};

/** 全部を同時に叩く．1 つが転んでも他の結果は返る． */
export function 点呼する(
  提供者一覧: 読み取り専用配列<モデル提供者>,
  モデル一覧: 読み取り専用配列<文字列>,
): 約束<配列<点呼の結果>> {
  return 揃える(写す(モデル一覧, (モデル) => 一つ呼ぶ(提供者一覧, モデル)));
}

function 一つ呼ぶ(提供者一覧: 読み取り専用配列<モデル提供者>, モデル: 文字列): 約束<点呼の結果> {
  const 始め = 現在時刻().epochMilliseconds;
  const 経過 = () => 引く(現在時刻().epochMilliseconds, 始め);
  const 提供者 = 探す(提供者一覧, (提供者) => 提供者.受け持つか(モデル));

  return 試みる<点呼の結果>({
    実行: () =>
      (提供者
        ? 提供者.実行する(モデル, 点呼の依頼)
        : すぐしくじる<発話の結果>(新しい例外("受け持つ提供者が無い"))
      ).んで((結果) => {
        const 文字数 = 長さ(前後の空白を落とす(結果.本文));

        return {
          モデル,
          答えたか: 否定(結果.拒否された) && 否定(空か(前後の空白を落とす(結果.本文))),
          ミリ秒: 経過(),
          文字数,
          費用ドル: 結果.費用ドル,
          異常: 結果.拒否された ? "拒否された" : 未定義,
        };
      }),
    しくじったら: (躓き) => ({
      モデル,
      答えたか: 偽,
      ミリ秒: 経過(),
      文字数: 0,
      費用ドル: 0,
      異常: 失敗を要約する(躓き),
    }),
  });
}
