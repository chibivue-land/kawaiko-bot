const 依頼 = { 指示書: "指示書", 指示文: "指示文" };

/** どのモデル id も受け持ち，渡された処理へ委ねる提供者． */
function 提供者を作る(実行: (モデル: 文字列) => Promise<string>): モデル提供者 {
  return {
    名前: "偽物",
    受け持つか: () => 真,
    async 実行する(モデル) {
      return { 本文: await 実行(モデル), 費用ドル: 0.001, モデル };
    },
  };
}

仕様("順に試す発話器", () => {
  検証("kawaiko を落とした「1 日の無料枠」のエラーでも次へ渡す", () => {
    // 本番の文面そのまま．以前の「再試行してよいか」判定の一覧のどれにも当たらず，
    // 次のモデルへ行かずに連鎖が切れた．
    const 枯渇 = 新しい例外(
      "4006: you have used up your daily free allocation of 10,000 neurons, " +
        "please upgrade to Cloudflare's Workers Paid plan if you would like to continue usage.",
    );
    枯渇.name = "AiError";

    const 実行 = 偽装.fn(async (モデル: 文字列) => {
      if (等しい(モデル, "@cf/一つ目")) throw 枯渇;

      return "二番目のモデルが答えた";
    });

    return 順に試す発話器([提供者を作る(実行)], ["@cf/一つ目", "@cf/二つ目"])
      .発話する(依頼)
      .then((結果) => {
        期待(結果.本文).である("二番目のモデルが答えた");
        期待(結果.モデル).である("@cf/二つ目");
        期待(実行).呼ばれた回数が(2);
      });
  });

  検証("誰も知らない失敗でも次へ渡す", async () => {
    const 実行 = 偽装.fn(async (モデル: 文字列) => {
      if (等しい(モデル, "あ")) throw 新しい例外("誰も数え上げていない失敗");

      return "生き残り";
    });

    期待((await 順に試す発話器([提供者を作る(実行)], ["あ", "い"]).発話する(依頼)).本文).である(
      "生き残り",
    );
  });

  検証("全部尽きたら最後の失敗を伝える", async () => {
    const 実行 = 偽装.fn(async (モデル: 文字列) => {
      throw 新しい例外(`${モデル} が落ちている`);
    });

    await 期待(順に試す発話器([提供者を作る(実行)], ["あ", "い"]).発話する(依頼)).しくじる(
      "い が落ちている",
    );
    期待(実行).呼ばれた回数が(2);
  });

  検証("最初のモデルで足りたらそこで止まる", async () => {
    const 実行 = 偽装.fn(async () => "一番目で足りた");

    const 結果 = await 順に試す発話器([提供者を作る(実行)], ["あ", "い"]).発話する(依頼);

    期待(結果.モデル).である("あ");
    期待(実行).呼ばれた回数が(1);
  });

  検証("モデルごとに，名乗り出た提供者へ振り分ける", async () => {
    const cf: モデル提供者 = {
      名前: "cf",
      受け持つか: (モデル) => モデル.startsWith("@cf/"),
      async 実行する(モデル) {
        throw 新しい例外(`${モデル} は使えない`);
      },
    };
    const gemini: モデル提供者 = {
      名前: "gemini",
      受け持つか: (モデル) => モデル.startsWith("gemini-"),
      async 実行する(モデル) {
        return { 本文: "gemini が答えた", 費用ドル: 0, モデル };
      },
    };

    const 結果 = await 順に試す発話器([cf, gemini], ["@cf/x", "gemini-y"]).発話する(依頼);

    期待(結果.本文).である("gemini が答えた");
  });

  検証("受け持つ提供者が居ないモデルは，落ちずに飛ばす", async () => {
    const gemini: モデル提供者 = {
      名前: "gemini",
      受け持つか: (モデル) => モデル.startsWith("gemini-"),
      async 実行する(モデル) {
        return { 本文: "よい", 費用ドル: 0, モデル };
      },
    };

    const 結果 = await 順に試す発話器([gemini], ["謎のモデル", "gemini-y"]).発話する(依頼);

    期待(結果.モデル).である("gemini-y");
  });

  検証("何も設定されていなければ投げる", async () => {
    await 期待(順に試す発話器([], []).発話する(依頼)).しくじる("モデルが 1 つも");
  });
});

