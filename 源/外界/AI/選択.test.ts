/** どのモデル id も受け持ち，渡された処理へ委ねる提供者． */
function 提供者を作る(実行: (モデル: 文字列) => 約束<文字列>): モデル提供者 {
  return {
    名前: "偽物",
    受け持つか: () => 真,
    画像を見られるか: () => 偽,
    実行する: (モデル) => 実行(モデル).んで((本文) => ({ 本文, 費用ドル: 0.001, モデル })),
  };
}

