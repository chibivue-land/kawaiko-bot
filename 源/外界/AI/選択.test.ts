仕様("失敗した提供者を休ませる", () => {
  const 休みの記録 = (): 提供者の記録 & { 中身: 記録<文字列, 提供者の休み> } => {
    const 中身: 記録<文字列, 提供者の休み> = {};

    return {
      中身,
      async 休んでいる提供者() {
        return 中身;
      },
      async 休ませる(提供者名, 休み) {
        中身[提供者名] = 休み;
      },
    };
  };

  const 落ちる提供者 = (名前: 文字列, 受け持つ: 文字列): モデル提供者 => ({
    名前,
    受け持つか: (モデル) => モデル.startsWith(受け持つ),
    画像を見られるか: () => 偽,
    async 実行する(モデル) {
      throw new Error(`${モデル} は無料枠切れ`);
    },
  });

  const 答える提供者 = (名前: 文字列, 受け持つ: 文字列): モデル提供者 => ({
    名前,
    受け持つか: (モデル) => モデル.startsWith(受け持つ),
    画像を見られるか: () => 偽,
    async 実行する(モデル) {
      return { 本文: "答えた", 費用ドル: 0, モデル };
    },
  });

  検証("失敗したら，その提供者を理由つきで休ませる", () => {
    const 記録係 = 休みの記録();
    return 順に試す発話器(
      [落ちる提供者("cf", "@cf/"), 答える提供者("gemini", "gemini-")],
      ["@cf/x", "gemini-y"],
      記録係,
    )
      .発話する(依頼)
      .んで(() => {
        期待(記録係.中身.cf).否.が未定義();
        期待(記録係.中身.cf!.理由).を含む("無料枠切れ");
        // 答えたほうは休ませない．
        期待(記録係.中身.gemini).が未定義();
      });
  });

  検証("休んでいる提供者は叩かずに飛ばす", () => {
    const 記録係 = 休みの記録();
    const 実行 = 偽装する(async (モデル: 文字列) => ({ 本文: "答えた", 費用ドル: 0, モデル }));
    記録係.中身.cf = {
      いつまで: 決め打ちの現在.epochMilliseconds + 60_000,
      理由: "前に落ちた",
      休ませた時刻: 0,
    };
    return 順に試す発話器(
      [
        {
          名前: "cf",
          受け持つか: (m) => m.startsWith("@cf/"),
          画像を見られるか: () => 偽,
          実行する: 実行,
        },
        答える提供者("gemini", "gemini-"),
      ],
      ["@cf/x", "gemini-y"],
      記録係,
    )
      .発話する(依頼)
      .んで((結果) => {
        期待(実行).否.呼ばれた();
        期待(結果.モデル).である("gemini-y");
      });
  });

  検証("記録係を渡さなくても動く (休みは省略可)", () => {
    return 順に試す発話器(
      [落ちる提供者("cf", "@cf/"), 答える提供者("gemini", "gemini-")],
      ["@cf/x", "gemini-y"],
    )
      .発話する(依頼)
      .んで((結果) => {
        期待(結果.モデル).である("gemini-y");
      });
  });
});

仕様("試す順に並べる", () => {
  const 目のある = {
    名前: "gemini",
    受け持つか: (モデル: 文字列) => モデル.startsWith("gemini-"),
    画像を見られるか: () => 真,
    実行する: () => すぐ返す({ 本文: "", 費用ドル: 0, モデル: "" }),
  };
  const 目のない = {
    名前: "cf",
    受け持つか: (モデル: 文字列) => モデル.startsWith("@cf/"),
    画像を見られるか: () => 偽,
    実行する: () => すぐ返す({ 本文: "", 費用ドル: 0, モデル: "" }),
  };
  const 提供者一覧 = [目のない, 目のある];
  const モデル一覧 = ["@cf/x", "@cf/y", "gemini-z"];

  検証("画像が無ければ設定どおりの順 (無料枠を先に使う)", () => {
    期待(試す順に並べる(モデル一覧, 提供者一覧, 依頼)).と等しい(モデル一覧);
  });

  検証("画像があれば，見られる提供者を前に出す", () => {
    期待(
      試す順に並べる(モデル一覧, 提供者一覧, {
        ...依頼,
        画像一覧: [{ 種別: "image/png", 中身: "…", 名前: "図.png" }],
      }),
    ).と等しい(["gemini-z", "@cf/x", "@cf/y"]);
  });

  検証("見えないモデルも落とさない．後ろに回るだけ", () => {
    const 並び = 試す順に並べる(モデル一覧, 提供者一覧, {
      ...依頼,
      画像一覧: [{ 種別: "image/png", 中身: "…", 名前: "図.png" }],
    });

    期待(長さ(並び)).である(長さ(モデル一覧));
  });
});
