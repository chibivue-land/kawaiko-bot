import { 仕様, 検証, 期待, 偽装する } from "../../試験/言葉";
import { WorkersAIの絵描き, 出来上がりの一辺, 描く手数, 絵のモデル, 絵描きなし } from "./絵";
import { 画像の概算費用ドル } from "./料金";
import { 偽, 文字列, 真 } from "../../共通/型";
import type { 不明, 記録, 配列 } from "../../共通/型";

function 推論を作る(応答: 不明) {
  const 呼ばれた: 配列<[文字列, 記録<文字列, 不明>]> = [];
  const 走らせる = 偽装する(async (モデル: 文字列, 入力: 記録<文字列, 不明>) => {
    呼ばれた.push([モデル, 入力]);

    return 応答;
  });

  return { 呼ばれた, ai: { run: 走らせる } as unknown as Ai };
}

仕様("WorkersAIの絵描き", () => {
  検証("flux へ渡すのは prompt と steps だけ", () => {
    const { 呼ばれた, ai } = 推論を作る({ image: "44GC" });

    return WorkersAIの絵描き(ai)
      .描く("a duck hotpot")
      .んで(() => {
        期待(呼ばれた[0]![0]).である(絵のモデル);
        // 余計な鍵を足すと «Additional or unevaluated properties» で断られる．
        期待(呼ばれた[0]![1]).と等しい({ prompt: "a duck hotpot", steps: 描く手数 });
      });
  });

  検証("base64 の中身と，Discord へ出す形を返す", () => {
    return WorkersAIの絵描き(推論を作る({ image: "44GC" }).ai)
      .描く("a cat")
      .んで((絵) => {
        期待(絵.中身).である("44GC");
        期待(絵.種別).である("image/jpeg");
        期待(絵.名前).を含む(".jpg");
      });
  });

  検証("費用は枚数ぶんの見積もりを載せる", () => {
    return WorkersAIの絵描き(推論を作る({ image: "44GC" }).ai)
      .描く("a cat")
      .んで((絵) => {
        期待(絵.費用ドル).とほぼ等しい(
          画像の概算費用ドル(出来上がりの一辺, 出来上がりの一辺, 描く手数),
          8,
        );
        // 言葉の返事 1 回と同じ桁に収まっていること．
        期待(絵.費用ドル).より小さい(0.002);
      });
  });

  検証("モデルが何も返さなければ転ぶ", () => {
    // 真っ白な絵を出すより，描けなかったと言うほうがまし．
    return 期待(WorkersAIの絵描き(推論を作る({}).ai).描く("a cat")).しくじる("何も返さなかった");
  });

  検証("絵描きなし は，繋がっていないと名乗る", () => {
    期待(絵描きなし.使えるか).である(偽);
  });

  検証("繋がっている絵描きは，使えると名乗る", () => {
    期待(WorkersAIの絵描き(推論を作る({ image: "44GC" }).ai).使えるか).である(真);
  });
});

仕様("画像の概算費用ドル", () => {
  検証("タイル数と手数で決まる", () => {
    // 1024x1024 は 512 のタイル 4 枚．
    期待(画像の概算費用ドル(1024, 1024, 4)).とほぼ等しい(4 * 0.0000528 + 4 * 0.0001056, 8);
  });

  検証("半端な大きさは切り上げる", () => {
    期待(画像の概算費用ドル(513, 512, 1)).とほぼ等しい(2 * 0.0000528 + 0.0001056, 8);
  });
});
