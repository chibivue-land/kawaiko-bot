/** 取れたぶんだけ拾う．落ちている / 遅いフィードは，単に件数が減るだけ． */
export const RSSの見出し: 見出し取得 = {
  見出し(種類: 見出しの種類, 上限: 数値 = 24): 約束<配列<文字列>> {
    return 揃える(写す(購読先[種類], 一つの購読から拾う)).んで((束) =>
      // フィードをまたいで同じ題名が来ることがあるので，順序を保ったまま重複を消す．
      取り出す([...新しい集合(交互に並べる(束))], 0, 上限),
    );
  },
};

/**
 * 購読先ごとの一覧を，1 件ずつ交互に並べる．
 *
 * そのまま繋ぐと，件数の多い最初のフィードだけで上限が埋まり，残りの購読先は
 * 一度も日の目を見ない (実際そうなっていた)．どのフィードも人気順なので，
 * 交互に取れば「各フィードの上位」が揃う．
 */
export function 交互に並べる<要素>(束: 読み取り専用配列<読み取り専用配列<要素>>): 配列<要素> {
  const 最長 = 畳む(束, (積, 一覧) => 数学.max(積, 長さ(一覧)), 0);

  return 平らにする(
    写す(範囲(0, 最長), (位置) =>
      写す(
        絞る(束, (一覧) => 位置 < 長さ(一覧)),
        (一覧) => 一覧[位置]!,
      ),
    ),
  );
}

function 一つの購読から拾う(購読: 文字列): 約束<配列<文字列>> {
  return 試みる<配列<文字列>>({
    実行: () =>
      fetch(購読, { headers: { "User-Agent": 名乗り }, signal: AbortSignal.timeout(4000) }).んで(
        (応答) =>
          もし(否定(応答.ok), {
            であれば: () => すぐ返す([]),
            でなければ: () => 応答.text().んで(題名を拾う),
          }),
      ),
    // 見出しは飾り．見出しの無い独り言も独り言ではある．
    しくじったら: () => [],
  });
}

/**
 * 実体参照を文字へ戻す．
 *
 * はてなブックマークは題名を丸ごと数値文字参照 (`&#x306F;`) で返してくるので，
 * 戻さないと見出しが 1 文字も読めない．`&amp;` は最後に戻す — 先に戻すと
 * `&amp;lt;` が `<` まで戻ってしまう．
 */
export function 実体参照を戻す(文: 文字列): 文字列 {
  const 符号から = (符号: 数値): 文字列 =>
    数値.isInteger(符号) && 符号 > 0 && 符号 <= 0x10_ff_ff ? String.fromCodePoint(符号) : "";

  return 畳む(
    [
      [
        /&#x([0-9a-f]+);/giu,
        (_一致: 文字列, 十六進: 文字列) => 符号から(数値.parseInt(十六進, 16)),
      ],
      [/&#(\d+);/gu, (_一致: 文字列, 十進: 文字列) => 符号から(数値.parseInt(十進, 10))],
      [/&lt;/gu, () => "<"],
      [/&gt;/gu, () => ">"],
      [/&quot;/gu, () => '"'],
      [/&apos;/gu, () => "'"],
      [/&amp;/gu, () => "&"],
    ] as const,
    (積, [型, 置換]) => 置き換える(積, 型, 置換),
    文,
  );
}

export function 題名を拾う(xml: 文字列): 配列<文字列> {
  const 一致一覧 = [...xml.matchAll(/<title>(?:<!\[CDATA\[)?(.*?)(?:\]\]>)?<\/title>/gs)];
  const 題名一覧 = 写す(一致一覧, (一致) =>
    前後の空白を落とす(置き換える(実体参照を戻す(一致[1]!), /\s+/gu, " ")),
  );
  // 最初の <title> はフィード自身の名前．<image> の中でもう一度名乗るフィードが
  // あるので，位置ではなく中身で落とす．
  const フィードの名前 = 題名一覧[0];

  return 絞る(題名一覧, (題名) => 否定(空か(題名)) && 等しくない(題名, フィードの名前));
}
