/**
 * 貼られた URL の先を，Cloudflare の Browser Run で読む．
 *
 * 素の fetch との違いは，本物のブラウザで開くこと — JS で組み立てるページも
 * 中身が取れる．Quick Action の markdown を使うので，こちらで HTML を刈る必要も
 * 無い．Workers Free でも使えるが，**ブラウザの時間は 1 日 10 分**しかないので，
 * 何ページ見に行くかは核 (核/参照.ts) が絞っている．
 *
 * 束縛から選べるのは既定のブラウザだけ．Kitesurf (agent 向けの軽いほう) は
 * いまのところ REST の `?browser=kitesurf` でしか選べず，そのためには Worker に
 * アカウントの API トークンを持たせることになる．たかがページ読みのために
 * 配布権限まで持つ鍵を置きたくないので，束縛のままにしてある．
 */
import type { 読んだ頁, 頁読み } from "../振る舞い/接続口";

import { 偽, 文字列, 未定義, 真 } from "../共通/型";
import type { 省略可, 約束 } from "../共通/型";
import { もし, 試みる } from "../共通/構文";
import { 否定 } from "../共通/演算";
import { すぐ返す } from "../共通/約束";
import { 注意 } from "../共通/記録";
import { 切り出す, 前後の空白を落とす, 空か } from "../共通/関数";

/** 指示文へ載せる長さ．ページ全文を入れても読み切れない． */
export const 頁の載せる文字数 = 4000;

export function BrowserRunの頁読み(browser: BrowserRun): 頁読み {
  // 覗き見のためだけに，最後の躓きを持っておく．
  let 躓き = 未定義 as 省略可<文字列>;

  return {
    使えるか: 真,
    直前の躓き: () => 躓き,

    読む(場所: 文字列): 約束<省略可<読んだ頁>> {
      return 試みる<省略可<読んだ頁>>({
        実行: () =>
          browser.quickAction("markdown", { url: 場所 }).んで((応答) =>
            もし<約束<省略可<読んだ頁>>>(否定(応答.ok), {
              であれば: () => {
                注意(`頁: ${場所} を開けなかった (${応答.status})`);

                return すぐ返す(未定義);
              },
              でなければ: () => 応答.text().んで((中身) => 頁にする(場所, 中身)),
            }),
          ),
        しくじったら: (転んだ) => {
          躓き = `${場所}: ${文字列(転んだ)}`;
          注意("頁:", 躓き);

          return 未定義;
        },
      });
    },
  };
}

function 頁にする(場所: 文字列, 生: 文字列): 省略可<読んだ頁> {
  const 中身 = 前後の空白を落とす(生);

  return もし(空か(中身), {
    であれば: (): 省略可<読んだ頁> => 未定義,
    でなければ: (): 省略可<読んだ頁> => ({ 場所, 中身: 切り出す(中身, 0, 頁の載せる文字数) }),
  });
}

/** ブラウザが繋がっていない構成のときの身代わり． */
export const 頁読みなし: 頁読み = {
  使えるか: 偽,
  読む: () => すぐ返す(未定義),
  直前の躓き: () => 未定義,
};
