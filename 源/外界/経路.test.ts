import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 認可されているか, 記憶への問いを読み取る } from "./経路";
import { 偽, 新しい場所, 新しい要求, 未定義, 真 } from "../共通/型";

const 行き先 = (経路: string, 問い合わせ = "") =>
  新しい場所(`https://kawaiko.example${経路}${問い合わせ}`);

仕様("記憶への問いを読み取る", () => {
  検証("サーバーの指定が無ければ一覧を返す", () => {
    期待(記憶への問いを読み取る("GET", 行き先("/memory"))).と等しい({ 種別: "サーバー一覧" });
  });

  検証("1 つのサーバーの現状を読む", () => {
    期待(記憶への問いを読み取る("GET", 行き先("/memory", "?guild=g1"))).と等しい({
      種別: "現状",
      サーバーid: "g1",
    });
  });

  検証("回の取り消しは理由も一緒に運ぶ", () => {
    期待(
      記憶への問いを読み取る(
        "POST",
        行き先("/memory/retract-batch", "?guild=g1&batch=b1&note=誤学習"),
      ),
    ).と等しい({ 種別: "回を取り消す", サーバーid: "g1", 識別子: "b1", 理由: "誤学習" });
  });

  検証("位置を指定して巻き戻す", () => {
    期待(記憶への問いを読み取る("POST", 行き先("/memory/rollback", "?guild=g1&seq=42"))).と等しい({
      種別: "巻き戻す",
      サーバーid: "g1",
      連番: 42,
      理由: 未定義,
    });
  });

  検証("対象の欠けた取り消しは受け取らない", () => {
    期待(記憶への問いを読み取る("POST", 行き先("/memory/retract-batch", "?guild=g1"))).が未定義();
    期待(記憶への問いを読み取る("POST", 行き先("/memory/retract-batch", "?batch=b1"))).が未定義();
    期待(記憶への問いを読み取る("POST", 行き先("/memory/rollback", "?seq=1"))).が未定義();
  });

  検証("位置の書き忘れを「0 へ巻き戻す」と読まない", () => {
    // 数値(null) も 数値("") も 0 になる．読み違えると，書き損じた要求が
    // 「このサーバーを丸ごと忘れる」になってしまう．
    for (const 問い合わせ of [
      "?guild=g1",
      "?guild=g1&seq=",
      "?guild=g1&seq=abc",
      "?guild=g1&seq=-1",
    ]) {
      期待(
        記憶への問いを読み取る("POST", 行き先("/memory/rollback", 問い合わせ)),
        問い合わせ,
      ).が未定義();
    }
  });

  検証("はっきり書かれた 0 は受け取る", () => {
    期待(
      記憶への問いを読み取る("POST", 行き先("/memory/rollback", "?guild=g1&seq=0")),
    ).の形をしている({ 種別: "巻き戻す", 連番: 0 });
  });

  検証("壊す操作を GET では受け付けない", () => {
    期待(記憶への問いを読み取る("GET", 行き先("/memory/rollback", "?guild=g1&seq=1"))).が未定義();
  });

  検証("知らない記憶の経路は断る", () => {
    期待(記憶への問いを読み取る("POST", 行き先("/memory/wipe", "?guild=g1"))).が未定義();
  });
});

仕様("認可されているか", () => {
  const 見出し付きの要求 = (値?: string) =>
    新しい要求("https://kawaiko.example/memory", {
      headers: 値 ? { Authorization: 値 } : {},
    });

  // HTTP のヘッダは ByteString なので，合言葉は ASCII に限られる (実物もそう)．
  const 合言葉 = "s3cret";

  検証("設定した合言葉を受け入れる", () => {
    期待(認可されているか(見出し付きの要求(`Bearer ${合言葉}`), 合言葉)).である(真);
  });

  検証("違う / 無い合言葉は断る", () => {
    期待(認可されているか(見出し付きの要求("Bearer wrong"), 合言葉)).である(偽);
    期待(認可されているか(見出し付きの要求(), 合言葉)).である(偽);
  });

  検証("合言葉が設定されていなければ何も通さない", () => {
    // でないと，秘密の設定漏れがそのまま口の開放になる．
    期待(認可されているか(見出し付きの要求("Bearer "), 未定義)).である(偽);
    期待(認可されているか(見出し付きの要求("Bearer undefined"), "")).である(偽);
  });
});
