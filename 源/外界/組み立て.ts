/**
 * 組み立ての場所 — バインディングを入れて，ポートを出す．
 *
 * 両側を知っているのはここだけ．ここより内側はすべて 振る舞い/接続口.ts の interface
 * しか名指ししていない．だからテストは同じユースケースを，Cloudflare の
 * ランタイム抜きで偽物だけ差し替えて動かせる．
 */
/**
 * 組み立ての場所であると同時に，永続体との境目．
 *
 * 永続体 (Durable Object) の RPC が返すのは約束ではないので，ポートにする前に
 * 必ず 約束に均す を通す (なぜ要るかは 共通/約束.ts に書いてある)．永続体を呼ぶ
 * 行がここ以外に増えたときも同じようにすること．
 */
export function 部品を組み立てる(環境: 環境): 部品一式 {
  const 予算の記録 = 環境.予算帳.get(環境.予算帳.idFromName("global"));

  const 予算番: 予算番 = {
    許すか: () =>
      約束に均す(予算の記録.予算を確認する(月の予算ドル(環境))).んで(
        ({ 許すか, 使用済みドル }) => ({
          許すか,
          使用済みドル,
        }),
      ),
    記録する: (費用ドル) => 約束に均す(予算の記録.支出を記録する(費用ドル)),
    仕事を終える: (種類, 成功か, 異常, モデル) =>
      約束に均す(予算の記録.仕事を記録する(種類, 成功か, 異常, モデル)),
  };

  const 提供者の記録: 提供者の記録 = {
    休んでいる提供者: () => 約束に均す(予算の記録.休んでいる提供者()),
    休ませる: (提供者名, 休み) => 約束に均す(予算の記録.提供者を休ませる(提供者名, 休み)),
  };

  const 利用制限: 利用制限 = {
    確認する: (利用者id) =>
      約束に均す(
        環境.利用制限帳
          .get(環境.利用制限帳.idFromName(利用者id))
          .確認して数える(数値(環境.時あたりの上限) || 5, 数値(環境.日あたりの上限) || 20),
      ),
  };

  const チャンネル記録: チャンネル記録 = {
    リセット時刻: (チャンネルid) =>
      約束に均す(
        環境.チャンネル記録帳.get(環境.チャンネル記録帳.idFromName(チャンネルid)).リセット時刻(),
      ),
    リセットする: (チャンネルid, 時刻) =>
      約束に均す(
        環境.チャンネル記録帳
          .get(環境.チャンネル記録帳.idFromName(チャンネルid))
          .リセットする(時刻),
      ).んで(() => 未定義),
  };

  return {
    チャット: Discordのチャット(環境),

    発話器: 順に試す発話器(
      [WorkersAI提供者(環境.推論), Gemini提供者(環境.GEMINI_API_KEY)],
      モデル一覧を読む(環境.モデル一覧),
      提供者の記録,
    ),

    記憶庫: 環境.記憶のD1 ? D1の記憶庫(環境.記憶のD1) : 記憶なし,

    予算番,
    提供者の記録,
    利用制限,
    チャンネル記録,

    調査係: webの調査係({ GitHubのトークン: 環境.GITHUB_API_TOKEN }),
    絵描き: WorkersAIの絵描き(環境.推論),
    添付読み: webの添付読み(),
    頁読み: 環境.閲覧 ? BrowserRunの頁読み(環境.閲覧) : 頁読みなし,
    見出し取得: RSSの見出し,

    自分のid: 環境.kawaikoのid,
    住処のチャンネルid: 環境.住処のチャンネルid,

    独言の確率: 環境.独言の確率,
    横槍の確率: 環境.横槍の確率,
    観測するか: 等しくない(環境.観測するか, "false"),

    現在時刻,
    乱数: 数学.random,
    新しい識別子: () => crypto.randomUUID(),
  };
}
