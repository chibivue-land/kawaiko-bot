/**
 * 永続体 (Durable Object) の身代わり．
 *
 * 本物の RPC は「知らないプロパティ＝向こう側のメソッド呼び出し」として扱うので，
 * 約束のつもりで `.んで` と書くと «んで» という名前のメソッドを探しにいって落ちる．
 * ここでも同じように，知らないプロパティを触られたら落ちる約束もどきを返す．
 * これが本番で kawaiko を黙らせた形そのもの．
 */
function RPCもどき<値>(値候補: 値): 不明 {
  // then を持つだけで約束ではないもの — それがこの検証の題材そのもの．
  // oxlint-disable-next-line unicorn/no-thenable
  const 素 = { then: (次: (値: 値) => 不明) => 次(値候補) };

  return new Proxy(素, {
    // 本物も記号 (Symbol.toStringTag など) までは咎めない．咎めるのは
    // 「メソッド名のつもりの，知らない文字列」だけ．
    get: (的, 名前) =>
      もし<不明>(等しい(typeof 名前, "string") && 否定(名前 in 的), {
        であれば: () =>
          しくじる(新しい例外(`The RPC receiver does not implement the method "${文字列(名前)}".`)),
        でなければ: () => Reflect.get(的, 名前),
      }),
  });
}

function 永続体を作る(中身: 記録<文字列, 不明>): 不明 {
  return {
    idFromName: (名前: 文字列) => 名前,
    get: () =>
      new Proxy(
        {},
        {
          get: (_的, 名前) => {
            const 実装 = 中身[文字列(名前)];

            return もし(等しい(実装, 未定義), {
              であれば: () =>
                しくじる(
                  新しい例外(`The RPC receiver does not implement the method "${文字列(名前)}".`),
                ),
              でなければ: () => 実装,
            });
          },
        },
      ),
  };
}

function 環境を作る(): 環境 {
  return {
    モデル一覧: "@cf/x",
    独言の確率: "1",
    横槍の確率: "1",
    時あたりの上限: "5",
    日あたりの上限: "20",
    月の予算ドル: "1",
    kawaikoのid: "bot-1",
    住処のチャンネルid: "住処",
    DISCORD_BOT_TOKEN: "とーくん",
    GEMINI_API_KEY: "かぎ",
    TRIGGER_TOKEN: "ひきがね",
    推論: { run: async () => ({}) },
    利用制限帳: 永続体を作る({
      確認して数える: () => RPCもどき({ 許すか: 真 }),
    }),
    予算帳: 永続体を作る({
      予算を確認する: () => RPCもどき({ 許すか: 真, 使用済みドル: 0.5 }),
      支出を記録する: () => RPCもどき(未定義),
      仕事を記録する: () => RPCもどき(未定義),
      休んでいる提供者: () => RPCもどき({}),
      提供者を休ませる: () => RPCもどき(未定義),
    }),
    Discord接続: 永続体を作る({ 確かめる: () => RPCもどき("繋がっている") }),
    チャンネル記録帳: 永続体を作る({
      リセット時刻: () => RPCもどき(0),
      リセットする: () => RPCもどき(123),
    }),
  } as unknown as 環境;
}

仕様("部品を組み立てる", () => {
  検証("永続体を呼ぶポートは，どれも本物の約束を返す", () => {
    const 部品 = 部品を組み立てる(環境を作る());

    // どれか 1 つでも RPC もどきのまま漏れていれば，`.んで` の時点で落ちる．
    return 揃える([
      部品.予算番.許すか().んで((判定) => 期待(判定.使用済みドル).である(0.5)),
      部品.予算番.記録する(0.01).んで(() => 未定義),
      部品.予算番.仕事を終える("独言", 真).んで(() => 未定義),
      部品.提供者の記録.休んでいる提供者().んで((休み) => 期待(休み).と等しい({})),
      部品.提供者の記録
        .休ませる("cf", { いつまで: 0, 理由: "", 休ませた時刻: 0 })
        .んで(() => 未定義),
      部品.利用制限.確認する("利用者-1").んで((判定) => 期待(判定.許すか).である(真)),
      部品.チャンネル記録.リセット時刻("ちゃんねる-1").んで((時刻) => 期待(時刻).である(0)),
      部品.チャンネル記録.リセットする("ちゃんねる-1", 123).んで(() => 未定義),
    ]).んで(() => 未定義);
  });
});
