/** scrape が返す封筒のうち，こちらが読む部分だけ． */
export interface 掬った答え {
  result?: 省略可<配列<{ results?: 省略可<配列<{ html?: 省略可<文字列> }>> }>>;
}

const 見出しの形 = /<h2[^>]*>\s*<a[^>]*href="(?<行き先>[^"]+)"[^>]*>(?<題>[\s\S]*?)<\/a>/u;
const 段落の形 = /<p[^>]*>(?<中身>[\s\S]*?)<\/p>/u;

/** 掬った要素の並びを，調べものの並びへ．広告など見出しの無い要素は落とす． */
export function Bingの結果を読む(中身: 掬った答え): 配列<調べもの> {
  const 要素一覧 = 平らにする(写す(中身.result ?? [], (組) => 組.results ?? []));

  return 取り出す(
    絞る(
      写す(要素一覧, (要素) => 結果の要素を読む(要素.html ?? "")),
      (件) => 否定(空か(件.題)),
    ),
    0,
    検索で載せる数,
  );
}

/** 1 件の結果 (outerHTML) から題・抜粋・行き先を拾う．読めなければ題が空． */
function 結果の要素を読む(html: 文字列): 調べもの {
  const 見出し = 見出しの形.exec(html)?.groups;

  return {
    題: 見出し ? `Web: ${切り出す(タグを落とす(見出し.題 ?? ""), 0, 80)}` : "",
    抜粋: 切り出す(タグを落とす(段落の形.exec(html)?.groups?.中身 ?? ""), 0, 180),
    場所: 見出し ? Bingの行き先を解く(置き換える(見出し.行き先 ?? "", /&amp;/g, "&")) : 未定義,
  };
}

/**
 * Bing の結果リンクは `https://www.bing.com/ck/a?...&u=a1<base64url>` と包まれて
 * いる．包みのままでも開けば飛べるが，指示文に載せるのも候補として開くのも
 * 素の行き先のほうがよい．解けない包みはそのまま返す．
 */
export function Bingの行き先を解く(生: 文字列): 文字列 {
  const 包み = /[?&]u=a1(?<中身>[A-Za-z0-9_-]+)/u.exec(生)?.groups?.中身;

  return もし(等しい(包み, 未定義), {
    であれば: () => 生,
    でなければ: () =>
      試す({
        実行: () => {
          const 素 = atob(詰め物を戻す(包み!));
          const 中身 = new TextDecoder().decode(Uint8Array.from(素, (字) => 字.charCodeAt(0)));

          return もし(始まるか(中身, "http"), {
            であれば: () => 中身,
            でなければ: () => 生,
          });
        },
        しくじったら: () => 生,
      }),
  });
}

/** base64url を素の base64 へ戻す (末尾の詰め物 `=` も足す)． */
function 詰め物を戻す(字句: 文字列): 文字列 {
  const 素 = 置き換える(置き換える(字句, /-/g, "+"), /_/g, "/");

  return `${素}${繰り返す("=", (4 - (長さ(素) % 4)) % 4)}`;
}

/** Google News の RSS は Workers から素直に返るし，日本語のニュースを拾える． */
function ニュースを引く(検索語: 文字列): 約束<配列<調べもの>> {
  return 時間を切って取る(
    `https://news.google.com/rss/search?q=${encodeURIComponent(検索語)}&hl=ja&gl=JP&ceid=JP:ja`,
  ).んで((応答) => 応答から拾う(応答, (応答) => 応答.text().んで((xml) => ニュースを読む(xml))));
}

/** RSS の <item> ごとに，題と行き先を組にして拾う． */
function ニュースを読む(xml: 文字列): 配列<調べもの> {
  const 記事一覧 = [...xml.matchAll(/<item>([\s\S]*?)<\/item>/gu)];

  return 絞る(
    写す(取り出す(記事一覧, 0, 4), (記事): 調べもの => {
      const 中 = 記事[1] ?? "";

      return {
        題: `News: ${タグを落とす(題を抜く(中))}`,
        抜粋: "",
        場所: 前後の空白を落とす(行き先を抜く(中)),
      };
    }),
    (件) => 否定(空か(件.題)),
  );
}

function 題を抜く(記事: 文字列): 文字列 {
  return /<title>(?:<!\[CDATA\[)?([\s\S]*?)(?:\]\]>)?<\/title>/u.exec(記事)?.[1] ?? "";
}

function 行き先を抜く(記事: 文字列): 文字列 {
  return /<link>([\s\S]*?)<\/link>/u.exec(記事)?.[1] ?? "";
}

/** ハンドルっぽい検索語なら GitHub のユーザーを引く (ここは開発者の集まりなので)． */
