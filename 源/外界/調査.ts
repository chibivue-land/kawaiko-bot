/** ざっくり HTML/XML を落として実体参照を戻す． */
function タグを落とす(生: 文字列): 文字列 {
  const 素 = 置き換える(生, /<[^>]*>/g, "");
  const 実体 = [
    [/&amp;/g, "&"],
    [/&lt;/g, "<"],
    [/&gt;/g, ">"],
    [/&quot;/g, '"'],
    [/&#x?\d+;/g, ""],
    [/\s+/g, " "],
  ] as const;

  return 前後の空白を落とす(畳む(実体, (文, [型, 置換]) => 置き換える(文, 型, 置換), 素));
}

/** 時間切れと失敗を空として扱う fetch． */
