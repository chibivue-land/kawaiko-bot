/** 指示文に差す短い参考情報を集める．役に立つものが無ければ空文字． */
/** 一度に指示文へ載せる抜粋の数． */
const 載せる件数 = 8;

/** さらに開いて読む先の候補として持ち帰る数． */
const 持ち帰る候補の数 = 3;

export interface 調査の設定 {
  GitHubのトークン?: 省略可<文字列>;
  /** 検索に使うブラウザ．繋がっていない構成では検索だけ抜ける． */
  閲覧?: 省略可<BrowserRun>;
}

export function 参考情報を集める(検索語: 文字列, 設定?: 省略可<調査の設定>): 約束<調べた結果> {
  // 四つは互いを待たない．遅い先が一つあっても，残りは同じ時間で揃う．
  // 検索を先頭に — 抜粋の枠も開く候補も，まず本物の検索結果で埋める．
  return 揃える([
    ブラウザで検索する(検索語, 設定?.閲覧),
    GitHubのひとを引く(検索語, 設定?.GitHubのトークン),
    ニュースを引く(検索語),
    HackerNewsを引く(検索語),
  ]).んで((束) => 結果にまとめる(取り出す(平らにする(束), 0, 載せる件数)));
}

function 結果にまとめる(一覧: 読み取り専用配列<調べもの>): 調べた結果 {
  return {
    抜粋: 繋ぐ(
      写す(一覧, (件) => (件.抜粋 ? `- ${件.題}: ${件.抜粋}` : `- ${件.題}`)),
      改行,
    ),
    候補: 取り出す(
      絞る(
        写す(一覧, (件) => 件.場所 ?? ""),
        (場所) => 否定(空か(場所)),
      ),
      0,
      持ち帰る候補の数,
    ),
  };
}

