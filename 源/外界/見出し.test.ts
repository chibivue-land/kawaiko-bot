import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 交互に並べる, 実体参照を戻す, 題名を拾う } from "./見出し";

仕様("交互に並べる", () => {
  検証("どの購読先からも上位が入る (件数の多い先頭に埋め尽くされない)", () => {
    期待(交互に並べる([["a1", "a2", "a3"], ["b1"], ["c1", "c2"]])).と等しい([
      "a1",
      "b1",
      "c1",
      "a2",
      "c2",
      "a3",
    ]);
  });

  検証("空の購読先があっても止まらない", () => {
    期待(交互に並べる([[], ["b1"]])).と等しい(["b1"]);
    期待(交互に並べる([])).と等しい([]);
  });
});

仕様("実体参照を戻す", () => {
  検証("数値文字参照を文字へ戻す (はてなブックマークの題名がこれ)", () => {
    期待(実体参照を戻す("&#x306F;&#x3066;&#x306A;")).である("はてな");
    期待(実体参照を戻す("&#12363;&#12418;")).である("かも");
  });

  検証("&amp; は最後に戻す — 先に戻すと二重に戻ってしまう", () => {
    期待(実体参照を戻す("a &amp;lt; b")).である("a &lt; b");
    期待(実体参照を戻す("Q&amp;A &lt;3&gt; &quot;x&quot;")).である('Q&A <3> "x"');
  });

  検証("文字にならない符号は落とす", () => {
    期待(実体参照を戻す("x&#0;y&#x110000;z")).である("xyz");
  });
});

仕様("題名を拾う", () => {
  検証("フィード自身の名前は，何度名乗っていても落とす", () => {
    // Zenn は <channel> と <image> の両方で名乗る．
    const xml = `
      <rss><channel>
        <title>Zennのトレンド</title>
        <image><title>Zennのトレンド</title></image>
        <item><title><![CDATA[鴨の飼い方]]></title></item>
        <item><title>Vue 4 released</title></item>
      </channel></rss>`;

    期待(題名を拾う(xml)).と等しい(["鴨の飼い方", "Vue 4 released"]);
  });

  検証("実体参照を戻し，改行と余白を 1 つの空白に畳む", () => {
    const xml = `<rdf><channel><title>f</title></channel>
      <item><title>&#x9D28;
        &amp; Rust</title></item></rdf>`;

    期待(題名を拾う(xml)).と等しい(["鴨 & Rust"]);
  });

  検証("題名が一つも無ければ空", () => {
    期待(題名を拾う("<html>503</html>")).と等しい([]);
  });
});
