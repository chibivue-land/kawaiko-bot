import { DurableObject } from "cloudflare:workers";

import type { 利用制限の判定 } from "../../振る舞い/接続口";

import { 現在時刻 } from "../../核/時刻";

import { 偽, 数値, 数学, 真 } from "../../共通/型";
import type { 省略可, 約束 } from "../../共通/型";
import { 振り分ける } from "../../共通/構文";
import { 以上, 等しい } from "../../共通/演算";

/**
 * 利用者ごとの制限．idFromName(Discord のユーザー id) で 1 人 1 インスタンス．
 * 固定窓 (時 / 日) の数え上げを SQLite 付きストレージに持つ．
 *
 * クラス名だけ英語なのは wrangler.jsonc の `class_name` がこれを指しているため
 * (identifier ではなく deployment の名前なので)．
 */
export class 利用制限帳 extends DurableObject {
  確認して数える(時あたり: 数値, 日あたり: 数値): 約束<利用制限の判定> {
    const 現在 = 現在時刻().epochMilliseconds;
    const 時の窓 = 数学.floor(現在 / 3_600_000);
    const 日の窓 = 数学.floor(現在 / 86_400_000);

    return this.ctx.storage
      .get<保存する数え>("counters")
      .んで((保存済み) =>
        this.数えて判定する(保存済み, { 現在, 時の窓, 日の窓, 時あたり, 日あたり }),
      );
  }

  private 数えて判定する(
    保存済み: 省略可<保存する数え>,
    窓: { 現在: 数値; 時の窓: 数値; 日の窓: 数値; 時あたり: 数値; 日あたり: 数値 },
  ): 約束<利用制限の判定> {
    const 状態: 保存する数え = {
      時の窓: 窓.時の窓,
      時の回数: 等しい(保存済み?.時の窓, 窓.時の窓) ? 保存済み!.時の回数 : 0,
      日の窓: 窓.日の窓,
      日の回数: 等しい(保存済み?.日の窓, 窓.日の窓) ? 保存済み!.日の回数 : 0,
    };

    return 振り分ける<利用制限の判定>(
      [
        {
          条件: () => 以上(状態.日の回数, 窓.日あたり),
          ならば: async () => ({
            許すか: 偽,
            再開まで分: 数学.ceil(((窓.日の窓 + 1) * 86_400_000 - 窓.現在) / 60_000),
          }),
        },
        {
          条件: () => 以上(状態.時の回数, 窓.時あたり),
          ならば: async () => ({
            許すか: 偽,
            再開まで分: 数学.ceil(((窓.時の窓 + 1) * 3_600_000 - 窓.現在) / 60_000),
          }),
        },
      ],
      {
        どれでもなければ: () =>
          this.ctx.storage
            .put("counters", {
              ...状態,
              時の回数: 状態.時の回数 + 1,
              日の回数: 状態.日の回数 + 1,
            })
            .んで(() => ({ 許すか: 真 })),
      },
    );
  }
}

/** 固定窓の数え上げ．ストレージにこの形で置く． */
interface 保存する数え {
  時の窓: 数値;

  時の回数: 数値;

  日の窓: 数値;

  日の回数: 数値;
}
