/**
 * 添付の中身を Discord の CDN から取ってくる．
 *
 * 取りに行く先は Discord が寄越した URL だが，念のため CDN のホストだけに絞って
 * ある．ゲートウェイの payload は Discord から来るので普段は問題にならないが，
 * 「発言に書かれた URL を kawaiko が黙って叩く」形には，そもそもしないでおく．
 *
 * どの添付を取りに行くかを決めるのは核 (添付.ts)．ここはその判断に従って運ぶだけ．
 */
import type { 添付読み, 取り込んだ画像 } from "../振る舞い/接続口";
import type { 添付 } from "../核/添付";
import { 偽, 数学, 文字列, 新しい場所, 未定義, 真偽 } from "../共通/型";
import type { 省略可, 約束 } from "../共通/型";
import { いずれか, 畳む, 長さ } from "../共通/関数";
import { 割る, 掛ける, 等しい, 足す } from "../共通/演算";
import { もし, 試す, 試みる } from "../共通/構文";
import { 範囲 } from "../共通/反復";
import { 注意 } from "../共通/記録";
import { 約束にする } from "../共通/約束";

/** 待てる時間．返事の途中で止まっているので，長くは待てない． */
const 待てる時間 = 6000;

/** ここ以外から取ってこない． */
const 取りに行けるホスト = ["cdn.discordapp.com", "media.discordapp.net"];

/** btoa へ一度に渡す量．引数に展開するので，展開しきれる大きさに区切る． */
const 塊の大きさ = 8192;

export function webの添付読み(): 添付読み {
  return {
    文書を読む(添付: 添付): 約束<省略可<文字列>> {
      return 取りに行く(添付).んで((応答) =>
        もし<約束<省略可<文字列>>>(等しい(応答, 未定義), {
          であれば: () => 約束にする(未定義),
          でなければ: () => 応答!.text(),
        }),
      );
    },

    画像を取り込む(添付: 添付): 約束<省略可<取り込んだ画像>> {
      return 取りに行く(添付).んで((応答) =>
        もし<約束<省略可<取り込んだ画像>>>(等しい(応答, 未定義), {
          であれば: () => 約束にする(未定義),
          でなければ: () =>
            応答!.arrayBuffer().んで((塊) => ({
              種別: 添付.種別,
              中身: base64にする(new Uint8Array(塊)),
              名前: 添付.名前,
            })),
        }),
      );
    },
  };
}

/** 落ちても投げない．読めない添付は「読めなかった」で済ませる． */
function 取りに行く(添付: 添付): 約束<省略可<Response>> {
  return もし<約束<省略可<Response>>>(信用できる場所か(添付.場所), {
    であれば: () =>
      試みる<省略可<Response>>({
        実行: () =>
          fetch(添付.場所, { signal: AbortSignal.timeout(待てる時間) }).んで((応答) =>
            もし(応答.ok, { であれば: () => 応答, でなければ: () => 未定義 }),
          ),
        しくじったら: (躓き) => {
          注意(`添付: ${添付.名前} を取れなかった:`, 文字列(躓き));

          return 未定義;
        },
      }),
    でなければ: () => {
      注意(`添付: ${添付.名前} は知らない置き場だったので取りに行かない`);

      return 約束にする(未定義);
    },
  });
}

/** Discord の CDN かどうか． */
export function 信用できる場所か(場所: 文字列): 真偽 {
  return 試す({
    実行: () => {
      const 行き先 = 新しい場所(場所);

      return (
        等しい(行き先.protocol, "https:") &&
        いずれか(取りに行けるホスト, (ホスト) => 等しい(行き先.hostname, ホスト))
      );
    },
    // URL として読めないものは，そもそも取りに行かない．
    しくじったら: () => 偽,
  });
}

/**
 * バイト列を base64 へ．
 *
 * 一気に展開すると引数の上限に当たるので，塊に切って順に足す．
 */
function base64にする(バイト列: Uint8Array): 文字列 {
  const 塊の数 = 数学.ceil(割る(長さ(バイト列), 塊の大きさ));
  const 文字 = 畳む(
    範囲(0, 塊の数),
    (積, 番) =>
      積 +
      String.fromCharCode(
        ...バイト列.subarray(掛ける(番, 塊の大きさ), 掛ける(足す(番, 1), 塊の大きさ)),
      ),
    "",
  );

  return btoa(文字);
}
