import { 仕様, 検証, 期待 } from "../試験/言葉";
import { Jevに問い合わせる } from "./Jev問い合わせ";
import type { 答え一覧 } from "../核/判定";
import { 偽の判定器を作る, 偽の部品一式を作る } from "../試験/偽物";
import { 真 } from "../共通/型";

仕様("Jevに問い合わせる", () => {
  検証("チャットの jev 命令と同じ書き方を受けて，答えと言い方を返す", () => {
    const 部品 = 偽の部品一式を作る({
      判定器: 偽の判定器を作る((): 答え一覧 => ({
        問い: { 種別: "選択", 選択: "麺", 確信: 0.9, 確率: { 麺: 0.8, 米: 0.2 } },
      })),
    });

    return Jevに問い合わせる(部品, { 問いかけ: "晩飯 [麺|米]", 状態: "腹が減った" }).んで(
      (結果) => {
        期待(結果.状態).である(200);
        期待(結果.本体).の形をしている({
          問い: { 種別: "選択", 指示: "晩飯" },
          答え: { 選択: "麺" },
          モデル: "偽の判定器",
        });
        期待((結果.本体 as { 言い方: string }).言い方).を含む("麺 (80%)");

        const [依頼] = 部品.判定器.受け取った依頼;
        期待(依頼!.状態).である("腹が減った");
        // 手で叩いているのだから，休んでいても起こしてみる．
        期待(依頼!.休みを無視するか).である(真);
        期待(部品.使った額).と等しい([0.0001]);
      },
    );
  });

  検証("問いかけか状態が空なら断る (判定器は叩かない)", () => {
    const 部品 = 偽の部品一式を作る();

    return Jevに問い合わせる(部品, { 問いかけ: "  ", 状態: "何か" })
      .んで((結果) => {
        期待(結果.状態).である(400);

        return Jevに問い合わせる(部品, { 問いかけ: "煽りか", 状態: "  " });
      })
      .んで((結果) => {
        期待(結果.状態).である(400);
        期待(部品.判定器.受け取った依頼).の長さが(0);
      });
  });

  検証("判定器が答えなければ，休んでいる理由を添えて 503", () => {
    // ここは認可の向こうなので，提供者が返した異常の文面を見せてよい．
    const 部品 = 偽の部品一式を作る();
    部品.休ませた記録["jev"] = {
      いつまで: 9e15,
      理由: "402: insufficient credits",
      休ませた時刻: 0,
    };

    return Jevに問い合わせる(部品, { 問いかけ: "煽りか", 状態: "何か" }).んで((結果) => {
      期待(結果.状態).である(503);
      期待(結果.本体).の形をしている({ 休み: { 理由: "402: insufficient credits" } });
    });
  });
});
