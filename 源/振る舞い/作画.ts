/**
 * 「描いて」と言われたときに，実際に 1 枚描いて出すまで．
 *
 * 2 回モデルを叩く．1 回目は言葉のモデルで，頼まれたものを画像生成モデルに効く
 * 英語のプロンプトへ翻す — ついでに絵に添える一言も同じ 1 回で書かせる．
 * 2 回目が画像生成そのもの．
 *
 * どちらも Workers AI の 1 日ぶんの無料枠から引かれる．絵 1 枚は 58 neuron ほどで，
 * 言葉の返事 1 回と同じ桁．とはいえ枠は小さいので，利用制限と予算の見張りは
 * 普通の返事とまったく同じものを通る (呼ぶ側でそうしてある)．
 */
import { 失敗を要約する } from "./接続口";
import type { 描いた絵, 部品一式 } from "./接続口";
import type { 届いた名指し } from "./返信";
import { 作画の指示書を組み立てる, 作画の返事を読み取る, 作画依頼を組み立てる } from "../核/作画";
import type { 描く頼み } from "../核/作画";
import { 作画しくじりの文, 定型文を選ぶ } from "../核/定型文";
import { 偽, 数値, 文字列, 未定義, 真, 真偽 } from "../共通/型";
import type { 不明, 無, 省略可, 約束 } from "../共通/型";
import { 切り出す, 空か, 置き換える, 長さ } from "../共通/関数";
import { 等しい, 足す } from "../共通/演算";
import { もし, 試みる } from "../共通/構文";
import { すぐ返す } from "../共通/約束";
import { 注意 } from "../共通/記録";

/** 一言が空だったときに添える言葉．無言で絵だけ置くのは kawaiko らしくない． */
const 既定の一言 = "描いた";

/** 描けたか，描けなかったならどこで転んだか． */
export interface 作画の結末 {
  成功か: 真偽;
  理由?: 省略可<文字列>;
}

export function 絵を描いて返す(
  部品: 部品一式,
  名指し: 届いた名指し,
  頼み: 描く頼み,
  返す: (本文: 文字列) => 約束<無>,
): 約束<作画の結末> {
  return 部品.チャット
    .入力中にする(名指し.チャンネルid, () => 一枚仕上げる(部品, 名指し, 頼み))
    .んで((出来上がり) =>
      もし<約束<作画の結末>>(等しい(出来上がり.絵, 未定義), {
        // どこで転んでも，黙って消えるよりは一言返す．
        であれば: () =>
          返す(定型文を選ぶ(作画しくじりの文)).んで((): 作画の結末 => ({
            成功か: 偽,
            理由: 出来上がり.理由,
          })),
        でなければ: () =>
          部品.予算番
            .記録する(出来上がり.費用ドル!)
            .んで(() =>
              部品.チャット.絵を投稿する(
                名指し.チャンネルid,
                出来上がり.一言!,
                出来上がり.絵!,
                名指し.発言id,
              ),
            )
            .んで((): 作画の結末 => ({ 成功か: 真 })),
      }),
    );
}

interface 出来上がり {
  絵?: 省略可<描いた絵>;
  一言?: 省略可<文字列>;
  費用ドル?: 省略可<数値>;
  /** 描けなかったときだけ入る． */
  理由?: 省略可<文字列>;
}

/** 何を描くか決めて，描く．転んだら理由だけを持ち帰る． */
function 一枚仕上げる(部品: 部品一式, 名指し: 届いた名指し, 頼み: 描く頼み): 約束<出来上がり> {
  return 試みる<出来上がり>({
    // 発話する は通さない．あちらの差し替え (漏洩・拒否・無言) は会話のための
    // もので，ここで欲しいのはラベル付きの 2 行．定型文に差し替えられると
    // 読めるものも読めなくなる．
    実行: () =>
      部品.発話器
        .発話する({
          指示書: 作画の指示書を組み立てる(),
          指示文: 作画依頼を組み立てる({ お題: 頼み.お題, 相手の名前: 名指し.相手の名前 }),
          深さ: "low",
          最大トークン: 512,
        })
        .んで((下書き) => 絵にする(部品, 下書き)),
    しくじったら: (躓き) => {
      const 理由 = 失敗を要約する(躓き);
      注意("作画: 描けなかった:", 理由);

      return { 理由 };
    },
  });
}

function 絵にする(部品: 部品一式, 下書き: { 本文: 文字列; 費用ドル: 数値 }): 約束<出来上がり> {
  const 読んだ = 作画の返事を読み取る(下書き.本文);

  return もし<約束<出来上がり>>(等しい(読んだ, 未定義), {
    であれば: () => {
      // 何が返ってきたのかまで残す．「読めなかった」だけでは次に直せない．
      const 理由 = `絵の指示が読めなかった: ${切り出す(置き換える(下書き.本文, /\s+/g, " "), 0, 200)}`;
      注意("作画:", 理由);

      return すぐ返す({ 理由 });
    },
    でなければ: () =>
      部品.絵描き.描く(読んだ!.絵の指示).んで((絵) => ({
        絵,
        一言: もし(空か(読んだ!.一言), {
          であれば: () => 既定の一言,
          でなければ: () => 読んだ!.一言,
        }),
        費用ドル: 足す(下書き.費用ドル, 絵.費用ドル),
      })),
  });
}

/**
 * 描かずに，途中経過だけを覗く．
 *
 * 本番で転んだときに「モデルが何を返して，それをどう読んだか」が分からないと
 * 直しようがない．Discord へは何も出さず，予算も触らない．認可の向こう側．
 */
export function 作画を覗く(部品: 部品一式, お題: 文字列): 約束<不明> {
  return 試みる<不明>({
    実行: () =>
      部品.発話器
        .発話する({
          指示書: 作画の指示書を組み立てる(),
          指示文: 作画依頼を組み立てる({ お題, 相手の名前: "覗き見" }),
          深さ: "low",
          最大トークン: 512,
        })
        .んで((下書き) => {
          const 読んだ = 作画の返事を読み取る(下書き.本文);

          return もし<約束<不明>>(等しい(読んだ, 未定義), {
            であれば: () =>
              すぐ返す({ お題, モデル: 下書き.モデル, 生の返事: 下書き.本文, 読めたか: 偽 }),
            でなければ: () =>
              // 絵まで実際に出す．画像モデルが転ぶのか，その手前で転ぶのかを分ける．
              試みる<不明>({
                実行: () =>
                  部品.絵描き.描く(読んだ!.絵の指示).んで((絵) => ({
                    お題,
                    モデル: 下書き.モデル,
                    生の返事: 下書き.本文,
                    読めたか: 真,
                    絵の指示: 読んだ!.絵の指示,
                    一言: 読んだ!.一言,
                    描けたか: 真,
                    絵の大きさ: 長さ(絵.中身),
                  })),
                しくじったら: (躓き) => ({
                  お題,
                  モデル: 下書き.モデル,
                  生の返事: 下書き.本文,
                  読めたか: 真,
                  絵の指示: 読んだ!.絵の指示,
                  描けたか: 偽,
                  絵の異常: 失敗を要約する(躓き),
                }),
              }),
          });
        }),
    しくじったら: (躓き) => ({ お題, 読めたか: 偽, 異常: 失敗を要約する(躓き) }),
  });
}
