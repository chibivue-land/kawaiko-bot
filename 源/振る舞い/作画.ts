/**
 * 「描いて」と言われたときに，実際に 1 枚描いて出すまで．
 *
 * 2 回モデルを叩く．1 回目は言葉のモデルで，頼まれたものを画像生成モデルに効く
 * 英語のプロンプトへ翻す — ついでに絵に添える一言も同じ 1 回で書かせる．
 * 2 回目が画像生成そのもの．
 *
 * どちらも Workers AI の 1 日ぶんの無料枠から引かれる．絵 1 枚は 58 neuron ほどで，
 * 言葉の返事 1 回と同じ桁．とはいえ枠は小さいので，利用制限と予算の見張りは
 * 普通の返事とまったく同じものを通る (呼ぶ側でそうしてある)．
 */
import { 発話する } from "./発話";
import type { 描いた絵, 部品一式 } from "./接続口";
import type { 届いた名指し } from "./返信";
import { 作画の返事を読み取る, 作画依頼を組み立てる } from "../核/作画";
import type { 描く頼み } from "../核/作画";
import { 人格指示書を組み立てる } from "../核/人格";
import { 作画しくじりの文, 定型文を選ぶ } from "../核/定型文";
import { 数値, 文字列, 未定義 } from "../共通/型";
import type { 無, 省略可, 約束 } from "../共通/型";
import { 空か } from "../共通/関数";
import { 等しい, 足す } from "../共通/演算";
import { もし, 試みる } from "../共通/構文";
import { すぐ返す } from "../共通/約束";
import { 注意 } from "../共通/記録";

/** 一言が空だったときに添える言葉．無言で絵だけ置くのは kawaiko らしくない． */
const 既定の一言 = "描いた";

export function 絵を描いて返す(
  部品: 部品一式,
  名指し: 届いた名指し,
  頼み: 描く頼み,
  返す: (本文: 文字列) => 約束<無>,
): 約束<無> {
  return 部品.チャット
    .入力中にする(名指し.チャンネルid, () => 一枚仕上げる(部品, 名指し, 頼み))
    .んで((出来上がり) =>
      もし<約束<無>>(等しい(出来上がり, 未定義), {
        // どこで転んでも，黙って消えるよりは一言返す．
        であれば: () => 返す(定型文を選ぶ(作画しくじりの文)),
        でなければ: () =>
          部品.予算番
            .記録する(出来上がり!.費用ドル)
            .んで(() =>
              部品.チャット.絵を投稿する(
                名指し.チャンネルid,
                出来上がり!.一言,
                出来上がり!.絵,
                名指し.発言id,
              ),
            ),
      }),
    );
}

interface 出来上がり {
  絵: 描いた絵;
  一言: 文字列;
  費用ドル: 数値;
}

/** 何を描くか決めて，描く．どこかで転んだら undefined． */
function 一枚仕上げる(
  部品: 部品一式,
  名指し: 届いた名指し,
  頼み: 描く頼み,
): 約束<省略可<出来上がり>> {
  return 試みる<省略可<出来上がり>>({
    実行: () =>
      発話する(部品.発話器, {
        指示書: 人格指示書を組み立てる(),
        指示文: 作画依頼を組み立てる({ お題: 頼み.お題, 相手の名前: 名指し.相手の名前 }),
        深さ: "low",
        最大トークン: 512,
      }).んで((下書き) => 絵にする(部品, 下書き)),
    しくじったら: (躓き) => {
      注意("作画: 描けなかった:", 文字列(躓き));

      return 未定義;
    },
  });
}

function 絵にする(
  部品: 部品一式,
  下書き: { 本文: 文字列; 費用ドル: 数値 },
): 約束<省略可<出来上がり>> {
  const 読んだ = 作画の返事を読み取る(下書き.本文);

  return もし<約束<省略可<出来上がり>>>(等しい(読んだ, 未定義), {
    であれば: () => {
      注意("作画: モデルが絵の指示を返さなかった");

      return すぐ返す(未定義);
    },
    でなければ: () =>
      部品.絵描き.描く(読んだ!.絵の指示).んで((絵) => ({
        絵,
        一言: もし(空か(読んだ!.一言), {
          であれば: () => 既定の一言,
          でなければ: () => 読んだ!.一言,
        }),
        費用ドル: 足す(下書き.費用ドル, 絵.費用ドル),
      })),
  });
}
