export async function 独り言を投稿する(
  部品: 部品一式,
  設定?: 省略可<{ 強制するか?: 省略可<真偽> }>,
): 約束<実行結果> {
  return 振り分ける<実行結果>(
    [
      {
        条件: () => 否定(設定?.強制するか) && 否定(投稿するか(部品.独言の確率, 部品.乱数)),
        ならば: () => {
          記す("独言: 確率ゲートで見送り");

          return { 成功か: 真, 省略した理由: "確率" };
        },
      },
    ],
    { どれでもなければ: () => 予算を見てから呟く(部品) },
  );
}

function 予算を見てから呟く(部品: 部品一式): 約束<実行結果> {
  return 部品.予算番.許すか().んで(({ 許すか, 使用済みドル }) =>
    振り分ける<実行結果>(
      [
        {
          条件: () => 否定(許すか),
          ならば: () => {
            注意(`独言: 月の予算超過 (約 $${小数で書く(使用済みドル, 2)}) のため見送り`);

            return { 成功か: 真, 省略した理由: "予算" };
          },
        },
      ],
      {
        どれでもなければ: () =>
          試みる<実行結果>({
            実行: () =>
              呟く(部品)
                .んで((モデル) => 部品.予算番.仕事を終える("独言", 真, 未定義, モデル))
                .んで(() => ({ 成功か: 真 })),
            しくじったら: (躓き) => {
              異常("独言に失敗:", 躓き);
              const 要約 = 失敗を要約する(躓き);

              return 部品.予算番
                .仕事を終える("独言", 偽, 要約)
                .んで(() => ({ 成功か: 偽, 異常: 要約 }));
            },
          }),
      },
    ),
  );
}

function 呟く(部品: 部品一式): 約束<文字列> {
  const チャンネルid = 部品.住処のチャンネルid;
  const お題 = お題を選ぶ(部品.乱数);

  // ここで最近言ったこと．独り言もそれを繰り返してはいけない．
  return 揃える([
    お題がニュースを要るか(お題) ? 部品.見出し取得.見出し() : すぐ返す([]),
    部品.チャット.直近の発言(チャンネルid, 30).しくじったら(() => []),
    部品.チャンネル記録.リセット時刻(チャンネルid),
    部品.チャット.サーバーを引く(チャンネルid),
  ])
    .んで(([見出し一覧, 取得, リセット時刻, サーバーid]) =>
      (サーバーid ? 部品.記憶庫.生きている事実(サーバーid) : すぐ返す([])).んで((事実一覧) => ({
        見出し一覧,
        事実一覧,
        自分の直近発言: 自分の直近発言を集める(
          リセット後に絞る(取得, リセット時刻),
          部品.自分のid,
          回避する件数,
        ),
      })),
    )
    .んで(({ 見出し一覧, 事実一覧, 自分の直近発言 }) =>
      部品.チャット.入力中にする(チャンネルid, () =>
        重複を避けて発話する(
          部品.発話器,
          {
            指示書: 人格指示書を組み立てる(),
            指示文: 独り言の指示文を組み立てる({
              時刻の表示: 日本時間の表示(部品.現在時刻()),
              時: 日本時間の時(部品.現在時刻()),
              お題,
              見出し一覧,
              事実一覧,
              自分の直近発言,
              乱数: 部品.乱数,
            }),
            深さ: "low",
            最大トークン: 2048,
          },
          自分の直近発言,
        ),
      ),
    )
    .んで(({ 本文, 費用ドル, モデル }) =>
      部品.予算番
        .記録する(費用ドル)
        .んで(() => 部品.チャット.投稿する(チャンネルid, 本文))
        .んで(() => {
          記す(`独言: ${モデル} で投稿 (約 $${小数で書く(費用ドル, 4)})`);

          return モデル;
        }),
    );
}
