import {
  お題がニュースを要るか,
  お題を選ぶ,
  投稿するか,
  独り言の指示文を組み立てる,
} from "../核/独言";
import { 人格指示書を組み立てる } from "../核/人格";
import { 日本時間の時, 日本時間の表示 } from "../核/予定";
