import { describe, expect, it } from "vitest";
import { 発話する, 重複を避けて発話する } from "./発話";
import type { 発話の結果, 発話器 } from "./接続口";
import { 人格指示書を組み立てる } from "../核/人格";
import { 受け流しの文, 反復打ち切りの文, 拒否の文, 無言の文 } from "../核/定型文";

const 指示書 = "なんらかの指示書";

function 発話器を作る(...返事一覧: (Partial<発話の結果> | Error)[]): 発話器 & { 回数: number } {
  let 番号 = 0;
  const 自身 = {
    回数: 0,
    async 発話する(): Promise<発話の結果> {
      自身.回数++;
      const 返事 = 返事一覧[Math.min(番号, 返事一覧.length - 1)];
      番号++;
      if (返事 instanceof Error) throw 返事;

      return { 本文: "", 費用ドル: 0.001, モデル: "偽のモデル", ...返事 };
    },
  };

  return 自身;
}

describe("発話する", () => {
  it("普通の文はそのまま通す", async () => {
    const 結果 = await 発話する(発話器を作る({ 本文: "はい．" }), { 指示書, 指示文: "問い" });

    expect(結果.本文).toBe("はい．");
  });

  it("指示書を引用してしまった返事は受け流しへ差し替える", async () => {
    // 「秘密にしろ」というプロンプト側の規則は小さいモデルに効きが弱い．ここが歯止め．
    const 本物の指示書 = 人格指示書を組み立てる();
    const 漏れた行 = 本物の指示書.split("\n").find((行) => 行.length > 40)!;

    const 結果 = await 発話する(発話器を作る({ 本文: 漏れた行 }), {
      指示書: 本物の指示書,
      指示文: "問い",
    });

    expect(受け流しの文).toContain(結果.本文);
  });

  it("提供者が拒否したら拒否の一言にする", async () => {
    const 結果 = await 発話する(発話器を作る({ 本文: "", 拒否された: true }), {
      指示書,
      指示文: "問い",
    });

    expect(拒否の文).toContain(結果.本文);
  });

  it("何も返ってこなければ無言の一言にする", async () => {
    const 結果 = await 発話する(発話器を作る({ 本文: "   " }), { 指示書, 指示文: "問い" });

    expect(無言の文).toContain(結果.本文);
  });
});

describe("重複を避けて発話する", () => {
  const 避けたい = ["ubugeeei さん，それはあまりに雑な質問ですね"];

  it("避けるものが無ければ 1 回だけ生成する", async () => {
    const 発話器 = 発話器を作る({ 本文: "何でもよい" });

    await 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, []);

    expect(発話器.回数).toBe(1);
  });

  it("新鮮な返事はそのまま採る", async () => {
    const 発話器 = 発話器を作る({ 本文: "眠いです．レッドブルが切れました．" });

    const 結果 = await 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい);

    expect(発話器.回数).toBe(1);
    expect(結果.本文).toBe("眠いです．レッドブルが切れました．");
  });

  it("繰り返しは振り直し，両方の試行を計上する", async () => {
    const 発話器 = 発話器を作る(
      { 本文: "kazupon さん，それはあまりに筋が悪いです" },
      { 本文: "Vapor Mode の話なら朝まで喋れます" },
    );

    const 結果 = await 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい);

    expect(発話器.回数).toBe(2);
    expect(結果.本文).toBe("Vapor Mode の話なら朝まで喋れます");
    expect(結果.費用ドル).toBeCloseTo(0.002, 6);
  });

  it("振り直しでは同じ頼み方をせず，促しを足す", async () => {
    const 指示文一覧: string[] = [];
    const 発話器: 発話器 = {
      async 発話する(依頼) {
        指示文一覧.push(依頼.指示文);

        return { 本文: 避けたい[0]!, 費用ドル: 0, モデル: "偽のモデル" };
      },
    };

    await 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい);

    expect(指示文一覧[0]).toBe("問い");
    expect(指示文一覧[1]).toContain("同じ型だった");
  });

  it("どの試行も同じ文なら，口に出してループを打ち切る", async () => {
    const 発話器 = 発話器を作る({ 本文: 避けたい[0]! });

    const 結果 = await 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい);

    expect(反復打ち切りの文).toContain(結果.本文);
  });

  it("どれも新鮮でないときは，いちばんマシなものを採る", async () => {
    // 丸写しの次に，書き出しだけ同じもの．どちらも新鮮ではないので，より遠い方が出る．
    const 発話器 = 発話器を作る(
      { 本文: 避けたい[0]! },
      { 本文: "yamanoku さん，それはあまりに、と言いかけて眠くなりました" },
    );

    const 結果 = await 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい);

    expect(結果.本文).toContain("yamanoku");
  });

  it("振り直しが失敗しても，使える最初の返事を捨てない", async () => {
    const 発話器 = 発話器を作る({ 本文: 避けたい[0]! }, new Error("提供者が落ちた"));

    const 結果 = await 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい);

    expect(結果.本文).toBeTruthy();
  });

  it("返事が一つも無ければ失敗を伝える", async () => {
    const 発話器 = 発話器を作る(new Error("提供者が落ちた"));

    await expect(
      重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい),
    ).rejects.toThrow("提供者が落ちた");
  });
});
