const 指示書 = "なんらかの指示書";

function 発話器を作る(...返事一覧: (Partial<発話の結果> | Error)[]): 発話器 & { 回数: number } {
  let 番号 = 0;
  const 自身 = {
    回数: 0,
    async 発話する(): 約束<発話の結果> {
      自身.回数++;
      const 返事 = 返事一覧[Math.min(番号, 返事一覧.length - 1)];
      番号++;
      if (返事 instanceof Error) throw 返事;

      return { 本文: "", 費用ドル: 0.001, モデル: "偽のモデル", ...返事 };
    },
  };

  return 自身;
}

仕様("発話する", () => {
  検証("普通の文はそのまま通す", () => {
    return 発話する(発話器を作る({ 本文: "はい．" }), { 指示書, 指示文: "問い" }).んで((結果) => {
      期待(結果.本文).である("はい．");
    });
  });

  検証("指示書を引用してしまった返事は受け流しへ差し替える", () => {
    // 「秘密にしろ」というプロンプト側の規則は小さいモデルに効きが弱い．ここが歯止め．
    const 本物の指示書 = 人格指示書を組み立てる();
    const 漏れた行 = 本物の指示書.split("\n").find((行) => 行.length > 40)!;
    return 発話する(発話器を作る({ 本文: 漏れた行 }), {
      指示書: 本物の指示書,
      指示文: "問い",
    }).んで((結果) => {
      期待(受け流しの文).を含む(結果.本文);
    });
  });

  検証("提供者が拒否したら拒否の一言にする", () => {
    return 発話する(発話器を作る({ 本文: "", 拒否された: 真 }), {
      指示書,
      指示文: "問い",
    }).んで((結果) => {
      期待(拒否の文).を含む(結果.本文);
    });
  });

  検証("何も返ってこなければ無言の一言にする", () => {
    return 発話する(発話器を作る({ 本文: "   " }), { 指示書, 指示文: "問い" }).んで((結果) => {
      期待(無言の文).を含む(結果.本文);
    });
  });
});

仕様("重複を避けて発話する", () => {
  const 避けたい = ["ubugeeei さん，それはあまりに雑な質問ですね"];

  検証("避けるものが無ければ 1 回だけ生成する", () => {
    const 発話器 = 発話器を作る({ 本文: "何でもよい" });
    return 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, []).んで(() => {
      期待(発話器.回数).である(1);
    });
  });

  検証("新鮮な返事はそのまま採る", () => {
    const 発話器 = 発話器を作る({ 本文: "眠いです．レッドブルが切れました．" });
    return 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい).んで((結果) => {
      期待(発話器.回数).である(1);
      期待(結果.本文).である("眠いです．レッドブルが切れました．");
    });
  });

  検証("繰り返しは振り直し，両方の試行を計上する", () => {
    const 発話器 = 発話器を作る(
      { 本文: "kazupon さん，それはあまりに筋が悪いです" },
      { 本文: "Vapor Mode の話なら朝まで喋れます" },
    );
    return 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい).んで((結果) => {
      期待(発話器.回数).である(2);
      期待(結果.本文).である("Vapor Mode の話なら朝まで喋れます");
      期待(結果.費用ドル).とほぼ等しい(0.002, 6);
    });
  });

  検証("振り直しでは同じ頼み方をせず，促しを足す", () => {
    const 指示文一覧: string[] = [];
    const 発話器: 発話器 = {
      async 発話する(依頼) {
        指示文一覧.push(依頼.指示文);

        return { 本文: 避けたい[0]!, 費用ドル: 0, モデル: "偽のモデル" };
      },
    };
    return 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい).んで(() => {
      期待(指示文一覧[0]).である("問い");
      期待(指示文一覧[1]).を含む("同じ型だった");
    });
  });

  検証("どの試行も同じ文なら，口に出してループを打ち切る", () => {
    const 発話器 = 発話器を作る({ 本文: 避けたい[0]! });
    return 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい).んで((結果) => {
      期待(反復打ち切りの文).を含む(結果.本文);
    });
  });

  検証("どれも新鮮でないときは，いちばんマシなものを採る", () => {
    // 丸写しの次に，書き出しだけ同じもの．どちらも新鮮ではないので，より遠い方が出る．
    const 発話器 = 発話器を作る(
      { 本文: 避けたい[0]! },
      { 本文: "yamanoku さん，それはあまりに、と言いかけて眠くなりました" },
    );
    return 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい).んで((結果) => {
      期待(結果.本文).を含む("yamanoku");
    });
  });

  検証("振り直しが失敗しても，使える最初の返事を捨てない", () => {
    const 発話器 = 発話器を作る({ 本文: 避けたい[0]! }, 新しい例外("提供者が落ちた"));
    return 重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい).んで((結果) => {
      期待(結果.本文).が真();
    });
  });

  検証("返事が一つも無ければ失敗を伝える", () => {
    const 発話器 = 発話器を作る(新しい例外("提供者が落ちた"));
    return 期待(重複を避けて発話する(発話器, { 指示書, 指示文: "問い" }, 避けたい)).しくじる(
      "提供者が落ちた",
    );
  });
});

仕様("重複を避けて発話する: 検品", () => {
  /** 受け取った依頼を覚えておき，返事を順に返す発話器． */
  function 覚える発話器(...返事一覧: string[]): 発話器 & { 依頼一覧: 発話の依頼[] } {
    const 依頼一覧: 発話の依頼[] = [];

    return {
      依頼一覧,
      async 発話する(依頼) {
        依頼一覧.push(依頼);

        return {
          本文: 返事一覧[Math.min(依頼一覧.length - 1, 返事一覧.length - 1)]!,
          費用ドル: 0.001,
          モデル: "偽のモデル",
        };
      },
    };
  }

  const 依頼: 発話の依頼 = {
    指示書,
    指示文: "問い",
    構え: "普通",
    深さ: "medium",
    最大トークン: 1024,
  };

  検証("検品に通れば，避けるものが無くても 1 回で済む", () => {
    const 発話器 = 覚える発話器("ごはん．kawaiko の負けです．");

    return 重複を避けて発話する(発話器, 依頼, [], async () => 真).んで((結果) => {
      期待(発話器.依頼一覧).の長さが(1);
      期待(結果.本文).である("ごはん．kawaiko の負けです．");
    });
  });

  検証("応じていない返事は，構えを熟考へ上げて作り直す", () => {
    // しりとりの «りんご» に «ご，ん．» と返した回が，これで拾える．
    const 発話器 = 覚える発話器("ご，ん．", "ごはん．kawaiko の負けです．");
    const 検品 = async (本文: string) => 本文.includes("ごはん");

    return 重複を避けて発話する(発話器, 依頼, [], 検品).んで((結果) => {
      期待(発話器.依頼一覧).の長さが(2);
      期待(結果.本文).である("ごはん．kawaiko の負けです．");
      期待(結果.費用ドル).とほぼ等しい(0.002, 6);

      const [, 二回目] = 発話器.依頼一覧;
      // 同じ頭でもう一度振っても同じところで転ぶ．賢いモデルへ，考える余地つきで．
      期待(二回目!.構え).である("熟考");
      期待(二回目!.深さ).である("high");
      期待(二回目!.最大トークン).以上(4096);
      期待(二回目!.指示文).を含む("応じていなかった");
      // 反復で落ちたわけではないので，«同じ型だった» とは言わない．
      期待(二回目!.指示文).否.を含む("同じ型だった");
    });
  });

  検証("反復でも検品でも落ちたら，両方の促しを足す", () => {
    const 避けたい = ["ubugeeei さん，それはあまりに雑な質問ですね"];
    const 発話器 = 覚える発話器(避けたい[0]!, "ごはん．");

    return 重複を避けて発話する(発話器, 依頼, 避けたい, async () => 偽).んで(() => {
      const [, 二回目] = 発話器.依頼一覧;

      期待(二回目!.指示文).を含む("同じ型だった");
      期待(二回目!.指示文).を含む("応じていなかった");
    });
  });

  検証("どの試行も検品に落ちたら，最後までで一番マシなものを出す (黙りはしない)", () => {
    const 発話器 = 覚える発話器("ご，ん．", "ん．");

    return 重複を避けて発話する(発話器, 依頼, [], async () => 偽).んで((結果) => {
      期待(発話器.依頼一覧).の長さが(2);
      期待(結果.本文).が真();
    });
  });

  検証("検品に通ったものは，通らなかったものより優先する", () => {
    // 1 回目: 応じているが，書き出しが直近の発言と同じ (丸写しではない)．
    // 2 回目: 新鮮だが応じていない．
    const 避けたい = ["ごはん．kawaiko の負けです．これで満足ですか．"];
    const 発話器 = 覚える発話器(
      "ごはん．kawaiko の負けです，と言いたいところですが眠いので寝ます．",
      "知りません．",
    );
    const 検品 = async (本文: string) => 本文.includes("ごはん");

    return 重複を避けて発話する(発話器, 依頼, 避けたい, 検品).んで((結果) => {
      期待(結果.本文).を含む("ごはん");
    });
  });
});
