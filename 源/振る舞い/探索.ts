/**
 * 調べ物の探索ループ．
 *
 * 巷のコーディングエージェント (Claude Code など) の web 検索と同じ回し方 —
 * まず引き，出てきた一覧を**モデルに見せてから**「どれを開くか」「語を変えて
 * 引き直すか」「もう十分か」を選ばせ，選べなくなるか十分と言うまで繰り返す．
 *
 * 何が選べて何が選べないか (上限・重複・見たことのない URL) は 核/探索.ts が
 * 決める．ここは選ばれた一手を実行して，見えたものを積んでいくだけ．
 */
import type { 発話器, 読んだ頁, 部品一式 } from "./接続口";

import {
  一手を検める,
  一手を読み取る,
  まだ動けるか,
  探索の役割,
  探索の指示を組み立てる,
  探索の最大手数,
  検索結果を書き出す,
  素の足あと,
  頁を短く書き出す,
} from "../核/探索";
import type { 探索の一手, 探索の足あと } from "../核/探索";

import { 数値, 文字列, 未定義, 偽, 真, 真偽 } from "../共通/型";
import type { 約束, 配列 } from "../共通/型";
import { 空行 } from "../共通/文字";
import { もし, 場合分け, 試みる } from "../共通/構文";
import { 否定, 等しい } from "../共通/演算";
import { すぐ返す } from "../共通/約束";
import { 打ち切るまで繰り返す } from "../共通/反復";
import { 写す, 空か, 絞る, 繋ぐ } from "../共通/関数";

/** 探索が終わって持ち帰るもの． */
export interface 探索の結末 {
  /** 最終の指示文の参考情報へ載せる，検索結果の書き出し． */
  抜粋: 文字列;
  /** 実際に開いて読めた頁．全文は 頁節 が指示文へ載せる． */
  頁一覧: 配列<読んだ頁>;
  /** 検索で見えた場所ぜんぶ．覗き見のためだけ． */
  候補: 配列<文字列>;
  /** ループの判断に使ったモデル呼び出しの合計． */
  費用ドル: 数値;
  /** 何をしたかの跡．覗き見のためだけ． */
  足どり: 配列<文字列>;
}

/** 見えたもの 1 つ．最終の参考情報に載せるのは検索の分だけ． */
interface 断片 {
  種類: "検索" | "頁";
  中身: 文字列;
}

interface 探索の途中 {
  足あと: 探索の足あと;
  断片一覧: 配列<断片>;
  頁一覧: 配列<読んだ頁>;
  費用ドル: 数値;
  足どり: 配列<文字列>;
}

/**
 * 初手の検索語で 1 回引いてから，モデルの判断でループする．
 *
 * 初手を機械的に引くのは往復を 1 つ削るため — どのエージェントも最初の一手は
 * どうせ検索で，そこにモデルの判断を挟む価値は無い．
 */
export function 探索して調べる(
  部品: 部品一式,
  問いかけ: 文字列,
  初手の検索語: 文字列,
): 約束<探索の結末> {
  const 始まり: 探索の途中 = {
    足あと: 素の足あと(),
    断片一覧: [],
    頁一覧: [],
    費用ドル: 0,
    足どり: [],
  };

  return 検索を実行する(部品, 始まり, 初手の検索語)
    .んで((途中) =>
      打ち切るまで繰り返す(探索の最大手数, 途中, (今) => 一手すすめる(部品, 問いかけ, 今)),
    )
    .んで(結末にする);
}

function 一手すすめる(
  部品: 部品一式,
  問いかけ: 文字列,
  今: 探索の途中,
): 約束<{ 状態: 探索の途中; 打ち切るか: 真偽 }> {
  return もし<約束<{ 状態: 探索の途中; 打ち切るか: 真偽 }>>(
    否定(まだ動けるか(今.足あと, 部品.頁読み.使えるか)),
    {
      であれば: () => すぐ返す({ 状態: 今, 打ち切るか: 真 }),
      でなければ: () =>
        次の一手を訊く(部品.発話器, 問いかけ, 今, 部品.頁読み.使えるか).んで(({ 手, 費用ドル }) =>
          一手を実行する(部品, { ...今, 費用ドル: 今.費用ドル + 費用ドル }, 手),
        ),
    },
  );
}

/**
 * モデルに次の一手を訊く．訊けなかったら「十分」．
 *
 * ここで転んでも，ここまでに集めた材料で答えられる — 判断が貰えないことは
 * 調べ物ごと捨てる理由にならない．
 */
function 次の一手を訊く(
  発話器: 発話器,
  問いかけ: 文字列,
  今: 探索の途中,
  開けるか: 真偽,
): 約束<{ 手: 探索の一手; 費用ドル: 数値 }> {
  return 試みる<{ 手: 探索の一手; 費用ドル: 数値 }>({
    実行: () =>
      発話器
        .発話する({
          指示書: 探索の役割,
          指示文: 探索の指示を組み立てる(問いかけ, 見えたものを繋ぐ(今), 今.足あと, 開けるか),
          深さ: "low",
          最大トークン: 64,
        })
        .んで((結果) => ({
          手: 一手を検める(一手を読み取る(結果.本文), 今.足あと, 開けるか),
          費用ドル: 結果.費用ドル,
        })),
    しくじったら: () => ({ 手: { 行動: "十分" }, 費用ドル: 0 }),
  });
}

function 見えたものを繋ぐ(今: 探索の途中): 文字列 {
  return 繋ぐ(
    写す(今.断片一覧, (断片) => 断片.中身),
    空行,
  );
}

function 一手を実行する(
  部品: 部品一式,
  今: 探索の途中,
  手: 探索の一手,
): 約束<{ 状態: 探索の途中; 打ち切るか: 真偽 }> {
  return 場合分け<探索の一手["行動"], 約束<{ 状態: 探索の途中; 打ち切るか: 真偽 }>>(手.行動, {
    検索: () =>
      検索を実行する(部品, 今, (手 as { 検索語: 文字列 }).検索語).んで((状態) => ({
        状態,
        打ち切るか: 偽,
      })),
    開く: () =>
      頁を開く(部品, 今, (手 as { 場所: 文字列 }).場所).んで((状態) => ({
        状態,
        打ち切るか: 偽,
      })),
    十分: () => すぐ返す({ 状態: { ...今, 足どり: [...今.足どり, "十分"] }, 打ち切るか: 真 }),
  })!;
}

/** 引く．転んでも「何も出なかった」として続ける． */
function 検索を実行する(部品: 部品一式, 今: 探索の途中, 検索語: 文字列): 約束<探索の途中> {
  return 部品.調査係
    .調べる(検索語)
    .しくじったら(() => ({ 抜粋: "", 候補: [], 件一覧: [] }))
    .んで((結果) => ({
      ...今,
      足あと: {
        ...今.足あと,
        検索した語: [...今.足あと.検索した語, 検索語],
        見えた場所: [
          ...今.足あと.見えた場所,
          ...絞る(
            写す(結果.件一覧, (件) => 件.場所 ?? ""),
            (場所) => 否定(空か(場所)),
          ),
        ],
      },
      断片一覧: [
        ...今.断片一覧,
        { 種類: "検索" as const, 中身: 検索結果を書き出す(検索語, 結果.件一覧) },
      ],
      足どり: [...今.足どり, `検索: ${検索語}`],
    }));
}

/**
 * 開く．開けなかった場所も足あとには残す — 次の手で同じ場所を選び直させない．
 */
function 頁を開く(部品: 部品一式, 今: 探索の途中, 場所: 文字列): 約束<探索の途中> {
  const 開いた = {
    ...今.足あと,
    開いた場所: [...今.足あと.開いた場所, 場所],
  };

  return 部品.頁読み.読む(場所).んで((頁) =>
    もし<探索の途中>(等しい(頁, 未定義), {
      であれば: () => ({
        ...今,
        足あと: 開いた,
        断片一覧: [...今.断片一覧, { 種類: "頁" as const, 中身: `開けなかった: ${場所}` }],
        足どり: [...今.足どり, `開く (読めず): ${場所}`],
      }),
      でなければ: () => ({
        ...今,
        足あと: 開いた,
        頁一覧: [...今.頁一覧, 頁!],
        断片一覧: [...今.断片一覧, { 種類: "頁" as const, 中身: 頁を短く書き出す(頁!) }],
        足どり: [...今.足どり, `開く: ${場所}`],
      }),
    }),
  );
}

function 結末にする(途中: 探索の途中): 探索の結末 {
  return {
    抜粋: 繋ぐ(
      写す(
        絞る(途中.断片一覧, (断片) => 等しい(断片.種類, "検索")),
        (断片) => 断片.中身,
      ),
      空行,
    ),
    頁一覧: 途中.頁一覧,
    候補: 途中.足あと.見えた場所,
    費用ドル: 途中.費用ドル,
    足どり: 途中.足どり,
  };
}
