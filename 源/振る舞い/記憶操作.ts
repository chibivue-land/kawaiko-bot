/**
 * kawaiko が覚えたことを読む / 取り消す．
 *
 * 記憶庫は追記専用ログなので，ここでの「取り消し」はどれも追記でしかない．
 * 復元も消失も起きないから，深夜に携帯から叩いても安全．
 */
import type { 部品一式 } from "./接続口";
import { 偽, 数値, 文字列, 真, 真偽 } from "../共通/型";
import type { 不明, 省略可, 約束 } from "../共通/型";
import { 否定 } from "../共通/演算";
import { もし, 場合分け } from "../共通/構文";
import { 異常 } from "../共通/記録";

export type 記憶への問い =
  | { 種別: "サーバー一覧" }
  | { 種別: "現状"; サーバーid: 文字列 }
  | { 種別: "回を取り消す"; サーバーid: 文字列; 識別子: 文字列; 理由?: 省略可<文字列> }
  | { 種別: "巻き戻す"; サーバーid: 文字列; 連番: 数値; 理由?: 省略可<文字列> };

export type 記憶操作の結果 =
  | { 状態: 503; 本体: { 異常: 文字列 } }
  | { 状態: 200; 本体: 不明 }
  | { 状態: 500; 本体: { 成功か: 真偽 } };

export function 記憶を操作する(部品: 部品一式, 問い: 記憶への問い): 約束<記憶操作の結果> {
  return もし(否定(部品.記憶庫.使えるか), {
    であれば: (): 約束<記憶操作の結果> =>
      Promise.resolve({ 状態: 503, 本体: { 異常: "記憶庫が繋がっていない" } }),
    でなければ: () =>
      場合分け(問い.種別, {
        サーバー一覧: () => サーバーを並べる(部品),
        現状: () => 現状を返す(部品, 問い as { サーバーid: 文字列 }),
        回を取り消す: () => 回を取り消す(部品, 問い as 取り消しの問い),
        巻き戻す: () => 巻き戻す(部品, 問い as 巻き戻しの問い),
      })!,
  });
}

type 取り消しの問い = { サーバーid: 文字列; 識別子: 文字列; 理由?: 省略可<文字列> };
type 巻き戻しの問い = { サーバーid: 文字列; 連番: 数値; 理由?: 省略可<文字列> };

function サーバーを並べる(部品: 部品一式): 約束<記憶操作の結果> {
  return 部品.記憶庫
    .観測したサーバー()
    .んで((サーバー一覧) => ({ 状態: 200, 本体: { サーバー一覧 } }));
}

function 現状を返す(部品: 部品一式, 問い: { サーバーid: 文字列 }): 約束<記憶操作の結果> {
  // 三つは互いを待たない．揃ってから一つの本体にまとめる．
  return Promise.all([
    部品.記憶庫.学習の読み取り位置(問い.サーバーid),
    部品.記憶庫.生きている事実(問い.サーバーid, { 上限: 200 }),
    部品.記憶庫.学習の履歴(問い.サーバーid),
  ]).んで(([読み取り位置, 事実一覧, 学習の履歴]) => ({
    状態: 200,
    本体: {
      サーバー: 問い.サーバーid,
      読み取り位置,
      事実一覧,
      学習の履歴,
    },
  }));
}

function 回を取り消す(部品: 部品一式, 問い: 取り消しの問い): 約束<記憶操作の結果> {
  return 部品.記憶庫
    .学習の回を取り消す(問い.サーバーid, 問い.識別子, 問い.理由)
    .んで((成功か) =>
      もし(成功か, {
        であれば: (): 記憶操作の結果 => ({
          状態: 200,
          本体: { 成功か: 真, 取り消した回: 問い.識別子 },
        }),
        でなければ: (): 記憶操作の結果 => ({ 状態: 500, 本体: { 成功か: 偽 } }),
      }),
    );
}

function 巻き戻す(部品: 部品一式, 問い: 巻き戻しの問い): 約束<記憶操作の結果> {
  return 部品.記憶庫
    .時点まで巻き戻す(問い.サーバーid, 問い.連番, 問い.理由)
    .んで((成功か) =>
      もし(成功か, {
        であれば: (): 記憶操作の結果 => ({
          状態: 200,
          本体: { 成功か: 真, 戻した位置: 問い.連番 },
        }),
        でなければ: (): 記憶操作の結果 => ({ 状態: 500, 本体: { 成功か: 偽 } }),
      }),
    );
}
