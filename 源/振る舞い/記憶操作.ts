/**
 * kawaiko が覚えたことを読む / 取り消す．
 *
 * 記憶庫は追記専用ログなので，ここでの「取り消し」はどれも追記でしかない．
 * 復元も消失も起きないから，深夜に携帯から叩いても安全．
 */
import type { 部品一式 } from "./接続口";
import { 数値, 文字列 } from "../共通/型";
import type { 不明, 省略可, 約束 } from "../共通/型";
import { 否定 } from "../共通/演算";
import { もし, 場合分け } from "../共通/構文";

export type 記憶への問い =
  | { 種別: "サーバー一覧" }
  | { 種別: "現状"; サーバーid: 文字列 }
  | { 種別: "回を取り消す"; サーバーid: 文字列; 識別子: 文字列; 理由?: 省略可<文字列> }
  | { 種別: "巻き戻す"; サーバーid: 文字列; 連番: 数値; 理由?: 省略可<文字列> };

export type 記憶操作の結果 =
  | { 状態: 503; 本体: { 異常: 文字列 } }
  | { 状態: 200; 本体: 不明 }
  | { 状態: 500; 本体: { 成功か: false } };

export async function 記憶を操作する(部品: 部品一式, 問い: 記憶への問い): 約束<記憶操作の結果> {
  return もし(否定(部品.記憶庫.使えるか), {
    であれば: async (): 約束<記憶操作の結果> => ({
      状態: 503,
      本体: { 異常: "記憶庫が繋がっていない" },
    }),
    でなければ: () =>
      場合分け(問い.種別, {
        サーバー一覧: () => サーバーを並べる(部品),
        現状: () => 現状を返す(部品, 問い as { サーバーid: 文字列 }),
        回を取り消す: () => 回を取り消す(部品, 問い as 取り消しの問い),
        巻き戻す: () => 巻き戻す(部品, 問い as 巻き戻しの問い),
      })!,
  });
}

type 取り消しの問い = { サーバーid: 文字列; 識別子: 文字列; 理由?: 省略可<文字列> };
type 巻き戻しの問い = { サーバーid: 文字列; 連番: 数値; 理由?: 省略可<文字列> };

async function サーバーを並べる(部品: 部品一式): 約束<記憶操作の結果> {
  return { 状態: 200, 本体: { サーバー一覧: await 部品.記憶庫.観測したサーバー() } };
}

async function 現状を返す(部品: 部品一式, 問い: { サーバーid: 文字列 }): 約束<記憶操作の結果> {
  return {
    状態: 200,
    本体: {
      サーバー: 問い.サーバーid,
      読み取り位置: await 部品.記憶庫.学習の読み取り位置(問い.サーバーid),
      事実一覧: await 部品.記憶庫.生きている事実(問い.サーバーid, { 上限: 200 }),
      学習の履歴: await 部品.記憶庫.学習の履歴(問い.サーバーid),
    },
  };
}

async function 回を取り消す(部品: 部品一式, 問い: 取り消しの問い): 約束<記憶操作の結果> {
  const 成功か = await 部品.記憶庫.学習の回を取り消す(問い.サーバーid, 問い.識別子, 問い.理由);

  return もし(成功か, {
    であれば: (): 記憶操作の結果 => ({
      状態: 200,
      本体: { 成功か: true, 取り消した回: 問い.識別子 },
    }),
    でなければ: (): 記憶操作の結果 => ({ 状態: 500, 本体: { 成功か: false } }),
  });
}

async function 巻き戻す(部品: 部品一式, 問い: 巻き戻しの問い): 約束<記憶操作の結果> {
  const 成功か = await 部品.記憶庫.時点まで巻き戻す(問い.サーバーid, 問い.連番, 問い.理由);

  return もし(成功か, {
    であれば: (): 記憶操作の結果 => ({
      状態: 200,
      本体: { 成功か: true, 戻した位置: 問い.連番 },
    }),
    でなければ: (): 記憶操作の結果 => ({ 状態: 500, 本体: { 成功か: false } }),
  });
}
