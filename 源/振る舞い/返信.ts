/** kawaiko 宛ての発言．ゲートウェイの生の payload から正規化したもの． */
export interface 届いた名指し {
  発言id: 文字列;
  チャンネルid: 文字列;
  サーバーid: 文字列;
  発言者id: 文字列;
  相手の名前: 文字列;
  /** 自分宛てのメンションタグを取り除いた本文． */
  本文: 文字列;
  /** 添えられていた画像やファイル． */
  添付一覧: 読み取り専用配列<添付>;
  /** この発言が誰かの発言への返信なら，その相手の発言．jev 命令の判定対象になる． */
  返信先?: 省略可<{ 発言者名: 文字列; 本文: 文字列 }>;
}

export type 返信の結末 =
  | { 種別: "リセット" }
  | { 種別: "利用制限" }
  | { 種別: "予算切れ" }
  /** jev 命令に答えた (判定器が黙っていた場合も含む)．生成はしていない． */
  | { 種別: "判定した" }
  | { 種別: "返事した"; モデル: 文字列 };

/** 熟考のときの出力枠．思考つきのモデルは，考えるのにも枠を食う． */
const 熟考の最大トークン = 4096;

/** jev 命令の判定対象にする，直近の流れの行数． */
const 判定に見せる行数 = 12;

export async function 名指しに返事する(部品: 部品一式, 名指し: 届いた名指し): 約束<返信の結末> {
  const 返す = (本文: 文字列) => 部品.チャット.投稿する(名指し.チャンネルid, 本文, 名指し.発言id);

  return 振り分ける<返信の結末>(
    [
      {
        // ループに嵌ったチャンネルの脱出口．トークンを使わないので，意図して
        // 利用制限と予算のゲートより前に置いてある．壊れたチャンネルを直そうと
        // した人が制限で弾かれるのは，間違った転び方なので．
        条件: () => リセット命令か(名指し.本文),
        ならば: () => チャンネルを忘れる(部品, 名指し, 返す),
      },
    ],
    { どれでもなければ: () => 制限を見てから返事する(部品, 名指し, 返す) },
  );
}

function チャンネルを忘れる(
  部品: 部品一式,
  名指し: 届いた名指し,
  返す: (本文: 文字列) => 約束<無>,
): 約束<返信の結末> {
  return 部品.チャンネル記録
    .リセットする(名指し.チャンネルid, 部品.現在時刻().epochMilliseconds)
    .んで(() => 返す(定型文を選ぶ(リセットの文)))
    .んで((): 返信の結末 => ({ 種別: "リセット" }));
}

function 制限を見てから返事する(
  部品: 部品一式,
  名指し: 届いた名指し,
  返す: (本文: 文字列) => 約束<無>,
): 約束<返信の結末> {
  return 揃える([部品.利用制限.確認する(名指し.発言者id), 部品.予算番.許すか()]).んで(
    ([判定, 予算]) =>
      振り分ける<返信の結末>(
        [
          {
            条件: () => 否定(判定.許すか),
            ならば: () =>
              返す(定型文を選ぶ(利用制限の文, { 分: 判定.再開まで分 })).んで((): 返信の結末 => ({
                種別: "利用制限",
              })),
          },
          {
            条件: () => 否定(予算.許すか),
            ならば: () =>
              返す(定型文を選ぶ(予算超過の文)).んで((): 返信の結末 => ({ 種別: "予算切れ" })),
          },
        ],
        { どれでもなければ: () => 実際に返事する(部品, 名指し, 返す) },
      ),
  );
}

function 実際に返事する(
  部品: 部品一式,
  名指し: 届いた名指し,
  返す: (本文: 文字列) => 約束<無>,
): 約束<返信の結末> {
  const 命令 = Jev命令を読む(名指し.本文);

  return もし(等しい(命令, 未定義), {
    であれば: () =>
      部品.チャット
        .入力中にする(名指し.チャンネルid, () => 一言を組み立てる(部品, 名指し))
        .んで(({ 本文, 費用ドル, モデル }) =>
          部品.予算番
            .記録する(費用ドル)
            .んで(() => 返す(本文))
            .んで((): 返信の結末 => ({ 種別: "返事した", モデル })),
        ),
    // 利用制限と予算の門は，もう通っている．判定は安いが，ただではない．
    でなければ: () =>
      部品.チャット
        .入力中にする(名指し.チャンネルid, () => Jevに訊く(部品, 名指し, 命令!))
        .んで((本文) => 返す(本文))
        .んで((): 返信の結末 => ({ 種別: "判定した" })),
  });
}

/** jev 命令 — 判定器の答えを，生成を挟まずにそのまま言う． */
function Jevに訊く(部品: 部品一式, 名指し: 届いた名指し, 命令: Jev命令): 約束<文字列> {
  // 判別可能ユニオンの絞り込みは，関数越しの型述語では効かない．ここは素の === で見る．
  return 命令.種別 === "使い方"
    ? すぐ返す(Jev命令の使い方)
    : 判定の対象を決める(部品, 名指し)
        .んで((状態) =>
          // 名指しで頼まれたのだから，休んでいても一度は起こしてみる．
          判定を仰ぐ(部品, 状態, { 問い: 命令.問い }, { 休みを無視するか: 真 }),
        )
        .んで((結果) => {
          const 答え = 結果?.答え一覧["問い"];

          return もし(等しい(答え, 未定義), {
            であれば: () => 定型文を選ぶ(判定不能の文),
            でなければ: () => Jevの答えを言う(命令.問い, 答え!, 結果!.モデル),
          });
        });
}

/** 返信に付けた命令ならその発言を，そうでなければ直近の流れを判定する． */
function 判定の対象を決める(部品: 部品一式, 名指し: 届いた名指し): 約束<文字列> {
  return もし<約束<文字列>>(等しい(名指し.返信先, 未定義), {
    であれば: () =>
      揃える([
        部品.チャット.直近の発言(名指し.チャンネルid, 30).しくじったら(() => []),
        部品.チャンネル記録.リセット時刻(名指し.チャンネルid),
      ]).んで(([取得, リセット時刻]) =>
        状態を書く([
          [
            "会話の流れ",
            会話ログを組み立てる(リセット後に絞る(取得, リセット時刻), {
              自分のid: 部品.自分のid,
              除外するid: 名指し.発言id,
              上限: 判定に見せる行数,
            }) || "(まだ誰も何も言っていない)",
          ],
        ]),
      ),
    でなければ: () =>
      すぐ返す(状態を書く([["対象の発言", `${名指し.返信先!.発言者名}: ${名指し.返信先!.本文}`]])),
  });
}

/** 会話ログ・記憶・見立て・裏取りを集めて，一言を作らせる． */
function 一言を組み立てる(部品: 部品一式, 名指し: 届いた名指し) {
  // 直近の履歴が kawaiko の会話記憶そのもの．広めに取る: よく似た自分の発言は
  // 会話ログを組み立てる側で畳まれて消えるため．
  return 揃える([
    部品.チャット.直近の発言(名指し.チャンネルid, 30).しくじったら(() => []),
    部品.チャンネル記録.リセット時刻(名指し.チャンネルid),
    // サーバー単位の長期記憶．チャンネルのリセットでは消えない．いま話している
    // 相手について知っていることを先頭に寄せてある．
    部品.記憶庫.生きている事実(名指し.サーバーid, { 主語id: 名指し.発言者id }),
    // 貼られた画像とファイル．読めたものは指示文へ，画像は目のある提供者へ．
    添付を読み込む(部品.添付読み, 名指し.添付一覧),
  ]).んで(([取得, リセット時刻, 事実一覧, 添付]) => {
    const 直近 = リセット後に絞る(取得, リセット時刻);
    const 自分の直近発言 = 自分の直近発言を集める(直近, 部品.自分のid, 回避する件数);
    const 会話ログ = 会話ログを組み立てる(直近, {
      自分のid: 部品.自分のid,
      除外するid: 名指し.発言id,
      上限: 12,
    });

    // 見立てが先．裏を取りに行くかも，どのモデルに当てるかも，これで決まる．
    return 見立てをつける(部品, 名指し, 会話ログ).んで((見立て) =>
      部品.調査係.調べる(名指し.本文, 見立て.調べるか).んで((参考情報) => {
        // 乱心は雑談のときだけ．正解のある問いの最中に狂われると，ただ役に立たない．
        const 乱心か = 等しい(見立て.構え, "反射") && 乱心するか(部品.乱心の確率, 部品.乱数);
        const 熟考か = 等しい(見立て.構え, "熟考");

        記す(`返信: 構え=${見立て.構え} 調べる=${文字列(見立て.調べるか)} 乱心=${文字列(乱心か)}`);

        return 重複を避けて発話する(
          部品.発話器,
          {
            指示書: 人格指示書を組み立てる(),
            画像一覧: 添付.画像一覧,
            指示文: 名指しへの指示文を組み立てる({
              時刻の表示: 日本時間の表示(部品.現在時刻()),
              時: 日本時間の時(部品.現在時刻()),
              相手の名前: 名指し.相手の名前,
              問いかけ: 名指し.本文,
              会話ログ,
              参考情報,
              添付一覧: 添付.読んだ一覧,
              事実一覧,
              自分の直近発言,
              乱数: 部品.乱数,
              構え: 見立て.構え,
              乱心か,
            }),
            構え: 見立て.構え,
            深さ: 熟考か ? "high" : "medium",
            最大トークン: 熟考か ? 熟考の最大トークン : 1024,
          },
          自分の直近発言,
          検品を用意する(部品, 名指し, 見立て, 会話ログ),
        );
      }),
    );
  });
}

/** 判定器に訊いて，構えと，調べるかを決める．訊けなければ決定的な合図へ落ちる． */
function 見立てをつける(部品: 部品一式, 名指し: 届いた名指し, 会話ログ: 文字列): 約束<見立て> {
  // 本文が無い (メンションだけ) なら，訊くまでもない．
  return (
    空か(名指し.本文)
      ? すぐ返す(未定義)
      : 判定してもらう(
          部品,
          見立ての状態({ 会話ログ, 相手の名前: 名指し.相手の名前, 問いかけ: 名指し.本文 }),
          見立ての問い,
        )
  ).んで((答え) => 見立てる(答え, 名指し.本文, 会話ログ));
}

/**
 * 出来た一言を検品する口．要らない場面では未定義 (= 検品しない):
 *
 * - 構えが「反射」— 雑談に「応じているか」は無い．鼻で笑うのも立派な返事
 * - 添付がある — 判定器には画像もファイルも見えていないので，見えている側の返事を
 *   見えていない側が裁くことになる
 */
function 検品を用意する(
  部品: 部品一式,
  名指し: 届いた名指し,
  見立て: 見立て,
  会話ログ: 文字列,
): 省略可<検品> {
  return もし(等しい(見立て.構え, "反射") || 否定(空か(名指し.添付一覧)), {
    であれば: (): 省略可<検品> => 未定義,
    でなければ: (): 省略可<検品> => (返事) =>
      判定してもらう(
        部品,
        検品の状態({
          会話ログ,
          相手の名前: 名指し.相手の名前,
          問いかけ: 名指し.本文,
          返事,
        }),
        検品の問い,
      ).んで(検品に通ったか),
  });
}
