/** kawaiko 宛ての発言．ゲートウェイの生の payload から正規化したもの． */
export interface 届いた名指し {
  発言id: 文字列;
  チャンネルid: 文字列;
  サーバーid: 文字列;
  発言者id: 文字列;
  相手の名前: 文字列;
  /** 自分宛てのメンションタグを取り除いた本文． */
  本文: 文字列;
  /** 添えられていた画像やファイル． */
  添付一覧: 読み取り専用配列<添付>;
}

export type 返信の結末 =
  | { 種別: "リセット" }
  | { 種別: "絵を描いた"; 成功か: 真偽; 理由?: 省略可<文字列> }
  | { 種別: "利用制限" }
  | { 種別: "予算切れ" }
  | { 種別: "返事した"; モデル: 文字列 };

export async function 名指しに返事する(部品: 部品一式, 名指し: 届いた名指し): 約束<返信の結末> {
  const 返す = (本文: 文字列) => 部品.チャット.投稿する(名指し.チャンネルid, 本文, 名指し.発言id);

  return 振り分ける<返信の結末>(
    [
      {
        // ループに嵌ったチャンネルの脱出口．トークンを使わないので，意図して
        // 利用制限と予算のゲートより前に置いてある．壊れたチャンネルを直そうと
        // した人が制限で弾かれるのは，間違った転び方なので．
        条件: () => リセット命令か(名指し.本文),
        ならば: () => チャンネルを忘れる(部品, 名指し, 返す),
      },
    ],
    { どれでもなければ: () => 制限を見てから返事する(部品, 名指し, 返す) },
  );
}

function チャンネルを忘れる(
  部品: 部品一式,
  名指し: 届いた名指し,
  返す: (本文: 文字列) => 約束<無>,
): 約束<返信の結末> {
  return 部品.チャンネル記録
    .リセットする(名指し.チャンネルid, 部品.現在時刻().epochMilliseconds)
    .んで(() => 返す(定型文を選ぶ(リセットの文)))
    .んで((): 返信の結末 => ({ 種別: "リセット" }));
}

function 制限を見てから返事する(
  部品: 部品一式,
  名指し: 届いた名指し,
  返す: (本文: 文字列) => 約束<無>,
): 約束<返信の結末> {
  return 揃える([部品.利用制限.確認する(名指し.発言者id), 部品.予算番.許すか()]).んで(
    ([判定, 予算]) =>
      振り分ける<返信の結末>(
        [
          {
            条件: () => 否定(判定.許すか),
            ならば: () =>
              返す(定型文を選ぶ(利用制限の文, { 分: 判定.再開まで分 })).んで((): 返信の結末 => ({
                種別: "利用制限",
              })),
          },
          {
            条件: () => 否定(予算.許すか),
            ならば: () =>
              返す(定型文を選ぶ(予算超過の文)).んで((): 返信の結末 => ({ 種別: "予算切れ" })),
          },
        ],
        { どれでもなければ: () => 言葉か絵かを決める(部品, 名指し, 返す) },
      ),
  );
}

/**
 * 「描いて」と言われていて，描ける構成なら描く．それ以外は言葉で返す．
 *
 * 利用制限と予算の見張りを通ったあとに置いてある．絵も無料枠を食べるので，
 * 普通の返事と同じ門をくぐらせる．
 */
function 言葉か絵かを決める(
  部品: 部品一式,
  名指し: 届いた名指し,
  返す: (本文: 文字列) => 約束<無>,
): 約束<返信の結末> {
  const 頼み = 描く頼みか(名指し.本文);

  return もし<約束<返信の結末>>(等しくない(頼み, 未定義) && 部品.絵描き.使えるか, {
    であれば: () =>
      絵を描いて返す(部品, 名指し, 頼み!, 返す).んで((結末): 返信の結末 => ({
        種別: "絵を描いた",
        ...結末,
      })),
    でなければ: () => 実際に返事する(部品, 名指し, 返す),
  });
}

function 実際に返事する(
  部品: 部品一式,
  名指し: 届いた名指し,
  返す: (本文: 文字列) => 約束<無>,
): 約束<返信の結末> {
  return 部品.チャット
    .入力中にする(名指し.チャンネルid, () => 一言を組み立てる(部品, 名指し))
    .んで(({ 本文, 費用ドル, モデル }) =>
      部品.予算番
        .記録する(費用ドル)
        .んで(() => 返す(本文))
        .んで((): 返信の結末 => ({ 種別: "返事した", モデル })),
    );
}

/** 会話ログ・記憶・裏取りを集めて，一言を作らせる． */
function 一言を組み立てる(部品: 部品一式, 名指し: 届いた名指し) {
  // 直近の履歴が kawaiko の会話記憶そのもの．広めに取る: よく似た自分の発言は
  // 会話ログを組み立てる側で畳まれて消えるため．
  return 揃える([
    部品.チャット.直近の発言(名指し.チャンネルid, 30).しくじったら(() => []),
    部品.チャンネル記録.リセット時刻(名指し.チャンネルid),
    // サーバー単位の長期記憶．チャンネルのリセットでは消えない．いま話している
    // 相手について知っていることを先頭に寄せてある．
    部品.記憶庫.生きている事実(名指し.サーバーid, { 主語id: 名指し.発言者id }),
    // 調べ物が要るかを決め，要るなら引いて，有望なら開いて読むところまで．
    調べものをする(部品, 名指し),
    // 貼られた画像とファイル．読めたものは指示文へ，画像は目のある提供者へ．
    添付を読み込む(部品.添付読み, 名指し.添付一覧),
  ]).んで(([取得, リセット時刻, 事実一覧, 調べもの, 添付]) => {
    const 直近 = リセット後に絞る(取得, リセット時刻);
    const 自分の直近発言 = 自分の直近発言を集める(直近, 部品.自分のid, 回避する件数);

    return 重複を避けて発話する(
      部品.発話器,
      {
        指示書: 人格指示書を組み立てる(),
        画像一覧: 添付.画像一覧,
        // 調べ物が要ると決まった回だけ，提供者の web 検索も許す．
        検索を許す: 調べもの.調べたか,
        指示文: 名指しへの指示文を組み立てる({
          時刻の表示: 日本時間の表示(部品.現在時刻()),
          時: 日本時間の時(部品.現在時刻()),
          // 引いて開いた回は，一言で切らない．
          調べたか: 調べもの.調べたか,
          相手の名前: 名指し.相手の名前,
          問いかけ: 名指し.本文,
          会話ログ: 会話ログを組み立てる(直近, {
            自分のid: 部品.自分のid,
            除外するid: 名指し.発言id,
            上限: 12,
          }),
          参考情報: 調べもの.抜粋,
          頁一覧: 調べもの.頁一覧,
          添付一覧: 添付.読んだ一覧,
          事実一覧,
          自分の直近発言,
          乱数: 部品.乱数,
        }),
        深さ: "medium",
        最大トークン: 1024,
      },
      自分の直近発言,
    );
  });
}

/** 調べ物の結末．指示文へ載せるものと，実際に調べたかどうか． */
interface 調べものの結末 {
  調べたか: 真偽;
  抜粋: 文字列;
  頁一覧: 配列<読んだ頁>;
  /** 開く前の候補．覗き見のためだけに持ち帰る． */
  候補: 読み取り専用配列<文字列>;
}

/**
 * 調べ物の道案内から，実際に読むまで．
 *
 * 貼られた URL があるなら，それが最優先 — 相手が「これ」と指したものより
 * 確かな手がかりは無い．無ければ道案内に判断させ，要ると出たときだけ引きに行く．
 * 引いた先のうち有望なものは，抜粋で終わらせず**実際に開いて読む**．
 */
function 調べものをする(部品: 部品一式, 名指し: 届いた名指し): 約束<調べものの結末> {
  const 貼られた = 貼られた場所(名指し.本文);

  return もし<約束<調べものの結末>>(否定(空か(貼られた)), {
    // 相手が指した先だけ読む．そこに答えがあるなら検索は要らない．
    であれば: () =>
      頁を読む(部品, 貼られた).んで((頁一覧): 調べものの結末 => ({
        調べたか: 真,
        抜粋: "",
        頁一覧,
        候補: 貼られた,
      })),
    でなければ: () => 検索から調べる(部品, 名指し.本文),
  });
}

function 検索から調べる(部品: 部品一式, 問いかけ: 文字列): 約束<調べものの結末> {
  return 調べ方を決める(部品, 問いかけ).んで((調べ方) => 決めた調べ方で調べる(部品, 調べ方));
}

/** 決まった調べ方で，引いて，開く． */
export function 決めた調べ方で調べる(部品: 部品一式, 調べ方: 調べ方): 約束<調べものの結末> {
  return もし<約束<調べものの結末>>(否定(調べ方.調べるか), {
    であれば: () => すぐ返す({ 調べたか: 偽, 抜粋: "", 頁一覧: [], 候補: [] }),
    でなければ: () =>
      部品.調査係.調べる(調べ方.検索語).んで((結果) =>
        頁を読む(部品, 結果.候補).んで((頁一覧): 調べものの結末 => ({
          調べたか: 真,
          抜粋: 結果.抜粋,
          頁一覧,
          候補: 結果.候補,
        })),
      ),
  });
}

/**
 * 安いモデルに決めさせる．使えないなら当て推量へ落ちる．
 *
 * **どちらかが「要る」と言えば調べる**．3B のモデルの判断はぶれる — 同じ
 * 「ryoppippi について教えて」で，はい と いいえ の両方を返すのを実測した．
 * 調べ損ねると「知らない」で終わってしまい，そちらのほうがずっと悪い．
 * 余分に引くほうの損は，数百 ms と無料枠の端数だけ．
 *
 * 検索語のほうはモデルの答えを優先する — そこはモデルのほうが当てる．
 */
export function 調べ方を決める(部品: 部品一式, 問いかけ: 文字列): 約束<調べ方> {
  const 当て推量 = 当て推量の調べ方(問いかけ);

  return もし<約束<省略可<調べ方>>>(部品.道案内.使えるか, {
    であれば: () => 部品.道案内.調べ方を決める(問いかけ),
    でなければ: () => すぐ返す(未定義),
  }).んで((決まった) =>
    もし(等しくない(決まった, 未定義), {
      であれば: (): 調べ方 => ({
        調べるか: 決まった!.調べるか || 当て推量.調べるか,
        検索語: もし(空か(決まった!.検索語), {
          であれば: () => 当て推量.検索語,
          でなければ: () => 決まった!.検索語,
        }),
      }),
      でなければ: () => 当て推量,
    }),
  );
}

/**
 * 候補を開いて読む．
 *
 * 読めなかったものは黙って落とす — ページが開けないことは，返事をしない理由には
 * ならない．何本開くかは 核/参照.ts が絞っている (ブラウザの時間は有限)．
 */
function 頁を読む(部品: 部品一式, 候補: 読み取り専用配列<文字列>): 約束<配列<読んだ頁>> {
  const 行き先一覧 = もし(部品.頁読み.使えるか, {
    であれば: () => 取り出す(絞る(候補, 読みに行ってよいか), 0, 一度に読む数),
    でなければ: (): 読み取り専用配列<文字列> => [],
  });

  return 揃える(写す(行き先一覧, (場所) => 部品.頁読み.読む(場所))).んで((読めた) =>
    絞る(読めた, (頁): 頁 is 読んだ頁 => 等しくない(頁, 未定義)),
  );
}

/**
 * 調べ物の経路を，答えを作らずに覗く．
 *
 * 「調べたはずなのに知らないと言う」が起きたとき，道案内が要らないと言ったのか，
 * 引いて何も出なかったのか，出たのに使わなかったのかで直し方がまるで違う．
 * Discord へは何も出さない．認可の向こう側．
 */
export function 調べものを覗く(部品: 部品一式, 問いかけ: 文字列): 約束<不明> {
  const 貼られた = 貼られた場所(問いかけ);

  // 決めるのは 1 回だけ．2 回呼ぶと，覗いている判断と実際に使う判断が別物になる
  // (実際にそうなっていて，はい と いいえ が同じ画面に並んだ)．
  return 調べ方を決める(部品, 問いかけ).んで((調べ方) =>
    決めた調べ方で調べる(部品, 調べ方).んで((調べもの) => ({
      問いかけ,
      貼られた場所: 貼られた,
      道案内: {
        使えるか: 部品.道案内.使えるか,
        生の返事: 部品.道案内.直前の返事(),
        ...調べ方,
      },
      調べたか: 調べもの.調べたか,
      検索の抜粋: 調べもの.抜粋,
      頁読みが使えるか: 部品.頁読み.使えるか,
      頁の躓き: 部品.頁読み.直前の躓き(),
      開く候補: 調べもの.候補,
      開いた頁: 写す(調べもの.頁一覧, (頁) => ({
        場所: 頁.場所,
        文字数: 長さ(頁.中身),
        頭: 切り出す(頁.中身, 0, 200),
      })),
    })),
  );
}
