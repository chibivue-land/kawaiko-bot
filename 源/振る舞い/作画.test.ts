import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 名指しに返事する } from "./返信";
import type { 届いた名指し } from "./返信";
import { 作画しくじりの文 } from "../核/定型文";
import { 偽の発話器を作る, 偽の絵描きを作る, 偽の部品一式を作る } from "../試験/偽物";
import { 偽, 新しい例外, 真 } from "../共通/型";
import { いずれか, 長さ } from "../共通/関数";
import { すぐしくじる } from "../共通/約束";

const 名指し: 届いた名指し = {
  発言id: "発言-9",
  チャンネルid: "ちゃんねる-1",
  サーバーid: "サーバー-1",
  発言者id: "利用者-1",
  相手の名前: "ubugeeei",
  本文: "鴨鍋の絵を描いて",
  添付一覧: [],
};

const 下書き = "絵: a duck hotpot on a portable stove, warm light\n一言: 鍋にした";

仕様("絵を描いて返す", () => {
  検証("頼まれたら，絵を 1 枚出す", () => {
    const 絵描き = 偽の絵描きを作る();
    const 部品 = 偽の部品一式を作る({ 発話器: 偽の発話器を作る([下書き]), 絵描き });

    return 名指しに返事する(部品, 名指し).んで((結末) => {
      期待(結末).と等しい({ 種別: "絵を描いた", 成功か: 真 });
      // 言葉のモデルが訳した英語のプロンプトが，そのまま画像モデルへ渡る．
      期待(絵描き.頼まれた指示).と等しい(["a duck hotpot on a portable stove, warm light"]);
      期待(部品.チャット.出した絵).の形をしている([
        { チャンネルid: "ちゃんねる-1", 本文: "鍋にした" },
      ]);
    });
  });

  検証("お題は指示文へ渡る", () => {
    const 発話器 = 偽の発話器を作る([下書き]);
    const 部品 = 偽の部品一式を作る({ 発話器 });

    return 名指しに返事する(部品, 名指し).んで(() => {
      期待(発話器.受け取った指示文[0]!).を含む("鴨鍋");
      期待(発話器.受け取った指示文[0]!).を含む("ubugeeei");
    });
  });

  検証("言葉と絵の費用を両方あわせて計上する", () => {
    const 部品 = 偽の部品一式を作る({ 発話器: 偽の発話器を作る([下書き]) });

    return 名指しに返事する(部品, 名指し).んで(() => {
      // 発話 0.001 + 絵 0.0006．
      期待(長さ(部品.使った額)).である(1);
      期待(部品.使った額[0]!).とほぼ等しい(0.0016, 6);
    });
  });

  検証("絵の指示が読めなければ，描けなかったと言う", () => {
    const 絵描き = 偽の絵描きを作る();
    const 部品 = 偽の部品一式を作る({ 発話器: 偽の発話器を作る(["わかりません"]), 絵描き });

    return 名指しに返事する(部品, 名指し).んで(() => {
      期待(長さ(絵描き.頼まれた指示)).である(0);
      期待(いずれか(作画しくじりの文, (文) => 文 === 部品.チャット.投稿済み[0]!.本文)).である(真);
    });
  });

  検証("画像モデルが転んでも，黙って消えない", () => {
    const 絵描き = 偽の絵描きを作る({
      描く: () => すぐしくじる(新しい例外("neuron が尽きた")),
    });
    const 部品 = 偽の部品一式を作る({ 発話器: 偽の発話器を作る([下書き]), 絵描き });

    return 名指しに返事する(部品, 名指し).んで(() => {
      期待(いずれか(作画しくじりの文, (文) => 文 === 部品.チャット.投稿済み[0]!.本文)).である(真);
      // 出せなかったものに金は払わない．
      期待(部品.使った額).と等しい([]);
    });
  });

  検証("絵描きが繋がっていなければ，普通に言葉で返す", () => {
    const 部品 = 偽の部品一式を作る({
      発話器: 偽の発話器を作る(["鍋の話ね"]),
      絵描き: 偽の絵描きを作る({ 使えるか: 偽 }),
    });

    return 名指しに返事する(部品, 名指し).んで((結末) => {
      期待(結末.種別).である("返事した");
      期待(部品.チャット.投稿済み[0]!.本文).である("鍋の話ね");
    });
  });

  検証("絵の頼みでない発言は，これまでどおり言葉で返す", () => {
    const 絵描き = 偽の絵描きを作る();
    const 部品 = 偽の部品一式を作る({ 発話器: 偽の発話器を作る(["ふーん"]), 絵描き });

    return 名指しに返事する(部品, { ...名指し, 本文: "おはよう" }).んで((結末) => {
      期待(結末.種別).である("返事した");
      期待(長さ(絵描き.頼まれた指示)).である(0);
    });
  });
});
