/** これより古い発言には割り込まない． */
const 割り込める古さ = 3 * 3_600_000;

export async function 横槍を入れる(
  部品: 部品一式,
  設定?: { 強制するか?: 省略可<boolean> },
): 約束<実行結果> {
  if (!設定?.強制するか && !投稿するか(部品.横槍の確率, 部品.乱数)) {
    記す("横槍: 確率ゲートで見送り");
    return { 成功か: true, 省略した理由: "確率" };
  }

  const { 許すか, 使用済みドル } = await 部品.予算番.許すか();
  if (!許すか) {
    注意(`横槍: 月の予算超過 (約 $${使用済みドル.toFixed(2)}) のため見送り`);
    return { 成功か: true, 省略した理由: "予算" };
  }

  try {
    const モデル = await 割り込む(部品);
    await 部品.予算番.仕事を終える("横槍", true, undefined, モデル);
    return { 成功か: true };
  } catch (躓き) {
    異常("横槍に失敗:", 躓き);
    const 要約 = 失敗を要約する(躓き);
    await 部品.予算番.仕事を終える("横槍", false, 要約);
    return { 成功か: false, 異常: 要約 };
  }
}

/** 絡む価値のある発言 — 新しくて，人間で，まだ kawaiko 宛てになっていないもの． */
export function 絡む相手を選ぶ(
  発言一覧: 読み取り専用配列<発言>,
  設定: { 自分のid: 文字列; 現在: 数値 },
): 配列<発言> {
  return 発言一覧.filter(
    (発言) =>
      !発言.bot発言か &&
      発言.本文.trim().length > 0 &&
      // メンションはゲートウェイ側が答える．二重に絡まない．
      !発言.本文.includes(`<@${設定.自分のid}>`) &&
      設定.現在 - (エポックミリ秒(発言.時刻) ?? 0) < 割り込める古さ,
  );
}

async function 割り込む(部品: 部品一式): 約束<省略可<文字列>> {
  const チャンネルid = 部品.住処のチャンネルid;
  const 発言一覧 = リセット後に絞る(
    await 部品.チャット.直近の発言(チャンネルid),
    await 部品.チャンネル記録.リセット時刻(チャンネルid),
  );
  const 候補 = 絡む相手を選ぶ(発言一覧, {
    自分のid: 部品.自分のid,
    現在: 部品.現在時刻().epochMilliseconds,
  });
  if (候補.length === 0) {
    記す("横槍: 絡めそうな人間の発言が無い");
    return undefined;
  }

  const 対象 = 候補[数学.floor(部品.乱数() * 候補.length)]!;
  const 会話ログ = 会話ログを組み立てる(発言一覧, {
    自分のid: 部品.自分のid,
    除外するid: 対象.id,
    上限: 8,
  });
  const 自分の直近発言 = 自分の直近発言を集める(発言一覧, 部品.自分のid, 回避する件数);
  const サーバーid = await 部品.チャット.サーバーを引く(チャンネルid);
  const 事実一覧 = サーバーid
    ? await 部品.記憶庫.生きている事実(サーバーid, { 主語id: 対象.発言者id })
    : [];

  const { 本文, 費用ドル, モデル } = await 部品.チャット.入力中にする(チャンネルid, () =>
    重複を避けて発話する(
      部品.発話器,
      {
        指示書: 人格指示書を組み立てる(),
        指示文: 横槍の指示文を組み立てる({
          時刻の表示: 日本時間の表示(部品.現在時刻()),
          相手の名前: 対象.発言者名,
          対象の発言: 対象.本文,
          会話ログ,
          事実一覧,
          自分の直近発言,
          乱数: 部品.乱数,
        }),
        深さ: "low",
        最大トークン: 2048,
      },
      自分の直近発言,
    ),
  );

  await 部品.予算番.記録する(費用ドル);
  await 部品.チャット.投稿する(チャンネルid, 本文, 対象.id);
  記す(`横槍: ${対象.id} に ${モデル} で返信 (約 $${費用ドル.toFixed(4)})`);
  return モデル;
}
