/** これより古い発言には割り込まない． */
const 割り込める古さ = 3 * 3_600_000;

export async function 横槍を入れる(
  部品: 部品一式,
  設定?: 省略可<{ 強制するか?: 省略可<真偽> }>,
): 約束<実行結果> {
  return 振り分ける<実行結果>(
    [
      {
        条件: () => 否定(設定?.強制するか) && 否定(投稿するか(部品.横槍の確率, 部品.乱数)),
        ならば: () => {
          記す("横槍: 確率ゲートで見送り");

          return { 成功か: 真, 省略した理由: "確率" };
        },
      },
    ],
    { どれでもなければ: () => 予算を見てから割り込む(部品) },
  );
}

function 予算を見てから割り込む(部品: 部品一式): 約束<実行結果> {
  return 部品.予算番.許すか().んで(({ 許すか, 使用済みドル }) =>
    振り分ける<実行結果>(
      [
        {
          条件: () => 否定(許すか),
          ならば: () => {
            注意(`横槍: 月の予算超過 (約 $${小数で書く(使用済みドル, 2)}) のため見送り`);

            return { 成功か: 真, 省略した理由: "予算" };
          },
        },
      ],
      {
        どれでもなければ: () =>
          試みる<実行結果>({
            実行: () =>
              割り込む(部品)
                .んで((モデル) => 部品.予算番.仕事を終える("横槍", 真, 未定義, モデル))
                .んで(() => ({ 成功か: 真 })),
            しくじったら: (躓き) => {
              異常("横槍に失敗:", 躓き);
              const 要約 = 失敗を要約する(躓き);

              return 部品.予算番
                .仕事を終える("横槍", 偽, 要約)
                .んで(() => ({ 成功か: 偽, 異常: 要約 }));
            },
          }),
      },
    ),
  );
}

/** 絡む価値のある発言 — 新しくて，人間で，まだ kawaiko 宛てになっていないもの． */
export function 絡む相手を選ぶ(
  発言一覧: 読み取り専用配列<発言>,
  設定: { 自分のid: 文字列; 現在: 数値 },
): 配列<発言> {
  return 絞る(
    発言一覧,
    (発言) =>
      否定(発言.bot発言か) &&
      否定(空か(前後の空白を落とす(発言.本文))) &&
      // メンションはゲートウェイ側が答える．二重に絡まない．
      否定(含む(発言.本文, `<@${設定.自分のid}>`)) &&
      より小さい(設定.現在 - (エポックミリ秒(発言.時刻) ?? 0), 割り込める古さ),
  );
}

function 割り込む(部品: 部品一式): 約束<省略可<文字列>> {
  const チャンネルid = 部品.住処のチャンネルid;

  return 揃える([
    部品.チャット.直近の発言(チャンネルid),
    部品.チャンネル記録.リセット時刻(チャンネルid),
  ]).んで(([取得, リセット時刻]) => {
    const 発言一覧 = リセット後に絞る(取得, リセット時刻);
    const 候補 = 絡む相手を選ぶ(発言一覧, {
      自分のid: 部品.自分のid,
      現在: 部品.現在時刻().epochMilliseconds,
    });

    return 振り分ける<省略可<文字列>>(
      [
        {
          条件: () => 空か(候補),
          ならば: () => {
            記す("横槍: 絡めそうな人間の発言が無い");

            return 未定義;
          },
        },
      ],
      { どれでもなければ: () => 誰かに絡む(部品, 発言一覧, 候補) },
    );
  });
}

function 誰かに絡む(
  部品: 部品一式,
  発言一覧: 読み取り専用配列<発言>,
  候補: 読み取り専用配列<発言>,
): 約束<文字列> {
  const チャンネルid = 部品.住処のチャンネルid;
  const 対象 = 候補[数学.floor(部品.乱数() * 長さ(候補))]!;
  const 自分の直近発言 = 自分の直近発言を集める(発言一覧, 部品.自分のid, 回避する件数);

  return 部品.チャット
    .サーバーを引く(チャンネルid)
    .んで((サーバーid) =>
      サーバーid ? 部品.記憶庫.生きている事実(サーバーid, { 主語id: 対象.発言者id }) : すぐ返す([]),
    )
    .んで((事実一覧) =>
      部品.チャット.入力中にする(チャンネルid, () =>
        重複を避けて発話する(
          部品.発話器,
          {
            指示書: 人格指示書を組み立てる(),
            指示文: 横槍の指示文を組み立てる({
              時刻の表示: 日本時間の表示(部品.現在時刻()),
              時: 日本時間の時(部品.現在時刻()),
              相手の名前: 対象.発言者名,
              対象の発言: 対象.本文,
              会話ログ: 会話ログを組み立てる(発言一覧, {
                自分のid: 部品.自分のid,
                除外するid: 対象.id,
                上限: 8,
              }),
              事実一覧,
              自分の直近発言,
              乱数: 部品.乱数,
            }),
            深さ: "low",
            最大トークン: 2048,
          },
          自分の直近発言,
        ),
      ),
    )
    .んで(({ 本文, 費用ドル, モデル }) =>
      部品.予算番
        .記録する(費用ドル)
        .んで(() => 部品.チャット.投稿する(チャンネルid, 本文, 対象.id))
        .んで(() => {
          記す(`横槍: ${対象.id} に ${モデル} で返信 (約 $${小数で書く(費用ドル, 4)})`);

          return モデル;
        }),
    );
}
