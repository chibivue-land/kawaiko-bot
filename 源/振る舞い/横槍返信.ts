/** これより古い発言には割り込まない． */
const 割り込める古さ = 3 * 3_600_000;

/**
 * 1 回の横槍で覗くチャンネルの数．
 *
 * 1 つ覗くごとに名前・履歴・リセット印の 3 往復を払う．Worker の 1 回の呼び出しで
 * 外へ出られる回数には上限があるので，賑わっているチャンネルを全部は回らない．
 */
export const 覗くチャンネルの数 = 4;

export async function 横槍を入れる(
  部品: 部品一式,
  設定?: 省略可<{ 強制するか?: 省略可<真偽> }>,
): 約束<実行結果> {
  return 振り分ける<実行結果>(
    [
      {
        条件: () => 否定(設定?.強制するか) && 否定(投稿するか(部品.横槍の確率, 部品.乱数)),
        ならば: () => {
          記す("横槍: 確率ゲートで見送り");

          return { 成功か: 真, 省略した理由: "確率" };
        },
      },
    ],
    { どれでもなければ: () => 予算を見てから割り込む(部品, 設定) },
  );
}

function 予算を見てから割り込む(
  部品: 部品一式,
  設定?: 省略可<{ 強制するか?: 省略可<真偽> }>,
): 約束<実行結果> {
  return 部品.予算番.許すか().んで(({ 許すか, 使用済みドル }) =>
    振り分ける<実行結果>(
      [
        {
          条件: () => 否定(許すか),
          ならば: () => {
            注意(`横槍: 月の予算超過 (約 $${小数で書く(使用済みドル, 2)}) のため見送り`);

            return { 成功か: 真, 省略した理由: "予算" };
          },
        },
      ],
      {
        どれでもなければ: () =>
          試みる<実行結果>({
            実行: () =>
              割り込む(部品, 設定?.強制するか)
                .んで((モデル) => 部品.予算番.仕事を終える("横槍", 真, 未定義, モデル))
                .んで(() => ({ 成功か: 真 })),
            しくじったら: (躓き) => {
              異常("横槍に失敗:", 躓き);
              const 要約 = 失敗を要約する(躓き);

              return 部品.予算番
                .仕事を終える("横槍", 偽, 要約)
                .んで(() => ({ 成功か: 偽, 異常: 要約 }));
            },
          }),
      },
    ),
  );
}

/**
 * 絡む価値のある発言 — 新しくて，人間で，kawaiko がまだ口を出していないもの．
 *
 * 横槍は返信にしないので，「この発言に返信した」はログに残らない．代わりに，
 * 自分の最新の発言より新しいものだけを拾う．一度口を出したら，それ以前の流れには
 * もう割り込まない．枠は 割り込める古さ より短い間隔で回る．
 * 返信済みの印も見る．名指しへの返事は返信のままなので，そちらは印が残る．
 */
export function 絡む相手を選ぶ(
  発言一覧: 読み取り専用配列<発言>,
  設定: { 自分のid: 文字列; 現在: 数値 },
): 配列<発言> {
  const 自分の発言 = 絞る(発言一覧, (発言) => 等しい(発言.発言者id, 設定.自分のid));
  const 自分の発言id = 写す(自分の発言, (発言) => 発言.id);
  const 返信済みの発言id = 写す(自分の発言, (発言) => 発言.返信先id);
  const 自分の最新 = 畳む(
    自分の発言,
    (最新, 発言) => 数学.max(最新, エポックミリ秒(発言.時刻) ?? 0),
    0,
  );

  return 絞る(
    発言一覧,
    (発言) =>
      否定(発言.bot発言か) &&
      否定(空か(前後の空白を落とす(発言.本文))) &&
      // 名指しと，kawaiko の発言への返信はゲートウェイ側が答える．二重に絡まない．
      否定(kawaiko宛てか(発言, 設定.自分のid, 自分の発言id)) &&
      否定(一覧に含む(返信済みの発言id, 発言.id)) &&
      より大きい(エポックミリ秒(発言.時刻) ?? 0, 自分の最新) &&
      窓の中か(発言, 設定.現在),
  );
}

/**
 * kawaiko に宛てた発言か．
 *
 * 本文の `<@id>` だけでは足りない．Discord の返信は本文にメンションを書かずに
 * 相手を鳴らすので，kawaiko の発言への返信は 言及されたid一覧 と返信先で見る．
 * 返信先が消えていて書き手が分からなくても，返信先の id が kawaiko の発言なら同じ．
 */
function kawaiko宛てか(発言: 発言, 自分のid: 文字列, 自分の発言id: 読み取り専用配列<文字列>): 真偽 {
  return (
    名指しされたか(自分のid, 発言.本文, 発言.言及されたid一覧) ||
    等しい(発言.返信先の発言者id, 自分のid) ||
    (等しくない(発言.返信先id, 未定義) && 一覧に含む(自分の発言id, 発言.返信先id!))
  );
}

/**
 * 茶化してはいけない話が流れているか．
 *
 * 絡む相手の発言だけでなく，窓の中の人間の発言を全部見る．誰かが「しんどい」と
 * 言ったすぐ後なら，別の人の雑談に茶々を入れる場面でもない．
 */
export function 流れが繊細か(発言一覧: 読み取り専用配列<発言>, 現在: 数値): 真偽 {
  return いずれか(
    発言一覧,
    (発言) => 否定(発言.bot発言か) && 窓の中か(発言, 現在) && 避ける話題か(発言.本文),
  );
}

function 窓の中か(発言: 発言, 現在: 数値): 真偽 {
  return より小さい(引く(現在, エポックミリ秒(発言.時刻) ?? 0), 割り込める古さ);
}

/**
 * 覗くチャンネルを，覗く順に並べる．
 *
 * 住処と，最近人間が喋ったチャンネル．重なりと，横槍を断られたチャンネルを除いて
 * 無作為に混ぜる — いつも同じ順に覗くと，先頭のチャンネルにしか絡まなくなる．
 */
export function 覗く順を決める(
  住処: 文字列,
  賑わっている: 読み取り専用配列<文字列>,
  除く: 読み取り専用配列<文字列>,
  乱数: () => 数値,
): 配列<文字列> {
  const 候補 = 絞る([...新しい集合([住処, ...賑わっている])], (id) => 否定(一覧に含む(除く, id)));
  const 札 = 写す(候補, (id) => ({ id, 鍵: 乱数() }));

  return 取り出す(
    写す(
      並べ替える(札, (左, 右) => 左.鍵 - 右.鍵),
      (一枚) => 一枚.id,
    ),
    0,
    覗くチャンネルの数,
  );
}

/** 絡む先が決まった 1 チャンネル． */
interface 絡む場 {
  チャンネルid: 文字列;
  発言一覧: 配列<発言>;
  候補: 配列<発言>;
}

function 割り込む(部品: 部品一式, 強制するか: 省略可<真偽>): 約束<省略可<文字列>> {
  const 現在 = 部品.現在時刻().epochMilliseconds;

  return (
    部品.賑わい
      .最近のチャンネル(引く(現在, 割り込める古さ))
      // 覚え書きが読めなくても，住処には絡める．
      .しくじったら(() => [])
      .んで((賑わっている) =>
        場を探す(
          部品,
          覗く順を決める(
            部品.住処のチャンネルid,
            賑わっている,
            部品.横槍しないチャンネルid一覧,
            部品.乱数,
          ),
        ),
      )
      .んで((場) =>
        振り分ける<省略可<文字列>>(
          [
            {
              条件: () => 等しい(場, 未定義),
              ならば: () => {
                記す("横槍: 絡めそうな人間の発言が無い");

                return 未定義;
              },
            },
            {
              // 住処に振り直すと，外を減らしたぶん住処が賑やかになる．外すだけにする．
              条件: () => 住処の外を見送るか(部品, 場, 強制するか),
              ならば: () => {
                記す(`横槍: ${場!.チャンネルid} は住処の外なので，稀にしか出ない枠で見送り`);

                return 未定義;
              },
            },
          ],
          { どれでもなければ: () => 誰かに絡む(部品, 場!) },
        ),
      )
  );
}

/**
 * 住処の外へ出る回だけ，もう一段稀にする．
 *
 * 横槍の枠そのものは住処にも外にも同じ頻度で来る．行き先が住処ならそのまま絡む．
 * 外だったときだけ 住処の外の横槍の確率 でもう一度引き，外れたらその回は誰にも絡まない．
 */
function 住処の外を見送るか(部品: 部品一式, 場: 省略可<絡む場>, 強制するか: 省略可<真偽>): 真偽 {
  return (
    等しくない(場?.チャンネルid, 未定義) &&
    等しくない(場?.チャンネルid, 部品.住処のチャンネルid) &&
    否定(強制するか) &&
    否定(投稿するか(部品.住処の外の横槍の確率, 部品.乱数))
  );
}

/** 覗く順にチャンネルを見て，絡める発言が最初に見つかったところで止まる． */
function 場を探す(部品: 部品一式, 覗く順: 読み取り専用配列<文字列>): 約束<省略可<絡む場>> {
  return 打ち切るまで繰り返す<省略可<絡む場>>(長さ(覗く順), 未定義, (_今, 回) =>
    チャンネルを覗く(部品, 覗く順[回]!).んで((場) => ({
      状態: 場,
      打ち切るか: 等しくない(場, 未定義),
    })),
  );
}

function チャンネルを覗く(部品: 部品一式, チャンネルid: 文字列): 約束<省略可<絡む場>> {
  const 現在 = 部品.現在時刻().epochMilliseconds;

  return 揃える([
    部品.チャット.チャンネル名を引く(チャンネルid),
    // 読めないチャンネルは，絡める発言が無いのと同じ．
    部品.チャット.直近の発言(チャンネルid).しくじったら(() => []),
    部品.チャンネル記録.リセット時刻(チャンネルid),
  ]).んで(([名前, 取得, リセット時刻]) => {
    const 発言一覧 = リセット後に絞る(取得, リセット時刻);
    const 候補 = 絡む相手を選ぶ(発言一覧, { 自分のid: 部品.自分のid, 現在 });

    return 振り分ける<省略可<絡む場>>(
      [
        {
          条件: () => 等しくない(名前, 未定義) && 避けるチャンネルか(名前!),
          ならば: () => {
            記す(`横槍: #${名前} は相談ごとの場所に見えるので覗かない`);

            return 未定義;
          },
        },
        {
          条件: () => 流れが繊細か(発言一覧, 現在),
          ならば: () => {
            記す(`横槍: ${チャンネルid} には茶化してはいけない話が流れているので見送り`);

            return 未定義;
          },
        },
        { 条件: () => 空か(候補), ならば: () => 未定義 },
      ],
      { どれでもなければ: () => ({ チャンネルid, 発言一覧, 候補 }) },
    );
  });
}

function 誰かに絡む(部品: 部品一式, 場: 絡む場): 約束<文字列> {
  const { チャンネルid, 発言一覧, 候補 } = 場;
  const 対象 = 候補[数学.floor(部品.乱数() * 長さ(候補))]!;
  const 自分の直近発言 = 自分の直近発言を集める(発言一覧, 部品.自分のid, 回避する件数);

  return 部品.チャット
    .サーバーを引く(チャンネルid)
    .んで((サーバーid) =>
      サーバーid ? 部品.記憶庫.生きている事実(サーバーid, { 主語id: 対象.発言者id }) : すぐ返す([]),
    )
    .んで((事実一覧) =>
      部品.チャット.入力中にする(チャンネルid, () =>
        重複を避けて発話する(
          部品.発話器,
          {
            指示書: 人格指示書を組み立てる(),
            指示文: 横槍の指示文を組み立てる({
              時刻の表示: 日本時間の表示(部品.現在時刻()),
              時: 日本時間の時(部品.現在時刻()),
              相手の名前: 対象.発言者名,
              対象の発言: 対象.本文,
              会話ログ: 会話ログを組み立てる(発言一覧, {
                自分のid: 部品.自分のid,
                除外するid: 対象.id,
                上限: 8,
              }),
              事実一覧,
              自分の直近発言,
              乱数: 部品.乱数,
            }),
            深さ: "low",
            最大トークン: 2048,
          },
          自分の直近発言,
        ),
      ),
    )
    .んで(({ 本文, 費用ドル, モデル }) =>
      部品.予算番
        .記録する(費用ドル)
        .んで(() =>
          もし<約束<無>>(横槍を見送る返事か(本文), {
            // 語の当てはめをすり抜けた繊細な話を，モデルが自分で止めた．
            であれば: () => {
              記す(`横槍: ${対象.id} は茶化す場面ではないとモデルが言うので見送り`);

              return 何もしない();
            },
            でなければ: () =>
              部品.チャット.投稿する(チャンネルid, 本文).んで(() => {
                記す(
                  `横槍: ${チャンネルid} に ${モデル} で投稿 (${対象.id} へ，約 $${小数で書く(費用ドル, 4)})`,
                );
              }),
          }),
        )
        .んで(() => モデル),
    );
}
