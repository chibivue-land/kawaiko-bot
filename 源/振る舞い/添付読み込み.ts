/**
 * 添えられた画像とファイルを，指示文へ載せられる形にする．
 *
 * どれを読むかの判断は核 (添付.ts) が持ち，取ってくるのは 添付読み ポートが持つ．
 * ここはその 2 つを繋ぐだけ — ただし「1 回の返事にどれだけ持ち込むか」の枠は
 * ここで決める．返事が遅くなるほうが，添付を全部見られないことより悪い．
 */
import type { 添付読み, 取り込んだ画像 } from "./接続口";
import { 添付の扱いを決める } from "../核/添付";
import type { 添付, 読んだ添付 } from "../核/添付";
import { 未定義 } from "../共通/型";
import type { 省略可, 約束, 読み取り専用配列, 配列 } from "../共通/型";
import { 写す, 取り出す, 絞る } from "../共通/関数";
import { 等しくない } from "../共通/演算";
import { 場合分け } from "../共通/構文";

/** 1 回の返事で見に行く添付の数．これを超えたぶんは「見えないもの」になる． */
export const 一度に読む数 = 4;

export interface 読み込んだ添付 {
  /** 指示文に並べるための，添付とその中身． */
  読んだ一覧: 配列<読んだ添付>;
  /** 目のある提供者へそのまま渡す画像． */
  画像一覧: 配列<取り込んだ画像>;
}

export function 添付を読み込む(読み: 添付読み, 一覧: 読み取り専用配列<添付>): 約束<読み込んだ添付> {
  const 見に行く分 = 取り出す(一覧, 0, 一度に読む数);

  // 添付どうしは互いを待たない．遅い 1 件で全部が止まらないように．
  return Promise.all(写す(見に行く分, (添付) => 一件を読む(読み, 添付))).んで((読めた) => ({
    読んだ一覧: [
      ...写す(読めた, (件) => 件.読んだ),
      // 枠から溢れたぶんも「添えられていた」ことだけは残す．
      ...写す(取り出す(一覧, 一度に読む数), (添付): 読んだ添付 => ({ 添付 })),
    ],
    画像一覧: 写す(
      絞る(読めた, (件) => 等しくない(件.画像, 未定義)),
      (件) => 件.画像!,
    ),
  }));
}

interface 一件の結果 {
  読んだ: 読んだ添付;
  画像?: 省略可<取り込んだ画像>;
}

function 一件を読む(読み: 添付読み, 添付: 添付): 約束<一件の結果> {
  return 場合分け(添付の扱いを決める(添付), {
    文書: () => 読み.文書を読む(添付).んで((中身) => ({ 読んだ: { 添付, 中身 } })),
    画像: () => 読み.画像を取り込む(添付).んで((画像) => ({ 読んだ: { 添付 }, 画像 })),
    // 触れないものは取りに行かない．添えられていたことだけ残る．
    触れない: () => Promise.resolve({ 読んだ: { 添付 } }),
  })!;
}
