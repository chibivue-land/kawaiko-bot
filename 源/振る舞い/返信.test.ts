/**
 * 訊かれた問いを見て答える判定器．本物と同じく，構え・裏取り・検品は別々に訊かれる．
 * 渡さなかった問いには答えない (= その問いだけ「分からない」)．
 */
function 判定器を作る(答え方: {
  考える量?: number;
  裏取り?: number;
  応じているか?: (状態: string) => number;
}) {
  return 偽の判定器を作る((依頼): 答え一覧 | undefined => {
    if ("考える量" in 依頼.問い一覧 && 答え方.考える量 !== undefined) {
      return { 考える量: { 種別: "段階", 点数: 答え方.考える量, 確信: 0.9 } };
    }

    if ("裏取り" in 依頼.問い一覧 && 答え方.裏取り !== undefined) {
      return { 裏取り: { 種別: "真偽", 確率: 答え方.裏取り } };
    }

    if ("応じているか" in 依頼.問い一覧 && 答え方.応じているか !== undefined) {
      return { 応じているか: { 種別: "真偽", 確率: 答え方.応じているか(依頼.状態) } };
    }

    return undefined;
  });
}

