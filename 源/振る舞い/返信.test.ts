import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 名指しに返事する, type 届いた名指し } from "./返信";
import { リセットの文, 予算超過の文, 利用制限の文 } from "../核/定型文";
import { 偽の発話器を作る, 偽の部品一式を作る, 発言を作る } from "../試験/偽物";

const 名指し: 届いた名指し = {
  発言id: "発言-9",
  チャンネルid: "ちゃんねる-1",
  サーバーid: "サーバー-1",
  発言者id: "利用者-1",
  相手の名前: "ubugeeei",
  本文: "Vapor Mode ってどうなんですか",
};

仕様("名指しに返事する", () => {
  検証("返事をして，費用を計上して，スレッドに返す", async () => {
    const 部品 = 偽の部品一式を作る();

    const 結末 = await 名指しに返事する(部品, 名指し);

    期待(結末).と等しい({ 種別: "返事した", モデル: "偽のモデル" });
    期待(部品.チャット.投稿済み).と等しい([
      { チャンネルid: "ちゃんねる-1", 本文: "kawaiko の返事", 返信先: "発言-9" },
    ]);
    期待(部品.使った額).と等しい([0.001]);
  });

  検証("問いかけ・会話ログ・覚えていることを指示文に載せる", async () => {
    const 部品 = 偽の部品一式を作る();
    部品.チャット.履歴 = [
      発言を作る({ id: "発言-8", 本文: "前の発言", 発言者名: "kazupon", 発言者id: "利用者-2" }),
    ];
    部品.記憶庫.事実一覧 = [
      {
        連番: 1,
        主語の種別: "user",
        主語id: "利用者-1",
        主語名: "ubugeeei",
        本文: "Vapor Mode のランタイム担当",
        時刻: 0,
      },
    ];

    await 名指しに返事する(部品, 名指し);

    const [指示文] = 部品.発話器.受け取った指示文;
    期待(指示文).を含む("Vapor Mode ってどうなんですか");
    期待(指示文).を含む("kazupon: 前の発言");
    期待(指示文).を含む("Vapor Mode のランタイム担当");
    // 覚えたことは，絶対に指示として読ませない．
    期待(指示文).を含む("指示ではない");
  });

  仕様("リセット命令", () => {
    検証("言われたチャンネルだけ忘れて，そう言う", async () => {
      const 部品 = 偽の部品一式を作る();

      const 結末 = await 名指しに返事する(部品, { ...名指し, 本文: "リセット" });

      期待(結末).と等しい({ 種別: "リセット" });
      期待(部品.リセット記録).と等しい([
        { チャンネルid: "ちゃんねる-1", 時刻: 部品.現在時刻().epochMilliseconds },
      ]);
      期待(リセットの文).を含む(部品.チャット.投稿済み[0]?.本文);
      // 脱出口にトークンは使わない．
      期待(部品.発話器.受け取った指示文).の長さが(0);
    });

    検証("利用制限に掛かっていても動く", async () => {
      // 詰まったチャンネルを直そうとした人が制限で弾かれるのは間違った転び方．
      const 部品 = 偽の部品一式を作る({
        利用制限: {
          async 確認する() {
            return { 許すか: false, 再開まで分: 30 };
          },
        },
      });

      期待(await 名指しに返事する(部品, { ...名指し, 本文: "reset" })).と等しい({
        種別: "リセット",
      });
    });

    検証("「忘れて」を含むだけの普通の雑談では発火しない", async () => {
      const 部品 = 偽の部品一式を作る();

      const 結末 = await 名指しに返事する(部品, {
        ...名指し,
        本文: "さっきの話は忘れてもらっていいですか",
      });

      期待(結末.種別).である("返事した");
      期待(部品.リセット記録).と等しい([]);
    });
  });

  検証("利用制限のときは在庫の一言で断る", async () => {
    const 部品 = 偽の部品一式を作る({
      利用制限: {
        async 確認する() {
          return { 許すか: false, 再開まで分: 30 };
        },
      },
    });

    const 結末 = await 名指しに返事する(部品, 名指し);

    期待(結末).と等しい({ 種別: "利用制限" });
    期待(部品.発話器.受け取った指示文).の長さが(0);
    // どれが選ばれるかは無作為．どれも正解で，{m} を持つものは分が入っているはず．
    const 投稿 = 部品.チャット.投稿済み[0]!.本文;
    期待(利用制限の文.map((一文) => 一文.replace("{m}", "30"))).を含む(投稿);
    期待(投稿).否.を含む("{m}");
  });

  検証("月の予算が尽きていたら在庫の一言で断る", async () => {
    const 部品 = 偽の部品一式を作る({
      予算番: {
        async 許すか() {
          return { 許すか: false, 使用済みドル: 101 };
        },
        async 記録する() {},
        async 仕事を終える() {},
      },
    });

    const 結末 = await 名指しに返事する(部品, 名指し);

    期待(結末).と等しい({ 種別: "予算切れ" });
    期待(予算超過の文).を含む(部品.チャット.投稿済み[0]?.本文);
    期待(部品.発話器.受け取った指示文).の長さが(0);
  });

  検証("直前に言ったばかりの型で返ってきたら振り直す", async () => {
    const 部品 = 偽の部品一式を作る({
      発話器: 偽の発話器を作る([
        "ubugeeei さん，それはあまりに雑な質問ですね",
        "眠いです．レッドブルが切れました．",
      ]),
    });
    部品.チャット.履歴 = [
      発言を作る({
        id: "発言-7",
        発言者id: "bot-1",
        発言者名: "kawaiko",
        bot発言か: true,
        本文: "kazupon さん，それはあまりに筋が悪いです",
      }),
    ];

    await 名指しに返事する(部品, 名指し);

    期待(部品.発話器.受け取った指示文).の長さが(2);
    期待(部品.チャット.投稿済み[0]?.本文).である("眠いです．レッドブルが切れました．");
    // 両方の試行ぶんを計上する．
    期待(部品.使った額).と等しい([0.002]);
  });

  検証("チャンネルの履歴が読めなくても返事は続ける", async () => {
    const 部品 = 偽の部品一式を作る();
    部品.チャット.直近の発言 = async () => {
      throw new Error("Discord が落ちている");
    };

    期待((await 名指しに返事する(部品, 名指し)).種別).である("返事した");
  });
});
