function 道案内を作る(調べ方: { 調べるか: boolean; 検索語: string }) {
  return { 使えるか: 真, 調べ方を決める: async () => 調べ方, 直前の返事: () => 未定義 };
}

function 調査係を作る(結果: {
  抜粋: string;
  候補: string[];
  件一覧?: Array<{ 題: string; 抜粋: string; 場所?: string }>;
}) {
  const 引いた語: string[] = [];
  // 件一覧を書かない検証は，候補をそのまま件に見立てる．
  const 件一覧 = 結果.件一覧 ?? 結果.候補.map((場所) => ({ 題: 場所, 抜粋: "", 場所 }));

  return {
    引いた語,
    調べる: async (検索語: string) => {
      引いた語.push(検索語);

      return { 抜粋: 結果.抜粋, 候補: 結果.候補, 件一覧 };
    },
  };
}

