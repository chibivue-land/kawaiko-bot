/**
 * 判定器 (Jev) を，HTTP の口から直に叩く．
 *
 * チャットの jev 命令 (返信.ts) と同じ書き方を受けるが，判定に掛ける状態は呼び出し側が
 * 文字列で渡す．手元の端末から curl で叩いて，問いの書き方や閾値を試すための口．
 * 判定が取れなかったときは，休んでいる理由も添える — ここは認可の向こうなので，
 * 提供者が返した異常の文面を見せてよい．
 */
import { 判定を仰ぐ } from "./判定";
import type { 部品一式 } from "./接続口";
import { Jevの答えを言う, Jev命令の中身を読む } from "../核/Jev命令";
import { 文字列, 未定義, 真 } from "../共通/型";
import type { 不明, 約束 } from "../共通/型";
import { 前後の空白を落とす, 空か } from "../共通/関数";
import { 等しい } from "../共通/演算";
import { もし } from "../共通/構文";
import { すぐ返す } from "../共通/約束";

export interface Jevへの問い合わせ {
  /** jev 命令の中身．«この文は煽りか» / «晩飯 [麺|米]» / «ヤバさ [低<中<高]»． */
  問いかけ: 文字列;

  /** 判定に掛ける状態． */
  状態: 文字列;
}

export type 問い合わせの結果 =
  | { 状態: 400; 本体: { 異常: 文字列 } }
  | { 状態: 503; 本体: { 異常: 文字列; 休み: 不明 } }
  | { 状態: 200; 本体: 不明 };

export function Jevに問い合わせる(
  部品: 部品一式,
  問い合わせ: Jevへの問い合わせ,
): 約束<問い合わせの結果> {
  const 命令 = Jev命令の中身を読む(問い合わせ.問いかけ);

  // 判別可能ユニオンの絞り込みは，関数越しの型述語では効かない．ここは素の === で見る．
  return 命令.種別 === "使い方" || 空か(前後の空白を落とす(問い合わせ.状態))
    ? すぐ返す<問い合わせの結果>({
        状態: 400,
        本体: { 異常: "q (問いかけ) と state (判定に掛ける状態) の両方が要る" },
      })
    : 判定を仰ぐ(部品, 問い合わせ.状態, { 問い: 命令.問い }, { 休みを無視するか: 真 }).んで(
        (結果) => {
          const 答え = 結果?.答え一覧["問い"];

          return もし<約束<問い合わせの結果>>(等しい(答え, 未定義), {
            であれば: () =>
              部品.提供者の記録.休んでいる提供者().んで((休み): 問い合わせの結果 => ({
                状態: 503,
                本体: { 異常: "判定器が答えなかった", 休み: 休み["jev"] },
              })),
            でなければ: () =>
              すぐ返す<問い合わせの結果>({
                状態: 200,
                本体: {
                  問い: 命令.問い,
                  答え,
                  言い方: Jevの答えを言う(命令.問い, 答え!, 結果!.モデル),
                  モデル: 結果!.モデル,
                  費用ドル: 結果!.費用ドル,
                },
              }),
          });
        },
      );
}
