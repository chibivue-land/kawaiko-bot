/**
 * 学習の一巡 — そのサーバーの新しい観測を，持続的な事実へ畳み込む．
 *
 * 発言ごとではなく毎時の cron で回す．おかげで生成は 1 時間に最大 1 回で済み，
 * それ以上に効くのは「1 回分がログの中で 1 つの識別子になる」こと．その単位が
 * そのままロールバックの単位で，読み取り位置は生きている回から導くので，
 * 1 回を取り消すと位置も一緒に巻き戻る．
 */
import { 発話する } from "./発話";
import { 失敗を要約する, type 実行結果, type 部品一式 } from "./接続口";
import {
  一度に読む観測数,
  学習に要る観測数,
  抽出係の指示書,
  抽出依頼を組み立てる,
  発言者索引,
  事実を読み取る,
} from "../核/学習";
import type { 文字列, 約束, 省略可 } from "../共通/型";
import { 記す, 注意, 異常 } from "../共通/記録";

export async function 学習を一巡させる(
  部品: 部品一式,
  設定?: { 強制するか?: 省略可<boolean> },
): 約束<実行結果> {
  if (!部品.記憶庫.使えるか) {
    記す("学習: 記憶庫が無いので、覚える先が無い");
    return { 成功か: true, 省略した理由: "記憶庫なし" };
  }

  const { 許すか, 使用済みドル } = await 部品.予算番.許すか();
  if (!許すか) {
    注意(`学習: 月の予算超過 (約 $${使用済みドル.toFixed(2)}) のため見送り`);
    return { 成功か: true, 省略した理由: "予算" };
  }

  try {
    const サーバー一覧 = await 部品.記憶庫.観測したサーバー();
    if (サーバー一覧.length === 0) {
      記す("学習: まだ観測したサーバーが無い");
      return { 成功か: true, 省略した理由: "観測なし" };
    }
    let モデル: 省略可<文字列>;
    for (const サーバーid of サーバー一覧) {
      モデル = (await 一つのサーバーを学ぶ(部品, サーバーid, 設定?.強制するか ?? false)) ?? モデル;
    }
    await 部品.予算番.仕事を終える("学習", true, undefined, モデル);
    return { 成功か: true };
  } catch (躓き) {
    異常("学習に失敗:", 躓き);
    const 要約 = 失敗を要約する(躓き);
    await 部品.予算番.仕事を終える("学習", false, 要約);
    return { 成功か: false, 異常: 要約 };
  }
}

async function 一つのサーバーを学ぶ(
  部品: 部品一式,
  サーバーid: 文字列,
  強制するか: boolean,
): 約束<省略可<文字列>> {
  const 読み取り位置 = await 部品.記憶庫.学習の読み取り位置(サーバーid);
  const 観測一覧 = await 部品.記憶庫.未学習の観測(サーバーid, 読み取り位置, 一度に読む観測数);
  // 閑散な時間帯はコストが出ない．新しい会話が足りなければ結論の出しようがなく，
  // モデルはそもそも呼ばれない．
  if (観測一覧.length < (強制するか ? 1 : 学習に要る観測数)) {
    記す(`学習: ${サーバーid} の未読は ${観測一覧.length} 件だけ。待つ`);
    return undefined;
  }

  const { 本文, 費用ドル, モデル } = await 発話する(部品.発話器, {
    指示書: 抽出係の指示書,
    指示文: 抽出依頼を組み立てる(観測一覧),
    深さ: "low",
    最大トークン: 512,
  });
  await 部品.予算番.記録する(費用ドル);

  const 識別子 = 部品.新しい識別子();
  const 読んだ位置 = 観測一覧[観測一覧.length - 1]!.連番;
  const 結果 = await 部品.記憶庫.学習を追記する({
    サーバーid,
    識別子,
    事実一覧: 事実を読み取る(本文, 発言者索引(観測一覧)),
    読んだ位置,
    モデル,
  });
  記す(
    `学習: ${サーバーid} 回=${識別子} 読了=${観測一覧.length} 位置=${読んだ位置} ` +
      `新規=${結果.学習} 更新=${結果.更新} 却下=${結果.却下} (約 $${費用ドル.toFixed(4)})`,
  );
  return モデル;
}
