/**
 * 学習の一巡 — そのサーバーの新しい観測を，持続的な事実へ畳み込む．
 *
 * 発言ごとではなく毎時の cron で回す．おかげで生成は 1 時間に最大 1 回で済み，
 * それ以上に効くのは「1 回分がログの中で 1 つの識別子になる」こと．その単位が
 * そのままロールバックの単位で，読み取り位置は生きている回から導くので，
 * 1 回を取り消すと位置も一緒に巻き戻る．
 */
import { 発話する } from "./発話";
import { 失敗を要約する, type 実行結果, type 部品一式 } from "./接続口";
import {
  一度に読む観測数,
  学習に要る観測数,
  抽出係の指示書,
  抽出依頼を組み立てる,
  発言者索引,
  事実を読み取る,
} from "../核/学習";
import type { 文字列, 真偽, 約束, 読み取り専用配列, 省略可 } from "../共通/型";
import { 小数で書く, 空か, 長さ } from "../共通/関数";
import { もし, 振り分ける, 試みる } from "../共通/構文";
import { 否定 } from "../共通/演算";
import { 記す, 注意, 異常 } from "../共通/記録";
import type { 観測 } from "../核/記憶";
import { 順に畳む } from "../共通/反復";

export async function 学習を一巡させる(
  部品: 部品一式,
  設定?: 省略可<{ 強制するか?: 省略可<真偽> }>,
): 約束<実行結果> {
  const 予算 = await もし(部品.記憶庫.使えるか, {
    であれば: () => 部品.予算番.許すか(),
    でなければ: async () => ({ 許すか: true, 使用済みドル: 0 }),
  });

  return 振り分ける<実行結果>(
    [
      {
        条件: () => 否定(部品.記憶庫.使えるか),
        ならば: () => {
          記す("学習: 記憶庫が無いので，覚える先が無い");

          return { 成功か: true, 省略した理由: "記憶庫なし" };
        },
      },
      {
        条件: () => 否定(予算.許すか),
        ならば: () => {
          注意(`学習: 月の予算超過 (約 $${小数で書く(予算.使用済みドル, 2)}) のため見送り`);

          return { 成功か: true, 省略した理由: "予算" };
        },
      },
    ],
    {
      どれでもなければ: () =>
        試みる<実行結果>({
          実行: () => すべてのサーバーを学ぶ(部品, 設定?.強制するか ?? false),
          しくじったら: async (躓き) => {
            異常("学習に失敗:", 躓き);
            const 要約 = 失敗を要約する(躓き);
            await 部品.予算番.仕事を終える("学習", false, 要約);

            return { 成功か: false, 異常: 要約 };
          },
        }),
    },
  );
}

async function すべてのサーバーを学ぶ(部品: 部品一式, 強制するか: 真偽): 約束<実行結果> {
  const サーバー一覧 = await 部品.記憶庫.観測したサーバー();

  return 振り分ける<実行結果>(
    [
      {
        条件: () => 空か(サーバー一覧),
        ならば: () => {
          記す("学習: まだ観測したサーバーが無い");

          return { 成功か: true, 省略した理由: "観測なし" };
        },
      },
    ],
    {
      どれでもなければ: async () => {
        const モデル = await 順に畳む<文字列, 省略可<文字列>>(
          サーバー一覧,
          async (直前, サーバーid) =>
            (await 一つのサーバーを学ぶ(部品, サーバーid, 強制するか)) ?? 直前,
          undefined,
        );

        await 部品.予算番.仕事を終える("学習", true, undefined, モデル);

        return { 成功か: true };
      },
    },
  );
}

async function 一つのサーバーを学ぶ(
  部品: 部品一式,
  サーバーid: 文字列,
  強制するか: 真偽,
): 約束<省略可<文字列>> {
  const 読み取り位置 = await 部品.記憶庫.学習の読み取り位置(サーバーid);
  const 観測一覧 = await 部品.記憶庫.未学習の観測(サーバーid, 読み取り位置, 一度に読む観測数);

  return 振り分ける<省略可<文字列>>(
    [
      {
        // 閑散な時間帯はコストが出ない．新しい会話が足りなければ結論の出しようが
        // なく，モデルはそもそも呼ばれない．
        条件: () => 長さ(観測一覧) < (強制するか ? 1 : 学習に要る観測数),
        ならば: () => {
          記す(`学習: ${サーバーid} の未読は ${長さ(観測一覧)} 件だけ．待つ`);

          return undefined;
        },
      },
    ],
    { どれでもなければ: () => 観測を事実へ畳む(部品, サーバーid, 観測一覧) },
  );
}

async function 観測を事実へ畳む(
  部品: 部品一式,
  サーバーid: 文字列,
  観測一覧: 読み取り専用配列<観測>,
): 約束<文字列> {
  const { 本文, 費用ドル, モデル } = await 発話する(部品.発話器, {
    指示書: 抽出係の指示書,
    指示文: 抽出依頼を組み立てる(観測一覧),
    深さ: "low",
    最大トークン: 512,
  });
  await 部品.予算番.記録する(費用ドル);

  const 識別子 = 部品.新しい識別子();
  const 読んだ位置 = 観測一覧[長さ(観測一覧) - 1]!.連番;
  const 結果 = await 部品.記憶庫.学習を追記する({
    サーバーid,
    識別子,
    事実一覧: 事実を読み取る(本文, 発言者索引(観測一覧)),
    読んだ位置,
    モデル,
  });

  記す(
    `学習: ${サーバーid} 回=${識別子} 読了=${長さ(観測一覧)} 位置=${読んだ位置} ` +
      `新規=${結果.学習} 更新=${結果.更新} 却下=${結果.却下} (約 $${小数で書く(費用ドル, 4)})`,
  );

  return モデル;
}
