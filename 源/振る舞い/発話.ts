/**
 * 「提供者が文字列を返した」と「kawaiko がそれを言う」の間に挟まる方針。
 *
 * これは提供者ではなく応用の関心事。どのモデルが答えたかは、その返事が指示書を
 * 漏らしたかどうかや、昨日の決め台詞を繰り返したかどうかに何の関係もない。ここに
 * 置いておけば、新しい提供者アダプタは何もせずに全部のガードを継承する。
 */
import type { 発話の依頼, 発話の結果, 発話器 } from "./接続口";
import { 反復しているか, 反復度 } from "../核/反復";
import { 指示書が漏れているか } from "../核/漏洩検知";
import { 言い直しの指示 } from "../核/指示文";
import { 受け流しの文, 反復打ち切りの文, 拒否の文, 定型文を選ぶ, 無言の文 } from "../核/定型文";
import { もし } from "../共通/構文";
import type { 文字列, 数値, 約束, 読み取り専用配列, 省略可 } from "../共通/型";
import { 数値 as 数値値 } from "../共通/型";
import { 注意 } from "../共通/記録";

/**
 * 1 回目を含めた試行回数。2 に留めてある。作り直しは毎回まるごと 1 回分の生成で、
 * 相手は小さな 1 日無料枠。それに 1 回振り直せば大半のループは切れる。
 */
const 試行回数 = 2;
/** これ以上なら、いちばんマシな候補もまだ同じ文でしかない。 */
const 完全な繰り返しとみなす点数 = 0.9;

/** 1 回だけ生成し、そのまま投稿してはいけないものを差し替える。 */
export async function 発話する(発話器: 発話器, 依頼: 発話の依頼): 約束<発話の結果> {
  const 結果 = await 発話器.発話する(依頼);
  // 指示書 (と人格コーパス) は、絶対にチャンネルへ出さない。
  if (指示書が漏れているか(結果.本文, 依頼.指示書)) {
    注意("発話: 指示書の漏洩を差し止めた");
    return { ...結果, 本文: 定型文を選ぶ(受け流しの文) };
  }
  if (結果.拒否された) return { ...結果, 本文: 定型文を選ぶ(拒否の文) };
  if (!結果.本文.trim()) return { ...結果, 本文: 定型文を選ぶ(無言の文) };
  return 結果;
}

/**
 * 発話する と同じだが、直前に言ったばかりのものは返さない。
 *
 * 指示文の会話ログには kawaiko 自身の発言が入っていて、小さいモデルはそれを
 * お手本の型として固定する。だからチャンネルが延々と同じ骨格を受け取ることになる。
 * 促しを添えて振り直し、いちばん重なりの少ない候補を採り、それでも丸写しなら
 * ループ打ち切りの一言へ逃げる。費用は試行ぶん合算するので、予算番には実際に
 * 使った額が見える。
 */
export async function 重複を避けて発話する(
  発話器: 発話器,
  依頼: 発話の依頼,
  避けたい発言: 読み取り専用配列<文字列>,
): 約束<発話の結果> {
  if (避けたい発言.length === 0) return 発話する(発話器, 依頼);

  let 最良: 省略可<発話の結果>;
  let 最良の点数 = 数値値.POSITIVE_INFINITY;
  let 費用ドル = 0;

  for (let 試行 = 0; 試行 < 試行回数; 試行++) {
    let 結果: 発話の結果;
    try {
      結果 = await 発話する(
        発話器,
        もし(試行 === 0, {
          であれば: () => 依頼,
          でなければ: () => ({ ...依頼, 指示文: `${依頼.指示文}\n\n${言い直しの指示}` }),
        }),
      );
    } catch (躓き) {
      // 振り直しはあくまで上乗せ。使える返事をそれで失ってはいけない。
      if (!最良) throw 躓き;
      注意(`発話: ${試行 + 1} 回目の振り直しに失敗。先の一言を採用する`);
      break;
    }
    費用ドル += 結果.費用ドル;
    const 点数: 数値 = 反復度(結果.本文, 避けたい発言);
    if (点数 < 最良の点数) {
      最良 = 結果;
      最良の点数 = 点数;
    }
    if (!反復しているか(結果.本文, 避けたい発言)) return { ...結果, 費用ドル };
    注意(`発話: ${試行 + 1} 回目は直近の発言と重なった (点数 ${点数.toFixed(2)})`);
  }

  const 採用 = 最良!;
  if (最良の点数 >= 完全な繰り返しとみなす点数) {
    注意("発話: どの試行も丸写しだったのでループを打ち切る");
    return { ...採用, 本文: 定型文を選ぶ(反復打ち切りの文), 費用ドル };
  }
  return { ...採用, 費用ドル };
}
