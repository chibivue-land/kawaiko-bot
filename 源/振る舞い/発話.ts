import { 前後の空白を落とす, 小数で書く, 空か, 絞る, 繋ぐ } from "../共通/関数";

/**
 * 1 回目を含めた試行回数．2 に留めてある．作り直しは毎回まるごと 1 回分の生成で，
 * 相手は小さな 1 日無料枠．それに 1 回振り直せば大半のループは切れる．
 */
const 試行回数 = 2;

/** これ以上なら，いちばんマシな候補もまだ同じ文でしかない． */
const 完全な繰り返しとみなす点数 = 0.9;

/** 1 回だけ生成し，そのまま投稿してはいけないものを差し替える． */
export function 発話する(発話器: 発話器, 依頼: 発話の依頼): 約束<発話の結果> {
  return 発話器.発話する(依頼).んで((結果) => 出してよい形に直す(結果, 依頼));
}

/** 生の一言を，そのままチャンネルへ出せる形にする． */
function 出してよい形に直す(結果: 発話の結果, 依頼: 発話の依頼): 約束<発話の結果> {
  return 振り分ける<発話の結果>(
    [
      {
        // 指示書 (と人格コーパス) は，絶対にチャンネルへ出さない．
        条件: () => 指示書が漏れているか(結果.本文, 依頼.指示書),
        ならば: () => {
          注意("発話: 指示書の漏洩を差し止めた");

          return { ...結果, 本文: 定型文を選ぶ(受け流しの文) };
        },
      },
      {
        条件: () => 結果.拒否された,
        ならば: () => ({ ...結果, 本文: 定型文を選ぶ(拒否の文) }),
      },
      {
        条件: () => 空か(前後の空白を落とす(結果.本文)),
        ならば: () => ({ ...結果, 本文: 定型文を選ぶ(無言の文) }),
      },
    ],
    { どれでもなければ: () => 結果 },
  );
}

/**
 * 作った一言が，相手の求めに応じているかを確かめる口 (核/検品.ts)．
 *
 * 呼び出し側が文脈 (相手の発言・会話の流れ) を閉じ込めて渡す．判定が取れなかった
 * ときは真を返す約束 — 検品できないことは，作り直す理由にならない．
 */
export type 検品 = (本文: 文字列) => 約束<真偽>;

/** 1 回分の試行と，その出来． */
interface 試行の記録 {
  結果: 省略可<発話の結果>;
  /** 直近の自分の発言との重なり (低いほど良い)． */
  点数: 数値;
  /** 採っている候補が検品に通っているか． */
  応じているか: 真偽;
  費用ドル: 数値;
  打ち切ったか: 真偽;
  /** 直前の試行が何で落ちたか．次の頼み方がこれで変わる． */
  直前の落ち方: { 反復か: 真偽; 検品か: 真偽 };
}

/** 検品で落ちた次の試行に与える思考の余地．思考つきのモデルは出力枠を食う． */
const 熟考の最大トークン = 4096;

/**
 * 発話する と同じだが，そのまま出すと恥ずかしいものは返さない．落とす理由は 2 つ:
 *
 * - **反復** — 直前に言ったばかりのもの．指示文の会話ログには kawaiko 自身の発言が
 *   入っていて，小さいモデルはそれをお手本の型として固定する．促しを添えて振り直す
 * - **検品** — 相手の求めに応じていないもの (しりとりで一手を出さない，質問に
 *   答えない)．構えを「熟考」へ上げて，賢いモデルに作り直させる．検品を渡された
 *   ときだけ
 *
 * いちばんマシな候補を採り，それでも丸写しならループ打ち切りの一言へ逃げる．
 * 費用は試行ぶん合算するので，予算番には実際に使った額が見える．
 */
export function 重複を避けて発話する(
  発話器: 発話器,
  依頼: 発話の依頼,
  避けたい発言: 読み取り専用配列<文字列>,
  検品?: 省略可<検品>,
): 約束<発話の結果> {
  return もし(空か(避けたい発言) && 等しい(検品, 未定義), {
    であれば: () => 発話する(発話器, 依頼),
    でなければ: () => 振り直しながら発話する(発話器, 依頼, 避けたい発言, 検品),
  });
}

function 振り直しながら発話する(
  発話器: 発話器,
  依頼: 発話の依頼,
  避けたい発言: 読み取り専用配列<文字列>,
  検品: 省略可<検品>,
): 約束<発話の結果> {
  const 初期: 試行の記録 = {
    結果: 未定義,
    点数: 数値.POSITIVE_INFINITY,
    応じているか: 偽,
    費用ドル: 0,
    打ち切ったか: 偽,
    直前の落ち方: { 反復か: 偽, 検品か: 偽 },
  };

  // 前の試行の結果で続けるかが決まるので，状態を持ち越しながら繰り返す．
  return 打ち切るまで繰り返す(試行回数, 初期, (これまで, 試行) =>
    一回振る(発話器, 依頼, 避けたい発言, 検品, 試行, これまで).んで((次) => ({
      状態: 次,
      打ち切るか: 次.打ち切ったか,
    })),
  ).んで((記録) => {
    const 採用 = 記録.結果!;

    return もし(以上(記録.点数, 完全な繰り返しとみなす点数), {
      であれば: () => {
        注意("発話: どの試行も丸写しだったのでループを打ち切る");

        return { ...採用, 本文: 定型文を選ぶ(反復打ち切りの文), 費用ドル: 記録.費用ドル };
      },
      でなければ: () => ({ ...採用, 費用ドル: 記録.費用ドル }),
    });
  });
}

/** 振り直しの頼み方．直前が何で落ちたかで変わる． */
function 振り直しの依頼(依頼: 発話の依頼, 落ち方: 試行の記録["直前の落ち方"]): 発話の依頼 {
  const 促し = 繋ぐ(
    絞る(
      [
        // 検品で落ちていないなら，これまでどおり「言い直し」だけを足す．
        落ち方.反復か || 否定(落ち方.検品か) ? 言い直しの指示 : "",
        落ち方.検品か ? 応じ直しの指示 : "",
      ],
      (節) => 否定(空か(節)),
    ),
    空行,
  );
  const 促した依頼 = { ...依頼, 指示文: `${依頼.指示文}${空行}${促し}` };

  return もし(落ち方.検品か, {
    // 応じ損ねたのは頭が足りなかったから．同じ頭でもう一度振っても同じところで転ぶ．
    であれば: (): 発話の依頼 => ({
      ...促した依頼,
      構え: "熟考",
      深さ: "high",
      最大トークン: 数学.max(依頼.最大トークン ?? 0, 熟考の最大トークン),
    }),
    でなければ: (): 発話の依頼 => 促した依頼,
  });
}

/** 1 回投げて，これまでの最良と突き合わせる． */
function 一回振る(
  発話器: 発話器,
  依頼: 発話の依頼,
  避けたい発言: 読み取り専用配列<文字列>,
  検品: 省略可<検品>,
  試行: 数値,
  これまで: 試行の記録,
): 約束<試行の記録> {
  return 試みる<省略可<発話の結果>>({
    実行: () =>
      発話する(
        発話器,
        もし(等しい(試行, 0), {
          であれば: () => 依頼,
          でなければ: () => 振り直しの依頼(依頼, これまで.直前の落ち方),
        }),
      ),
    // 振り直しはあくまで上乗せ．使える返事をそれで失ってはいけない．
    しくじったら: (躓き) =>
      もし(等しい(これまで.結果, 未定義), {
        であれば: (): 省略可<発話の結果> => しくじる(躓き),
        でなければ: (): 省略可<発話の結果> => {
          注意(`発話: ${足す(試行, 1)} 回目の振り直しに失敗．先の一言を採用する`);

          return 未定義;
        },
      }),
  }).んで((結果) =>
    もし<約束<試行の記録>>(等しい(結果, 未定義), {
      であれば: () => すぐ返す({ ...これまで, 打ち切ったか: 真 }),
      でなければ: () =>
        // 検品が無ければ，応じているものとして扱う．
        (検品 ? 検品(結果!.本文) : すぐ返す(真)).んで((応じているか) =>
          これまでと比べる(結果!, 応じているか, 避けたい発言, 試行, これまで),
        ),
    }),
  );
}

function これまでと比べる(
  結果: 発話の結果,
  応じているか: 真偽,
  避けたい発言: 読み取り専用配列<文字列>,
  試行: 数値,
  これまで: 試行の記録,
): 試行の記録 {
  const 点数 = 反復度(結果.本文, 避けたい発言);
  const 費用ドル = 足す(これまで.費用ドル, 結果.費用ドル);
  // 応じているものが先．どちらも同じなら，重なりの少ないほう．
  const 今回が勝つか = もし(等しい(応じているか, これまで.応じているか), {
    であれば: () => より小さい(点数, これまで.点数),
    でなければ: () => 応じているか,
  });
  const 最良 = もし(今回が勝つか || 等しい(これまで.結果, 未定義), {
    であれば: () => ({ 結果, 点数, 応じているか }),
    でなければ: () => ({
      結果: これまで.結果,
      点数: これまで.点数,
      応じているか: これまで.応じているか,
    }),
  });
  const 新鮮か = 否定(反復しているか(結果.本文, 避けたい発言));

  もし(新鮮か, {
    でなければ: () =>
      注意(`発話: ${試行 + 1} 回目は直近の発言と重なった (点数 ${小数で書く(点数, 2)})`),
    であれば: () => 未定義,
  });

  もし(応じているか, {
    でなければ: () => 注意(`発話: ${試行 + 1} 回目は相手の求めに応じていなかった (検品)`),
    であれば: () => 未定義,
  });

  return もし(新鮮か && 応じているか, {
    であれば: (): 試行の記録 => ({
      結果,
      点数,
      応じているか,
      費用ドル,
      打ち切ったか: 真,
      直前の落ち方: { 反復か: 偽, 検品か: 偽 },
    }),
    でなければ: (): 試行の記録 => ({
      ...最良,
      費用ドル,
      打ち切ったか: 偽,
      直前の落ち方: { 反復か: 否定(新鮮か), 検品か: 否定(応じているか) },
    }),
  });
}
