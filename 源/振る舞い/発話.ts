/**
 * 「提供者が文字列を返した」と「kawaiko がそれを言う」の間に挟まる方針．
 *
 * これは提供者ではなく振る舞いの関心事．どのモデルが答えたかは，その返事が指示書を
 * 漏らしたかどうかや，昨日の決め台詞を繰り返したかどうかに何の関係もない．ここに
 * 置いておけば，新しい提供者アダプタは何もせずに全部のガードを継承する．
 */
import { 反復しているか, 反復度 } from "../核/反復";
import { 指示書が漏れているか } from "../核/漏洩検知";
import { 言い直しの指示 } from "../核/指示文";
import { 受け流しの文, 反復打ち切りの文, 定型文を選ぶ, 拒否の文, 無言の文 } from "../核/定型文";
import type { 発話の依頼, 発話の結果, 発話器 } from "./接続口";
import { 偽, 数値, 文字列, 未定義, 真, 真偽 } from "../共通/型";
import type { 省略可, 約束, 読み取り専用配列 } from "../共通/型";
import { 前後の空白を落とす, 小数で書く, 空か } from "../共通/関数";
import { 以上, 否定, 等しい, より小さい, 足す } from "../共通/演算";
import { しくじる, もし, 振り分ける, 試みる } from "../共通/構文";
import { 打ち切るまで繰り返す } from "../共通/反復";
import { 注意 } from "../共通/記録";

/**
 * 1 回目を含めた試行回数．2 に留めてある．作り直しは毎回まるごと 1 回分の生成で，
 * 相手は小さな 1 日無料枠．それに 1 回振り直せば大半のループは切れる．
 */
const 試行回数 = 2;

/** これ以上なら，いちばんマシな候補もまだ同じ文でしかない． */
const 完全な繰り返しとみなす点数 = 0.9;

/** 1 回だけ生成し，そのまま投稿してはいけないものを差し替える． */
export function 発話する(発話器: 発話器, 依頼: 発話の依頼): 約束<発話の結果> {
  return 発話器.発話する(依頼).んで((結果) => 出してよい形に直す(結果, 依頼));
}

/** 生の一言を，そのままチャンネルへ出せる形にする． */
function 出してよい形に直す(結果: 発話の結果, 依頼: 発話の依頼): 約束<発話の結果> {
  return 振り分ける<発話の結果>(
    [
      {
        // 指示書 (と人格コーパス) は，絶対にチャンネルへ出さない．
        条件: () => 指示書が漏れているか(結果.本文, 依頼.指示書),
        ならば: () => {
          注意("発話: 指示書の漏洩を差し止めた");

          return { ...結果, 本文: 定型文を選ぶ(受け流しの文) };
        },
      },
      {
        条件: () => 結果.拒否された,
        ならば: () => ({ ...結果, 本文: 定型文を選ぶ(拒否の文) }),
      },
      {
        条件: () => 空か(前後の空白を落とす(結果.本文)),
        ならば: () => ({ ...結果, 本文: 定型文を選ぶ(無言の文) }),
      },
    ],
    { どれでもなければ: () => 結果 },
  );
}

/** 1 回分の試行と，その重なり具合． */
interface 試行の記録 {
  結果: 省略可<発話の結果>;
  点数: 数値;
  費用ドル: 数値;
  打ち切ったか: 真偽;
}

/**
 * 発話する と同じだが，直前に言ったばかりのものは返さない．
 *
 * 指示文の会話ログには kawaiko 自身の発言が入っていて，小さいモデルはそれを
 * お手本の型として固定する．だからチャンネルが延々と同じ骨格を受け取ることになる．
 * 促しを添えて振り直し，いちばん重なりの少ない候補を採り，それでも丸写しなら
 * ループ打ち切りの一言へ逃げる．費用は試行ぶん合算するので，予算番には実際に
 * 使った額が見える．
 */
export function 重複を避けて発話する(
  発話器: 発話器,
  依頼: 発話の依頼,
  避けたい発言: 読み取り専用配列<文字列>,
): 約束<発話の結果> {
  return もし(空か(避けたい発言), {
    であれば: () => 発話する(発話器, 依頼),
    でなければ: () => 振り直しながら発話する(発話器, 依頼, 避けたい発言),
  });
}

function 振り直しながら発話する(
  発話器: 発話器,
  依頼: 発話の依頼,
  避けたい発言: 読み取り専用配列<文字列>,
): 約束<発話の結果> {
  const 初期: 試行の記録 = {
    結果: 未定義,
    点数: 数値.POSITIVE_INFINITY,
    費用ドル: 0,
    打ち切ったか: 偽,
  };

  // 前の試行の結果で続けるかが決まるので，状態を持ち越しながら繰り返す．
  return 打ち切るまで繰り返す(試行回数, 初期, (これまで, 試行) =>
    一回振る(発話器, 依頼, 避けたい発言, 試行, これまで).んで((次) => ({
      状態: 次,
      打ち切るか: 次.打ち切ったか,
    })),
  ).んで((記録) => {
    const 採用 = 記録.結果!;

    return もし(以上(記録.点数, 完全な繰り返しとみなす点数), {
      であれば: () => {
        注意("発話: どの試行も丸写しだったのでループを打ち切る");

        return { ...採用, 本文: 定型文を選ぶ(反復打ち切りの文), 費用ドル: 記録.費用ドル };
      },
      でなければ: () => ({ ...採用, 費用ドル: 記録.費用ドル }),
    });
  });
}

/** 1 回投げて，これまでの最良と突き合わせる． */
function 一回振る(
  発話器: 発話器,
  依頼: 発話の依頼,
  避けたい発言: 読み取り専用配列<文字列>,
  試行: 数値,
  これまで: 試行の記録,
): 約束<試行の記録> {
  return 試みる<省略可<発話の結果>>({
    実行: () =>
      発話する(
        発話器,
        もし(等しい(試行, 0), {
          であれば: () => 依頼,
          でなければ: () => ({ ...依頼, 指示文: `${依頼.指示文}\n\n${言い直しの指示}` }),
        }),
      ),
    // 振り直しはあくまで上乗せ．使える返事をそれで失ってはいけない．
    しくじったら: (躓き) =>
      もし(等しい(これまで.結果, 未定義), {
        であれば: (): 省略可<発話の結果> => しくじる(躓き),
        でなければ: (): 省略可<発話の結果> => {
          注意(`発話: ${足す(試行, 1)} 回目の振り直しに失敗．先の一言を採用する`);

          return 未定義;
        },
      }),
  }).んで((結果) =>
    もし(等しい(結果, 未定義), {
      であれば: (): 試行の記録 => ({ ...これまで, 打ち切ったか: 真 }),
      でなければ: () => これまでと比べる(結果!, 避けたい発言, 試行, これまで),
    }),
  );
}

function これまでと比べる(
  結果: 発話の結果,
  避けたい発言: 読み取り専用配列<文字列>,
  試行: 数値,
  これまで: 試行の記録,
): 試行の記録 {
  const 点数 = 反復度(結果.本文, 避けたい発言);
  const 費用ドル = 足す(これまで.費用ドル, 結果.費用ドル);
  const 最良 = もし(より小さい(点数, これまで.点数), {
    であれば: () => ({ 結果, 点数 }),
    でなければ: () => ({ 結果: これまで.結果, 点数: これまで.点数 }),
  });
  const 新鮮か = 否定(反復しているか(結果.本文, 避けたい発言));

  もし(新鮮か, {
    でなければ: () =>
      注意(`発話: ${試行 + 1} 回目は直近の発言と重なった (点数 ${小数で書く(点数, 2)})`),
    であれば: () => 未定義,
  });

  return もし(新鮮か, {
    であれば: (): 試行の記録 => ({ 結果, 点数, 費用ドル, 打ち切ったか: 真 }),
    でなければ: (): 試行の記録 => ({ ...最良, 費用ドル, 打ち切ったか: 偽 }),
  });
}
