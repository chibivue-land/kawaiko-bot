import { describe, expect, it } from "vitest";
import { 記憶を操作する } from "./記憶操作";
import { 偽の記憶庫を作る, 偽の部品一式を作る } from "../試験/偽物";

describe("記憶を操作する", () => {
  it("記憶庫が無ければそう言う", async () => {
    const 部品 = 偽の部品一式を作る({ 記憶庫: 偽の記憶庫を作る({ 使えるか: false }) });

    expect((await 記憶を操作する(部品, { 種別: "サーバー一覧" })).状態).toBe(503);
  });

  it("観測したサーバーを並べる", async () => {
    expect(await 記憶を操作する(偽の部品一式を作る(), { 種別: "サーバー一覧" })).toEqual({
      状態: 200,
      本体: { サーバー一覧: ["サーバー-1"] },
    });
  });

  it("信じていることと、取り消せる回を返す", async () => {
    const 部品 = 偽の部品一式を作る();
    部品.記憶庫.事実一覧 = [
      { 連番: 3, 主語の種別: "server", 主語id: null, 主語名: null, 本文: "深夜は過疎", 時刻: 0 },
    ];

    const 結果 = await 記憶を操作する(部品, { 種別: "現状", サーバーid: "サーバー-1" });

    expect(結果.状態).toBe(200);
    expect(結果.本体).toMatchObject({
      サーバー: "サーバー-1",
      読み取り位置: 0,
      学習の履歴: [],
    });
  });

  it("学習 1 回を取り消す", async () => {
    const 結果 = await 記憶を操作する(偽の部品一式を作る(), {
      種別: "回を取り消す",
      サーバーid: "サーバー-1",
      識別子: "回-1",
    });

    expect(結果).toEqual({ 状態: 200, 本体: { 成功か: true, 取り消した回: "回-1" } });
  });

  it("知識をある位置へ戻す", async () => {
    const 結果 = await 記憶を操作する(偽の部品一式を作る(), {
      種別: "巻き戻す",
      サーバーid: "サーバー-1",
      連番: 42,
    });

    expect(結果).toEqual({ 状態: 200, 本体: { 成功か: true, 戻した位置: 42 } });
  });

  it("記憶庫が取り消しを断ったら、それを表に出す", async () => {
    const 記憶庫 = 偽の記憶庫を作る();
    記憶庫.時点まで巻き戻す = async () => false;

    const 結果 = await 記憶を操作する(偽の部品一式を作る({ 記憶庫 }), {
      種別: "巻き戻す",
      サーバーid: "サーバー-1",
      連番: 42,
    });

    expect(結果.状態).toBe(500);
  });
});
