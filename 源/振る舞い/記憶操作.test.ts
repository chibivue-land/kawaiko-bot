import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 記憶を操作する } from "./記憶操作";
import { 偽の記憶庫を作る, 偽の部品一式を作る } from "../試験/偽物";
import { 偽, 真, 空 } from "../共通/型";

仕様("記憶を操作する", () => {
  検証("記憶庫が無ければそう言う", () => {
    const 部品 = 偽の部品一式を作る({ 記憶庫: 偽の記憶庫を作る({ 使えるか: 偽 }) });

    return 記憶を操作する(部品, { 種別: "サーバー一覧" }).んで((結果) => {
      期待(結果.状態).である(503);
    });
  });

  検証("観測したサーバーを並べる", () => {
    return 記憶を操作する(偽の部品一式を作る(), { 種別: "サーバー一覧" }).んで((結果) => {
      期待(結果).と等しい({
        状態: 200,
        本体: { サーバー一覧: ["サーバー-1"] },
      });
    });
  });

  検証("信じていることと，取り消せる回を返す", () => {
    const 部品 = 偽の部品一式を作る();
    部品.記憶庫.事実一覧 = [
      { 連番: 3, 主語の種別: "server", 主語id: 空, 主語名: 空, 本文: "深夜は過疎", 時刻: 0 },
    ];

    return 記憶を操作する(部品, { 種別: "現状", サーバーid: "サーバー-1" }).んで((結果) => {
      期待(結果.状態).である(200);
      期待(結果.本体).の形をしている({
        サーバー: "サーバー-1",
        読み取り位置: 0,
        学習の履歴: [],
      });
    });
  });

  検証("学習 1 回を取り消す", () => {
    return 記憶を操作する(偽の部品一式を作る(), {
      種別: "回を取り消す",
      サーバーid: "サーバー-1",
      識別子: "回-1",
    }).んで((結果) => {
      期待(結果).と等しい({ 状態: 200, 本体: { 成功か: 真, 取り消した回: "回-1" } });
    });
  });

  検証("知識をある位置へ戻す", () => {
    return 記憶を操作する(偽の部品一式を作る(), {
      種別: "巻き戻す",
      サーバーid: "サーバー-1",
      連番: 42,
    }).んで((結果) => {
      期待(結果).と等しい({ 状態: 200, 本体: { 成功か: 真, 戻した位置: 42 } });
    });
  });

  検証("記憶庫が取り消しを断ったら，それを表に出す", () => {
    const 記憶庫 = 偽の記憶庫を作る();
    記憶庫.時点まで巻き戻す = async () => 偽;

    return 記憶を操作する(偽の部品一式を作る({ 記憶庫 }), {
      種別: "巻き戻す",
      サーバーid: "サーバー-1",
      連番: 42,
    }).んで((結果) => {
      期待(結果.状態).である(500);
    });
  });
});
