/**
 * 直近で失敗した提供者を，しばらく飛ばすための覚え書き．
 *
 * 無料枠が尽きた提供者を毎回律儀に叩くと，返事のたびに確実に失敗する往復を
 * 払うことになる．かといって順番を変えて無料枠を捨てるのも違うので，失敗した
 * ものを短時間だけ休ませて，時間が経ったらまた試す．
 */
export interface 提供者の記録 {
  休んでいる提供者(): 約束<記録<文字列, 提供者の休み>>;

  休ませる(提供者名: 文字列, 休み: 提供者の休み): 約束<無>;
}

