/** 投げられた値を，保存する価値のある一行へ均す． */
export function 失敗を要約する(躓き: 不明): 文字列 {
  return もし(躓き instanceof 例外, {
    であれば: () => 前後の空白を落とす(`${(躓き as 例外).name}: ${(躓き as 例外).message}`),
    でなければ: () =>
      試す({
        実行: () => JSON.stringify(躓き),
        しくじったら: () => 文字列(躓き),
      }),
  });
}
