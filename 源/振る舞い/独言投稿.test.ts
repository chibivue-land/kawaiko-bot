import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 独り言を投稿する } from "./独言投稿";
import { お題の見出しの種類, お題一覧 } from "../核/独言";
import { 偽の判定器を作る, 偽の部品一式を作る, 発言を作る } from "../試験/偽物";
import { 偽, 新しい例外, 未定義, 真 } from "../共通/型";

/** そのお題が選ばれる賽の目 (お題の並びのちょうど真ん中を指す)． */
function お題を指す賽(お題: string): () => number {
  return () => (お題一覧.indexOf(お題) + 0.5) / お題一覧.length;
}

const 世間の流行のお題 = お題一覧.find((お題) => お題の見出しの種類(お題) === "世間の流行")!;

仕様("独り言を投稿する", () => {
  検証("確率ゲートで見送るときは何も使わない", () => {
    const 部品 = 偽の部品一式を作る({ 独言の確率: "0", 乱数: () => 0.5 });
    return 独り言を投稿する(部品).んで((結果) => {
      期待(結果).と等しい({ 成功か: 真, 省略した理由: "確率" });
      期待(部品.発話器.受け取った指示文).の長さが(0);
    });
  });

  検証("予算が尽きていたら見送る", () => {
    const 部品 = 偽の部品一式を作る({
      予算番: {
        async 許すか() {
          return { 許すか: 偽, 使用済みドル: 200 };
        },
        async 記録する() {},
        async 仕事を終える() {},
      },
    });
    return 独り言を投稿する(部品).んで((結果) => {
      期待(結果).と等しい({ 成功か: 真, 省略した理由: "予算" });
    });
  });

  検証("住処のチャンネルへ，スレッドにせず投げる", () => {
    const 部品 = 偽の部品一式を作る();
    return 独り言を投稿する(部品).んで((結果) => {
      期待(結果).と等しい({ 成功か: 真 });
      期待(部品.チャット.投稿済み).と等しい([
        { チャンネルid: "住処", 本文: "kawaiko の返事", 返信先: 未定義 },
      ]);
      期待(部品.発話器.受け取った指示文[0]).を含む(お題一覧[0]!);
      期待(部品.終えた仕事).と等しい([{ 種類: "独言", 成功か: 真, 異常: 未定義 }]);
    });
  });

  検証("見出しは，それを要るお題のときだけ取りに行く", () => {
    let 訊いた回数 = 0;
    const 部品 = 偽の部品一式を作る({
      見出し取得: {
        async 見出し() {
          訊いた回数++;

          return ["Vue 4 released"];
        },
      },
    });
    return 独り言を投稿する(部品).んで(() => {
      // 乱数が 0 なので最初のお題が選ばれ，それは見出しを要らない．
      期待(訊いた回数).である(0);
    });
  });

  検証("流行のお題なら，その種類の見出しを取ってきて指示文に載せる", () => {
    const 訊かれた種類: string[] = [];
    const 部品 = 偽の部品一式を作る({
      乱数: お題を指す賽(世間の流行のお題),
      見出し取得: {
        async 見出し(種類) {
          訊かれた種類.push(種類);

          return ["鴨のぬいぐるみが品薄"];
        },
      },
    });

    return 独り言を投稿する(部品).んで(() => {
      期待(訊かれた種類).と等しい(["世間の流行"]);
      期待(部品.発話器.受け取った指示文[0]).を含む("- 鴨のぬいぐるみが品薄");
      期待(部品.発話器.受け取った指示文[0]).を含む("いま世間で流行っているもの");
    });
  });

  検証("茶化してはいけない見出しは，語でも判定でも落とす", () => {
    const 部品 = 偽の部品一式を作る({
      乱数: お題を指す賽(世間の流行のお題),
      見出し取得: {
        async 見出し() {
          return ["高速道路で多重事故", "人気俳優の私生活", "鴨のぬいぐるみが品薄"];
        },
      },
      // 語では落とせない «私生活» を，判定器が落とす．
      判定器: 偽の判定器を作る((依頼) => ({
        茶化せないか: { 種別: "真偽", 確率: 依頼.状態.includes("私生活") ? 0.9 : 0.05 },
      })),
    });

    return 独り言を投稿する(部品).んで(() => {
      const [指示文] = 部品.発話器.受け取った指示文;

      期待(指示文).を含む("鴨のぬいぐるみが品薄");
      期待(指示文).否.を含む("多重事故");
      期待(指示文).否.を含む("私生活");
      // 語で落ちた見出しは，判定器にすら見せない．
      期待(部品.判定器.受け取った依頼).の長さが(2);
    });
  });

  検証("見出しが取れなくても，独り言は出す", () => {
    const 部品 = 偽の部品一式を作る({
      乱数: お題を指す賽(世間の流行のお題),
      見出し取得: {
        async 見出し() {
          throw 新しい例外("フィードが落ちている");
        },
      },
    });

    return 独り言を投稿する(部品).んで((結果) => {
      期待(結果).と等しい({ 成功か: 真 });
      期待(部品.チャット.投稿済み).の長さが(1);
    });
  });

  検証("賽が当たれば乱心して呟く", () => {
    const 部品 = 偽の部品一式を作る({ 乱心の確率: "1" });

    return 独り言を投稿する(部品).んで(() => {
      期待(部品.発話器.受け取った指示文[0]).を含む("乱心している");
    });
  });

  検証("さっき呟いたことを繰り返すなと伝える", () => {
    const 部品 = 偽の部品一式を作る();
    部品.チャット.履歴 = [
      発言を作る({
        id: "前",
        発言者id: "bot-1",
        発言者名: "kawaiko",
        bot発言か: 真,
        本文: "また新しい JS フレームワークが生まれたらしい",
      }),
    ];
    return 独り言を投稿する(部品).んで(() => {
      期待(部品.発話器.受け取った指示文[0]).を含む("また新しい JS フレームワーク");
    });
  });

  検証("cron の中で投げっぱなしにせず，失敗として報告する", () => {
    const 部品 = 偽の部品一式を作る();
    部品.発話器.発話する = async () => {
      throw 新しい例外("モデルが爆発した");
    };
    return 独り言を投稿する(部品).んで((結果) => {
      期待(結果.成功か).である(偽);
      期待(部品.終えた仕事[0]).の形をしている({ 種類: "独言", 成功か: 偽 });
    });
  });
});
