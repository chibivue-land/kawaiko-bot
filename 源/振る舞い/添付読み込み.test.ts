import type { 添付読み } from "./接続口";
import { 一度に読む数, 添付を読み込む } from "./添付読み込み";

import type { 添付 } from "../核/添付";

import { 仕様, 検証, 期待, 偽装する } from "../試験/言葉";

import { 範囲 } from "../共通/反復";
import { 未定義 } from "../共通/型";
import { 写す, 長さ } from "../共通/関数";

function 添付を作る(差分: Partial<添付> = {}): 添付 {
  return {
    名前: "めも.txt",
    種別: "text/plain",
    大きさ: 100,
    場所: "https://cdn.discordapp.com/めも.txt",
    ...差分,
  };
}

const 図 = 添付を作る({
  名前: "図.png",
  種別: "image/png",
  場所: "https://cdn.discordapp.com/図.png",
});
const 束 = 添付を作る({ 名前: "束.zip", 種別: "application/zip" });

function 読みを作る(差分: Partial<添付読み> = {}): 添付読み {
  return {
    文書を読む: async () => "中身です",
    画像を取り込む: async (添付) => ({ 種別: 添付.種別, 中身: "base64", 名前: 添付.名前 }),
    ...差分,
  };
}

仕様("添付を読み込む", () => {
  検証("ファイルは中身を読んで指示文へ回す", () => {
    return 添付を読み込む(読みを作る(), [添付を作る()]).んで((読んだ) => {
      期待(読んだ.読んだ一覧).と等しい([{ 添付: 添付を作る(), 中身: "中身です" }]);
      期待(読んだ.画像一覧).と等しい([]);
    });
  });

  検証("画像は取り込んで提供者へ回す", () => {
    return 添付を読み込む(読みを作る(), [図]).んで((読んだ) => {
      期待(読んだ.画像一覧).と等しい([{ 種別: "image/png", 中身: "base64", 名前: "図.png" }]);
      // 指示文にも「画像が来た」ことは残る．
      期待(読んだ.読んだ一覧).と等しい([{ 添付: 図 }]);
    });
  });

  検証("触れないものは取りに行かない", () => {
    const 文書を読む = 偽装する(async () => "読んでしまった");
    const 画像を取り込む = 偽装する(async () => 未定義);

    return 添付を読み込む(読みを作る({ 文書を読む, 画像を取り込む }), [束]).んで((読んだ) => {
      期待(文書を読む).否.呼ばれた();
      期待(画像を取り込む).否.呼ばれた();
      期待(読んだ.読んだ一覧).と等しい([{ 添付: 束 }]);
    });
  });

  検証("取れなかったファイルも，添えられていたことは残す", () => {
    return 添付を読み込む(読みを作る({ 文書を読む: async () => 未定義 }), [添付を作る()]).んで(
      (読んだ) => {
        期待(読んだ.読んだ一覧).と等しい([{ 添付: 添付を作る(), 中身: 未定義 }]);
      },
    );
  });

  検証("一度に見に行く数を超えたぶんは，取りに行かず名前だけ残す", () => {
    const 文書を読む = 偽装する(async () => "中身です");
    const 一覧 = 写す(範囲(0, 一度に読む数 + 3), (番) => 添付を作る({ 名前: `めも${番}.txt` }));

    return 添付を読み込む(読みを作る({ 文書を読む }), 一覧).んで((読んだ) => {
      期待(文書を読む).呼ばれた回数が(一度に読む数);
      // 溢れたぶんも一覧からは消えない．
      期待(長さ(読んだ.読んだ一覧)).である(長さ(一覧));
    });
  });

  検証("何も添えられていなければ空", () => {
    return 添付を読み込む(読みを作る(), []).んで((読んだ) => {
      期待(読んだ.読んだ一覧).と等しい([]);
      期待(読んだ.画像一覧).と等しい([]);
    });
  });
});
