/**
 * 判定器への訊き方．
 *
 * どの振る舞いも同じ 3 つをやる — 訊く，費用を計上する，転んでも先へ進む．
 * 判定はどれも上乗せ (見立て・検品・相手選び・門番) で，取れなければ決定的な
 * 見立てへ落ちるだけ．だからここから外へは何も投げない．
 */
import type { 判定の結果, 部品一式 } from "./接続口";

import type { 問い, 答え一覧 } from "../核/判定";

import { 文字列, 未定義, 真偽 } from "../共通/型";
import type { 省略可, 約束, 記録 } from "../共通/型";
import { もし, 試みる } from "../共通/構文";
import { 等しい } from "../共通/演算";
import { すぐ返す } from "../共通/約束";
import { 注意 } from "../共通/記録";

/** 訊いて，費用を計上して，結果まるごと返す．取れなければ未定義． */
export function 判定を仰ぐ(
  部品: 部品一式,
  状態: 文字列,
  問い一覧: 記録<文字列, 問い>,
  設定?: 省略可<{ 休みを無視するか?: 省略可<真偽> }>,
): 約束<省略可<判定の結果>> {
  return 試みる<省略可<判定の結果>>({
    実行: () =>
      部品.判定器
        .判定する({ 状態, 問い一覧, 休みを無視するか: 設定?.休みを無視するか })
        .んで((結果) =>
          もし<約束<省略可<判定の結果>>>(等しい(結果, 未定義), {
            であれば: () => すぐ返す(未定義),
            でなければ: () => 部品.予算番.記録する(結果!.費用ドル).んで(() => 結果),
          }),
        ),
    // 判定器は投げない約束だが，計上のほうが転ぶことはある．どちらにせよ先へ進む．
    しくじったら: (躓き) => {
      注意("判定: 取れなかったので決定的な見立てへ落ちる:", 文字列(躓き));

      return 未定義;
    },
  });
}

/** 答えだけ欲しいとき． */
export function 判定してもらう(
  部品: 部品一式,
  状態: 文字列,
  問い一覧: 記録<文字列, 問い>,
): 約束<省略可<答え一覧>> {
  return 判定を仰ぐ(部品, 状態, 問い一覧).んで((結果) => 結果?.答え一覧);
}
