import { 探索して調べる } from "./探索";

import { 検索の上限 } from "../核/探索";

import { 偽の発話器を作る, 偽の部品一式を作る, 偽の頁読みを作る } from "../試験/偽物";
import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 長さ } from "../共通/関数";

function 調査係を作る(件一覧: Array<{ 題: string; 抜粋: string; 場所?: string }>) {
  const 引いた語: string[] = [];

  return {
    引いた語,
    調べる: async (検索語: string) => {
      引いた語.push(検索語);

      return { 抜粋: "", 候補: [], 件一覧 };
    },
  };
}

const 一件 = { 題: "Vapor Mode の解説", 抜粋: "刷新の話", 場所: "https://a.example/x" };

仕様("探索して調べる", () => {
  検証("初手で引き，モデルが十分と言えば，そこで終わる", () => {
    const 調査係 = 調査係を作る([一件]);
    const 発話器 = 偽の発話器を作る(["次: 十分\n中身:"]);
    const 部品 = 偽の部品一式を作る({ 調査係, 発話器 });

    return 探索して調べる(部品, "Vapor Mode って何", "Vue Vapor Mode").んで((結末) => {
      期待(調査係.引いた語).と等しい(["Vue Vapor Mode"]);
      期待(結末.抜粋).を含む("検索「Vue Vapor Mode」:");
      期待(結末.抜粋).を含む("Vapor Mode の解説");
      期待(結末.足どり).と等しい(["検索: Vue Vapor Mode", "十分"]);
      // 判断 1 回分の費用を持ち帰る (偽の発話器は 1 回 0.001)．
      期待(結末.費用ドル).とほぼ等しい(0.001);
    });
  });

  検証("モデルが選んだ結果を開き，頁として持ち帰る", () => {
    const 調査係 = 調査係を作る([一件]);
    const 頁読み = 偽の頁読みを作る();
    const 発話器 = 偽の発話器を作る(["次: 開く\n中身: https://a.example/x", "次: 十分\n中身:"]);
    const 部品 = 偽の部品一式を作る({ 調査係, 発話器, 頁読み });

    return 探索して調べる(部品, "Vapor Mode って何", "Vue Vapor Mode").んで((結末) => {
      期待(頁読み.読んだ場所).と等しい(["https://a.example/x"]);
      期待(結末.頁一覧).の長さが(1);
      期待(結末.足どり).と等しい(["検索: Vue Vapor Mode", "開く: https://a.example/x", "十分"]);
    });
  });

  検証("語を変えた引き直しを実行する．同じ語なら実行せず終わる", () => {
    const 調査係 = 調査係を作る([一件]);
    const 発話器 = 偽の発話器を作る([
      "次: 検索\n中身: Vapor Mode リリース",
      // 同じ語をもう一度 — 検められて「十分」に落ちる．
      "次: 検索\n中身: Vapor Mode リリース",
    ]);
    const 部品 = 偽の部品一式を作る({ 調査係, 発話器 });

    return 探索して調べる(部品, "Vapor Mode って何", "Vue Vapor Mode").んで((結末) => {
      期待(調査係.引いた語).と等しい(["Vue Vapor Mode", "Vapor Mode リリース"]);
      期待(結末.足どり).と等しい(["検索: Vue Vapor Mode", "検索: Vapor Mode リリース", "十分"]);
    });
  });

  検証("検索結果に出ていない URL を開けとは言わせない", () => {
    const 調査係 = 調査係を作る([一件]);
    const 頁読み = 偽の頁読みを作る();
    const 発話器 = 偽の発話器を作る(["次: 開く\n中身: https://作り話.example/x"]);
    const 部品 = 偽の部品一式を作る({ 調査係, 発話器, 頁読み });

    return 探索して調べる(部品, "Vapor Mode って何", "Vue Vapor Mode").んで((結末) => {
      期待(頁読み.読んだ場所).と等しい([]);
      期待(結末.足どり).と等しい(["検索: Vue Vapor Mode", "十分"]);
    });
  });

  検証("モデルが答えの形を守らなくても，集めた材料で終わる", () => {
    const 調査係 = 調査係を作る([一件]);
    const 発話器 = 偽の発話器を作る(["わかりました！引いてみますね！"]);
    const 部品 = 偽の部品一式を作る({ 調査係, 発話器 });

    return 探索して調べる(部品, "Vapor Mode って何", "Vue Vapor Mode").んで((結末) => {
      期待(結末.抜粋).を含む("Vapor Mode の解説");
      期待(結末.足どり).と等しい(["検索: Vue Vapor Mode", "十分"]);
    });
  });

  検証("検索し続けても上限で止まる", () => {
    const 調査係 = 調査係を作る([]);
    // 毎回ちがう語で引き続けようとするモデル．
    let 回数 = 0;
    const 発話器 = {
      async 発話する() {
        回数++;

        return { 本文: `次: 検索\n中身: 語その${回数}`, 費用ドル: 0.001, モデル: "偽のモデル" };
      },
    };
    const 部品 = 偽の部品一式を作る({ 調査係, 発話器 });

    return 探索して調べる(部品, "何か", "初手の語").んで(() => {
      期待(長さ(調査係.引いた語)).である(検索の上限);
    });
  });
});
