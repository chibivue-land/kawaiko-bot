import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 横槍を入れる, 絡む相手を選ぶ } from "./横槍返信";
import { 決め打ちの現在, 偽の判定器を作る, 偽の部品一式を作る, 発言を作る } from "../試験/偽物";
import { 偽, 新しい例外, 未定義, 真 } from "../共通/型";

const 現在 = 決め打ちの現在.epochMilliseconds;

仕様("絡む相手を選ぶ", () => {
  const 新しい時刻 = "2026-08-21T13:40:00Z";

  検証("新しい人間の発言を拾う", () => {
    const 候補 = 絡む相手を選ぶ([発言を作る({ id: "1", 時刻: 新しい時刻 })], {
      自分のid: "bot-1",
      現在,
    });

    期待(候補.map((発言) => 発言.id)).と等しい(["1"]);
  });

  検証("bot・空・古い発言には触らない", () => {
    const 候補 = 絡む相手を選ぶ(
      [
        発言を作る({ id: "bot", bot発言か: 真, 時刻: 新しい時刻 }),
        発言を作る({ id: "空", 本文: "   ", 時刻: 新しい時刻 }),
        発言を作る({ id: "古い", 時刻: "2026-08-20T13:40:00Z" }),
        発言を作る({ id: "よい", 時刻: 新しい時刻 }),
      ],
      { 自分のid: "bot-1", 現在 },
    );

    期待(候補.map((発言) => 発言.id)).と等しい(["よい"]);
  });

  検証("ゲートウェイが既に答える発言には二重に絡まない", () => {
    const 候補 = 絡む相手を選ぶ(
      [発言を作る({ id: "名指し", 本文: "<@bot-1> ねえ", 時刻: 新しい時刻 })],
      { 自分のid: "bot-1", 現在 },
    );

    期待(候補).と等しい([]);
  });

  検証("kawaiko がもう返信した発言には，二度と絡まない", () => {
    // 割り込める古さが 3 時間で，枠が 2 時間おき．この歯止めが無かったころは，
    // 静かなチャンネルで同じ発言に 2 度も 3 度も絡んでいた．
    const 候補 = 絡む相手を選ぶ(
      [
        発言を作る({
          id: "前の横槍",
          発言者id: "bot-1",
          bot発言か: 真,
          返信先id: "絡み済み",
          時刻: 新しい時刻,
        }),
        発言を作る({ id: "絡み済み", 時刻: 新しい時刻 }),
        発言を作る({ id: "まだ", 時刻: 新しい時刻 }),
      ],
      { 自分のid: "bot-1", 現在 },
    );

    期待(候補.map((発言) => 発言.id)).と等しい(["まだ"]);
  });

  検証("他人どうしの返信は，返信済みに数えない", () => {
    const 候補 = 絡む相手を選ぶ(
      [
        発言を作る({ id: "返事", 発言者id: "利用者-2", 返信先id: "元", 時刻: 新しい時刻 }),
        発言を作る({ id: "元", 時刻: 新しい時刻 }),
      ],
      { 自分のid: "bot-1", 現在 },
    );

    期待(候補.map((発言) => 発言.id)).と等しい(["返事", "元"]);
  });
});

仕様("横槍を入れる", () => {
  検証("確率ゲートで見送るときは何も使わない", () => {
    const 部品 = 偽の部品一式を作る({ 横槍の確率: "0", 乱数: () => 0.5 });
    return 横槍を入れる(部品).んで((結果) => {
      期待(結果).と等しい({ 成功か: 真, 省略した理由: "確率" });
      期待(部品.発話器.受け取った指示文).の長さが(0);
    });
  });

  検証("強制すればゲートを無視する", () => {
    const 部品 = 偽の部品一式を作る({ 横槍の確率: "0" });
    部品.チャット.履歴 = [発言を作る({ id: "1", 時刻: "2026-08-21T13:40:00Z" })];
    return 横槍を入れる(部品, { 強制するか: 真 }).んで((結果) => {
      期待(結果).と等しい({ 成功か: 真 });
    });
  });

  検証("絡む相手が居なければ何も言わない", () => {
    const 部品 = 偽の部品一式を作る();
    return 横槍を入れる(部品).んで((結果) => {
      期待(結果).と等しい({ 成功か: 真 });
      期待(部品.チャット.投稿済み).の長さが(0);
    });
  });

  検証("返信の形で割り込み，費用を計上する", () => {
    const 部品 = 偽の部品一式を作る();
    部品.チャット.履歴 = [発言を作る({ id: "相手", 本文: "眠い", 時刻: "2026-08-21T13:40:00Z" })];
    return 横槍を入れる(部品).んで((結果) => {
      期待(結果).と等しい({ 成功か: 真 });
      期待(部品.チャット.投稿済み).と等しい([
        { チャンネルid: "住処", 本文: "kawaiko の返事", 返信先: "相手" },
      ]);
      期待(部品.発話器.受け取った指示文[0]).を含む("眠い");
      期待(部品.使った額).と等しい([0.001]);
      期待(部品.終えた仕事).と等しい([{ 種類: "横槍", 成功か: 真, 異常: 未定義 }]);
    });
  });

  検証("cron の中で投げっぱなしにせず，失敗として報告する", () => {
    const 部品 = 偽の部品一式を作る();
    部品.チャット.履歴 = [発言を作る({ id: "相手", 時刻: "2026-08-21T13:40:00Z" })];
    部品.発話器.発話する = async () => {
      throw 新しい例外("モデルが爆発した");
    };
    return 横槍を入れる(部品).んで((結果) => {
      期待(結果.成功か).である(偽);
      期待(部品.終えた仕事[0]).の形をしている({ 種類: "横槍", 成功か: 偽 });
    });
  });

  検証("同じ発言に 2 回続けては絡まない (絡み終えたら，次の枠では候補が無い)", () => {
    const 部品 = 偽の部品一式を作る();
    部品.チャット.履歴 = [発言を作る({ id: "相手", 本文: "眠い", 時刻: "2026-08-21T13:40:00Z" })];

    return 横槍を入れる(部品)
      .んで(() => {
        // 投稿したものが，次の枠では履歴の先頭に見えている．
        部品.チャット.履歴 = [
          発言を作る({
            id: "横槍",
            発言者id: "bot-1",
            bot発言か: 真,
            本文: "kawaiko の返事",
            返信先id: "相手",
            時刻: "2026-08-21T13:45:00Z",
          }),
          ...部品.チャット.履歴,
        ];

        return 横槍を入れる(部品);
      })
      .んで((結果) => {
        期待(結果).と等しい({ 成功か: 真 });
        期待(部品.チャット.投稿済み).の長さが(1);
      });
  });

  検証("判定器が居れば，絡みがいのある発言を選び，落ち込んでいる人は避ける", () => {
    // 状態にはチャンネルの流れも載っている．偽物も本物と同じく，注目している発言だけを見る．
    const 注目 = (状態: string) => 状態.split("[注目している発言]")[1] ?? "";
    const 部品 = 偽の部品一式を作る({
      判定器: 偽の判定器を作る((依頼) => ({
        絡みがい: { 種別: "段階", 点数: 注目(依頼.状態).includes("Rust") ? 3 : 0, 確信: 0.9 },
        そっとしておくべきか: {
          種別: "真偽",
          確率: 注目(依頼.状態).includes("つらい") ? 0.95 : 0.02,
        },
      })),
      乱数: () => 0.5,
    });
    部品.チャット.履歴 = [
      発言を作る({ id: "相槌", 本文: "うん", 時刻: "2026-08-21T13:40:00Z" }),
      発言を作る({
        id: "落ち込み",
        本文: "もうつらい．全部やめたい",
        時刻: "2026-08-21T13:39:00Z",
      }),
      発言を作る({ id: "主張", 本文: "全部 Rust で書き直すべき", 時刻: "2026-08-21T13:38:00Z" }),
    ];

    return 横槍を入れる(部品, { 強制するか: 真 }).んで(() => {
      期待(部品.チャット.投稿済み[0]?.返信先).である("主張");
    });
  });

  検証("茶化してよい発言が一つも無ければ，見送る", () => {
    const 部品 = 偽の部品一式を作る({
      判定器: 偽の判定器を作る(() => ({
        絡みがい: { 種別: "段階", 点数: 3, 確信: 0.9 },
        そっとしておくべきか: { 種別: "真偽", 確率: 0.9 },
      })),
    });
    部品.チャット.履歴 = [発言を作る({ id: "相手", 本文: "つらい", 時刻: "2026-08-21T13:40:00Z" })];

    return 横槍を入れる(部品).んで((結果) => {
      期待(結果).と等しい({ 成功か: 真 });
      期待(部品.チャット.投稿済み).の長さが(0);
      期待(部品.発話器.受け取った指示文).の長さが(0);
    });
  });

  検証("賽が当たれば乱心して絡む", () => {
    const 部品 = 偽の部品一式を作る({ 乱心の確率: "1" });
    部品.チャット.履歴 = [発言を作る({ id: "相手", 本文: "眠い", 時刻: "2026-08-21T13:40:00Z" })];

    return 横槍を入れる(部品).んで(() => {
      期待(部品.発話器.受け取った指示文[0]).を含む("乱心している");
    });
  });
});
