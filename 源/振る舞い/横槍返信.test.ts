import { describe, expect, it } from "vitest";
import { 横槍を入れる, 絡む相手を選ぶ } from "./横槍返信";
import { 決め打ちの現在, 偽の部品一式を作る, 発言を作る } from "../試験/偽物";

const 現在 = 決め打ちの現在.epochMilliseconds;

describe("絡む相手を選ぶ", () => {
  const 新しい時刻 = "2026-08-21T13:40:00Z";

  it("新しい人間の発言を拾う", () => {
    const 候補 = 絡む相手を選ぶ([発言を作る({ id: "1", 時刻: 新しい時刻 })], {
      自分のid: "bot-1",
      現在,
    });

    expect(候補.map((発言) => 発言.id)).toEqual(["1"]);
  });

  it("bot・空・古い発言には触らない", () => {
    const 候補 = 絡む相手を選ぶ(
      [
        発言を作る({ id: "bot", bot発言か: true, 時刻: 新しい時刻 }),
        発言を作る({ id: "空", 本文: "   ", 時刻: 新しい時刻 }),
        発言を作る({ id: "古い", 時刻: "2026-08-20T13:40:00Z" }),
        発言を作る({ id: "よい", 時刻: 新しい時刻 }),
      ],
      { 自分のid: "bot-1", 現在 },
    );

    expect(候補.map((発言) => 発言.id)).toEqual(["よい"]);
  });

  it("ゲートウェイが既に答える発言には二重に絡まない", () => {
    const 候補 = 絡む相手を選ぶ(
      [発言を作る({ id: "名指し", 本文: "<@bot-1> ねえ", 時刻: 新しい時刻 })],
      { 自分のid: "bot-1", 現在 },
    );

    expect(候補).toEqual([]);
  });
});

describe("横槍を入れる", () => {
  it("確率ゲートで見送るときは何も使わない", async () => {
    const 部品 = 偽の部品一式を作る({ 横槍の確率: "0", 乱数: () => 0.5 });

    expect(await 横槍を入れる(部品)).toEqual({ 成功か: true, 省略した理由: "確率" });
    expect(部品.発話器.受け取った指示文).toHaveLength(0);
  });

  it("強制すればゲートを無視する", async () => {
    const 部品 = 偽の部品一式を作る({ 横槍の確率: "0" });
    部品.チャット.履歴 = [発言を作る({ id: "1", 時刻: "2026-08-21T13:40:00Z" })];

    expect(await 横槍を入れる(部品, { 強制するか: true })).toEqual({ 成功か: true });
  });

  it("絡む相手が居なければ何も言わない", async () => {
    const 部品 = 偽の部品一式を作る();

    expect(await 横槍を入れる(部品)).toEqual({ 成功か: true });
    expect(部品.チャット.投稿済み).toHaveLength(0);
  });

  it("返信の形で割り込み，費用を計上する", async () => {
    const 部品 = 偽の部品一式を作る();
    部品.チャット.履歴 = [発言を作る({ id: "相手", 本文: "眠い", 時刻: "2026-08-21T13:40:00Z" })];

    expect(await 横槍を入れる(部品)).toEqual({ 成功か: true });
    expect(部品.チャット.投稿済み).toEqual([
      { チャンネルid: "住処", 本文: "kawaiko の返事", 返信先: "相手" },
    ]);
    expect(部品.発話器.受け取った指示文[0]).toContain("眠い");
    expect(部品.使った額).toEqual([0.001]);
    expect(部品.終えた仕事).toEqual([{ 種類: "横槍", 成功か: true, 異常: undefined }]);
  });

  it("cron の中で投げっぱなしにせず，失敗として報告する", async () => {
    const 部品 = 偽の部品一式を作る();
    部品.チャット.履歴 = [発言を作る({ id: "相手", 時刻: "2026-08-21T13:40:00Z" })];
    部品.発話器.発話する = async () => {
      throw new Error("モデルが爆発した");
    };

    const 結果 = await 横槍を入れる(部品);

    expect(結果.成功か).toBe(false);
    expect(部品.終えた仕事[0]).toMatchObject({ 種類: "横槍", 成功か: false });
  });
});
