仕様("覗く順を決める", () => {
  検証("住処と賑わっているチャンネルを，重なりと断られたものを除いて並べる", () => {
    const 順 = 覗く順を決める("住処", ["雑談", "住処", "告知", "雑談"], ["告知"], () => 0);

    期待([...順].sort()).と等しい(["住処", "雑談"]);
  });

  検証("乱数で順が変わる", () => {
    const 賽 = [0.9, 0.1];
    const 順 = 覗く順を決める("住処", ["雑談"], [], () => 賽.shift()!);

    期待(順).と等しい(["雑談", "住処"]);
  });

  検証("覗く数には天井がある", () => {
    const 順 = 覗く順を決める("住処", ["a", "b", "c", "d", "e", "f"], [], () => 0.5);

    期待(順).の長さが(覗くチャンネルの数);
  });

  検証("住処が断られていれば住処も覗かない", () => {
    期待(覗く順を決める("住処", ["雑談"], ["住処"], () => 0)).と等しい(["雑談"]);
  });
});

