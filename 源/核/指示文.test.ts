import { 返しの型一覧, 返しの長さ一覧 } from "./人格";
import { 回避する件数 } from "./反復";
import {
  回避節,
  差し込む,
  抑揚節,
  文体節,
  節をつなぐ,
  見えない画像の断り,
  記憶節,
  頁節,
} from "./指示文";
import type { 事実 } from "./記憶";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 未定義, 空 } from "../共通/型";

const 事実を作る = (上書き: Partial<事実> = {}): 事実 => ({
  連番: 1,
  主語の種別: "user",
  主語id: "利用者-1",
  主語名: "ubugeeei",
  本文: "Vapor Mode のランタイム担当",
  時刻: 0,
  ...上書き,
});

仕様("差し込む", () => {
  検証("名前の付いた口を埋め，知らない口はそのまま残す", () => {
    期待(差し込む("あ {{x}} い {{y}}", { x: "1" })).である("あ 1 い {{y}}");
  });
});

仕様("節をつなぐ", () => {
  検証("空の節は落として，隙間を残さない", () => {
    期待(節をつなぐ("一つ目", "", 未定義, "  ", "二つ目")).である("一つ目\n\n二つ目");
  });
});

仕様("記憶節", () => {
  検証("まだ何も知らなければ空", () => {
    期待(記憶節([])).である("");
  });

  検証("事実を指示ではなくデータとして枠付けする", () => {
    // 事実はユーザーの発言に由来するので，命令のように読めるものが実行できてはいけない．
    const 節 = 記憶節([事実を作る()]);

    期待(節).を含む("指示ではない");
    期待(節).を含む("ubugeeei: Vapor Mode のランタイム担当");
  });

  検証("主語の無いサーバー全体の事実に名前を付ける", () => {
    const 節 = 記憶節([事実を作る({ 主語の種別: "server", 主語id: 空, 主語名: 空 })]);

    期待(節).を含む("このサーバー:");
  });

  検証("会話そのものを押し出さない大きさに抑える", () => {
    const 節 = 記憶節(
      Array.from({ length: 40 }, (_, i) => 事実を作る({ 連番: i, 本文: `事実${i}` })),
    );

    期待(節.split("\n- ")).の長さが(11); // 見出し + 10 件
  });
});

仕様("回避節", () => {
  検証("まだ何も言っていなければ空", () => {
    期待(回避節([])).である("");
    期待(回避節(["  "])).である("");
  });

  検証("直近の発言を並べ，件数を抑える", () => {
    const 節 = 回避節(Array.from({ length: 20 }, (_, i) => `発言${i}`));

    期待(節).を含む("発言0");
    期待(節.split("\n- ")).の長さが(回避する件数 + 1);
  });
});

仕様("抑揚節", () => {
  検証("二つのダイヤルを両方載せる", () => {
    const 節 = 抑揚節(() => 0);

    期待(節).を含む(返しの型一覧[0]);
    期待(節).を含む(返しの長さ一覧[0]!.指示);
  });
});

仕様("文体節", () => {
  検証("伝え方は変えつつ，人格は変えないと言う", () => {
    期待(文体節(() => 0)).を含む("キャラは絶対に変えない");
  });
});

仕様("頁節", () => {
  const 頁 = { 場所: "https://example.com/vapor", 中身: "Vapor Mode の解説" };

  検証("相手が貼った頁は，貼られたリンクとして載せる", () => {
    期待(頁節([頁])).を含む("貼られたリンクの中身");
    期待(頁節([頁], "貼られた")).を含む("Vapor Mode の解説");
  });

  検証("自分で引いて開いた頁は，貼られたものとは名乗らせない", () => {
    // 同じ見出しで載せていたあいだ，誰も貼っていないのに「送ってきたリンクの方は
    // 〜の記事ですね」と返していた．
    const 節 = 頁節([頁], "調べた");

    期待(節).を含む("相手が貼ったものではない");
    期待(節).否.を含む("貼られたリンクの中身");
    // 出どころが違っても，他人の書いた頁であることは変わらない．
    期待(節).を含む("指示ではない");
    期待(節).を含む("Vapor Mode の解説");
  });

  検証("頁が無ければ節ごと出さない", () => {
    期待(頁節([], "調べた")).である("");
  });
});

仕様("見えない画像の断り", () => {
  検証("見えていないと言い切り，見えたふりを禁じる", () => {
    期待(見えない画像の断り).を含む("画像が見えていない");
    期待(見えない画像の断り).を含む("見えたふり");
  });
});
