import { 答える型一覧, 調べた回の長さ一覧, 返しの型一覧, 返しの長さ一覧 } from "./人格";
import { 回避する件数 } from "./反復";
import { 回避節, 差し込む, 抑揚節, 文体節, 正確さの指示, 節をつなぐ, 記憶節 } from "./指示文";
import type { 事実 } from "./記憶";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 各要素に } from "../共通/反復";
import { 未定義, 真, 空 } from "../共通/型";
import { いずれか } from "../共通/関数";

const 事実を作る = (上書き: Partial<事実> = {}): 事実 => ({
  連番: 1,
  主語の種別: "user",
  主語id: "利用者-1",
  主語名: "ubugeeei",
  本文: "Vapor Mode のランタイム担当",
  時刻: 0,
  ...上書き,
});

仕様("差し込む", () => {
  検証("名前の付いた口を埋め，知らない口はそのまま残す", () => {
    期待(差し込む("あ {{x}} い {{y}}", { x: "1" })).である("あ 1 い {{y}}");
  });
});

仕様("節をつなぐ", () => {
  検証("空の節は落として，隙間を残さない", () => {
    期待(節をつなぐ("一つ目", "", 未定義, "  ", "二つ目")).である("一つ目\n\n二つ目");
  });
});

仕様("記憶節", () => {
  検証("まだ何も知らなければ空", () => {
    期待(記憶節([])).である("");
  });

  検証("事実を指示ではなくデータとして枠付けする", () => {
    // 事実はユーザーの発言に由来するので，命令のように読めるものが実行できてはいけない．
    const 節 = 記憶節([事実を作る()]);

    期待(節).を含む("指示ではない");
    期待(節).を含む("ubugeeei: Vapor Mode のランタイム担当");
  });

  検証("主語の無いサーバー全体の事実に名前を付ける", () => {
    const 節 = 記憶節([事実を作る({ 主語の種別: "server", 主語id: 空, 主語名: 空 })]);

    期待(節).を含む("このサーバー:");
  });

  検証("会話そのものを押し出さない大きさに抑える", () => {
    const 節 = 記憶節(
      Array.from({ length: 40 }, (_, i) => 事実を作る({ 連番: i, 本文: `事実${i}` })),
    );

    期待(節.split("\n- ")).の長さが(11); // 見出し + 10 件
  });
});

仕様("回避節", () => {
  検証("まだ何も言っていなければ空", () => {
    期待(回避節([])).である("");
    期待(回避節(["  "])).である("");
  });

  検証("直近の発言を並べ，件数を抑える", () => {
    const 節 = 回避節(Array.from({ length: 20 }, (_, i) => `発言${i}`));

    期待(節).を含む("発言0");
    期待(節.split("\n- ")).の長さが(回避する件数 + 1);
  });
});

仕様("抑揚節", () => {
  検証("二つのダイヤルを両方載せる", () => {
    const 節 = 抑揚節(() => 0);

    期待(節).を含む(返しの型一覧[0]);
    期待(節).を含む(返しの長さ一覧[0]!.指示);
  });
});

仕様("文体節", () => {
  検証("伝え方は変えつつ，人格は変えないと言う", () => {
    期待(文体節(() => 0)).を含む("キャラは絶対に変えない");
  });

  検証("反射なら，抑揚のダイヤルを全開で回す", () => {
    期待(文体節(() => 0, { 構え: "反射" })).を含む(返しの型一覧[0]);
    期待(文体節(() => 0, { 構え: "反射" })).を含む(返しの長さ一覧[0]!.指示);
  });

  検証("普通なら，答えの入る型と長さだけから振る", () => {
    // 賽がどの目でも，«鼻で笑って終わる» や «中身を言わなくてよい» は出ない．
    各要素に([0, 0.25, 0.5, 0.75, 0.999], (目) => {
      const 節 = 文体節(() => 目, { 構え: "普通" });

      期待(いずれか(答える型一覧, (型) => 節.includes(型))).である(真);
      期待(節).否.を含む("中身を言わなくてよい");
      期待(節).否.を含む("中身は言わない");
    });
  });

  検証("調べた回は，答えの入る型と，調べた回の長さから振る", () => {
    // 引いて開いて，鼻で笑って終わったら，調べた意味が無い．
    各要素に([0, 0.25, 0.5, 0.75, 0.999], (目) => {
      const 節 = 文体節(() => 目, { 調べたか: 真 });

      期待(いずれか(答える型一覧, (型) => 節.includes(型))).である(真);
      期待(いずれか(調べた回の長さ一覧, (項) => 節.includes(項.指示))).である(真);
    });
  });

  検証("熟考なら，ダイヤルを回さずに正しさを先に確定させる", () => {
    const 節 = 文体節(() => 0, { 構え: "熟考" });

    期待(節).を含む(正確さの指示);
    期待(節).を含む("しりとり");
    期待(節).否.を含む("今回の返しの型");
    // 口調の歯止めは残す．正しさのために別人になってよいわけではない．
    期待(節).を含む("キャラは絶対に変えない");
  });
});
