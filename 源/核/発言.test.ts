import { 仕様, 検証, 期待 } from "../試験/言葉";
import { メンションを取り除く, 名指しされたか } from "./発言";
import { 偽, 未定義, 真 } from "../共通/型";

const 自分のid = "1540328713248440390";

仕様("名指しされたか", () => {
  検証("mentions の一覧を見る", () => {
    期待(名指しされたか(自分のid, "やあ", [自分のid])).である(真);
    期待(名指しされたか(自分のid, "やあ", ["999"])).である(偽);
  });

  検証("生のメンションタグ (ニックネーム形も) を拾う", () => {
    期待(名指しされたか(自分のid, `<@${自分のid}> やあ`, 未定義)).である(真);
    期待(名指しされたか(自分のid, `<@!${自分のid}> やあ`, 未定義)).である(真);
  });

  検証("@everyone と他人へのメンションは無視する", () => {
    期待(名指しされたか(自分のid, "@everyone やあ", [])).である(偽);
    期待(名指しされたか(自分のid, "<@999> やあ", [])).である(偽);
  });
});

仕様("メンションを取り除く", () => {
  検証("自分のタグだけ消して空白を詰める", () => {
    期待(メンションを取り除く(自分のid, `<@${自分のid}>  こんにちは   kawaiko `)).である(
      "こんにちは kawaiko",
    );
    期待(メンションを取り除く(自分のid, `<@!${自分のid}>元気?`)).である("元気?");
  });

  検証("他人へのメンションは残す", () => {
    期待(メンションを取り除く(自分のid, `<@${自分のid}> <@999> みて`)).である("<@999> みて");
  });
});
