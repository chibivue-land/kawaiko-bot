/**
 * 名指しの見立て — 返事を作る前に，この発言にどう構えるかを決める．
 *
 * kawaiko は無料枠の小さいモデルで喋っている．雑談ならそれで足りるが，しりとりの
 * 一手や計算のように**正解がある**発言まで同じ構えで返すと，口調のダイヤル
 * (「質問で返す」「鼻で笑って終わる」) が正しさと喧嘩して，ただの馬鹿になる．
 * 実際になった — 「りんご」に「ご，ん．」と返した．
 *
 * なので先に見立てる．訊くことは 2 つで，使う場所が違うので別々に訊く:
 *
 *   構え    反射 (いつもの雑談) / 普通 (中身のある答えが要る) / 熟考 (正解がある)．
 *           会話の流れを見て決める — «りんご» が遊びの一手かは，流れを見ないと
 *           分からない
 *   裏取り  外へ裏を取りに行くべきか．調べ方を決める票の一つになる
 *           (振る舞い/返信.ts の 調べ方を決める)．こちらは発言だけを見る
 *
 * 見立ては判定器 (Jev) に訊く．訊けなかったときは，下の決定的な合図へ落ちる．
 * 問いの文面と閾値は隣の 見立て-問い.json にある — 調整はコードではなくあちらで．
 */
import 定義 from "./見立て-問い.json";

import { 末尾の行, 段階の点数, 状態を書く, 真の確率, type 問い, type 答え一覧 } from "./判定";

import { 数値, 新しい型, 文字列, 未定義, 真偽 } from "../共通/型";
import type { 省略可, 記録 } from "../共通/型";
import { もし } from "../共通/構文";
import { 以上, 以下, 等しい } from "../共通/演算";
import { 繋ぐ } from "../共通/関数";

export type 構え = "反射" | "普通" | "熟考";

/**
 * 裏取りの票．「要らない」は，判定器がはっきりそう言ったときだけ．迷っている
 * とき (確率が間に落ちたとき) と，判定が取れなかったときは未定義 = 票を入れない．
 */
export type 裏取り = "要る" | "要らない";

const 問い一覧 = 定義.問い as 記録<文字列, 問い>;

/** 構えを決めるための問い (会話の流れつきの状態に掛ける)． */
export const 構えの問い: 記録<文字列, 問い> = { 考える量: 問い一覧["考える量"]! };

/** 裏を取りに行くべきかの問い (発言だけの状態に掛ける)． */
export const 裏取りの問い: 記録<文字列, 問い> = { 裏取り: 問い一覧["裏取り"]! };

/** 判定に見せる会話ログの行数．要るのは直近の流れだけ． */
const 見せる行数 = 8;

export function 見立ての状態(状況: {
  会話ログ: 文字列;
  相手の名前: 文字列;
  問いかけ: 文字列;
}): 文字列 {
  return 状態を書く([
    ["会話の流れ", 末尾の行(状況.会話ログ, 見せる行数)],
    ["今回の発言", `${状況.相手の名前}: ${状況.問いかけ}`],
  ]);
}

/**
 * ルールのある遊びの名前．これが流れの中に見えていたら，今回の発言が一語だけ
 * («りんご») でも遊びの一手として読む．精度の高い合図なので，判定が取れている
 * ときでもこれは効かせる．
 */
const 遊びの合図 = 新しい型(
  繋ぐ(
    [
      "しりとり",
      "クイズ",
      "なぞなぞ",
      "謎かけ",
      "大喜利",
      "連想ゲーム",
      "山手線ゲーム",
      "古今東西",
      "マジカルバナナ",
      "アナグラム",
      "回文",
      "縛り",
    ],
    "|",
  ),
);

/** 発言そのものが，正確さの要る頼みごとである合図． */
const 正確さの合図 = 新しい型(
  繋ぐ(
    [
      "計算",
      "証明",
      "何文字",
      "逆から",
      "並べ替え",
      "翻訳して",
      "要約して",
      "実装して",
      "コードを?書",
      "正規表現",
    ],
    "|",
  ),
);

/** 雑談ではなく，中身のある答えを求めている合図． */
const 問いの合図 = 新しい型(
  繋ぐ(
    [
      "[?？]",
      "とは",
      "教えて",
      "どう",
      "なぜ",
      "なんで",
      "違い",
      "方法",
      "やり方",
      "おすすめ",
      "解説",
      "説明",
    ],
    "|",
  ),
);

/** 遊びが進行中か．発言そのものと，直近の流れの両方を見る． */
export function 遊びの最中か(問いかけ: 文字列, 会話ログ: 文字列): 真偽 {
  return 遊びの合図.test(問いかけ) || 遊びの合図.test(末尾の行(会話ログ, 見せる行数));
}

/** 判定が取れなかったときの構え．合図の語だけで決める． */
export function 決定的な構え(問いかけ: 文字列, 会話ログ: 文字列): 構え {
  return もし(遊びの最中か(問いかけ, 会話ログ) || 正確さの合図.test(問いかけ), {
    であれば: (): 構え => "熟考",
    でなければ: () =>
      もし(問いの合図.test(問いかけ), {
        であれば: (): 構え => "普通",
        でなければ: (): 構え => "反射",
      }),
  });
}

/** 段階の点数は間へ落ちる連続値．丸めずに，閾値で切る． */
function 点数から構え(点数: 数値): 構え {
  return もし(以上(点数, 定義.閾値.熟考), {
    であれば: (): 構え => "熟考",
    でなければ: () =>
      もし(以上(点数, 定義.閾値.普通), {
        であれば: (): 構え => "普通",
        でなければ: (): 構え => "反射",
      }),
  });
}

/** 判定器の答え (無ければ未定義) から，構えを決める． */
export function 見立てる(答え: 省略可<答え一覧>, 問いかけ: 文字列, 会話ログ: 文字列): 構え {
  const 点数 = 段階の点数(答え, "考える量");

  return もし(等しい(点数, 未定義), {
    であれば: () => 決定的な構え(問いかけ, 会話ログ),
    // 判定が取れていても，遊びの合図だけは上書きで効かせる．
    でなければ: (): 構え => (遊びの最中か(問いかけ, 会話ログ) ? "熟考" : 点数から構え(点数!)),
  });
}

/** 判定器の答えから，裏取りの票を読む．間に落ちた確率は「分からない」として扱う． */
export function 裏取りを読む(答え: 省略可<答え一覧>): 省略可<裏取り> {
  const 確率 = 真の確率(答え, "裏取り");

  return もし(等しい(確率, 未定義), {
    であれば: (): 省略可<裏取り> => 未定義,
    でなければ: (): 省略可<裏取り> =>
      もし(以上(確率!, 定義.閾値.調べる), {
        であれば: (): 省略可<裏取り> => "要る",
        でなければ: (): 省略可<裏取り> => (以下(確率!, 定義.閾値.調べない) ? "要らない" : 未定義),
      }),
  });
}
