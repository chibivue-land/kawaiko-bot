/**
 * kawaiko が同じことを言い続けるのを出力側で止める決定的なガード．
 *
 * 返信の指示文にはチャンネルの会話ログが差し込まれ，そこには kawaiko 自身の
 * 過去の発言も入っている．小さいモデルは似た形の自分の発言が並んでいるのを
 * few-shot のお手本として読み，その型に固定される．だから 1 つのチャンネルが
 * 誰が何を言おうと同じ骨格 (「〇〇さん，それはあまりに〜〜」) しか返さなくなる．
 * 指示文側の「同じことを繰り返さない」だけでは到底このループを切れないので，
 * 重なり具合をこちらで測り，呼び出し側に作り直させる．
 *
 * ここでやるのは類似度の計算だけ．「これを再利用するな」という指示文の組み立ては
 * 指示文.ts の担当．
 */

/** この bigram (Dice) 重なり以上なら「また同じこと」とみなす． */
export const 類似の閾値 = 0.6;

/** これだけ書き出しが一致していれば，それだけで型に嵌っている． */
const 書き出しの長さ = 7;

/** 書き出し一致に与える点数．後ろに何が続くかによらない． */
const 書き出し一致の点数 = 0.75;

/** これより短い発言は完全一致だけを見る (短文は偶然かぶる)． */
const 比較できる最短長 = 6;

/** 過去の自分の発言を，いくつまで見せる / 比べるか． */
export const 回避する件数 = 6;

/**
 * 同じ型の 2 つの発言の間で変わる部分を全部落とす．メンション・絵文字・リンク・
 * 句読点，そして先頭の「〇〇さん，」という呼びかけ (名前は毎回変わるが，その裏の
 * 骨格は変わらない)．
 */
export function 発言を正規化する(本文: 文字列): 文字列 {
  return (
    本文
      .replace(/<a?:\w+:\d+>/g, "")
      .replace(/<@!?&?\d+>/g, "")
      .replace(/https?:\/\/\S+/g, "")
      // 先頭の「〇〇さん，」．敬称の後ろに区切りを要求しているのは，単に「さん」を
      // 含むだけの語 (「さんまが好き」) を巻き込まないため．
      .replace(
        /^\s*\S{1,24}?\s*(?:さん|くん|ちゃん|様|氏)(?=[、,，。．!！?？:：\s]|$)[、,，。．!！?？:：\s]*/u,
        "",
      )
      .replace(/[\s\p{P}\p{S}]/gu, "")
      .toLowerCase()
  );
}

function 二文字組(本文: 文字列): 配列<文字列> {
  return 写す(本文.slice(0, -1).split(""), (_文字, 位置) => 本文.slice(位置, 位置 + 2));
}

/** 文字 bigram の Dice 係数 (日本語によく効く)． */
function ダイス係数(左辺: 文字列, 右辺: 文字列): 数値 {
  const 左 = 二文字組(左辺);
  const 右 = 二文字組(右辺);

  return もし(空か(左) || 空か(右), {
    であれば: () => (等しい(左辺, 右辺) ? 1 : 0),
    でなければ: () => (2 * 一致した組の数(左, 右)) / (長さ(左) + 長さ(右)),
  });
}

/** 左の在庫を右が食べていく．同じ組は，ある数だけしか数えない． */
function 一致した組の数(左: 読み取り専用配列<文字列>, 右: 読み取り専用配列<文字列>): 数値 {
  const 在庫 = 新しい対応表<文字列, 数値>();
  各要素に(左, (組) => {
    在庫.set(組, (在庫.get(組) ?? 0) + 1);
  });

  let 一致数 = 0;
  各要素に(右, (組) => {
    const 残り = 在庫.get(組) ?? 0;

    もし(残り > 0, {
      であれば: () => {
        在庫.set(組, 残り - 1);
        一致数++;
      },
    });
  });

  return 一致数;
}
/** 正規化済みの 2 つの発言がどれだけ重なっているか． */
function 一組の点数(候補: 文字列, 過去: 文字列): 数値 {
  return もし(等しい(候補, 過去), {
    であれば: () => 1,
    でなければ: () =>
      もし(数学.min(長さ(候補), 長さ(過去)) < 比較できる最短長, {
        であれば: () => 0,
        でなければ: () => 書き出しも見た点数(候補, 過去),
      }),
  });
}

function 書き出しも見た点数(候補: 文字列, 過去: 文字列): 数値 {
  const 素点 = ダイス係数(候補, 過去);
  const 書き出しが同じ =
    以上(数学.min(長さ(候補), 長さ(過去)), 書き出しの長さ) &&
    等しい(候補.slice(0, 書き出しの長さ), 過去.slice(0, 書き出しの長さ));

  return もし(書き出しが同じ, {
    であれば: () => 数学.max(素点, 書き出し一致の点数),
    でなければ: () => 素点,
  });
}

/** 0 (無関係) 〜 1 (同一)．最も似ている過去の発言との比較． */
export function 反復度(本文: 文字列, 過去の発言: 読み取り専用配列<文字列>): 数値 {
  const 候補 = 発言を正規化する(本文);

  return もし(空か(候補), {
    であれば: () => 0,
    でなければ: () =>
      数学.max(
        0,
        ...写す(過去の発言, (発言) => {
          const 過去 = 発言を正規化する(発言);

          return もし(空か(過去), {
            であれば: () => 0,
            でなければ: () => 一組の点数(候補, 過去),
          });
        }),
      ),
  });
}

/** 直近の発言と近すぎて，ループに見えるか． */
export function 反復しているか(本文: 文字列, 過去の発言: 読み取り専用配列<文字列>): 真偽 {
  return 以上(反復度(本文, 過去の発言), 類似の閾値);
}
