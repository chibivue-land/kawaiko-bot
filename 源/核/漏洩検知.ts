/**
 * 指示書の丸写しを出力側で止める決定的なガード．
 *
 * 「秘密にしろ」というプロンプト側のルールは小さいモデルには効きが弱い．そこで
 * 投稿前に，生成文がシステムプロンプトの特徴的な行をそのまま含んでいないか
 * (まともな返事なら絶対に起きないこと) を調べ，起きていたら在庫の受け流しに
 * 差し替える．
 */
import { 対応表, 文字列, 真偽 } from "../共通/型";

const 番人の最短長 = 20;
const 番人の上限 = 60;

/** 指示書から取った「見張り用の行」．プロンプト文字列ごとにキャッシュする． */
const 番人キャッシュ = new 対応表<文字列, 文字列[]>();

export function 番人の行を作る(指示書: 文字列): 文字列[] {
  const 既存 = 番人キャッシュ.get(指示書);
  if (既存) return 既存;

  const 番人 = 指示書
    .split("\n")
    .map((行) => 行.replace(/^[-*#\s]+/, "").trim())
    .filter((行) => 行.length >= 番人の最短長)
    .slice(0, 番人の上限);

  番人キャッシュ.set(指示書, 番人);
  return 番人;
}

/** 返事が指示書を再現してしまっているように見えるか． */
export function 指示書が漏れているか(本文: 文字列, 指示書: 文字列): 真偽 {
  if (!本文) return false;
  // 空白を潰して比較する．軽い整形で検知を回避されないように．
  const 潰す = (文: 文字列) => 文.replace(/\s+/g, "");
  const 対象 = 潰す(本文);
  for (const 番人 of 番人の行を作る(指示書)) {
    // 内部の行が 1 つでも丸写しなら，その時点で真っ黒．
    if (対象.includes(潰す(番人))) return true;
  }
  return false;
}
