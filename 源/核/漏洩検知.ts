import { 文字列, 新しい対応表, 真偽 } from "../共通/型";
import type { 配列 } from "../共通/型";
import {
  いずれか,
  写す,
  分ける,
  前後の空白を落とす,
  取り出す,
  含む,
  空か,
  絞る,
  置き換える,
  長さ,
} from "../共通/関数";
import { 以上 } from "../共通/演算";
import { もし } from "../共通/構文";
import { 改行 } from "../共通/文字";
/**
 * 指示書の丸写しを出力側で止める決定的なガード．
 *
 * 「秘密にしろ」というプロンプト側のルールは小さいモデルには効きが弱い．そこで
 * 投稿前に，生成文がシステムプロンプトの特徴的な行をそのまま含んでいないか
 * (まともな返事なら絶対に起きないこと) を調べ，起きていたら在庫の受け流しに
 * 差し替える．
 */

const 番人の最短長 = 20;
const 番人の上限 = 60;

/** 指示書から取った「見張り用の行」．プロンプト文字列ごとにキャッシュする． */
const 番人キャッシュ = 新しい対応表<文字列, 文字列[]>();

export function 番人の行を作る(指示書: 文字列): 配列<文字列> {
  return 番人キャッシュ.get(指示書) ?? 番人の行を作り直す(指示書);
}

function 番人の行を作り直す(指示書: 文字列): 配列<文字列> {
  const 番人 = 取り出す(
    絞る(
      写す(分ける(指示書, 改行), (行) => 前後の空白を落とす(置き換える(行, /^[-*#\s]+/, ""))),
      (行) => 以上(長さ(行), 番人の最短長),
    ),
    0,
    番人の上限,
  );

  番人キャッシュ.set(指示書, 番人);

  return 番人;
}
/** 返事が指示書を再現してしまっているように見えるか． */
export function 指示書が漏れているか(本文: 文字列, 指示書: 文字列): 真偽 {
  // 空白を潰して比較する．軽い整形で検知を回避されないように．
  const 潰す = (文: 文字列) => 置き換える(文, /\s+/g, "");
  const 対象 = 潰す(本文);

  return もし(空か(本文), {
    であれば: () => false,
    // 内部の行が 1 つでも丸写しなら，その時点で真っ黒．
    でなければ: () => いずれか(番人の行を作る(指示書), (番人) => 含む(対象, 潰す(番人))),
  });
}
