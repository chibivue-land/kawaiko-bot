/**
 * 発言の中に貼られた URL．
 *
 * 「これ何？」と URL だけ投げられることは多いのに，kawaiko はこれまでその先を
 * 見に行っていなかった．どれを見に行ってよいかの判断は純粋なので核に置く．
 * 実際に読むのは外界 (外界/頁.ts)．
 */
import { 文字列, 新しい場所, 偽, 真偽 } from "../共通/型";
import type { 配列 } from "../共通/型";
import { もし, 試す } from "../共通/構文";
import { より小さい, 否定, 等しい } from "../共通/演算";
import { いずれか, 写す, 取り出す, 終わるか, 絞る, 長さ } from "../共通/関数";

/** 読んできた 1 ページ． */
export interface 読んだ頁 {
  場所: 文字列;
  /** markdown に均した中身． */
  中身: 文字列;
}

/**
 * 1 発言につき読みに行く上限．
 *
 * ブラウザの時間は無料枠で 1 日 10 分しかない．1 通に 5 本貼られて全部読むと，
 * それだけで数十秒使う．先頭の 1 本だけ見れば，たいていの「これ何？」は足りる．
 */
export const 一度に読む数 = 1;

/**
 * URL に出てよい字だけを並べたもの (RFC 3986)．
 *
 * 「空白まで全部」で採ると，日本語は URL の直後に空白を置かないので
 * `https://example.com/a、どう？` を丸ごと URL にしてしまう．ASCII に絞れば
 * そこで自然に切れる．
 */
const 場所の形 = /https?:\/\/[A-Za-z0-9\-._~:/?#[\]@!$&'*+,;=%()]+/gu;

/** 発言に貼られた URL を，前から順に拾う． */
export function 貼られた場所(本文: 文字列): 配列<文字列> {
  const 候補 = 写す(本文.match(場所の形) ?? [], 末尾の飾りを落とす);

  return 取り出す(絞る(候補, 読みに行ってよいか), 0, 一度に読む数);
}

/**
 * 文末に巻き込まれた記号を落とす．
 *
 * 閉じ括弧だけは開き括弧と数が合わないときにしか落とさない — Wikipedia の
 * `..._(programming)` のように，括弧まで含めて 1 つの URL のことがある．
 */
function 末尾の飾りを落とす(場所: 文字列): 文字列 {
  const 刈った = 場所.replace(/[.,!?:;'"]+$/u, "");

  return もし(釣り合わない閉じ括弧か(刈った), {
    であれば: () => 末尾の飾りを落とす(刈った.slice(0, -1)),
    でなければ: () => 刈った,
  });
}

function 釣り合わない閉じ括弧か(場所: 文字列): 真偽 {
  return 終わるか(場所, ")") && より小さい(長さ(場所.split("(")), 長さ(場所.split(")")));
}

/**
 * その URL を読みに行ってよいか．
 *
 * http(s) だけ．Discord の CDN は除く — あちらは添付として別の道で読んでおり，
 * 画像やファイルをブラウザで開いても意味が無い．
 */
export function 読みに行ってよいか(場所: 文字列): 真偽 {
  return 試す({
    実行: () => {
      const 行き先 = 新しい場所(場所);
      const 仕組み = 行き先.protocol;

      return (
        (等しい(仕組み, "https:") || 等しい(仕組み, "http:")) &&
        否定(いずれか(添付の置き場, (ホスト) => 等しい(行き先.hostname, ホスト)))
      );
    },
    // URL として読めないものは，そもそも見に行かない．
    しくじったら: () => 偽,
  });
}

const 添付の置き場 = ["cdn.discordapp.com", "media.discordapp.net"];
