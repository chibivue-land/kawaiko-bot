/**
 * kawaiko に会話をさせるときの頼み方．名指しに答える場合と，頼まれてもいないのに
 * 横槍を入れる場合の 2 つ．
 *
 * 両者で共通するもの (会話ログ・記憶・回避一覧・抑揚) は 指示文.ts から来る．
 * ここに置くのは，その 2 つの状況を分ける指示だけ．
 */
import 横槍の規則 from "./会話-横槍.md?raw";
import 会話の規則 from "./会話-規則.md?raw";

import type { 読んだ頁 } from "./参照";
import {
  回避節,
  会話ログ節,
  参考情報節,
  頁節,
  添付節,
  文体節,
  機嫌節,
  節をつなぐ,
  記憶節,
} from "./指示文";
import type { 読んだ添付 } from "./添付";
import type { 事実 } from "./記憶";

import { 数値, 文字列 } from "../共通/型";
import type { 省略可, 真偽, 読み取り専用配列 } from "../共通/型";
import { 否定 } from "../共通/演算";
import { 前後の空白を落とす, 空か, 繋ぐ } from "../共通/関数";

export interface 会話の状況 {
  時刻の表示: 文字列;
  /** 日本時間の時 (0-23)．kawaiko の機嫌は時間帯で変わる． */
  時: 数値;
  /** この回，web を引いたか．引いた回は一言で切らない． */
  調べたか?: 省略可<真偽>;
  相手の名前: 文字列;
  会話ログ: 文字列;
  事実一覧: 読み取り専用配列<事実>;
  自分の直近発言: 読み取り専用配列<文字列>;
  乱数?: 省略可<() => 数値>;
}

const 会話のルール = 前後の空白を落とす(会話の規則);

/** 誰かが kawaiko に直接話しかけてきた． */
export function 名指しへの指示文を組み立てる(
  状況: 会話の状況 & {
    問いかけ: 文字列;
    参考情報: 文字列;
    頁一覧: 読み取り専用配列<読んだ頁>;
    添付一覧: 読み取り専用配列<読んだ添付>;
  },
): 文字列 {
  return 節をつなぐ(
    `今は ${状況.時刻の表示}。`,
    会話ログ節(状況.会話ログ),
    繋ぐ(
      [
        `この流れで、${状況.相手の名前} さんが kawaiko に言った:`,
        "",
        否定(空か(状況.問いかけ)) ? 状況.問いかけ : "(本文なし、メンションだけ)",
      ],
      "\n",
    ),
    添付節(状況.添付一覧),
    頁節(状況.頁一覧),
    参考情報節(状況.参考情報),
    記憶節(状況.事実一覧),
    回避節(状況.自分の直近発言),
    会話のルール,
    機嫌節(状況.時),
    文体節(状況.乱数, 状況.調べたか),
  );
}

/** 誰も頼んでいないのに，kawaiko が人の発言に割り込む． */
export function 横槍の指示文を組み立てる(状況: 会話の状況 & { 対象の発言: 文字列 }): 文字列 {
  return 節をつなぐ(
    `今は ${状況.時刻の表示}。`,
    否定(空か(状況.会話ログ)) ? `チャンネルの直近の流れ:\n${状況.会話ログ}` : "",
    繋ぐ([`この中で ${状況.相手の名前} さんのこの発言に注目した:`, "", 状況.対象の発言], "\n"),
    前後の空白を落とす(横槍の規則),
    記憶節(状況.事実一覧),
    回避節(状況.自分の直近発言),
    機嫌節(状況.時),
    文体節(状況.乱数),
  );
}
