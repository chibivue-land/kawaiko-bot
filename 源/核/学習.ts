/** 1 回で覚える事実の数．kawaiko は百科事典を作っているのではない． */
export const 一度に学ぶ事実の数 = 3;

/** これ未満だと，結論を出せるだけの新しい会話が無い． */
export const 学習に要る観測数 = 8;

/** 1 回で読む上限．指示文の大きさ (とコスト) の上限でもある． */
export const 一度に読む観測数 = 60;

/** 事実 1 行の最大長． */
const 事実一行の最大長 = 100;

/**
 * あえて kawaiko の人格ではない．ここは抽出する係であって，演じる係ではない．
 * 読ませる会話ログは信用できないユーザー文なので，その枠付けも書いてある．
 */
export const 抽出係の指示書: 文字列 = 前後の空白を落とす(
  差し込む(抽出の指示, {
    一度に学ぶ数: 文字列(一度に学ぶ事実の数),
    一行の最大長: 文字列(事実一行の最大長),
  }),
);

/** `- [主語] 事実`．小さいモデルが選びがちな記号の揺れを吸収する． */
const 事実の行 = /^\s*[-*・•]?\s*[[［]([^\]］]{1,40})[\]］]\s*[:：]?\s*(.+?)\s*$/u;

const サーバーを指す語 = 新しい集合(["server", "サーバー", "このサーバー", "全体", "guild"]);

export function 抽出依頼を組み立てる(観測一覧: 読み取り専用配列<観測>): 文字列 {
  const 窓 = 繋ぐ(
    写す(観測一覧, (観測) => {
      const 名前 = 観測.kawaikoの発言か ? "kawaiko" : 観測.発言者名;
      return `${名前}: ${切り出す(置き換える(観測.本文, /\s+/g, " "), 0, 200)}`;
    }),
    "\n",
  );
  return 前後の空白を落とす(
    差し込む(依頼のひな型, { 窓, 一度に学ぶ数: 文字列(一度に学ぶ事実の数) }),
  );
}

/** 表示名 -> Discord のユーザー id．その窓で喋った人ぶん． */
export function 発言者索引(観測一覧: 読み取り専用配列<観測>): 対応表<文字列, 文字列> {
  const 索引 = 新しい対応表<文字列, 文字列>();

  各要素に(
    絞る(観測一覧, (観測) => !観測.kawaikoの発言か),
    (観測) => {
      索引.set(小文字にする(観測.発言者名), 観測.発言者id);
    },
  );

  return 索引;
}
/**
 * モデルの出力を事実へ読み取り，主語を実際に喋った人へ突き合わせる (表示名が
 * 安定した Discord の id になる)．
 */
export function 事実を読み取る(
  本文: 文字列,
  発言者: 読み取り専用対応表<文字列, 文字列>,
): 配列<学習した事実> {
  const 読めた行 = 絞る(
    写す(分ける(本文, 改行), (行) => 事実の行.exec(行)),
    (一致): 一致 is RegExpExecArray => 等しくない(一致, 空),
  );

  const 事実一覧 = 絞る(
    写す(読めた行, (一致) => 一行を事実にする(一致, 発言者)),
    (事実): 事実 is 学習した事実 => 等しくない(事実, 未定義),
  );

  // 上限は最後に掛ける．どの行から来たかによらず同じ数に揃うように．
  return 取り出す(事実一覧, 0, 一度に学ぶ事実の数);
}

/** 1 行を事実にする．短すぎる / 長すぎる本文はここで落ちる． */
function 一行を事実にする(
  一致: RegExpExecArray,
  発言者: 読み取り専用対応表<文字列, 文字列>,
): 省略可<学習した事実> {
  const 主語名 = 前後の空白を落とす(一致[1]!);
  const 事実の本文 = 前後の空白を落とす(一致[2]!);

  return もし(空か(事実の本文) || 長さ(事実の本文) > 事実一行の最大長, {
    であれば: (): 省略可<学習した事実> => 未定義,
    でなければ: () => 主語を解決する(主語名, 事実の本文, 発言者),
  });
}

/** 主語がサーバー全体か，喋った人か，それ以外の話題か． */
function 主語を解決する(
  主語名: 文字列,
  本文: 文字列,
  発言者: 読み取り専用対応表<文字列, 文字列>,
): 学習した事実 {
  return もし(サーバーを指す語.has(小文字にする(主語名)), {
    であれば: (): 学習した事実 => ({ 主語の種別: "server", 主語名: "このサーバー", 本文 }),
    でなければ: () => {
      const 主語id: 省略可<文字列> = 発言者.get(小文字にする(主語名));

      return もし(等しくない(主語id, 未定義), {
        であれば: (): 学習した事実 => ({ 主語の種別: "user", 主語id, 主語名, 本文 }),
        でなければ: (): 学習した事実 => ({ 主語の種別: "topic", 主語名, 本文 }),
      });
    },
  });
}
