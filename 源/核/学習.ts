/**
 * 会話を持続的な事実へ変える部分 — 抽出の指示文と、返ってきたものの読み取り。
 * 純粋。モデルを呼ぶのは 振る舞い/学習実行.ts の仕事。
 */
import {
  切り出す,
  前後の空白を落とす,
  分ける,
  小文字にする,
  写す,
  繋ぐ,
  置き換える,
} from "../共通/関数";
import { 対応表, 文字列 } from "../共通/型";
import type { 配列, 読み取り専用対応表, 読み取り専用配列, 省略可 } from "../共通/型";
import type { 学習した事実, 観測 } from "./記憶";
import { 差し込む } from "./指示文";
import 抽出の指示 from "./学習-抽出指示.md?raw";
import 依頼のひな型 from "./学習-依頼.md?raw";

/** 1 回で覚える事実の数。kawaiko は百科事典を作っているのではない。 */
export const 一度に学ぶ事実の数 = 3;
/** これ未満だと、結論を出せるだけの新しい会話が無い。 */
export const 学習に要る観測数 = 8;
/** 1 回で読む上限。指示文の大きさ (とコスト) の上限でもある。 */
export const 一度に読む観測数 = 60;
/** 事実 1 行の最大長。 */
const 事実一行の最大長 = 100;

/**
 * あえて kawaiko の人格ではない。ここは抽出する係であって、演じる係ではない。
 * 読ませる会話ログは信用できないユーザー文なので、その枠付けも書いてある。
 */
export const 抽出係の指示書: 文字列 = 前後の空白を落とす(
  差し込む(抽出の指示, {
    一度に学ぶ数: 文字列(一度に学ぶ事実の数),
    一行の最大長: 文字列(事実一行の最大長),
  }),
);

/** `- [主語] 事実`。小さいモデルが選びがちな記号の揺れを吸収する。 */
const 事実の行 = /^\s*[-*・•]?\s*[[［]([^\]］]{1,40})[\]］]\s*[:：]?\s*(.+?)\s*$/u;

const サーバーを指す語 = new Set(["server", "サーバー", "このサーバー", "全体", "guild"]);

export function 抽出依頼を組み立てる(観測一覧: 読み取り専用配列<観測>): 文字列 {
  const 窓 = 繋ぐ(
    写す(観測一覧, (観測) => {
      const 名前 = 観測.kawaikoの発言か ? "kawaiko" : 観測.発言者名;
      return `${名前}: ${切り出す(置き換える(観測.本文, /\s+/g, " "), 0, 200)}`;
    }),
    "\n",
  );
  return 前後の空白を落とす(
    差し込む(依頼のひな型, { 窓, 一度に学ぶ数: 文字列(一度に学ぶ事実の数) }),
  );
}

/** 表示名 -> Discord のユーザー id。その窓で喋った人ぶん。 */
export function 発言者索引(観測一覧: 読み取り専用配列<観測>): 対応表<文字列, 文字列> {
  const 索引 = new 対応表<文字列, 文字列>();
  for (const 観測 of 観測一覧) {
    if (観測.kawaikoの発言か) continue;
    索引.set(小文字にする(観測.発言者名), 観測.発言者id);
  }
  return 索引;
}

/**
 * モデルの出力を事実へ読み取り、主語を実際に喋った人へ突き合わせる (表示名が
 * 安定した Discord の id になる)。
 */
export function 事実を読み取る(
  本文: 文字列,
  発言者: 読み取り専用対応表<文字列, 文字列>,
): 配列<学習した事実> {
  const 事実一覧: 配列<学習した事実> = [];
  for (const 行 of 分ける(本文, "\n")) {
    // 先に上限を見る。下のどの枝を通っても効くように。
    if (事実一覧.length >= 一度に学ぶ事実の数) break;
    const 一致 = 事実の行.exec(行);
    if (!一致) continue;
    const 主語名 = 前後の空白を落とす(一致[1]!);
    const 事実の本文 = 前後の空白を落とす(一致[2]!);
    if (!事実の本文 || 事実の本文.length > 事実一行の最大長) continue;

    if (サーバーを指す語.has(小文字にする(主語名))) {
      事実一覧.push({ 主語の種別: "server", 主語名: "このサーバー", 本文: 事実の本文 });
      continue;
    }
    const 主語id: 省略可<文字列> = 発言者.get(小文字にする(主語名));
    事実一覧.push(
      主語id
        ? { 主語の種別: "user", 主語id, 主語名, 本文: 事実の本文 }
        : { 主語の種別: "topic", 主語名, 本文: 事実の本文 },
    );
  }
  return 事実一覧;
}
