/**
 * モデルが作った URL を，投稿の前に落とす決定的なガード．
 *
 * 小さいモデルは「リンクを教えて」と言われると，それっぽい URL を平気で組み立てる．
 * 実在しない Spotify のアルバムを，id の後ろが `XfXfXf…` と暴走したまま貼った
 * ことがある (2026-10-28)．URL は口調ではなく事実の主張なので，「作るな」という
 * プロンプト側の頼みだけには任せない．モデルが見たもの (指示書と指示文 — 会話ログ・
 * 参考情報・読んだ頁) に出てこなかった URL は，チャンネルへ出さない．
 *
 * 純粋．判断に使うのは出力と，モデルが見たものの 2 つの文字列だけ．
 */
import { 場所の形, 場所を拾う, 末尾の飾りを落とす } from "./参照";

import { 文字列, 真偽 } from "../共通/型";
import type { 省略可, 読み取り専用配列, 配列 } from "../共通/型";
import { もし } from "../共通/構文";
import { 等しい } from "../共通/演算";
import {
  いずれか,
  一覧に含む,
  切り出す,
  前後の空白を落とす,
  始まるか,
  末尾に足す,
  空か,
  置き換える,
  長さ,
} from "../共通/関数";

export interface 落とした結果 {
  本文: 文字列;
  /** 見たことのない URL として落としたもの．ログ用． */
  落とした場所: 配列<文字列>;
}

/**
 * モデルが見たものに無い URL を落とす．
 *
 * 1 つ目は 断り に差し替え，2 つ目以降は黙って消す — 同じ断りが 1 通に何度も
 * 並ぶのは，それ自体が壊れて見える．
 */
export function 確かめていない場所を落とす(
  本文: 文字列,
  見たもの: 文字列,
  断り: 文字列,
): 落とした結果 {
  const 見た場所一覧 = 場所を拾う(見たもの);
  const 落とした場所: 配列<文字列> = [];

  const 書き換えた = 置き換える(本文, 場所の形, (生: 文字列) => {
    const 場所 = 末尾の飾りを落とす(生);
    // 文末の「．」や閉じ括弧は URL ではないので，消すときも残す．
    const 飾り = 切り出す(生, 長さ(場所));

    return もし(見たことがあるか(場所, 見た場所一覧), {
      であれば: () => 生,
      でなければ: () => {
        末尾に足す(落とした場所, 場所);

        return `${等しい(長さ(落とした場所), 1) ? 断り : ""}${飾り}`;
      },
    });
  });

  return {
    本文: もし(空か(落とした場所), {
      であれば: () => 本文,
      // 消した跡の空白の重なりを均す．
      でなければ: () => 前後の空白を落とす(置き換える(書き換えた, /[ \t]{2,}/g, " ")),
    }),
    落とした場所,
  };
}

/**
 * 見たものの中に同じ URL があったか．
 *
 * 見た URL を区切り (`/` `?` `#`) で短くしたものも通す — 記事の URL を見て
 * そのリポジトリの根を指すのは作り話ではない．逆向き (見た URL の後ろに
 * 何かを継ぎ足したもの) は通さない．`.../album/` の後ろを捏造するのがまさにそれ．
 */
export function 見たことがあるか(場所: 文字列, 見た場所一覧: 読み取り専用配列<文字列>): 真偽 {
  const 探す場所 = 末尾の斜線を落とす(場所);

  return いずれか(見た場所一覧, (見た) => {
    const 見た場所 = 末尾の斜線を落とす(見た);

    return (
      等しい(見た場所, 探す場所) ||
      (始まるか(見た場所, 探す場所) && 一覧に含む(区切り, 見た場所[長さ(探す場所)]))
    );
  });
}

const 区切り: 読み取り専用配列<省略可<文字列>> = ["/", "?", "#"];

function 末尾の斜線を落とす(場所: 文字列): 文字列 {
  return 置き換える(場所, /\/+$/u, "");
}
