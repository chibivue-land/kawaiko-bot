/**
 * 毎時ディスパッチの方針．
 *
 * Workers Free の cron は 1 アカウント 5 本までなので，投稿枠ごとに cron を
 * 生やす代わりに毎時のディスパッチャを 1 本だけ回し，その時刻に何をするかを
 * ここ (日本時間) で決める．確率ゲートは各ユースケース側の担当．
 */
import { 数値, 文字列 } from "../共通/型";
import { 現在時刻, 日本時間, Temporal } from "./時刻";
import { 一覧に含む, 前を埋める } from "../共通/関数";
import { もし } from "../共通/構文";
import { 余り } from "../共通/演算";

/** 独り言の枠に割り当てた日本時間の時刻 (確率ゲート後で 1 日 3 回ほど)． */
export const 独言の時刻: readonly 数値[] = [9, 13, 18, 23];

export type 担当 = "独言" | "横槍" | "学習";

/**
 * 指定の時刻は独り言，偶数時は誰かの発言への横槍，残りは観測を記憶へ畳み込む．
 * 学習は閑散時にはコストが出ない (未読が一定数たまるまでモデルを呼ばない)．
 */
export function その時刻の担当(時: 数値): 担当 {
  return もし(一覧に含む(独言の時刻, 時), {
    であれば: (): 担当 => "独言",
    でなければ: () =>
      もし(余り(時, 2) === 0, {
        であれば: (): 担当 => "横槍",
        でなければ: (): 担当 => "学習",
      }),
  });
}

/** kawaiko の壁掛け時計． */
function 日本時間で(時刻: Temporal.Instant): Temporal.ZonedDateTime {
  return 時刻.toZonedDateTimeISO(日本時間);
}

/** 日本時間の時 (0-23)． */
export function 日本時間の時(時刻: Temporal.Instant = 現在時刻()): 数値 {
  return 日本時間で(時刻).hour;
}

/** 日本時間の表示．例: 「8月21日(木) 22:50」． */
export function 日本時間の表示(時刻: Temporal.Instant = 現在時刻()): 文字列 {
  const 現地 = 日本時間で(時刻);
  const 曜日一覧 = ["月", "火", "水", "木", "金", "土", "日"];
  // Temporal の曜日は月曜が 1 から始まる．上の並びもそれに合わせてある．
  const 曜日 = 曜日一覧[現地.dayOfWeek - 1]!;
  const 分 = 前を埋める(文字列(現地.minute), 2, "0");
  return `${現地.month}月${現地.day}日(${曜日}) ${現地.hour}:${分}`;
}
