import type { 答え一覧 } from "./判定";
import { 横槍の状態, 絡む相手を決める, type 見立てた候補 } from "./横槍";

import { 発言を作る } from "../試験/偽物";
import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 未定義 } from "../共通/型";

function 答えを作る(絡みがい: number, そっとしておく: number): 答え一覧 {
  return {
    絡みがい: { 種別: "段階", 点数: 絡みがい, 確信: 0.9 },
    そっとしておくべきか: { 種別: "真偽", 確率: そっとしておく },
  };
}

function 候補を作る(id: string, 答え: 答え一覧 | undefined): 見立てた候補 {
  return { 発言: 発言を作る({ id }), 答え };
}

仕様("絡む相手を決める", () => {
  検証("茶化してはいけない発言は，どれだけ絡みがいがあっても選ばない", () => {
    const 結末 = 絡む相手を決める(
      [候補を作る("落ち込んでいる", 答えを作る(3, 0.9)), 候補を作る("雑談", 答えを作る(1, 0.05))],
      () => 0,
    );

    期待(結末).の形をしている({ 種別: "選んだ", 発言: { id: "雑談" } });
  });

  検証("触れてよい発言が一つも無ければ見送る", () => {
    期待(絡む相手を決める([候補を作る("つらい", 答えを作る(2, 0.8))], () => 0)).と等しい({
      種別: "見送り",
    });
  });

  検証("絡みがいで重みを付ける．高いものほど当たりやすいが，決め打ちはしない", () => {
    const 候補一覧 = [候補を作る("うん", 答えを作る(0, 0)), 候補を作る("主張", 答えを作る(3, 0))];
    const 選ぶ = (賽: number) => {
      const 結末 = 絡む相手を決める(候補一覧, () => 賽);

      return 結末.種別 === "選んだ" ? 結末.発言.id : "見送り";
    };

    // 重みは 0.05 対 9.05．賽のほとんどの目が «主張» に落ちる．
    期待(選ぶ(0.5)).である("主張");
    期待(選ぶ(0.99)).である("主張");
    // それでも «うん» の目は残っている (同じ発言に 2 度絡まないための揺らぎ)．
    期待(選ぶ(0)).である("うん");
  });

  検証("判定が一つも取れなければ，これまでどおり無作為に選ぶ", () => {
    const 候補一覧 = [候補を作る("一", 未定義), 候補を作る("二", 未定義)];

    期待(絡む相手を決める(候補一覧, () => 0)).の形をしている({ 発言: { id: "一" } });
    期待(絡む相手を決める(候補一覧, () => 0.99)).の形をしている({ 発言: { id: "二" } });
  });
});

仕様("横槍の状態", () => {
  検証("流れと，注目している発言を分けて書く", () => {
    const 状態 = 横槍の状態(発言を作る({ id: "1", 本文: "眠い", 発言者名: "kazupon" }), "流れ");

    期待(状態).を含む("[チャンネルの流れ]\n流れ");
    期待(状態).を含む("[注目している発言]\nkazupon: 眠い");
  });
});
