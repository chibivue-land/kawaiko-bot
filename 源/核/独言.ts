export function お題を選ぶ(乱数: () => 数値 = 数学.random): 文字列 {
  return お題一覧[数学.floor(乱数() * 長さ(お題一覧))]!;
}

/** 定期枠の確率ゲート．数値として読めない設定値は常に投稿する． */
export function 投稿するか(確率: 文字列, 乱数: () => 数値 = 数学.random): 真偽 {
  const 値 = 数値.parseFloat(確率);

  return もし(!数値.isFinite(値), {
    であれば: () => 真,
    でなければ: () => 乱数() < 数学.min(数学.max(値, 0), 1),
  });
}
export function 独り言の指示文を組み立てる(状況: {
  時刻の表示: 文字列;
  /** 日本時間の時 (0-23)．kawaiko の機嫌は時間帯で変わる． */
  時: 数値;
  お題: 文字列;
  /** お題が見出しを要るときだけ中身がある．選別は振る舞いの側で済んでいる． */
  見出し一覧: 読み取り専用配列<文字列>;
  事実一覧: 読み取り専用配列<事実>;
  自分の直近発言: 読み取り専用配列<文字列>;
  乱数?: 省略可<() => 数値>;
  /** 今回だけ乱心しているか (機嫌.ts)．賽は振る舞いの側で振ってある． */
  乱心か?: 省略可<真偽>;
}): 文字列 {
  const 乱数 = 状況.乱数 ?? 数学.random;
  const 種類 = お題の見出しの種類(状況.お題) ?? "ニュース";
  const ニュース = 否定(空か(状況.見出し一覧))
    ? 節をつなぐ(
        繋ぐ(
          [
            見出しの書き出し[種類],
            ...写す(取り出す(状況.見出し一覧, 0, 載せる見出しの数), (見出し) => `- ${見出し}`),
          ],
          "\n",
        ),
        見出しの扱い,
      )
    : "";
  return 節をつなぐ(
    `今は ${状況.時刻の表示}。${独言の書き出し}`,
    `ネタの方向性: ${状況.お題}`,
    ニュース,
    独言の作法,
    記憶節(状況.事実一覧),
    回避節(状況.自分の直近発言),
    機嫌節(状況.時, 状況.乱心か),
    // 乱心しているときの長さは，乱心の指示のほうが決める．
    状況.乱心か
      ? ""
      : 繋ぐ(
          [
            `今回の長さ (毎回変える。直前の呟きと同じ分量にしない): ${返しの長さを選ぶ(乱数)}`,
            "毎回同じような書き出しにしない。",
          ],
          "\n",
        ),
  );
}
