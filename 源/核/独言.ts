/** 判定器の答えを踏まえて，その見出しを載せてよいか．判定が取れなければ載せる． */
export function 見出しを載せてよいか(答え: 省略可<答え一覧>): 真偽 {
  return 否定(閾値を超えるか(真の確率(答え, "茶化せないか"), 見出しの定義.閾値.茶化せない, 偽));
}

