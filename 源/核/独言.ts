/**
 * 定期の独り言 — kawaiko が誰に宛てるでもなく喋るやつ。お題、トーン、1 回分の
 * 指示文。純粋。
 */
import { 前後の空白を落とす, 繋ぐ, 写す } from "../共通/関数";
import { 数学, 数値 } from "../共通/型";
import type { 文字列, 真偽, 読み取り専用配列, 省略可 } from "../共通/型";
import type { 事実 } from "./記憶";
import { 返しの長さを選ぶ } from "./人格";
import { 回避節, 節をつなぐ, 記憶節 } from "./指示文";
import 作法 from "./独言-作法.md?raw";
import お題集 from "./独言-お題.json";

/**
 * お題の種 (独言-お題.json)。1 投稿につき 1 つ無作為に選ぶ。基調は「ネタツイ」:
 * インターネットオタク仕草で、少し捻くれていて、乾いていて暗い。説教くさくない。
 */
export const お題一覧: 読み取り専用配列<文字列> = お題集.お題;

/** そのお題が最新の見出しを要るかどうか。 */
export function お題がニュースを要るか(お題: 文字列): 真偽 {
  return お題.startsWith("ニュース");
}

const 独言の作法 = 前後の空白を落とす(作法);
const 独言の書き出し = "Discord の雑談チャンネルに、誰に宛てるでもなくテキトーに一言呟いて。";

export function お題を選ぶ(乱数: () => 数値 = 数学.random): 文字列 {
  return お題一覧[数学.floor(乱数() * お題一覧.length)]!;
}

/** 定期枠の確率ゲート。数値として読めない設定値は常に投稿する。 */
export function 投稿するか(確率: 文字列, 乱数: () => 数値 = 数学.random): 真偽 {
  const 値 = 数値.parseFloat(確率);
  if (!数値.isFinite(値)) return true;
  return 乱数() < 数学.min(数学.max(値, 0), 1);
}

export function 独り言の指示文を組み立てる(状況: {
  時刻の表示: 文字列;
  お題: 文字列;
  見出し一覧: 読み取り専用配列<文字列>;
  事実一覧: 読み取り専用配列<事実>;
  自分の直近発言: 読み取り専用配列<文字列>;
  乱数?: 省略可<() => 数値>;
}): 文字列 {
  const 乱数 = 状況.乱数 ?? 数学.random;
  const ニュース =
    状況.見出し一覧.length > 0
      ? 繋ぐ(["直近のニュース見出し:", ...写す(状況.見出し一覧, (見出し) => `- ${見出し}`)], "\n")
      : "";
  return 節をつなぐ(
    `今は ${状況.時刻の表示}。${独言の書き出し}`,
    `ネタの方向性: ${状況.お題}`,
    ニュース,
    独言の作法,
    記憶節(状況.事実一覧),
    回避節(状況.自分の直近発言),
    繋ぐ(
      [
        `今回の長さ (毎回変える。直前の呟きと同じ分量にしない): ${返しの長さを選ぶ(乱数)}`,
        "毎回同じような書き出しにしない。",
      ],
      "\n",
    ),
  );
}
