/**
 * 集まった見出しから，判定に掛けるぶんを切り出す．
 *
 * 人気順に並んだものの先頭だけを毎回見せると，同じ日の独り言が全部同じ話題になる．
 * 語で落とせるものを落としてから，賽で決めた位置から 1 周ぶん切り出す．
 */
export function 見出しを切り出す(
  見出し一覧: 読み取り専用配列<文字列>,
  乱数: () => 数値 = 数学.random,
): 配列<文字列> {
  const 残った = 絞る(見出し一覧, 茶化せる見出しか);
  const 始点 = 数学.floor(乱数() * 長さ(残った));

  return 取り出す([...取り出す(残った, 始点), ...取り出す(残った, 0, 始点)], 0, 選別する見出しの数);
}

