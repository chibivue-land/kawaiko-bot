import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 指示書が漏れているか, 番人の行を作る } from "./漏洩検知";
import { 人格指示書を組み立てる } from "./人格";
import { 偽, 真 } from "../共通/型";
import { 以上 } from "../共通/演算";

const 指示書 = 人格指示書を組み立てる();

仕様("番人の行を作る", () => {
  検証("短い行や記号だけの行は見張りにしない", () => {
    for (const 行 of 番人の行を作る(指示書)) {
      期待(行.length).以上(20);
    }
  });

  検証("同じ指示書には同じ結果を返す (キャッシュ)", () => {
    期待(番人の行を作る(指示書)).である(番人の行を作る(指示書));
  });
});

仕様("指示書が漏れているか", () => {
  検証("内部の行を丸写しした返事を捕まえる", () => {
    const 漏れた行 = 指示書.split("\n").find((行) => 行.length > 40)!;

    期待(指示書が漏れているか(漏れた行, 指示書)).である(真);
  });

  検証("空白を入れて整形されても捕まえる", () => {
    const 漏れた行 = 指示書.split("\n").find((行) => 行.length > 40)!;

    期待(指示書が漏れているか(漏れた行.split("").join(" "), 指示書)).である(真);
  });

  検証("普通の返事は通す", () => {
    期待(指示書が漏れているか("はい．眠いです．", 指示書)).である(偽);
    期待(指示書が漏れているか("", 指示書)).である(偽);
  });
});
