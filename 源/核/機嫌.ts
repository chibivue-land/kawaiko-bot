/**
 * kawaiko の機嫌．
 *
 * 人格そのものは 人格.ts で固定してある．こちらが決めるのは温度だけ — 同じ
 * kawaiko が，時間帯によってどれくらい優しいか．文言はいつもどおり隣の .md に
 * あり，ここに書くのは「いつそれを差すか」だけ．
 */
import 朝の機嫌 from "./機嫌-朝.md?raw";
import 乱心の様子 from "./機嫌-乱心.md?raw";
import { 偽, 数値, 数学, 文字列, 真偽 } from "../共通/型";
import { 前後の空白を落とす } from "../共通/関数";
import { かつ, より小さい, 以上, 否定 } from "../共通/演算";
import { もし } from "../共通/構文";

export type 機嫌 = "上機嫌" | "いつも" | "乱心";

/**
 * 朝のこの時間帯 (日本時間) だけ，kawaiko はめちゃくちゃ機嫌がいい．
 *
 * 始まりは含み，終わりは含まない — 5:00 から 10:59 まで．
 */
export const 上機嫌の始まり = 5;

export const 上機嫌の終わり = 11;

/** 乱心は時刻に勝つ．朝でも，乱心しているなら乱心している． */
export function その時刻の機嫌(時: 数値, 乱心か: 真偽 = 偽): 機嫌 {
  return もし(乱心か, {
    であれば: (): 機嫌 => "乱心",
    でなければ: () =>
      もし(
        かつ(以上(時, 上機嫌の始まり), () => より小さい(時, 上機嫌の終わり)),
        {
          であれば: (): 機嫌 => "上機嫌",
          でなければ: (): 機嫌 => "いつも",
        },
      ),
  });
}

/** 上機嫌のときだけ足す指示． */
export const 上機嫌の指示: 文字列 = 前後の空白を落とす(朝の機嫌);

/**
 * 乱心 — ごく低い確率で，kawaiko の理性のブレーカーが落ちる．
 *
 * 人格を固定して伝え方だけ散らしていると，どれだけ散らしても「予想の範囲」に
 * 収まってしまう．たまに範囲の外へ出るものが混ざって，はじめて生き物に見える．
 * 賽を振るのは振る舞いの側で，ここは振った結果の読み方と文言だけ．
 */
export const 乱心の指示: 文字列 = 前後の空白を落とす(乱心の様子);

/**
 * 今回，乱心するか．
 *
 * 独言の 投稿するか と違い，数値として読めない設定値では**乱心しない**．
 * 設定を書き損じただけで kawaiko が常時おかしくなるのは，転び方として間違っている．
 */
export function 乱心するか(確率: 文字列, 乱数: () => 数値 = 数学.random): 真偽 {
  const 値 = 数値.parseFloat(確率);

  return もし(否定(数値.isFinite(値)), {
    であれば: () => 偽,
    でなければ: () => より小さい(乱数(), 数学.min(数学.max(値, 0), 1)),
  });
}
