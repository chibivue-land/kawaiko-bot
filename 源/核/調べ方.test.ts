import { 仕様, 検証, 期待 } from "../試験/言葉";

import {
  検索語の最大長,
  当て推量の調べ方,
  調べ方の依頼を組み立てる,
  調べ方を読み取る,
} from "./調べ方";

import { 偽, 真 } from "../共通/型";
import { 繰り返す, 長さ } from "../共通/関数";
import { 各要素に } from "../共通/反復";

仕様("調べ方の依頼を組み立てる", () => {
  検証("問いかけを差し込み，答え方を指定する", () => {
    const 依頼 = 調べ方の依頼を組み立てる("Vapor Mode って何");

    期待(依頼).を含む("Vapor Mode って何");
    期待(依頼).を含む("調べる:");
    期待(依頼).を含む("検索語:");
  });
});

仕様("調べ方を読み取る", () => {
  検証("要ると出たら，その語で引く", () => {
    期待(調べ方を読み取る("調べる: はい\n検索語: Vue Vapor Mode", "Vapor Mode って何")).と等しい({
      調べるか: 真,
      検索語: "Vue Vapor Mode",
    });
  });

  検証("要らないと出たら引かない", () => {
    期待(調べ方を読み取る("調べる: いいえ\n検索語:", "おはよう").調べるか).である(偽);
  });

  検証("英語で答えても読む", () => {
    期待(調べ方を読み取る("search: yes\nquery: rust async", "rust の async").調べるか).である(真);
  });

  検証("飾りが付いていても読む", () => {
    // 小さいモデルは平気で太字にするし箇条書きにもする．
    各要素に(["**調べる:** はい\n**検索語:** Vue", "- 調べる: はい\n- 検索語: Vue"], (答え) => {
      期待(調べ方を読み取る(答え, "Vue とは")).と等しい({ 調べるか: 真, 検索語: "Vue" });
    });
  });

  検証("要ると出たのに語が空なら，問いかけから当てはめる", () => {
    期待(調べ方を読み取る("調べる: はい\n検索語:", "ubugeeei って知ってる？").検索語).である(
      "ubugeeei",
    );
    期待(調べ方を読み取る("調べる: はい\n検索語:", "Vapor Mode とは").検索語).である("Vapor Mode");
  });

  検証("読めない答えなら，まるごと当て推量へ落ちる", () => {
    // 判断できなかったことを理由に，調べ物ごと諦めはしない．
    期待(調べ方を読み取る("わかりません", "Vapor Mode とは")).と等しい(
      当て推量の調べ方("Vapor Mode とは"),
    );
  });

  検証("長すぎる検索語は刈る", () => {
    const 読んだ = 調べ方を読み取る(`調べる: はい\n検索語: ${繰り返す("あ", 300)}`, "問い");

    期待(長さ(読んだ.検索語)).である(検索語の最大長);
  });
});

仕様("当て推量の調べ方", () => {
  検証("問いかけの形なら引きにいく", () => {
    期待(当て推量の調べ方("Vapor Mode とは").調べるか).である(真);
  });

  検証("ただの雑談なら引かない", () => {
    期待(当て推量の調べ方("おはよう").調べるか).である(偽);
  });
});
