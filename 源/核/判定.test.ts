import {
  末尾の行,
  段階の点数,
  状態を書く,
  真の確率,
  選ばれたもの,
  閾値を超えるか,
  type 答え一覧,
} from "./判定";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 偽, 未定義, 真 } from "../共通/型";

const 答え: 答え一覧 = {
  急ぎか: { 種別: "真偽", 確率: 0.93 },
  部署: { 種別: "選択", 選択: "経理", 確信: 0.8, 確率: { 経理: 0.87, 技術: 0.13 } },
  切迫度: { 種別: "段階", 点数: 2.14, 確信: 0.6 },
};

仕様("答えの読み方", () => {
  検証("問いの形に合った読み方だけが値を返す", () => {
    期待(真の確率(答え, "急ぎか")).である(0.93);
    期待(選ばれたもの(答え, "部署")).である("経理");
    期待(段階の点数(答え, "切迫度")).である(2.14);
  });

  検証("形の違う答えを，別の形として読まない", () => {
    // 段階の点数を確率として読んだりしない．
    期待(真の確率(答え, "切迫度")).が未定義();
    期待(段階の点数(答え, "急ぎか")).が未定義();
    期待(選ばれたもの(答え, "急ぎか")).が未定義();
  });

  検証("答えが無ければ未定義 (判定が取れなかった日)", () => {
    期待(真の確率(未定義, "急ぎか")).が未定義();
    期待(真の確率(答え, "訊いていない問い")).が未定義();
  });
});

仕様("閾値を超えるか", () => {
  検証("閾値ちょうどは超えたことにする", () => {
    期待(閾値を超えるか(0.5, 0.5, 偽)).である(真);
    期待(閾値を超えるか(0.49, 0.5, 真)).である(偽);
  });

  検証("分からないときは，呼び出し側が決めた側へ倒れる", () => {
    期待(閾値を超えるか(未定義, 0.5, 真)).である(真);
    期待(閾値を超えるか(未定義, 0.5, 偽)).である(偽);
  });
});

仕様("状態を書く", () => {
  検証("見出し付きの塊を，空行で区切って並べる", () => {
    期待(
      状態を書く([
        ["会話の流れ", "ubugeeei: しりとり"],
        ["今回の発言", "ubugeeei: りんご"],
      ]),
    ).である("[会話の流れ]\nubugeeei: しりとり\n\n[今回の発言]\nubugeeei: りんご");
  });

  検証("中身の無い塊は，見出しごと落とす", () => {
    期待(
      状態を書く([
        ["会話の流れ", "   "],
        ["今回の発言", "やあ"],
      ]),
    ).である("[今回の発言]\nやあ");
  });
});

仕様("末尾の行", () => {
  検証("直近の行だけ残す", () => {
    期待(末尾の行("一\n二\n三", 2)).である("二\n三");
    期待(末尾の行("一", 5)).である("一");
  });
});
