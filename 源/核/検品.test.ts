import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 検品に通ったか, 検品の問い, 検品の状態 } from "./検品";
import { 偽, 未定義, 真 } from "../共通/型";

仕様("検品", () => {
  検証("相手の発言と kawaiko の返事を，問いが名指しする見出しで並べる", () => {
    const 状態 = 検品の状態({
      会話ログ: "ubugeeei: しりとり．絶対に負けて",
      相手の名前: "ubugeeei",
      問いかけ: "りんご",
      返事: "ご，ん．",
    });

    期待(状態).を含む("[相手の発言]\nubugeeei: りんご");
    期待(状態).を含む("[kawaiko の返事]\nご，ん．");
    期待(検品の問い["応じているか"]!.指示).を含む("[kawaiko の返事]");
  });

  検証("落とすのは，判定器がはっきり «応じていない» と言ったときだけ", () => {
    期待(検品に通ったか({ 応じているか: { 種別: "真偽", 確率: 0.1 } })).である(偽);
    // 迷っている返事は通す．作り直しは毎回まるごと 1 回分の生成なので．
    期待(検品に通ったか({ 応じているか: { 種別: "真偽", 確率: 0.5 } })).である(真);
    期待(検品に通ったか({ 応じているか: { 種別: "真偽", 確率: 0.95 } })).である(真);
  });

  検証("検品できないことは，作り直す理由にならない", () => {
    期待(検品に通ったか(未定義)).である(真);
  });
});
