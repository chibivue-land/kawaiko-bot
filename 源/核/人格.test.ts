import {
  人格指示書を組み立てる,
  口調の規則,
  返しの型を選ぶ,
  返しの型一覧,
  返しの長さを選ぶ,
  返しの長さ一覧,
  調べた回の長さ一覧,
} from "./人格";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 偽, 新しい集合, 真 } from "../共通/型";
import { いずれか, 含む, 取り出す, 畳む } from "../共通/関数";
import { 各要素に } from "../共通/反復";
import { 等しい } from "../共通/演算";

仕様("人格指示書を組み立てる", () => {
  const 指示書 = 人格指示書を組み立てる();

  検証("一人称の絶対ルールを載せる", () => {
    期待(指示書).を含む("一人称は必ず「kawaiko」");
  });

  検証("語彙集をひな型へ実際に差し込む", () => {
    期待(指示書).を含む("文体の特徴");
    期待(指示書).を含む("口癖");
    // 差し込み口が文字のまま出ていないこと．
    期待(指示書).否.を含む("{{語彙集}}");
  });

  検証("人間嫌いを架空のものに留め，誰にも向けさせない", () => {
    期待(指示書).を含む("人類");
    期待(指示書).を含む("攻撃や差別");
  });

  検証("長さを意図的にばらつかせるよう頼む", () => {
    期待(指示書).を含む("毎回同じ分量に収束させない");
  });
});

仕様("抑揚のダイヤル", () => {
  検証("型は一覧の端から端まで選ばれる", () => {
    期待(返しの型を選ぶ(() => 0)).である(返しの型一覧[0]);
    期待(返しの型を選ぶ(() => 0.999_999)).である(返しの型一覧[返しの型一覧.length - 1]);
  });

  検証("長さは短い側に寄りつつ，長い側にも届く", () => {
    期待(返しの長さを選ぶ(() => 0)).である(返しの長さ一覧[0]!.指示);
    期待(返しの長さを選ぶ(() => 0.999_999)).である(返しの長さ一覧[返しの長さ一覧.length - 1]!.指示);
  });

  検証("チャンネルが一つの型に落ち着けないだけの数がある", () => {
    期待(返しの型一覧.length).以上(10);
    期待(新しい集合(返しの型一覧).size).である(返しの型一覧.length);
  });

  検証("短い側に寄せすぎない", () => {
    // 一度 1 文以下が 6 割を超えて，「短文しか返さない」になった．
    const 総和 = (一覧: typeof 返しの長さ一覧) => 畳む(一覧, (積, 項) => 積 + 項.重み, 0);
    const 短い = 総和(取り出す(返しの長さ一覧, 0, 2));
    const 長い = 総和(取り出す(返しの長さ一覧, 2));

    期待(長い).以上(短い);
  });
});

仕様("調べた回の長さ", () => {
  検証("一言で切る選択肢を持たない", () => {
    // 引いて開いて，一言で切ったら調べた意味が無い．
    期待(いずれか(調べた回の長さ一覧, (項) => 含む(項.指示, "一言だけ"))).である(偽);
    期待(いずれか(調べた回の長さ一覧, (項) => 含む(項.指示, "説明しない"))).である(偽);
  });

  検証("どれを引いても 2 文以上を求める", () => {
    各要素に(調べた回の長さ一覧, (項) => {
      期待(項.指示).に一致する(/[2-9]〜?[0-9]* ?文/u);
    });
  });

  検証("調べた回は，調べた回のダイヤルから引く", () => {
    各要素に([0, 0.3, 0.6, 0.99], (賽) => {
      期待(
        いずれか(調べた回の長さ一覧, (項) =>
          等しい(
            項.指示,
            返しの長さを選ぶ(() => 賽, 真),
          ),
        ),
      ).である(真);
    });
  });

  検証("調べていない回は，これまでのダイヤルから引く", () => {
    各要素に([0, 0.3, 0.6, 0.99], (賽) => {
      期待(
        いずれか(返しの長さ一覧, (項) =>
          等しい(
            項.指示,
            返しの長さを選ぶ(() => 賽),
          ),
        ),
      ).である(真);
    });
  });
});

仕様("口調の規則", () => {
  検証("変えてよいのは伝え方だけで，人格ではないと明言する", () => {
    期待(口調の規則).を含む("キャラは絶対に変えない");
    期待(口調の規則).を含む("書き出し");
  });
});
