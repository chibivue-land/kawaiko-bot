import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 新しい集合 } from "../共通/型";
import { 等しい } from "../共通/演算";
import {
  人格指示書を組み立てる,
  口調の規則,
  返しの型を選ぶ,
  返しの型一覧,
  返しの長さを選ぶ,
  返しの長さ一覧,
} from "./人格";

仕様("人格指示書を組み立てる", () => {
  const 指示書 = 人格指示書を組み立てる();

  検証("一人称の絶対ルールを載せる", () => {
    期待(指示書).を含む("一人称は必ず「kawaiko」");
  });

  検証("語彙集をひな型へ実際に差し込む", () => {
    期待(指示書).を含む("文体の特徴");
    期待(指示書).を含む("口癖");
    // 差し込み口が文字のまま出ていないこと．
    期待(指示書).否.を含む("{{語彙集}}");
  });

  検証("人間嫌いを架空のものに留め，誰にも向けさせない", () => {
    期待(指示書).を含む("人類");
    期待(指示書).を含む("攻撃や差別");
  });

  検証("長さを意図的にばらつかせるよう頼む", () => {
    期待(指示書).を含む("毎回同じ分量に収束させない");
  });
});

仕様("抑揚のダイヤル", () => {
  検証("型は一覧の端から端まで選ばれる", () => {
    期待(返しの型を選ぶ(() => 0)).である(返しの型一覧[0]);
    期待(返しの型を選ぶ(() => 0.999_999)).である(返しの型一覧[返しの型一覧.length - 1]);
  });

  検証("長さは短い側に寄りつつ，長い側にも届く", () => {
    期待(返しの長さを選ぶ(() => 0)).である(返しの長さ一覧[0]!.指示);
    期待(返しの長さを選ぶ(() => 0.999_999)).である(返しの長さ一覧[返しの長さ一覧.length - 1]!.指示);
  });

  検証("チャンネルが一つの型に落ち着けないだけの数がある", () => {
    期待(返しの型一覧.length).以上(10);
    期待(新しい集合(返しの型一覧).size).である(返しの型一覧.length);
  });

  検証("短い側が出やすく，長い側は稀である", () => {
    const 重み = (指示: string) => 返しの長さ一覧.find((項) => 等しい(項.指示, 指示))!.重み;

    期待(重み(返しの長さ一覧[0]!.指示)).より大きい(
      重み(返しの長さ一覧[返しの長さ一覧.length - 1]!.指示),
    );
  });
});

仕様("口調の規則", () => {
  検証("変えてよいのは伝え方だけで，人格ではないと明言する", () => {
    期待(口調の規則).を含む("キャラは絶対に変えない");
    期待(口調の規則).を含む("書き出し");
  });
});
