/** 調べて出てきた 1 件．どの集め先から来たかに依らない共通の形． */
export interface 調べた一件 {
  題: 文字列;
  抜粋: 文字列;
  /** さらに開いて読める先．拾えたときだけ． */
  場所?: 省略可<文字列>;
}

/** モデルが選ぶ次の一手． */
export type 探索の一手 =
  | { 行動: "検索"; 検索語: 文字列 }
  | { 行動: "開く"; 場所: 文字列 }
  | { 行動: "十分" };

const 十分: 探索の一手 = { 行動: "十分" };

/**
 * 上限たち．モデルの暴走からブラウザ時間 (1 日 10 分) と料金を守る天井で，
 * 賢い判断を縛るためのものではない．
 */
/** モデルに次の一手を訊く回数の上限． */
export const 探索の最大手数 = 4;

/** 1 回の返事で検索してよい回数 (初手を含む)． */
export const 検索の上限 = 3;

/** 1 回の返事で開いてよい頁数． */
export const 開くの上限 = 2;

/** ここまでに何をしたか．一手を検めるのに使う． */
export interface 探索の足あと {
  検索した語: 配列<文字列>;
  開いた場所: 配列<文字列>;
  /** 検索結果に出てきた場所．開いてよいのはこの中だけ (作り話の URL を開かない)． */
  見えた場所: 配列<文字列>;
}

export const 素の足あと = (): 探索の足あと => ({ 検索した語: [], 開いた場所: [], 見えた場所: [] });

const 次の行 = /^[*_\s-]*(?:次|next)[*_\s]*[:：][*_\s]*(?<中身>.+)$/imu;
const 中身の行 = /^[*_\s-]*(?:中身|arg)[*_\s]*[:：][*_\s]*(?<中身>.+)$/imu;
const 場所の形 = /https?:\/\/[^\s>)"']+/u;

/**
 * モデルの答えを一手として読む．
 *
 * 読めない答えはすべて「十分」— 判断が読めなかったからといって，ここまでに
 * 集めた材料まで捨てる理由は無い．
 */
export function 一手を読み取る(本文: 文字列): 探索の一手 {
  const 行動 = 小文字にする(前後の空白を落とす(次の行.exec(本文)?.groups?.中身 ?? ""));
  const 中身 = 前後の空白を落とす(中身の行.exec(本文)?.groups?.中身 ?? "");
  const 場所 = 場所の形.exec(中身)?.[0];

  return もし<探索の一手>((含む(行動, "検索") || 含む(行動, "search")) && 否定(空か(中身)), {
    であれば: (): 探索の一手 => ({ 行動: "検索", 検索語: 切り出す(中身, 0, 検索語の最大長) }),
    でなければ: () =>
      もし<探索の一手>((含む(行動, "開") || 含む(行動, "open")) && 等しくない(場所, 未定義), {
        であれば: (): 探索の一手 => ({ 行動: "開く", 場所: 場所! }),
        でなければ: () => 十分,
      }),
  });
}

/**
 * その一手を実行してよいか検める．だめなら「十分」に落とす．
 *
 * 同じ語をもう一度引く・見たことのない URL を開く・上限を超える，のどれも
 * ここで止まる．止め方が「十分」なのは 一手を読み取る と同じ理由．
 */
export function 一手を検める(手: 探索の一手, 足あと: 探索の足あと, 開けるか: 真偽): 探索の一手 {
  return 場合分け<探索の一手["行動"], 探索の一手>(手.行動, {
    検索: () => (検索してよいか((手 as { 検索語: 文字列 }).検索語, 足あと) ? 手 : 十分),
    開く: () => (開いてよいか((手 as { 場所: 文字列 }).場所, 足あと, 開けるか) ? 手 : 十分),
    十分: () => 手,
  })!;
}

function 検索してよいか(検索語: 文字列, 足あと: 探索の足あと): 真偽 {
  return (
    より小さい(長さ(足あと.検索した語), 検索の上限) &&
    否定(空か(検索語)) &&
    否定(一覧に含む(足あと.検索した語, 検索語))
  );
}

function 開いてよいか(場所: 文字列, 足あと: 探索の足あと, 開けるか: 真偽): 真偽 {
  return (
    開けるか &&
    より小さい(長さ(足あと.開いた場所), 開くの上限) &&
    一覧に含む(足あと.見えた場所, 場所) &&
    否定(一覧に含む(足あと.開いた場所, 場所)) &&
    読みに行ってよいか(場所)
  );
}

/** 一手でも指せる余地が残っているか．無いならモデルに訊くだけ無駄． */
export function まだ動けるか(足あと: 探索の足あと, 開けるか: 真偽): 真偽 {
  return (
    より小さい(長さ(足あと.検索した語), 検索の上限) ||
    (開けるか && より小さい(長さ(足あと.開いた場所), 開くの上限) && 否定(空か(開ける場所(足あと))))
  );
}

function 開ける場所(足あと: 探索の足あと): 配列<文字列> {
  return 絞る(
    足あと.見えた場所,
    (場所) => 否定(一覧に含む(足あと.開いた場所, 場所)) && 読みに行ってよいか(場所),
  );
}

/** 次の一手を訊く指示文．役割 (システム側) は 探索の役割 で渡す． */
export const 探索の役割 = 前後の空白を落とす(役割のひな型);

export function 探索の指示を組み立てる(
  問いかけ: 文字列,
  これまで: 文字列,
  足あと: 探索の足あと,
  開けるか: 真偽,
): 文字列 {
  return 前後の空白を落とす(
    差し込む(手順のひな型, {
      問いかけ,
      これまで: もし(空か(前後の空白を落とす(これまで)), {
        であれば: () => "(まだ何も無い)",
        でなければ: () => これまで,
      }),
      選べる一手: 選べる一手を書き出す(足あと, 開けるか),
    }),
  );
}

function 選べる一手を書き出す(足あと: 探索の足あと, 開けるか: 真偽): 文字列 {
  const 残り検索 = 検索の上限 - 長さ(足あと.検索した語);
  const 残り開く = もし(開けるか, {
    であれば: () => 開くの上限 - 長さ(足あと.開いた場所),
    でなければ: () => 0,
  });

  return 繋ぐ(
    絞る(
      [
        残り検索 > 0 ? `検索 (あと ${残り検索} 回)` : "",
        残り開く > 0 ? `開く (あと ${残り開く} 頁)` : "",
        "十分",
      ],
      (かけら) => 否定(空か(かけら)),
    ),
    " / ",
  );
}

/** 検索 1 回分を，ループの文脈と最終の指示文の両方に載せる形で書き出す． */
export function 検索結果を書き出す(検索語: 文字列, 一覧: 読み取り専用配列<調べた一件>): 文字列 {
  const 行 = 写す(一覧, (件) =>
    繋ぐ(
      絞る(
        [`- ${件.題}${件.抜粋 ? `: ${件.抜粋}` : ""}`, 件.場所 ? `  ${件.場所}` : ""],
        (かけら) => 否定(空か(かけら)),
      ),
      改行,
    ),
  );

  return 繋ぐ(
    [
      `検索「${検索語}」:`,
      ...もし(空か(行), { であれば: () => ["(何も出なかった)"], でなければ: () => 行 }),
    ],
    改行,
  );
}

/** ループの文脈用に，開いた頁を短く書き出す．全文は最終の指示文の 頁節 が持つ． */
export const 途中で見せる頁の文字数 = 800;

export function 頁を短く書き出す(頁: 読んだ頁): 文字列 {
  return 繋ぐ(
    [`開いた ${頁.場所}:`, 切り出す(置き換える(頁.中身, /\s+/g, " "), 0, 途中で見せる頁の文字数)],
    改行,
  );
}
