/**
 * 調べ物の探索ループの純粋な部分．
 *
 * 巷のコーディングエージェントの web 検索と同じ形にする — 「引く」と「開く」を
 * 一回ずつ機械的にやるのではなく，検索の結果を**見てから**「どれを開くか」
 * 「語を変えて引き直すか」「もう十分か」をモデル自身に決めさせる．
 *
 * ここが持つのは頼み方・答えの読み方・上限の番だけで，実際に引いたり開いたり
 * するのは 振る舞い/探索.ts．純粋．
 */
