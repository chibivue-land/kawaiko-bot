import { その時刻の担当, 日本時間の時, 日本時間の表示, 独言の時刻 } from "./予定";
import { Temporal } from "./時刻";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 等しい } from "../共通/演算";

const 時点 = (iso: string) => Temporal.Instant.from(iso);

仕様("その時刻の担当", () => {
  検証("指定した時刻は独り言", () => {
    for (const 時 of 独言の時刻) {
      期待(その時刻の担当(時)).である("独言");
    }
  });

  検証("4 時間おきに学習する", () => {
    for (const 時 of [3, 7, 11, 15, 19]) {
      期待(その時刻の担当(時)).である("学習");
    }
  });

  検証("独り言でも学習でもない時は横槍", () => {
    期待(その時刻の担当(0)).である("横槍");
    期待(その時刻の担当(1)).である("横槍");
    期待(その時刻の担当(14)).である("横槍");
    期待(その時刻の担当(21)).である("横槍");
    期待(その時刻の担当(22)).である("横槍");
  });

  検証("独り言の時刻は学習の規則より優先される", () => {
    // 23 は 4 時間おきの学習に当たるが，独り言の枠に指定してある．
    期待(その時刻の担当(23)).である("独言");
  });

  検証("1 日を 3 つの仕事へ配る", () => {
    const 担当一覧 = [...Array(24).keys()].map(その時刻の担当);
    期待(担当一覧.filter((担当) => 等しい(担当, "独言"))).の長さが(4);
    期待(担当一覧.filter((担当) => 等しい(担当, "横槍")).length).以上(14);
    期待(担当一覧.filter((担当) => 等しい(担当, "学習")).length).以上(4);
  });
});

仕様("日本時間の時", () => {
  検証("UTC ではなく東京の時を読む", () => {
    期待(日本時間の時(時点("2026-08-21T00:07:00Z"))).である(9);
    期待(日本時間の時(時点("2026-08-21T15:07:00Z"))).である(0);
  });
});

仕様("日本時間の表示", () => {
  検証("時点を日本の壁掛け時計として書く", () => {
    // 2026-08-21T13:50Z は同じ日の 22:50 JST (金)
    期待(日本時間の表示(時点("2026-08-21T13:50:00Z"))).である("8月21日(金) 22:50");
  });

  検証("日本時間の深夜をまたぐと日付が繰り上がる", () => {
    // 2026-08-21T16:30Z -> 2026-08-22 01:30 JST (土)
    期待(日本時間の表示(時点("2026-08-21T16:30:00Z"))).である("8月22日(土) 1:30");
  });

  検証("曜日をすべて正しく出す", () => {
    // 2026-08-17 は月曜．日本時間で 1 週間ぶん歩く．
    const 表示一覧 = [...Array(7).keys()].map((差) =>
      日本時間の表示(時点(`2026-08-${17 + 差}T03:00:00Z`)),
    );
    const 曜日を取る = (表示: string) => /\((.)\)/.exec(表示)?.[1];
    期待(表示一覧.map(曜日を取る)).と等しい(["月", "火", "水", "木", "金", "土", "日"]);
  });
});
