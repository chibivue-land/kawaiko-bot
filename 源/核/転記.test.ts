import { 仕様, 検証, 期待 } from "../試験/言葉";
import { リセット後に絞る, 会話ログを組み立てる, 自分の直近発言を集める } from "./転記";
import type { 発言 } from "./発言";
import { 長さ } from "../共通/関数";
import { より小さい, 等しい } from "../共通/演算";

const 自分のid = "bot-1";

function 発言(
  id: string,
  発言者id: string,
  本文: string,
  発言者名 = `利用者${発言者id}`,
  時刻 = "2026-08-21T13:00:00Z",
): 発言 {
  return { id, 本文, 時刻, 発言者id, 発言者名, bot発言か: 等しい(発言者id, 自分のid) };
}

仕様("会話ログを組み立てる", () => {
  検証("古い順に並べ，bot の行は kawaiko と書く", () => {
    // チャット API は新しい順で返す．
    const 発言一覧 = [
      発言("3", "222", "続きの質問", "ubugeeei"),
      発言("2", 自分のid, "kawaiko の返事"),
      発言("1", "222", "最初の質問", "ubugeeei"),
    ];

    期待(会話ログを組み立てる(発言一覧, { 自分のid })).である(
      "ubugeeei: 最初の質問\nkawaiko: kawaiko の返事\nubugeeei: 続きの質問",
    );
  });

  検証("引き金になった発言と空の発言を除く", () => {
    const 発言一覧 = [
      発言("3", "222", "いま来たやつ"),
      発言("2", "222", "  "),
      発言("1", "222", "前の発言"),
    ];

    期待(会話ログを組み立てる(発言一覧, { 自分のid, 除外するid: "3" })).である(
      "利用者222: 前の発言",
    );
  });

  検証("長い発言を切り詰める", () => {
    const 長さ = 会話ログを組み立てる([発言("1", "222", "あ".repeat(500))], { 自分のid }).length;

    期待(長さ).より小さい(200);
  });

  検証("kawaiko のよく似た発言は最新の 1 件だけ残す", () => {
    // 固着の正体: bot の行が全部同じ形で，モデルがそれをお手本として読み返す．
    const 発言一覧 = [
      発言("5", 自分のid, "yamanoku さん，それはあまりに浅いです"),
      発言("4", "222", "三番目"),
      発言("3", 自分のid, "kazupon さん，それはあまりに筋が悪いです"),
      発言("2", "222", "二番目"),
      発言("1", 自分のid, "ubugeeei さん，それはあまりに雑な質問ですね"),
    ];

    const 会話ログ = 会話ログを組み立てる(発言一覧, { 自分のid });

    期待(会話ログ.match(/kawaiko:/g)).の長さが(1);
    期待(会話ログ).を含む("yamanoku さん，それはあまりに浅いです");
    // bot の返事が畳まれても，人間の発言は絶対に落ちない．
    期待(会話ログ).を含む("二番目");
    期待(会話ログ).を含む("三番目");
  });

  検証("違う内容の kawaiko の発言は残す (進行中の遊びが壊れない)", () => {
    const 発言一覧 = [
      発言("3", 自分のid, "じゃあ次は「ごりら」です"),
      発言("2", "222", "しりとりしよう"),
      発言("1", 自分のid, "眠いです．レッドブルが切れました．"),
    ];

    期待(会話ログを組み立てる(発言一覧, { 自分のid }).match(/kawaiko:/g)).の長さが(2);
  });
});

仕様("自分の直近発言を集める", () => {
  検証("kawaiko 自身の発言を新しい順で返す", () => {
    const 発言一覧 = [
      発言("3", 自分のid, "新しい方"),
      発言("2", "222", "人間の発言"),
      発言("1", 自分のid, "古い方"),
    ];

    期待(自分の直近発言を集める(発言一覧, 自分のid)).と等しい(["新しい方", "古い方"]);
  });

  検証("上限を守り，空の発言は飛ばす", () => {
    const 発言一覧 = [
      発言("3", 自分のid, "あ"),
      発言("2", 自分のid, "   "),
      発言("1", 自分のid, "い"),
    ];

    期待(自分の直近発言を集める(発言一覧, 自分のid, 1)).と等しい(["あ"]);
  });
});

仕様("リセット後に絞る", () => {
  const 発言一覧 = [
    発言("3", "222", "リセット後", "利用者", "2026-08-21T13:00:00Z"),
    発言("2", "222", "リセット前", "利用者", "2026-08-21T11:00:00Z"),
  ];

  検証("一度もリセットしていなければ全部通す", () => {
    期待(リセット後に絞る(発言一覧, 0)).の長さが(2);
  });

  検証("印より前を落とす", () => {
    const 境界 = Date.UTC(2026, 7, 21, 12);

    期待(リセット後に絞る(発言一覧, 境界).map((発言) => 発言.本文)).と等しい(["リセット後"]);
  });

  検証("読めない時刻は，どの印より古いものとして扱う", () => {
    const 壊れた = [発言("9", "222", "壊れた", "利用者", "時刻ではない")];

    期待(リセット後に絞る(壊れた, 1)).と等しい([]);
  });
});
