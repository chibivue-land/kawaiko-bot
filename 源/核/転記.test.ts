import { describe, expect, it } from "vitest";
import { リセット後に絞る, 会話ログを組み立てる, 自分の直近発言を集める } from "./転記";
import type { 発言 } from "./発言";

const 自分のid = "bot-1";

function 発言(
  id: string,
  発言者id: string,
  本文: string,
  発言者名 = `利用者${発言者id}`,
  時刻 = "2026-08-21T13:00:00Z",
): 発言 {
  return { id, 本文, 時刻, 発言者id, 発言者名, bot発言か: 発言者id === 自分のid };
}

describe("会話ログを組み立てる", () => {
  it("古い順に並べ，bot の行は kawaiko と書く", () => {
    // チャット API は新しい順で返す．
    const 発言一覧 = [
      発言("3", "222", "続きの質問", "ubugeeei"),
      発言("2", 自分のid, "kawaiko の返事"),
      発言("1", "222", "最初の質問", "ubugeeei"),
    ];

    expect(会話ログを組み立てる(発言一覧, { 自分のid })).toBe(
      "ubugeeei: 最初の質問\nkawaiko: kawaiko の返事\nubugeeei: 続きの質問",
    );
  });

  it("引き金になった発言と空の発言を除く", () => {
    const 発言一覧 = [
      発言("3", "222", "いま来たやつ"),
      発言("2", "222", "  "),
      発言("1", "222", "前の発言"),
    ];

    expect(会話ログを組み立てる(発言一覧, { 自分のid, 除外するid: "3" })).toBe(
      "利用者222: 前の発言",
    );
  });

  it("長い発言を切り詰める", () => {
    const 長さ = 会話ログを組み立てる([発言("1", "222", "あ".repeat(500))], { 自分のid }).length;

    expect(長さ).toBeLessThan(200);
  });

  it("kawaiko のよく似た発言は最新の 1 件だけ残す", () => {
    // 固着の正体: bot の行が全部同じ形で，モデルがそれをお手本として読み返す．
    const 発言一覧 = [
      発言("5", 自分のid, "yamanoku さん，それはあまりに浅いです"),
      発言("4", "222", "三番目"),
      発言("3", 自分のid, "kazupon さん，それはあまりに筋が悪いです"),
      発言("2", "222", "二番目"),
      発言("1", 自分のid, "ubugeeei さん，それはあまりに雑な質問ですね"),
    ];

    const 会話ログ = 会話ログを組み立てる(発言一覧, { 自分のid });

    expect(会話ログ.match(/kawaiko:/g)).toHaveLength(1);
    expect(会話ログ).toContain("yamanoku さん，それはあまりに浅いです");
    // bot の返事が畳まれても，人間の発言は絶対に落ちない．
    expect(会話ログ).toContain("二番目");
    expect(会話ログ).toContain("三番目");
  });

  it("違う内容の kawaiko の発言は残す (進行中の遊びが壊れない)", () => {
    const 発言一覧 = [
      発言("3", 自分のid, "じゃあ次は「ごりら」です"),
      発言("2", "222", "しりとりしよう"),
      発言("1", 自分のid, "眠いです．レッドブルが切れました．"),
    ];

    expect(会話ログを組み立てる(発言一覧, { 自分のid }).match(/kawaiko:/g)).toHaveLength(2);
  });
});

describe("自分の直近発言を集める", () => {
  it("kawaiko 自身の発言を新しい順で返す", () => {
    const 発言一覧 = [
      発言("3", 自分のid, "新しい方"),
      発言("2", "222", "人間の発言"),
      発言("1", 自分のid, "古い方"),
    ];

    expect(自分の直近発言を集める(発言一覧, 自分のid)).toEqual(["新しい方", "古い方"]);
  });

  it("上限を守り，空の発言は飛ばす", () => {
    const 発言一覧 = [
      発言("3", 自分のid, "あ"),
      発言("2", 自分のid, "   "),
      発言("1", 自分のid, "い"),
    ];

    expect(自分の直近発言を集める(発言一覧, 自分のid, 1)).toEqual(["あ"]);
  });
});

describe("リセット後に絞る", () => {
  const 発言一覧 = [
    発言("3", "222", "リセット後", "利用者", "2026-08-21T13:00:00Z"),
    発言("2", "222", "リセット前", "利用者", "2026-08-21T11:00:00Z"),
  ];

  it("一度もリセットしていなければ全部通す", () => {
    expect(リセット後に絞る(発言一覧, 0)).toHaveLength(2);
  });

  it("印より前を落とす", () => {
    const 境界 = Date.UTC(2026, 7, 21, 12);

    expect(リセット後に絞る(発言一覧, 境界).map((発言) => 発言.本文)).toEqual(["リセット後"]);
  });

  it("読めない時刻は，どの印より古いものとして扱う", () => {
    const 壊れた = [発言("9", "222", "壊れた", "利用者", "時刻ではない")];

    expect(リセット後に絞る(壊れた, 1)).toEqual([]);
  });
});
