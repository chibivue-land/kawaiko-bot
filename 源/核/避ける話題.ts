/**
 * 頼まれてもいない横槍を入れてはいけない話題．
 *
 * kawaiko の横槍は茶々とツッコミで，相手を少しからかう．誰かが心や体の調子・
 * 悩み・別れや死別の話をしているところへそれをやるのは，辛口ではなくただの加害．
 * 名指しで話しかけられたなら答えるが，自分から首を突っ込むのはやめておく．
 *
 * 判定は語の当てはめで，わざと広めに取ってある．「辛いラーメン」でも見送るが，
 * 見送って失うのは横槍 1 回ぶんだけ．逆向きの取りこぼしのほうがずっと高くつく．
 * 語の一覧は隣の 避ける話題.json にある．
 */
import 一覧 from "./避ける話題.json";

import { 文字列, 真偽 } from "../共通/型";
import type { 読み取り専用配列 } from "../共通/型";
import { いずれか, 含む, 小文字にする } from "../共通/関数";

export const 避ける語: 読み取り専用配列<文字列> = 一覧.話題;

export const 避けるチャンネル名の語: 読み取り専用配列<文字列> = 一覧.チャンネル名;

/** 発言が，茶化してはいけない話に触れているか． */
export function 避ける話題か(本文: 文字列): 真偽 {
  return どれかを含むか(本文, 避ける語);
}

/** そもそも相談や吐き出しのための場所に見えるチャンネルか． */
export function 避けるチャンネルか(名前: 文字列): 真偽 {
  return どれかを含むか(名前, 避けるチャンネル名の語);
}

function どれかを含むか(文: 文字列, 語一覧: 読み取り専用配列<文字列>): 真偽 {
  const 小文字 = 小文字にする(文);

  return いずれか(語一覧, (語) => 含む(小文字, 語));
}
