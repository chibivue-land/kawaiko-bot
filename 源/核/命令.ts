/**
 * メンションされたときに kawaiko が理解するチャット命令。
 *
 * あえて Discord のスラッシュコマンドにしていない。あちらはアプリ側の登録と
 * interactions エンドポイントが要るが、メンション命令なら bot が読める
 * チャンネルすべてで今すぐ動く。
 *
 * 判定は (末尾の句読点を落としたうえで) 完全一致。ただ「忘れて」という語を
 * 含むだけの普通の雑談を命令として飲み込まないため。
 */
import { 文字列, 真偽 } from "../共通/型";
import type { 読み取り専用集合 } from "../共通/型";

const リセット命令: 読み取り専用集合<文字列> = new Set([
  "reset",
  "/reset",
  "!reset",
  "forget",
  "/forget",
  "リセット",
  "りせっと",
  "記憶リセット",
  "会話リセット",
  "メモリリセット",
  "記憶を消して",
  "記憶消して",
  "忘れて",
  "全部忘れて",
  "全部忘れろ",
  "会話を忘れて",
  "ログを忘れて",
  "いったん忘れて",
  "一旦忘れて",
]);

/** 前後の空白と、末尾の句読点・引用符を落とす。 */
function 命令として整える(本文: 文字列): 文字列 {
  return 本文
    .trim()
    .replace(/^[「『"'`]+/u, "")
    .replace(/[」』"'`]+$/u, "")
    .replace(/[。．、，!！?？…\s]+$/u, "")
    .trim()
    .toLowerCase();
}

/**
 * メンション本文が「このチャンネルを忘れて」命令かどうか。
 * どのチャンネルに限定するかは呼び出し側の責任。
 */
export function リセット命令か(本文: 文字列): 真偽 {
  return リセット命令.has(命令として整える(本文));
}
