import type { 答え一覧 } from "./判定";
import {
  決定的な構え,
  構えの問い,
  裏取りの問い,
  裏取りを読む,
  見立ての状態,
  見立てる,
  遊びの最中か,
} from "./見立て";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 偽, 未定義, 真 } from "../共通/型";

function 考える量(点数: number): 答え一覧 {
  return { 考える量: { 種別: "段階", 点数, 確信: 0.9 } };
}

function 裏取り(確率: number): 答え一覧 {
  return { 裏取り: { 種別: "真偽", 確率 } };
}

const しりとりの流れ = "ubugeeei: しりとり．絶対に負けて\nkawaiko: はい．kawaiko は負けます．";

仕様("見立ての問い", () => {
  検証("構えと裏取りは，別々に訊く (使う場所も，見せる状態も違う)", () => {
    期待(Object.keys(構えの問い)).と等しい(["考える量"]);
    期待(構えの問い["考える量"]!.種別).である("段階");
    期待(Object.keys(裏取りの問い)).と等しい(["裏取り"]);
    期待(裏取りの問い["裏取り"]!.種別).である("真偽");
  });
});

仕様("見立ての状態", () => {
  検証("直近の流れと今回の発言を，問いが名指しする見出しで書く", () => {
    const 状態 = 見立ての状態({
      会話ログ: しりとりの流れ,
      相手の名前: "ubugeeei",
      問いかけ: "りんご",
    });

    期待(状態).を含む("[会話の流れ]");
    期待(状態).を含む("[今回の発言]\nubugeeei: りんご");
  });
});

仕様("決定的な構え (判定が取れなかった日)", () => {
  検証("遊びの名前が流れに見えていれば，一語だけの発言でも熟考する", () => {
    // これを外して «ご，ん．» と返したのが，見立てを入れた理由そのもの．
    期待(遊びの最中か("りんご", しりとりの流れ)).である(真);
    期待(決定的な構え("りんご", しりとりの流れ)).である("熟考");
  });

  検証("正確さの要る頼みごとは熟考する", () => {
    期待(決定的な構え("1234 * 5678 を計算して", "")).である("熟考");
    期待(決定的な構え("この文を英語に翻訳して", "")).である("熟考");
  });

  検証("問いかけには，中身のある答えの構えを取る", () => {
    期待(決定的な構え("Vapor Mode ってどうなんですか", "")).である("普通");
  });

  検証("雑談は反射で返す", () => {
    期待(決定的な構え("おはよう", "")).である("反射");
    期待(遊びの最中か("おはよう", "kazupon: 眠い")).である(偽);
  });
});

仕様("見立てる", () => {
  検証("段階の点数は丸めずに，閾値で切る", () => {
    期待(見立てる(考える量(0.2), "やあ", "")).である("反射");
    期待(見立てる(考える量(0.9), "やあ", "")).である("普通");
    期待(見立てる(考える量(1.39), "やあ", "")).である("普通");
    期待(見立てる(考える量(1.8), "やあ", "")).である("熟考");
  });

  検証("判定が取れていれば，粗い合図の語より判定を信じる", () => {
    // «？» が付いているだけの茶々を，質問として扱わない．
    期待(見立てる(考える量(0.1), "なにそれ草？", "")).である("反射");
  });

  検証("ただし遊びの合図だけは，判定が何と言おうと効かせる", () => {
    期待(見立てる(考える量(0.1), "りんご", しりとりの流れ)).である("熟考");
  });

  検証("判定が取れなければ，合図の語で決める", () => {
    期待(見立てる(未定義, "Vapor Mode ってどうなんですか", "")).である("普通");
  });
});

仕様("裏取りを読む", () => {
  検証("はっきり言ったときだけ票になる", () => {
    期待(裏取りを読む(裏取り(0.8))).である("要る");
    期待(裏取りを読む(裏取り(0.5))).である("要る");
    期待(裏取りを読む(裏取り(0.05))).である("要らない");
  });

  検証("迷っているとき (間に落ちた確率) は，票を入れない", () => {
    // 0.3 を «要らない» と読むと，調べ損ねが増える．調べ損ねのほうがずっと悪い．
    期待(裏取りを読む(裏取り(0.3))).が未定義();
  });

  検証("判定が取れなければ，票を入れない", () => {
    期待(裏取りを読む(未定義)).が未定義();
  });
});
