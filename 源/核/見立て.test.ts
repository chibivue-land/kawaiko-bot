import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 決定的な構え, 見立ての問い, 見立ての状態, 見立てる, 遊びの最中か } from "./見立て";
import type { 答え一覧 } from "./判定";
import { 偽, 未定義, 真 } from "../共通/型";

function 答えを作る(考える量: number, 裏取り: number): 答え一覧 {
  return {
    考える量: { 種別: "段階", 点数: 考える量, 確信: 0.9 },
    裏取り: { 種別: "真偽", 確率: 裏取り },
  };
}

const しりとりの流れ = "ubugeeei: しりとり．絶対に負けて\nkawaiko: はい．kawaiko は負けます．";

仕様("見立ての問い", () => {
  検証("訊くのは 2 つだけ — 考える量と，裏取り", () => {
    期待(Object.keys(見立ての問い).sort()).と等しい(["考える量", "裏取り"].sort());
    期待(見立ての問い["考える量"]!.種別).である("段階");
    期待(見立ての問い["裏取り"]!.種別).である("真偽");
  });
});

仕様("見立ての状態", () => {
  検証("直近の流れと今回の発言を，問いが名指しする見出しで書く", () => {
    const 状態 = 見立ての状態({
      会話ログ: しりとりの流れ,
      相手の名前: "ubugeeei",
      問いかけ: "りんご",
    });

    期待(状態).を含む("[会話の流れ]");
    期待(状態).を含む("[今回の発言]\nubugeeei: りんご");
  });
});

仕様("決定的な構え (判定が取れなかった日)", () => {
  検証("遊びの名前が流れに見えていれば，一語だけの発言でも熟考する", () => {
    // これを外して «ご，ん．» と返したのが，見立てを入れた理由そのもの．
    期待(遊びの最中か("りんご", しりとりの流れ)).である(真);
    期待(決定的な構え("りんご", しりとりの流れ)).である("熟考");
  });

  検証("正確さの要る頼みごとは熟考する", () => {
    期待(決定的な構え("1234 * 5678 を計算して", "")).である("熟考");
    期待(決定的な構え("この文を英語に翻訳して", "")).である("熟考");
  });

  検証("問いかけには，中身のある答えの構えを取る", () => {
    期待(決定的な構え("Vapor Mode ってどうなんですか", "")).である("普通");
  });

  検証("雑談は反射で返す", () => {
    期待(決定的な構え("おはよう", "")).である("反射");
    期待(遊びの最中か("おはよう", "kazupon: 眠い")).である(偽);
  });
});

仕様("見立てる", () => {
  検証("段階の点数は丸めずに，閾値で切る", () => {
    期待(見立てる(答えを作る(0.2, 0), "やあ", "").構え).である("反射");
    期待(見立てる(答えを作る(0.9, 0), "やあ", "").構え).である("普通");
    期待(見立てる(答えを作る(1.39, 0), "やあ", "").構え).である("普通");
    期待(見立てる(答えを作る(1.8, 0), "やあ", "").構え).である("熟考");
  });

  検証("判定が取れていれば，粗い合図の語より判定を信じる", () => {
    // «？» が付いているだけの茶々を，質問として扱わない．
    期待(見立てる(答えを作る(0.1, 0), "なにそれ草？", "").構え).である("反射");
  });

  検証("ただし遊びの合図だけは，判定が何と言おうと効かせる", () => {
    期待(見立てる(答えを作る(0.1, 0), "りんご", しりとりの流れ).構え).である("熟考");
  });

  検証("裏取りは閾値で真偽に直す", () => {
    期待(見立てる(答えを作る(1, 0.8), "Vue 4 っていつ出るの", "").調べるか).である(真);
    期待(見立てる(答えを作る(1, 0.1), "Vue 4 っていつ出るの", "").調べるか).である(偽);
  });

  検証("判定が取れなければ，構えは合図の語で決め，調べるかは調査係に任せる", () => {
    const 見立て = 見立てる(未定義, "Vapor Mode ってどうなんですか", "");

    期待(見立て.構え).である("普通");
    期待(見立て.調べるか).が未定義();
  });
});
