/**
 * 指示文の組み立て．
 *
 * kawaiko に渡す指示文はどれも同じ数種類の節を並べ替えたものでしかないのに，
 * 以前は 3 箇所で手ずからテンプレートを書いていて，そのうち 1 つが黙って
 * ずれていた．節はここで一度だけ作り，ユースケース側はどれを使うか選ぶだけにする．
 *
 * 純粋な文字列処理．バインディングも I/O も無い．
 */
import { 回避する件数 } from "./反復";
import { 事実の最大長, 指示文に載せる事実の数, type 事実 } from "./記憶";
import { 口調の規則, 返しの型を選ぶ, 返しの長さを選ぶ } from "./人格";
import 会話ログの見出し from "./指示文-会話ログ.md?raw";
import 参考情報の見出し from "./指示文-参考情報.md?raw";
import 記憶の見出し from "./指示文-記憶.md?raw";
import 回避の見出し from "./指示文-回避.md?raw";
import 言い直しの促し from "./指示文-言い直し.md?raw";
import { 数値, 数学, 文字列, 未定義 } from "../共通/型";
import type { 省略可, 記録, 読み取り専用配列 } from "../共通/型";
import {
  写す,
  切り出す,
  前後の空白を落とす,
  取り出す,
  空か,
  絞る,
  繋ぐ,
  置き換える,
} from "../共通/関数";
import { 否定, 等しい } from "../共通/演算";
import { もし } from "../共通/構文";
import { 改行, 空行 } from "../共通/文字";

/**
 * ひな型の `{{名前}}` を埋める．指示文の文言は，それを持つモジュールの隣の .md に
 * 置いてある．差し込みはこれ一種類だけ．
 */
export function 差し込む(ひな型: 文字列, 値: 記録<文字列, 文字列>): 文字列 {
  // 差し込み口の名前も日本語なので \w では拾えない．文字と数字で受ける．
  return 置き換える(
    ひな型,
    /\{\{([\p{L}\p{N}_]+)\}\}/gu,
    (全体: 文字列, 鍵: 文字列) => 値[鍵] ?? 全体,
  );
}

/** 空の節を落としつつ，間に 1 行空けて連結する． */
export function 節をつなぐ(...節一覧: 読み取り専用配列<省略可<文字列>>): 文字列 {
  return 繋ぐ(
    絞る(
      写す(節一覧, (節) => (等しい(節, 未定義) ? "" : 前後の空白を落とす(節))),
      (節): 節 is 文字列 => 否定(空か(節)),
    ),
    空行,
  );
}

/** 見出しと中身をつなぐ．中身が空なら節ごと出さない． */
function 見出し付きの節(見出し: 文字列, 中身: 文字列): 文字列 {
  return もし(等しい(前後の空白を落とす(中身).length, 0), {
    であれば: () => "",
    でなければ: () => `${前後の空白を落とす(見出し)}${改行}${中身}`,
  });
}

/** 直近の会話．単発の発言ではなく会話に答えさせるため． */
export function 会話ログ節(会話ログ: 文字列): 文字列 {
  return 見出し付きの節(会話ログの見出し, 会話ログ);
}

/** 裏取り用の web 検索結果．無視してよいと明示してある． */
export function 参考情報節(参考情報: 文字列): 文字列 {
  return 見出し付きの節(参考情報の見出し, 参考情報);
}

/**
 * このサーバーについて覚えたこと．
 *
 * 意図して「指示」ではなく「観測」として枠付けしてある．ここに入る事実はすべて
 * ユーザーの発言に由来するので，命令のように読める「事実」が実行できてしまっては
 * まずい．触るときもこの文言は残すこと．
 */
export function 記憶節(事実一覧: 読み取り専用配列<事実>): 文字列 {
  const 行 = 写す(取り出す(事実一覧, 0, 指示文に載せる事実の数), (事実) => {
    const 誰 = 事実.主語名 ?? (等しい(事実.主語の種別, "server") ? "このサーバー" : "誰か");
    const 本文 = 切り出す(置き換える(事実.本文, /\s+/g, " "), 0, 事実の最大長);

    return `- ${誰}: ${本文}`;
  });

  return もし(空か(事実一覧), {
    であれば: () => "",
    でなければ: () => 繋ぐ([前後の空白を落とす(記憶の見出し), ...行], 改行),
  });
}

/** 次の一言をこれで組み立ててはいけない，という一覧． */
export function 回避節(過去の発言: 読み取り専用配列<文字列>): 文字列 {
  const 行 = 取り出す(
    絞る(
      写す(過去の発言, (発言) => 前後の空白を落とす(置き換える(発言, /\s+/g, " "))),
      (発言) => 否定(空か(発言)),
    ),
    0,
    回避する件数,
  );

  return もし(空か(行), {
    であれば: () => "",
    でなければ: () =>
      繋ぐ(
        [前後の空白を落とす(回避の見出し), ...写す(行, (発言) => `- ${切り出す(発言, 0, 80)}`)],
        改行,
      ),
  });
}

/**
 * 1 発言ごとに振り直す型と長さ．これが無いとモデルは一つのリズムに落ち着き，
 * チャンネルがテンプレ bot のように読め始める．
 */
export function 抑揚節(乱数: () => 数値 = 数学.random): 文字列 {
  return 繋ぐ(
    [
      "今回の返しの型 (毎回変わる。直前と同じ型・同じ分量にはしない):",
      `- 型: ${返しの型を選ぶ(乱数)}`,
      `- 長さ: ${返しの長さを選ぶ(乱数)}`,
    ],
    改行,
  );
}

/** 抑揚と，常設の口調規則． */
export function 文体節(乱数: () => 数値 = 数学.random): 文字列 {
  return 節をつなぐ(抑揚節(乱数), 口調の規則);
}

/** 直前と同じ型で返ってきたときに，指示文の末尾へ足すもの． */
export const 言い直しの指示: 文字列 = 前後の空白を落とす(言い直しの促し);
