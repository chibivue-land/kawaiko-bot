/**
 * 型付きの問いと，その答え．
 *
 * 文章を書かせるのではなく，ある状態を決まった形の問いに照らして**判定させる**
 * ときの語彙．形は 3 つだけ:
 *
 *   真偽  ある命題が成り立つ確率 (0〜1)
 *   選択  並べた選択肢からひとつ．選択肢ごとの確率と，確信の度合いつき
 *   段階  順序のある段階のどこに居るか．段階と段階の間にも落ちる連続値
 *
 * 外界ではこれを Jev (TypeSafe の判定モデル) が Noul / Choice / Score として
 * 受け持つが，核はそれを知らない．ここにあるのは問いの形と，答えの読み方だけ．純粋．
 *
 * 問いはどれも「一つのことだけ」を訊く．二つ訊きたければ問いを二つ並べる —
 * 問い同士は互いを見ないので，並べても答えが濁らない．
 */
import { 数値, 文字列, 未定義, 真偽 } from "../共通/型";
import type { 省略可, 記録, 読み取り専用配列 } from "../共通/型";
import { 写す, 分ける, 前後の空白を落とす, 取り出す, 空か, 絞る, 繋ぐ } from "../共通/関数";
import { 以上, 否定 } from "../共通/演算";
import { 改行, 空行 } from "../共通/文字";

export interface 真偽の問い {
  種別: "真偽";

  指示: 文字列;

  /** 何をもって真 / 偽とするか．指示と食い違わせないこと (答えが鈍る)． */
  基準?: 省略可<{ 真: 文字列; 偽: 文字列 }>;
}

export interface 選択の問い {
  種別: "選択";

  指示: 文字列;

  /** 選択肢 -> その選択肢の説明．似た選択肢を並べすぎると確率が平たくなる． */
  基準: 記録<文字列, 文字列>;
}

export interface 段階の問い {
  種別: "段階";

  指示: 文字列;

  /** 低いほうから順に並べた段階の説明 (2〜10 段)． */
  基準: 読み取り専用配列<文字列>;
}

export type 問い = 真偽の問い | 選択の問い | 段階の問い;

export interface 真偽の答え {
  種別: "真偽";

  /** 真である確率．0.5 は「半分くらい真」ではなく「分からない」． */
  確率: 数値;
}

export interface 選択の答え {
  種別: "選択";

  選択: 文字列;

  /** 確率の山がどれだけ尖っているか (0〜1)． */
  確信: 数値;

  確率: 記録<文字列, 数値>;
}

export interface 段階の答え {
  種別: "段階";

  /** 0 始まりの段階の位置．確率で重み付けした値なので 1.4 のように間へ落ちる． */
  点数: 数値;

  確信: 数値;
}

export type 答え = 真偽の答え | 選択の答え | 段階の答え;

export type 答え一覧 = 記録<文字列, 答え>;

/**
 * 判定に掛ける状態を，見出し付きの塊として書き出す．中身が空の塊は落とす．
 *
 *   [会話の流れ]
 *   ubugeeei: しりとり
 *
 *   [今回の発言]
 *   ubugeeei: りんご
 *
 * 問いの指示は，この見出しを名指しして書く («[今回の発言] は〜か»)．
 */
export function 状態を書く(
  塊一覧: 読み取り専用配列<readonly [見出し: 文字列, 中身: 文字列]>,
): 文字列 {
  return 繋ぐ(
    写す(
      絞る(塊一覧, ([, 中身]) => 否定(空か(前後の空白を落とす(中身)))),
      ([見出し, 中身]) => `[${見出し}]${改行}${前後の空白を落とす(中身)}`,
    ),
    空行,
  );
}

/** 会話ログの末尾だけ．判定に要るのは直近の流れで，全部ではない． */
export function 末尾の行(文: 文字列, 行数: 数値): 文字列 {
  return 繋ぐ(取り出す(分ける(文, 改行), -行数), 改行);
}

// 判別可能ユニオンの絞り込みは，関数越しの型述語では効かない．ここは素の === で見る．

/** その問いが真である確率．答えが無いか，真偽の答えでなければ未定義． */
export function 真の確率(一覧: 省略可<答え一覧>, 鍵: 文字列): 省略可<数値> {
  const 答え = 一覧?.[鍵];

  return 答え?.種別 === "真偽" ? 答え.確率 : 未定義;
}

/** その問いの段階の点数．答えが無いか，段階の答えでなければ未定義． */
export function 段階の点数(一覧: 省略可<答え一覧>, 鍵: 文字列): 省略可<数値> {
  const 答え = 一覧?.[鍵];

  return 答え?.種別 === "段階" ? 答え.点数 : 未定義;
}

/** その問いで選ばれた選択肢．答えが無いか，選択の答えでなければ未定義． */
export function 選ばれたもの(一覧: 省略可<答え一覧>, 鍵: 文字列): 省略可<文字列> {
  const 答え = 一覧?.[鍵];

  return 答え?.種別 === "選択" ? 答え.選択 : 未定義;
}

/**
 * 「分からない」を，こちらの都合の良い側へ倒して読む．
 *
 * 判定が取れなかったとき (判定器が無い・休んでいる・転んだ) に何が起きるべきかは
 * 問いごとに違うので，既定を呼び出し側に言わせる．
 */
export function 閾値を超えるか(確率: 省略可<数値>, 閾値: 数値, 分からないとき: 真偽): 真偽 {
  return 確率 === 未定義 ? 分からないとき : 以上(確率, 閾値);
}
