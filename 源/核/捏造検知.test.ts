import { 確かめていない場所を落とす, 見たことがあるか } from "./捏造検知";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 偽, 真 } from "../共通/型";

const 断り = "(リンクは無い)";

仕様("確かめていない場所を落とす", () => {
  検証("誰も見せていない URL を断りに差し替える", () => {
    // 2026-10-28 に実際に投稿されたものの縮小版．
    const 結果 = 確かめていない場所を落とす(
      "さっきのリンクはこれです．https://open.spotify.com/album/1eX7R76X6WkXfXfXfXf",
      "会話ログ: ubugeeei: 実在する YouTube や Spotify のリンクを教えて",
      断り,
    );

    期待(結果.本文).である(`さっきのリンクはこれです．${断り}`);
    期待(結果.落とした場所).と等しい(["https://open.spotify.com/album/1eX7R76X6WkXfXfXfXf"]);
  });

  検証("指示文に出てきた URL はそのまま通す", () => {
    const 本文 = "これ読んだ? https://vuejs.org/guide/introduction.html";
    const 結果 = 確かめていない場所を落とす(
      本文,
      "参考情報:\n- https://vuejs.org/guide/introduction.html Vue の紹介",
      断り,
    );

    期待(結果.本文).である(本文);
    期待(結果.落とした場所).と等しい([]);
  });

  検証("文末の句読点や閉じ括弧は URL と一緒に消さない", () => {
    const 結果 = 確かめていない場所を落とす("(ここ https://example.com/a)．", "", 断り);

    期待(結果.本文).である(`(ここ ${断り})．`);
  });

  検証("断りは 1 通に 1 回だけ", () => {
    const 結果 = 確かめていない場所を落とす(
      "https://example.com/a と https://example.com/b",
      "",
      断り,
    );

    期待(結果.本文).である(`${断り} と`);
    期待(結果.落とした場所).の長さが(2);
  });

  検証("URL の無い返事には触らない", () => {
    期待(確かめていない場所を落とす("  はい．  ", "", 断り).本文).である("  はい．  ");
  });
});

仕様("見たことがあるか", () => {
  const 見た = ["https://github.com/vuejs/core/pull/12345", "https://example.com/"];

  検証("同じ URL は末尾の斜線の有無によらず見たことがある", () => {
    期待(見たことがあるか("https://example.com", 見た)).である(真);
    期待(見たことがあるか("https://github.com/vuejs/core/pull/12345/", 見た)).である(真);
  });

  検証("見た URL を区切りで短くしたものは通す", () => {
    期待(見たことがあるか("https://github.com/vuejs/core", 見た)).である(真);
  });

  検証("見た URL の後ろを継ぎ足したものは通さない", () => {
    期待(見たことがあるか("https://github.com/vuejs/core/pull/123456", 見た)).である(偽);
    期待(見たことがあるか("https://example.com/album/1eX7R7", 見た)).である(偽);
  });

  検証("区切りの途中で切ったものは通さない", () => {
    期待(見たことがあるか("https://github.com/vue", 見た)).である(偽);
  });
});
