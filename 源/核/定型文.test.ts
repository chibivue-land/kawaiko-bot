import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 偽, 数学, 新しい集合, 未定義 } from "../共通/型";
import { 写す, 切り出す, 含む, 長さ } from "../共通/関数";
import { より大きい, 以上, 以下, 等しい } from "../共通/演算";
import {
  リセットの文,
  予算超過の文,
  利用制限の文,
  受け流しの文,
  反復打ち切りの文,
  定型文を選ぶ,
  拒否の文,
  無言の文,
  異常の文,
} from "./定型文";

const 在庫 = {
  利用制限の文,
  予算超過の文,
  異常の文,
  拒否の文,
  無言の文,
  反復打ち切りの文,
  リセットの文,
  受け流しの文,
};

仕様("定型文を選ぶ", () => {
  検証("待ち時間を差し込む", () => {
    期待(定型文を選ぶ(["{m}分待って"], { 分: 12 })).である("12分待って");
  });

  検証("待ち時間を渡さなければ既定になる", () => {
    期待(定型文を選ぶ(["{m}分待って"])).である("60分待って");
  });

  検証("在庫の端から端まで選ばれる", () => {
    const 候補 = ["あ", "い", "う"];

    期待(定型文を選ぶ(候補, 未定義, () => 0)).である("あ");
    期待(定型文を選ぶ(候補, 未定義, () => 0.999_999)).である("う");
  });
});

仕様("在庫の一言", () => {
  検証("同じ状況に何度当たっても機械的に見えないだけの数がある", () => {
    for (const [名前, 候補] of Object.entries(在庫)) {
      期待(長さ(候補), 名前).以上(40);
      期待(新しい集合(候補).size, 名前).である(長さ(候補));
    }
  });

  検証("在庫をまたいでも文言が重ならない", () => {
    // 同じ一言が二つの状況で出ると，どちらの意味なのか読めなくなる．
    const 全部 = Object.values(在庫).flat();

    期待(新しい集合(全部).size).である(長さ(全部));
  });

  検証("Discord の 1 通に収まる長さで，空でもない", () => {
    for (const [名前, 候補] of Object.entries(在庫)) {
      for (const 一文 of 候補) {
        期待(長さ(一文), `${名前}: ${一文}`).より大きい(0);
        期待(長さ(一文), `${名前}: ${一文}`).以下(120);
      }
    }
  });

  検証("句読点はコーパスに合わせて「，．」を使う", () => {
    // 人格-語彙集.md が最初の行からそう書いている．
    for (const [名前, 候補] of Object.entries(在庫)) {
      for (const 一文 of 候補) {
        期待(含む(一文, "。"), `${名前}: ${一文}`).である(偽);
        期待(含む(一文, "、"), `${名前}: ${一文}`).である(偽);
      }
    }
  });

  検証("書き出しが一箇所に固まっていない", () => {
    // 全部が「はい．」で始まったら，増やした意味が無い．
    for (const [名前, 候補] of Object.entries(在庫)) {
      const 書き出し = 新しい集合(写す(候補, (一文) => 切り出す(一文, 0, 3)));

      期待(書き出し.size, 名前).以上(数学.floor(長さ(候補) / 4));
    }
  });

  検証("kawaiko は「私」も「僕」も言わない", () => {
    for (const [名前, 候補] of Object.entries(在庫)) {
      for (const 一文 of 候補) {
        期待(一文, `${名前}: ${一文}`).否.に一致する(/[私僕俺]/);
      }
    }
  });

  検証("待ち時間の差し込み口を持つのは利用制限だけ", () => {
    for (const [名前, 候補] of Object.entries(在庫)) {
      if (等しい(名前, "利用制限の文")) continue;
      期待(
        候補.some((一文) => 一文.includes("{m}")),
        名前,
      ).である(偽);
    }
  });
});
