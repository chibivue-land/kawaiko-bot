import { 機嫌節 } from "./指示文";
import { その時刻の機嫌, 上機嫌の始まり, 上機嫌の終わり, 上機嫌の指示 } from "./機嫌";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 各要素に, 範囲 } from "../共通/反復";

仕様("その時刻の機嫌", () => {
  検証("朝の枠のあいだは上機嫌", () => {
    各要素に(範囲(上機嫌の始まり, 上機嫌の終わり), (時) => {
      期待(その時刻の機嫌(時)).である("上機嫌");
    });
  });

  検証("枠の外はいつもの kawaiko", () => {
    各要素に([0, 4, 11, 12, 18, 23], (時) => {
      期待(その時刻の機嫌(時)).である("いつも");
    });
  });

  検証("始まりは含み，終わりは含まない", () => {
    期待(その時刻の機嫌(上機嫌の始まり)).である("上機嫌");
    期待(その時刻の機嫌(上機嫌の終わり)).である("いつも");
  });
});

仕様("機嫌節", () => {
  検証("朝だけ上機嫌の指示が差さる", () => {
    期待(機嫌節(7)).を含む("明るい");
    期待(機嫌節(7)).である(上機嫌の指示);
  });

  検証("それ以外の時間は何も差さない", () => {
    期待(機嫌節(22)).である("");
  });

  検証("上機嫌でも kawaiko をやめない歯止めが入っている", () => {
    期待(機嫌節(9)).を含む("kawaiko であることはやめない");
  });
});
