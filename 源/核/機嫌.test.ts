import { 機嫌節, 文体節 } from "./指示文";
import {
  その時刻の機嫌,
  上機嫌の始まり,
  上機嫌の終わり,
  上機嫌の指示,
  乱心するか,
  乱心の指示,
} from "./機嫌";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 各要素に, 範囲 } from "../共通/反復";
import { 偽, 真 } from "../共通/型";

仕様("その時刻の機嫌", () => {
  検証("朝の枠のあいだは上機嫌", () => {
    各要素に(範囲(上機嫌の始まり, 上機嫌の終わり), (時) => {
      期待(その時刻の機嫌(時)).である("上機嫌");
    });
  });

  検証("枠の外はいつもの kawaiko", () => {
    各要素に([0, 4, 11, 12, 18, 23], (時) => {
      期待(その時刻の機嫌(時)).である("いつも");
    });
  });

  検証("始まりは含み，終わりは含まない", () => {
    期待(その時刻の機嫌(上機嫌の始まり)).である("上機嫌");
    期待(その時刻の機嫌(上機嫌の終わり)).である("いつも");
  });
});

仕様("機嫌節", () => {
  検証("朝だけ上機嫌の指示が差さる", () => {
    期待(機嫌節(7)).を含む("明るい");
    期待(機嫌節(7)).である(上機嫌の指示);
  });

  検証("それ以外の時間は何も差さない", () => {
    期待(機嫌節(22)).である("");
  });

  検証("上機嫌でも kawaiko をやめない歯止めが入っている", () => {
    期待(機嫌節(9)).を含む("kawaiko であることはやめない");
  });
});

仕様("乱心", () => {
  検証("低い確率でだけ乱心する", () => {
    期待(乱心するか("0.05", () => 0.01)).である(真);
    期待(乱心するか("0.05", () => 0.05)).である(偽);
    期待(乱心するか("0.05", () => 0.9)).である(偽);
    期待(乱心するか("0", () => 0)).である(偽);
  });

  検証("設定を書き損じただけでは乱心しない", () => {
    // 独言の確率とは逆．常時おかしい kawaiko は，転び方として間違っている．
    期待(乱心するか("ばなな", () => 0)).である(偽);
    期待(乱心するか("", () => 0)).である(偽);
  });

  検証("乱心は時刻に勝つ．朝でも乱心しているなら乱心している", () => {
    期待(その時刻の機嫌(7, 真)).である("乱心");
    期待(機嫌節(7, 真)).である(乱心の指示);
    期待(機嫌節(22, 真)).である(乱心の指示);
  });

  検証("乱心していても越えない線が，指示の中に書いてある", () => {
    期待(乱心の指示).を含む("一人称は「kawaiko」のまま");
    期待(乱心の指示).を含む("攻撃や差別");
    期待(乱心の指示).を含む("絶対に出さない");
  });

  検証("乱心しているときは，«キャラは絶対に変えない» を差さない", () => {
    // 真っ向からぶつかる指示を同時に渡すと，小さいモデルは両方とも半端に守る．
    期待(文体節(() => 0, { 乱心か: 真 })).である("");
  });
});
