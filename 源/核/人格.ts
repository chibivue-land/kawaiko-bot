/**
 * kawaiko とは誰か．
 *
 * 文言はこのファイルに一切書かない．人格を調整するのはテンプレートリテラルを
 * 書き換えて再デプロイすることではなく，文章を書き直すことであってほしい．
 * 実際の言葉は隣のデータファイルにある:
 *
 *   人格-指示書.md   システムプロンプト．{{語彙集}} の差し込み口がある
 *   人格-語彙集.md   そこへ入る，観測された文体コーパス
 *   人格-口調.md     常設の「テンプレ化するな」規則
 *   人格-抑揚.json   1 発言ごとに振り直す型と長さ
 *
 * ここに残すのは，その周りのわずかな振る舞いだけ．
 */
import 口調規則 from "./人格-口調.md?raw";
import 抑揚 from "./人格-抑揚.json";
import 指示書のひな型 from "./人格-指示書.md?raw";
import 語彙集 from "./人格-語彙集.md?raw";

import { 差し込む } from "./指示文";

import { 偽, 数値, 数学, 文字列, 真偽 } from "../共通/型";
import type { 読み取り専用配列 } from "../共通/型";
import { 探す, 畳む, 長さ } from "../共通/関数";
import { もし } from "../共通/構文";

/**
 * 1 発言ごとに選び直す「今回の返しの型」．
 *
 * 人格は意図して固定してある．固定してはいけないのは伝え方のほう．これが無いと
 * モデルは直前に使った骨格へ落ち着き，チャンネルがテンプレ bot のように読める．
 * 並んでいるものはどれも kawaiko のままで，変わるのは構造と語り口だけ．
 */
export const 返しの型一覧: 読み取り専用配列<文字列> = 抑揚.型;

/**
 * 長さのダイヤル．これが無いと毎回同じ分量へ収束し，言葉が違っても型に見える．
 * 短いほうがやや出やすいが，寄せすぎない — 一度 1 文以下が 6 割を超えて，
 * 「短文しか返さない」になった．
 */
export const 返しの長さ一覧: 読み取り専用配列<{ 指示: 文字列; 重み: 数値 }> = 抑揚.長さ;

/**
 * 調べた回だけの，別のダイヤル．
 *
 * web を引いてページまで開いた回に一言で切ったら，調べた意味が無い．こちらには
 * 「一言だけ」が入っていない．
 */
export const 調べた回の長さ一覧: 読み取り専用配列<{ 指示: 文字列; 重み: 数値 }> =
  抑揚.調べた回の長さ;

/** 「伝え方」だけに掛かる常設規則．反復ガードが人格を薄めないための歯止め． */
export const 口調の規則: 文字列 = 口調規則.trim();

/** 今回の返しの型を選ぶ． */
export function 返しの型を選ぶ(乱数: () => 数値 = 数学.random): 文字列 {
  return 返しの型一覧[数学.floor(乱数() * 長さ(返しの型一覧))]!;
}

/** 今回の長さを選ぶ．調べた回はもう一方のダイヤルから引く． */
export function 返しの長さを選ぶ(乱数: () => 数値 = 数学.random, 調べたか: 真偽 = 偽): 文字列 {
  const 候補 = もし(調べたか, {
    であれば: () => 調べた回の長さ一覧,
    でなければ: () => 返しの長さ一覧,
  });
  const 賽 = 乱数() * 畳む(候補, (積, 項) => 積 + 項.重み, 0);

  // 重みを順に積んで，賽を追い越した最初の項が当たり．
  let 積み上げ = 0;
  const 当たり = 探す(候補, (項) => {
    積み上げ += 項.重み;

    return 賽 < 積み上げ;
  });

  return (当たり ?? 候補[長さ(候補) - 1]!).指示;
}
/** システムプロンプト: 絶対のルール，人格コーパス，振る舞いの注意． */
export function 人格指示書を組み立てる(): 文字列 {
  return 差し込む(指示書のひな型, { 語彙集 }).trim();
}
