/**
 * 「描いて」と言われたときの読み取りと，頼み方．
 *
 * 画像そのものを作るのは外界 (外界/AI/絵.ts) の仕事．ここが持つのは，どの発言が
 * 絵の頼みなのか，何を描けと言われたのか，そしてモデルへの頼み文だけ．純粋．
 */
import 依頼のひな型 from "./作画-依頼.md?raw";
import 役割のひな型 from "./作画-役割.md?raw";

import { 口調の規則 } from "./人格";
import { 差し込む } from "./指示文";

import { 文字列, 新しい型, 未定義, 空 } from "../共通/型";
import type { 省略可 } from "../共通/型";
import { もし } from "../共通/構文";
import { 等しい } from "../共通/演算";
import { 前後の空白を落とす, 切り出す, 空か, 置き換える } from "../共通/関数";

/** 画像生成モデルへ渡すプロンプトの上限．長すぎるものは効かないので刈る． */
export const 絵の指示の最大長 = 400;

/** お題の上限．発言まるごとを投げ込まれても困る． */
export const お題の最大長 = 200;

/**
 * 「〜を描いて」の形．
 *
 * 命令を**末尾に**しか認めないのが肝心．「〜って書いてあった」のような普通の
 * 雑談には命令の語がふつうに出てくるので，含むかどうかで採ると誤爆する．
 */
const 末尾の頼み =
  /^(?<お題>[\s\S]*?)(?:の)?\s*(?:絵|イラスト|画像)?\s*(?:を|で|に)?\s*(?:描いて|書いて|かいて|えがいて|描け|描いてくれ|生成して|作って)(?:ください|下さい|くれ|くん|ね|よ|〜|ー)*$/u;

/** 「描いて 〜」の形． */
const 先頭の頼み =
  /^(?:絵|イラスト|画像)?\s*(?:を)?\s*(?:描いて|draw|generate)\s+(?<お題>[\s\S]+)$/iu;

/** 末尾の句読点と引用符を落とす． */
function 整える(本文: 文字列): 文字列 {
  return 前後の空白を落とす(置き換える(前後の空白を落とす(本文), /[。．、，!！?？…\s]+$/u, ""));
}

/**
 * この発言は絵の頼みか．頼みなら，何を描くか．
 *
 * お題が空 (「描いて」だけ) でも頼みは頼み．何を描くかは kawaiko が決める．
 */
export function 描く頼みか(本文: 文字列): 省略可<描く頼み> {
  const 整えた = 整える(本文);
  const 一致 = 先頭の頼み.exec(整えた) ?? 末尾の頼み.exec(整えた);

  return もし(等しい(一致, 空), {
    であれば: (): 省略可<描く頼み> => 未定義,
    でなければ: (): 省略可<描く頼み> => ({
      お題: 切り出す(整える(一致!.groups?.お題 ?? ""), 0, お題の最大長),
    }),
  });
}

export interface 描く頼み {
  /** 何を描くか．空なら「お任せ」． */
  お題: 文字列;
}

/**
 * 絵の下ごしらえをさせるときの指示書．
 *
 * 人格指示書は使わない．あちらは「見出しも箇条書きも使うな」「いきなり本文だけ
 * を返せ」と強く言っていて，ラベル付きの 2 行という**書式の指示と真っ向から
 * 喧嘩する** — 実際に本番でそうなり，絵の指示が 1 度も読めなかった．
 *
 * 声だけは残したいので，人格のうち「伝え方」の規則 (口調) だけを差し込む．
 * 人格コーパスは入れない．ここで作るのは会話ではないので要らない．
 */
export function 作画の指示書を組み立てる(): 文字列 {
  return 前後の空白を落とす(差し込む(役割のひな型, { 口調: 口調の規則 }));
}

/** モデルに，絵の指示と添える一言をまとめて作らせる． */
export function 作画依頼を組み立てる(頼み: { お題: 文字列; 相手の名前: 文字列 }): 文字列 {
  return 前後の空白を落とす(
    差し込む(依頼のひな型, {
      相手の名前: 頼み.相手の名前,
      お題: もし(空か(頼み.お題), {
        であれば: () => "(何を描くかは指定されていない。kawaiko が勝手に決める)",
        でなければ: () => 頼み.お題,
      }),
    }),
  );
}

/**
 * ラベルの拾い方は緩くしてある．
 *
 * 小さいモデルは平気で `**絵:**` と太字にするし，`- 絵:` と箇条書きにもする．
 * 書式を守らせるのは指示書の仕事で，読む側は守られなかった場合に備える．
 */
const 飾り = "[*_\\-–—•\\s]*";

// 閉じの飾り (`**絵:** a cat` の後ろの `**`) も落とす．ここに `-` は入れない —
// 中身そのものが `-` で始まることがある．
const 閉じの飾り = "[*_\\s]*";

const 絵の行 = 新しい型(
  `^${飾り}(?:絵|画像|prompt|image)${飾り}[:：]${閉じの飾り}(?<中身>.+)$`,
  "imu",
);

const 一言の行 = 新しい型(
  `^${飾り}(?:一言|ひとこと|caption|comment)${飾り}[:：]${閉じの飾り}(?<中身>.+)$`,
  "imu",
);

/** ラテン文字が主で，絵の指示として通りそうな行． */
const 英語らしい行 = /^[\s*_\-–—•]*(?<中身>[A-Za-z][A-Za-z0-9 ,.'"()\-/]{19,})$/mu;

export interface 作画の返事 {
  /** 画像生成モデルへ渡す英語のプロンプト． */
  絵の指示: 文字列;
  /** 絵を差し出すときの一言．読めなければ空． */
  一言: 文字列;
}

/**
 * モデルの返事から 2 行を拾う．
 *
 * 絵の指示が読めなければ諦める — 空のプロンプトで真っ白な絵を出すより，
 * 描けなかったと言うほうがまし．
 */
export function 作画の返事を読み取る(本文: 文字列): 省略可<作画の返事> {
  // ラベルが無くても，英語の 1 行だけは拾ってやる．書式を守らないモデルのために
  // 描かないより，読めたものを描くほうがまし．
  const 指示 = 前後の空白を落とす(
    絵の行.exec(本文)?.groups?.中身 ?? 英語らしい行.exec(本文)?.groups?.中身 ?? "",
  );

  return もし(空か(指示), {
    であれば: (): 省略可<作画の返事> => 未定義,
    でなければ: (): 省略可<作画の返事> => ({
      絵の指示: 切り出す(指示, 0, 絵の指示の最大長),
      一言: 前後の空白を落とす(一言の行.exec(本文)?.groups?.中身 ?? ""),
    }),
  });
}
