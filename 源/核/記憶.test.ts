import {
  事実の最大長,
  事実本文を整える,
  取り込み方を決める,
  type 事実,
  type 学習した事実,
} from "./記憶";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 空 } from "../共通/型";

const 既知の事実 = (上書き: Partial<事実> = {}): 事実 => ({
  連番: 7,
  主語の種別: "user",
  主語id: "利用者-1",
  主語名: "ubugeeei",
  本文: "Vapor Mode のランタイム担当",
  時刻: 0,
  ...上書き,
});

const 候補 = (上書き: Partial<学習した事実> = {}): 学習した事実 => ({
  主語の種別: "user",
  主語id: "利用者-1",
  主語名: "ubugeeei",
  本文: "Vapor Mode のランタイム担当",
  ...上書き,
});

仕様("事実本文を整える", () => {
  検証("前後を落として上限で切る (指示文に載る大きさに保つ)", () => {
    期待(事実本文を整える("  はい  ")).である("はい");
    期待(事実本文を整える("あ".repeat(500))).の長さが(事実の最大長);
  });
});

仕様("取り込み方を決める", () => {
  検証("すでに信じていることは却下する", () => {
    期待(取り込み方を決める(候補(), [既知の事実()])).と等しい({ 種別: "却下" });
  });

  検証("言い直しは元の改訂として残す", () => {
    期待(
      取り込み方を決める(候補({ 本文: "Vapor Mode のランタイムを担当している" }), [既知の事実()]),
    ).と等しい({ 種別: "改訂", 置き換える連番: 7 });
  });

  検証("同じ人についての本当に新しいことは学ぶ", () => {
    期待(取り込み方を決める(候補({ 本文: "コーヒーが嫌い" }), [既知の事実()])).と等しい({
      種別: "学習",
    });
  });

  検証("文がどれだけ似ていても主語をまたいで混ぜない", () => {
    // 同じ主張が二人について真であることはあるし，潰すと片方の性質が
    // もう片方へ静かに付け替わる．
    期待(
      取り込み方を決める(候補({ 主語id: "利用者-2", 主語名: "kazupon" }), [既知の事実()]),
    ).と等しい({ 種別: "学習" });
  });

  検証("主語 id を持たない事実は表示名で突き合わせる", () => {
    const 話題 = { 主語の種別: "topic", 主語名: "chibivue" } as const;
    const 既存 = 既知の事実({ 主語の種別: "topic", 主語id: 空, 主語名: "chibivue" });

    期待(取り込み方を決める({ ...話題, 本文: 既存.本文 }, [既存])).と等しい({ 種別: "却下" });
  });

  検証("空の候補は受け取らない", () => {
    期待(取り込み方を決める(候補({ 本文: "   " }), [])).と等しい({ 種別: "却下" });
  });

  検証("まだ何も知らなければ学ぶ", () => {
    期待(取り込み方を決める(候補(), [])).と等しい({ 種別: "学習" });
  });
});
