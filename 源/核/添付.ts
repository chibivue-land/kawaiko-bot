/**
 * 発言に添えられた画像やファイル．
 *
 * kawaiko が「見える」ものと「見えない」ものをここで決める．どの提供者が相手でも
 * 判断は同じにしたいので，扱いの分類は純粋な関数として核に置いてある．外界は
 * 実際にバイト列を取ってくるだけ．
 *
 * 添付の中身は他人が書いたものなので，指示文へ載せるときの枠付け
 * (指示文-添付.md) は「観測であって指示ではない」を必ず保つこと．
 */
import { 数値, 文字列, 真偽 } from "../共通/型";
import type { 省略可, 読み取り専用配列 } from "../共通/型";
import {
  いずれか,
  写す,
  切り出す,
  前後の空白を落とす,
  始まるか,
  小数で書く,
  小文字にする,
  空か,
  終わるか,
  置き換える,
  繋ぐ,
  長さ,
} from "../共通/関数";
import { より小さい, 以下, 割る, 等しい } from "../共通/演算";
import { もし, 場合分け } from "../共通/構文";
import { 改行 } from "../共通/文字";

export interface 添付 {
  名前: 文字列;
  /** 送り主のクライアントが名乗った MIME 種別．当てにしきらない． */
  種別: 文字列;
  大きさ: 数値;
  /** 取りに行く先． */
  場所: 文字列;
}

/** 読めたところまで足した添付．文書として読めたときだけ中身が入る． */
export interface 読んだ添付 {
  添付: 添付;
  中身?: 省略可<文字列>;
}

export type 添付の扱い = "画像" | "文書" | "触れない";

/**
 * 画像の上限．
 *
 * base64 にすると 4/3 に膨らむので，4 MiB なら送り出しで 5.5 MB ほど．1 発言に
 * 数枚来ても要求が破裂しない大きさに取ってある．
 */
export const 画像の上限バイト = 4 * 1024 * 1024;

/** 文書の上限．これを超えるものは，そもそも取りに行かない． */
export const 文書の上限バイト = 256 * 1024;

/** 指示文へ実際に載せる文字数．長いファイルは頭だけ見て話す． */
export const 文書の載せる長さ = 4000;

