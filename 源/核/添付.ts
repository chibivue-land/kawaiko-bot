function 画像か(添付: 添付): 真偽 {
  return いずれか(見られる画像, (種別) => 等しい(小文字にする(添付.種別), 種別));
}

function 文書か(添付: 添付): 真偽 {
  const 種別 = 小文字にする(添付.種別);
  const 名前 = 小文字にする(添付.名前);

  return (
    始まるか(種別, "text/") ||
    いずれか(文書の種別, (既知) => 等しい(種別, 既知)) ||
    いずれか(文書の拡張子, (拡張子) => 終わるか(名前, 拡張子))
  );
}

/**
 * この添付をどう扱うか．
 *
 * 大きすぎるものは，種別が何であれ触れない — 取りに行く時間も送り出す枠も，
 * 1 回の返事に見合わない．
 */
export function 添付の扱いを決める(添付: 添付): 添付の扱い {
  return もし<添付の扱い>(画像か(添付), {
    であれば: () => (以下(添付.大きさ, 画像の上限バイト) ? "画像" : "触れない"),
    でなければ: () =>
      もし<添付の扱い>(文書か(添付), {
        であれば: () => (以下(添付.大きさ, 文書の上限バイト) ? "文書" : "触れない"),
        でなければ: () => "触れない",
      }),
  });
}

/** 人が読む大きさ表記． */
export function 大きさの表示(バイト: 数値): 文字列 {
  return もし(より小さい(バイト, 1024), {
    であれば: () => `${バイト} B`,
    でなければ: () =>
      もし(より小さい(バイト, 1024 * 1024), {
        であれば: () => `${小数で書く(割る(バイト, 1024), 1)} KB`,
        でなければ: () => `${小数で書く(割る(バイト, 1024 * 1024), 1)} MB`,
      }),
  });
}

/** 添付 1 件を指示文の 1 かたまりにする． */
function 一件を書く(読んだ: 読んだ添付): 文字列 {
  const 添付 = 読んだ.添付;
  const 見出し = `${添付.名前} (${添付.種別}, ${大きさの表示(添付.大きさ)})`;

  return 場合分け<添付の扱い, 文字列>(添付の扱いを決める(添付), {
    画像: () => `- 画像: ${見出し}`,
    文書: () =>
      もし(空か(前後の空白を落とす(読んだ.中身 ?? "")), {
        であれば: () => `- ファイル: ${見出し} — 中身は取れなかった`,
        でなければ: () =>
          繋ぐ([`- ファイル: ${見出し}`, "  ```", 中身を字下げする(読んだ.中身!), "  ```"], 改行),
      }),
    触れない: () => `- 添えられていたが見えないもの: ${見出し}`,
  })!;
}

/** 引用の中を 2 字下げして，見出しとぶら下がりの関係を保つ． */
function 中身を字下げする(中身: 文字列): 文字列 {
  const 刈った = 切り出す(中身, 0, 文書の載せる長さ);
  const 続きあり = より小さい(文書の載せる長さ, 長さ(中身)) ? `${改行}…(以下略)` : "";

  return 置き換える(`  ${刈った}${続きあり}`, /\n/g, `${改行}  `);
}

/**
 * 添付の節．画像は「見えている」，読めたファイルは中身ごと，それ以外は
 * 「見えていない」と正直に並べる．
 */
export function 添付を書き出す(一覧: 読み取り専用配列<読んだ添付>): 文字列 {
  return もし(空か(一覧), {
    であれば: () => "",
    でなければ: () => 繋ぐ(写す(一覧, 一件を書く), 改行),
  });
}

/** 観測ログや会話ログに残す，1 行の短い印． */
export function 添付の印(一覧: 読み取り専用配列<添付>): 文字列 {
  return もし(空か(一覧), {
    であれば: () => "",
    でなければ: () =>
      `[添付: ${繋ぐ(
        写す(一覧, (添付) => 添付.名前),
        ", ",
      )}]`,
  });
}
