import { 文字列, 真, 真偽 } from "../共通/型";
import type { 省略可, 読み取り専用配列 } from "../共通/型";
import { いずれか, すべて置き換える, 前後の空白を落とす, 含む, 置き換える } from "../共通/関数";
import { 等しい } from "../共通/演算";
import { もし } from "../共通/構文";

/**
 * kawaiko にとっての「発言」と，その読み方．
 *
 * ゲートウェイと REST API はそれぞれ別の形の JSON を返してくるが，内側に渡る前に
 * 必ずこの形へ正規化する．おかげで核にもユースケースにも Discord の JSON を
 * 直接読んでいる箇所は一つもない．
 */

export interface 発言 {
  id: 文字列;
  本文: 文字列;
  /** チャットプラットフォームが振った ISO 時刻． */
  時刻: 文字列;
  発言者id: 文字列;
  /** ニックネーム・表示名・ユーザー名のうち，実際に表示されているもの． */
  発言者名: 文字列;
  bot発言か: 真偽;
}

/** 明示的に名指しされたか (@everyone / @here は含まない)． */
export function 名指しされたか(
  自分のid: 文字列,
  本文: 文字列,
  言及されたid一覧: 省略可<読み取り専用配列<文字列>>,
): 真偽 {
  return もし(
    いずれか(言及されたid一覧 ?? [], (id) => 等しい(id, 自分のid)),
    {
      であれば: () => 真,
      でなければ: () => 含む(本文, `<@${自分のid}>`) || 含む(本文, `<@!${自分のid}>`),
    },
  );
}

/** 自分宛てのメンションタグを取り除いて残りを整える． */
export function メンションを取り除く(自分のid: 文字列, 本文: 文字列): 文字列 {
  const 外した = すべて置き換える(
    すべて置き換える(本文, `<@${自分のid}>`, ""),
    `<@!${自分のid}>`,
    "",
  );

  return 前後の空白を落とす(置き換える(外した, /\s+/g, " "));
}
