/**
 * 横槍の相手選び — 誰の発言に絡むか．
 *
 * 以前は候補から無作為に 1 つ選んでいた．それだと «うん» に絡みにいくことも，
 * 本気で落ち込んでいる人を茶化しにいくこともある．前者はつまらなく，後者は
 * やってはいけない．なので候補ごとに判定器へ 2 つ訊く:
 *
 *   絡みがい              0 (絡みようがない) 〜 3 (絶好)
 *   そっとしておくべきか  茶化すと人を傷つける類の発言か
 *
 * そっとしておくべき発言は候補から外し，残りから絡みがいで重みを付けて選ぶ．
 * いちばん高いものに決め打ちしないのは，静かなチャンネルで同じ発言に 2 度絡むのを
 * 避けるため．判定が 1 つも取れなければ，これまでどおり無作為．
 *
 * 問いの文面と閾値は隣の 横槍-問い.json にある．純粋．
 */
import 定義 from "./横槍-問い.json";

import { 段階の点数, 状態を書く, 真の確率, 閾値を超えるか, type 問い, type 答え一覧 } from "./判定";
import type { 発言 } from "./発言";

import { 偽, 数値, 数学, 文字列, 未定義 } from "../共通/型";
import type { 省略可, 記録, 読み取り専用配列 } from "../共通/型";
import { もし } from "../共通/構文";
import { 否定, 等しくない } from "../共通/演算";
import { いずれか, 写す, 探す, 畳む, 空か, 絞る, 長さ } from "../共通/関数";

export const 横槍の問い = 定義.問い as 記録<文字列, 問い>;

/** 判定に掛ける候補の数．新しいものから．1 候補が判定 1 回なので，上限を置く． */
export const 見立てる候補の数 = 6;

/** 絡みがいが 0 でも，ごく稀には選ばれる余地を残す． */
const 重みの底 = 0.05;

export function 横槍の状態(対象: 発言, 会話ログ: 文字列): 文字列 {
  return 状態を書く([
    ["チャンネルの流れ", 会話ログ],
    ["注目している発言", `${対象.発言者名}: ${対象.本文}`],
  ]);
}

export interface 見立てた候補 {
  発言: 発言;

  /** 判定が取れなかった候補は未定義． */
  答え: 省略可<答え一覧>;
}

export type 相手選びの結末 =
  | { 種別: "選んだ"; 発言: 発言 }
  /** 候補はあったが，どれも茶化してはいけない発言だった． */
  | { 種別: "見送り" };

/** 見立てた候補から，絡む相手を選ぶ． */
export function 絡む相手を決める(
  候補一覧: 読み取り専用配列<見立てた候補>,
  乱数: () => 数値 = 数学.random,
): 相手選びの結末 {
  const 判定が取れたか = いずれか(候補一覧, (候補) => 等しくない(候補.答え, 未定義));
  const 触れてよい候補 = 絞る(候補一覧, (候補) =>
    否定(閾値を超えるか(真の確率(候補.答え, "そっとしておくべきか"), 定義.閾値.そっとしておく, 偽)),
  );

  return もし(空か(触れてよい候補), {
    であれば: (): 相手選びの結末 => ({ 種別: "見送り" }),
    でなければ: (): 相手選びの結末 => ({
      種別: "選んだ",
      発言: もし(判定が取れたか, {
        であれば: () => 重み付きで選ぶ(触れてよい候補, 乱数),
        // 判定が 1 つも取れなかった．これまでどおり無作為に．
        でなければ: () => 触れてよい候補[数学.floor(乱数() * 長さ(触れてよい候補))]!,
      }).発言,
    }),
  });
}

/** 絡みがいの 2 乗で重みを付ける．3 と 1 の差は 3 倍ではなく 9 倍にしたい． */
function 重み(候補: 見立てた候補): 数値 {
  return 数学.max(段階の点数(候補.答え, "絡みがい") ?? 0, 0) ** 2 + 重みの底;
}

function 重み付きで選ぶ(候補一覧: 読み取り専用配列<見立てた候補>, 乱数: () => 数値): 見立てた候補 {
  const 重み一覧 = 写す(候補一覧, 重み);
  const 賽 = 乱数() * 畳む(重み一覧, (積, 値) => 積 + 値, 0);

  // 重みを順に積んで，賽を追い越した最初の候補が当たり (人格.ts の長さ選びと同じ)．
  let 積み上げ = 0;
  const 当たり = 探す(候補一覧, (_候補, 位置) => {
    積み上げ += 重み一覧[位置]!;

    return 賽 < 積み上げ;
  });

  return 当たり ?? 候補一覧[長さ(候補一覧) - 1]!;
}
