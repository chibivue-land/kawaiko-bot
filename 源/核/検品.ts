/**
 * 返事の検品 — 作った一言が，相手の求めに応じているか．
 *
 * 反復と漏洩は決定的に測れる (反復.ts / 漏洩検知.ts) が，「しりとりの一手として
 * 成立しているか」「質問に答えたか」は文字の重なりでは測れない．そこだけ判定器に
 * 訊く．落ちたら，振る舞いの側が構えを上げて作り直す (振る舞い/発話.ts)．
 *
 * 検品は上乗せの品質管理であって関所ではない．判定が取れなければ通す — 検品が
 * できないことは，返事をしない理由にも，作り直す理由にもならない．
 *
 * 問いの文面と閾値は隣の 検品-問い.json にある．純粋．
 */
import 定義 from "./検品-問い.json";

import { 末尾の行, 状態を書く, 真の確率, 閾値を超えるか, type 問い, type 答え一覧 } from "./判定";

import { 文字列, 真, 真偽 } from "../共通/型";
import type { 省略可, 記録 } from "../共通/型";

export const 検品の問い = 定義.問い as 記録<文字列, 問い>;

/** 検品に見せる会話ログの行数．遊びのルールは，たいてい数行前に決まっている． */
const 見せる行数 = 8;

export function 検品の状態(状況: {
  会話ログ: 文字列;
  相手の名前: 文字列;
  問いかけ: 文字列;
  返事: 文字列;
}): 文字列 {
  return 状態を書く([
    ["会話の流れ", 末尾の行(状況.会話ログ, 見せる行数)],
    ["相手の発言", `${状況.相手の名前}: ${状況.問いかけ}`],
    ["kawaiko の返事", 状況.返事],
  ]);
}

/**
 * 検品に通ったか．
 *
 * 閾値は意図して低い．落とすのは判定器が「応じていない」とはっきり言ったときだけで，
 * 迷っている返事 (0.5 近辺) は通す．作り直しは毎回まるごと 1 回分の生成なので，
 * 疑わしきは通す側へ倒す．
 */
export function 検品に通ったか(答え: 省略可<答え一覧>): 真偽 {
  return 閾値を超えるか(真の確率(答え, "応じているか"), 定義.閾値.応じている, 真);
}
