import { 仕様, 検証, 期待 } from "../試験/言葉";
import { Jevの答えを言う, Jev命令の中身を読む, Jev命令の使い方, Jev命令を読む } from "./Jev命令";
import type { 問い } from "./判定";

仕様("Jev命令を読む", () => {
  検証("jev で始まらない発言は命令ではない", () => {
    期待(Jev命令を読む("Vapor Mode ってどうなんですか")).が未定義();
    // 語の途中の jev や，jev で始まる別の語を飲み込まない．
    期待(Jev命令を読む("jevって何")).が未定義();
    期待(Jev命令を読む("昨日 jev 触った")).が未定義();
  });

  検証("中身が無ければ使い方を返す", () => {
    期待(Jev命令を読む("jev")).と等しい({ 種別: "使い方" });
    期待(Jev命令を読む("  /JEV  ")).と等しい({ 種別: "使い方" });
  });

  検証("角括弧が無ければ真偽の問い", () => {
    期待(Jev命令を読む("jev この発言は煽りか")).と等しい({
      種別: "問い",
      問い: { 種別: "真偽", 指示: "この発言は煽りか" },
    });
  });

  検証("| 区切りの角括弧は選択の問い", () => {
    期待(Jev命令を読む("jev 今日の晩飯 [ラーメン|カレー| 寿司 ]")).と等しい({
      種別: "問い",
      問い: {
        種別: "選択",
        指示: "今日の晩飯",
        基準: { ラーメン: "ラーメン", カレー: "カレー", 寿司: "寿司" },
      },
    });
  });

  検証("< 区切りの角括弧は段階の問い．全角でも受ける", () => {
    期待(Jev命令を読む("!jev このコードのヤバさ ［平和＜怪しい＜炎上］")).と等しい({
      種別: "問い",
      問い: { 種別: "段階", 指示: "このコードのヤバさ", 基準: ["平和", "怪しい", "炎上"] },
    });
  });

  検証("選択にも段階にも読めない角括弧は，真偽として扱う", () => {
    const 命令 = Jev命令を読む("jev これは本当か [要出典]");

    期待(命令).の形をしている({ 種別: "問い", 問い: { 種別: "真偽" } });
  });

  検証("HTTP の口は，jev を付けずに中身だけで読める", () => {
    期待(Jev命令の中身を読む(" 晩飯 [麺|米] ")).の形をしている({
      種別: "問い",
      問い: { 種別: "選択", 指示: "晩飯" },
    });
  });
});

仕様("Jevの答えを言う", () => {
  const 真偽の問い: 問い = { 種別: "真偽", 指示: "煽りか" };

  検証("真偽は百分率と，確率の帯の一言", () => {
    期待(Jevの答えを言う(真偽の問い, { 種別: "真偽", 確率: 0.93 }, "jev-1.13.0")).である(
      "93%．ほぼ確実に真．\n-# jev-1.13.0",
    );
    // 0.5 は「半分くらい真」ではなく「分からない」．
    期待(Jevの答えを言う(真偽の問い, { 種別: "真偽", 確率: 0.5 }, "jev")).を含む("分からない");
    期待(Jevの答えを言う(真偽の問い, { 種別: "真偽", 確率: 0.02 }, "jev")).を含む("ほぼ確実に偽");
  });

  検証("選択は選ばれたものを先に，残りを確率の高い順に", () => {
    const 言い方 = Jevの答えを言う(
      { 種別: "選択", 指示: "晩飯", 基準: { 麺: "麺", 米: "米", 芋: "芋" } },
      { 種別: "選択", 選択: "麺", 確信: 0.9, 確率: { 芋: 0.08, 麺: 0.62, 米: 0.3 } },
      "jev",
    );

    期待(言い方).を含む("麺 (62%)．残りは 米 30%，芋 8%．");
    期待(言い方).否.を含む("確信は薄い");
  });

  検証("確信が薄いときだけ，そう言う", () => {
    期待(
      Jevの答えを言う(
        { 種別: "選択", 指示: "晩飯", 基準: { 麺: "麺", 米: "米" } },
        { 種別: "選択", 選択: "麺", 確信: 0.2, 確率: { 麺: 0.51, 米: 0.49 } },
        "jev",
      ),
    ).を含む("確信は薄い");
  });

  検証("段階はいちばん近い段階の名前を添えるが，数字は丸めない", () => {
    期待(
      Jevの答えを言う(
        { 種別: "段階", 指示: "ヤバさ", 基準: ["平和", "怪しい", "炎上"] },
        { 種別: "段階", 点数: 1.37, 確信: 0.8 },
        "jev",
      ),
    ).を含む("怪しい 寄り．1.37 / 2．");
  });
});

仕様("Jev命令の使い方", () => {
  検証("3 つの書き方を全部載せている", () => {
    期待(Jev命令の使い方).を含む("[A|B|C]");
    期待(Jev命令の使い方).を含む("[低<中<高]");
    期待(Jev命令の使い方).を含む("返信");
  });
});
