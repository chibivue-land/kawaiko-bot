import { 仕様, 検証, 期待 } from "../試験/言葉";
import { リセット命令か } from "./命令";
import { 偽, 真 } from "../共通/型";

仕様("リセット命令か", () => {
  検証("用意した言い方に反応する", () => {
    for (const 命令 of ["reset", "/reset", "RESET", "リセット", "忘れて", "記憶リセット"]) {
      期待(リセット命令か(命令), 命令).である(真);
    }
  });

  検証("末尾の句読点や鉤括弧は無視する", () => {
    期待(リセット命令か("  リセット！ ")).である(真);
    期待(リセット命令か("「reset」")).である(真);
  });

  検証("普通の雑談を飲み込まない", () => {
    for (const 本文 of [
      "さっきの話は忘れてもらっていいですか",
      "reset ってどういう意味ですか",
      "リセットしたほうがいい?",
      "",
    ]) {
      期待(リセット命令か(本文), 本文).である(偽);
    }
  });
});
