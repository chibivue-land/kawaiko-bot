/**
 * 「@kawaiko jev …」— 判定器 (Jev) を，チャットからそのまま叩く命令．
 *
 * 見立てや検品のような内側の使い道とは別に，人が直に判定を頼めるようにする．
 * リセット命令と同じ理由でスラッシュコマンドではなくメンション命令 (命令.ts)．
 *
 * 書き方は 3 つ．角括弧の中身で，問いの形が決まる:
 *
 *   jev この発言は煽りか                 真偽 (角括弧なし)
 *   jev 今日の晩飯 [ラーメン|カレー|寿司]   選択 (| 区切り)
 *   jev このコードのヤバさ [平和<怪しい<炎上]  段階 (< 区切り．低いほうから)
 *
 * 何を判定するか (状態) は呼び出し側が決める — 返信に付けたならその発言，そうで
 * なければ直近の流れ．ここは命令の読み取りと，答えの言い方だけ．純粋．
 */
import 言い方 from "./Jev命令-言い方.json";

import type { 問い, 答え } from "./判定";

import { 数値, 数学, 文字列, 未定義 } from "../共通/型";
import type { 省略可, 記録, 読み取り専用配列 } from "../共通/型";
import { もし } from "../共通/構文";
import { 以上, 否定, 等しい } from "../共通/演算";
import {
  並べ替える,
  写す,
  分ける,
  前後の空白を落とす,
  取り出す,
  小数で書く,
  探す,
  空か,
  絞る,
  繋ぐ,
  置き換える,
  長さ,
} from "../共通/関数";

/** 先頭の «jev» (と，付いていれば / や !)．後ろは空白か行末． */
const 命令の型 = /^[/!]?jev(?:\s+|$)/iu;

/** 末尾の角括弧．全角でも受ける． */
const 括弧の型 = /[[［]([^\]］]*)[\]］]\s*$/u;

/** 選択肢は多くても読めないし，似たものを並べるほど確率が平たくなる． */
const 選択肢の上限 = 12;

/** 段階は 2〜10 段 (判定器の側の決まり)． */
const 段階の上限 = 10;

export type Jev命令 =
  /** 本文が無い．使い方を返す． */
  { 種別: "使い方" } | { 種別: "問い"; 問い: 問い };

/** メンション本文が jev 命令なら読み取る．そうでなければ未定義． */
export function Jev命令を読む(本文: 文字列): 省略可<Jev命令> {
  const 整えた = 前後の空白を落とす(本文);

  return もし(命令の型.test(整えた), {
    であれば: (): 省略可<Jev命令> =>
      中身を読む(前後の空白を落とす(置き換える(整えた, 命令の型, ""))),
    でなければ: (): 省略可<Jev命令> => 未定義,
  });
}

/**
 * «jev» を取り除いたあとの中身を読む．HTTP の口 (POST /jev) は最初から中身だけを
 * 受け取るので，ここから入る．
 */
export function Jev命令の中身を読む(中身: 文字列): Jev命令 {
  return 中身を読む(前後の空白を落とす(中身));
}

function 中身を読む(中身: 文字列): Jev命令 {
  const 括弧 = 括弧の型.exec(中身);
  const 指示 = 前後の空白を落とす(括弧 ? 置き換える(中身, 括弧の型, "") : 中身);
  const 問い = 括弧 ? 括弧から問いを作る(指示, 括弧[1]!) : 未定義;

  return もし(空か(指示), {
    であれば: (): Jev命令 => ({ 種別: "使い方" }),
    でなければ: (): Jev命令 => ({ 種別: "問い", 問い: 問い ?? { 種別: "真偽", 指示 } }),
  });
}

/** 区切りで割って，空のかけらを落とす． */
function 割る(中身: 文字列, 区切り: RegExp): 読み取り専用配列<文字列> {
  return 絞る(
    写す(分ける(中身, 区切り), (かけら) => 前後の空白を落とす(かけら)),
    (かけら) => 否定(空か(かけら)),
  );
}

/** 括弧の中身が選択にも段階にも読めなければ未定義 (= 真偽として扱う)． */
function 括弧から問いを作る(指示: 文字列, 括弧の中身: 文字列): 省略可<問い> {
  const 選択肢 = 割る(括弧の中身, /[|｜]/u);
  const 段階 = 割る(括弧の中身, /[<＜]/u);

  return もし(以上(長さ(選択肢), 2), {
    であれば: (): 省略可<問い> => ({
      種別: "選択",
      指示,
      基準: Object.fromEntries(
        写す(取り出す(選択肢, 0, 選択肢の上限), (選択肢) => [選択肢, 選択肢] as const),
      ),
    }),
    でなければ: (): 省略可<問い> =>
      もし(以上(長さ(段階), 2), {
        であれば: (): 省略可<問い> => ({
          種別: "段階",
          指示,
          基準: 取り出す(段階, 0, 段階の上限),
        }),
        でなければ: (): 省略可<問い> => 未定義,
      }),
  });
}

/** 0〜1 を百分率の整数へ． */
function 百分率(確率: 数値): 文字列 {
  return `${数学.round(数学.min(数学.max(確率, 0), 1) * 100)}%`;
}

/** 確率の帯ごとの言い方 (Jev命令-言い方.json)．下限の大きいほうから並んでいる． */
const 真偽の言い方: 読み取り専用配列<{ 下限: 数値; 文: 文字列 }> = 言い方.真偽;

/** 命令に何も書かれていなかったときの返事． */
export const Jev命令の使い方: 文字列 = 繋ぐ(言い方.使い方, "\n");

/**
 * 答えを kawaiko の声で言う．
 *
 * 生成は挟まない — 数字を言うだけの返事にモデルを噛ませると，数字のほうが
 * 変わってしまう．言い回しは在庫から選ぶだけで，数字は判定器が出したまま．
 */
export function Jevの答えを言う(問い: 問い, 答え: 答え, モデル: 文字列): 文字列 {
  return `${本体を言う(問い, 答え)}\n-# ${モデル}`;
}

function 本体を言う(問い: 問い, 答え: 答え): 文字列 {
  // 判別可能ユニオンの絞り込みは，関数越しの型述語では効かない．ここは素の === で見る．
  return 答え.種別 === "真偽"
    ? 真偽を言う(答え.確率)
    : 答え.種別 === "選択"
      ? 選択を言う(答え.選択, 答え.確率, 答え.確信)
      : 段階を言う(問い, 答え.点数, 答え.確信);
}

function 真偽を言う(確率: 数値): 文字列 {
  const 帯 =
    探す(真偽の言い方, (帯) => 以上(確率, 帯.下限)) ?? 真偽の言い方[長さ(真偽の言い方) - 1]!;

  return `${百分率(確率)}．${帯.文}`;
}

function 選択を言う(選択: 文字列, 確率: 記録<文字列, 数値>, 確信: 数値): 文字列 {
  const 残り = 写す(
    並べ替える(
      絞る(Object.entries(確率), ([名前]) => 否定(等しい(名前, 選択))),
      ([, 左], [, 右]) => 右 - 左,
    ),
    ([名前, 値]) => `${名前} ${百分率(値)}`,
  );

  return 繋ぐ(
    絞る(
      [
        `${選択} (${百分率(確率[選択] ?? 0)})．`,
        空か(残り) ? "" : `残りは ${繋ぐ(残り, "，")}．`,
        確信の一言(確信),
      ],
      (かけら) => 否定(空か(かけら)),
    ),
    "",
  );
}

function 段階を言う(問い: 問い, 点数: 数値, 確信: 数値): 文字列 {
  const 段階 = 問い.種別 === "段階" ? 問い.基準 : [];
  const 最大 = 数学.max(長さ(段階) - 1, 0);
  // 点数は段階の間へ落ちる．いちばん近い段階の名前を添えるが，数字は丸めない．
  const 近い段階 = 段階[数学.min(数学.max(数学.round(点数), 0), 最大)];

  return 繋ぐ(
    絞る(
      [
        近い段階 ? `${近い段階} 寄り．` : "",
        `${小数で書く(点数, 2)} / ${最大}．`,
        確信の一言(確信),
      ],
      (かけら) => 否定(空か(かけら)),
    ),
    "",
  );
}

/** 確信が薄いときだけ，そう言う．濃いときは黙っている． */
function 確信の一言(確信: 数値): 文字列 {
  return 確信 < 言い方.確信が薄い.未満 ? 言い方.確信が薄い.文 : "";
}
