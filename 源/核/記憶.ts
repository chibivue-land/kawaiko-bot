/** 学習 1 回分．何を取り消すか選ぶときに見せる単位． */
export interface 学習の回 {
  識別子: 文字列;

  時刻: 数値;

  事実の数: 数値;

  読んだ位置: 数値 | 空;

  生きている数: 数値;
}

/** ここまで似ていれば言い直しでしかない．捨てる． */
export const 重複とみなす点数 = 0.85;

/** ここまで似ていれば「同じことをより良く言った」．改訂として残す． */
export const 改訂とみなす点数 = 0.55;

/** 事実は文脈であって作文ではない． */
export const 事実の最大長 = 120;

/** 覚えたことが会話そのものを押し出さないように． */
export const 指示文に載せる事実の数 = 10;

/** この候補を追記するとログがどうなるか． */
export type 取り込み方 =
  | { 種別: "却下" }
  | { 種別: "学習" }
  | { 種別: "改訂"; 置き換える連番: 数値 };

/** 保存する価値のある形に整える．空になったら価値がなかったということ． */
export function 事実本文を整える(本文: 文字列): 文字列 {
  return 切り出す(前後の空白を落とす(本文), 0, 事実の最大長);
}
/**
 * 候補の事実を，既知の信念と突き合わせる．
 *
 * 比べるのは同じ主語についての事実だけ．同じ文が二人について同時に真であることは
 * あるし，そこを潰すと片方の性質がもう片方に静かに付け替わってしまう．
 */
export function 取り込み方を決める(候補: 学習した事実, 既知: 読み取り専用配列<事実>): 取り込み方 {
  const 本文 = 事実本文を整える(候補.本文);

  return もし(空か(本文), {
    であれば: (): 取り込み方 => ({ 種別: "却下" }),
    でなければ: () =>
      最も近い事実で決める(
        本文,
        絞る(既知, (事実) => 同じ主語か(事実, 候補)),
      ),
  });
}

/** 同じ主語の事実のうち，いちばん近いものとの距離で取り込み方を決める． */
function 最も近い事実で決める(本文: 文字列, 同じ主語: 読み取り専用配列<事実>): 取り込み方 {
  const 最も近い = 畳む(
    写す(同じ主語, (事実) => ({ 事実, 点数: 反復度(本文, [事実.本文]) })),
    (最高, 一件) => (一件.点数 > 最高.点数 ? 一件 : 最高),
    { 事実: 未定義 as 省略可<事実>, 点数: 0 },
  );

  return もし(以上(最も近い.点数, 重複とみなす点数), {
    であれば: (): 取り込み方 => ({ 種別: "却下" }),
    でなければ: () =>
      もし(以上(最も近い.点数, 改訂とみなす点数) && 等しくない(最も近い.事実, 未定義), {
        であれば: (): 取り込み方 => ({
          種別: "改訂",
          置き換える連番: (最も近い.事実 as 事実).連番,
        }),
        でなければ: (): 取り込み方 => ({ 種別: "学習" }),
      }),
  });
}
function 同じ主語か(事実: 事実, 候補: 学習した事実): 真偽 {
  return もし(等しくない(事実.主語の種別, 候補.主語の種別), {
    であれば: () => 偽,
    // Discord の id が付いていればそれが正．id を持たない主語 (話題・サーバー
    // 自身) のときだけ，表示名で突き合わせる．
    でなければ: () =>
      もし(等しくない(事実.主語id, 空) || 等しくない(候補.主語id, 未定義), {
        であれば: () => 等しい(事実.主語id, 候補.主語id ?? 空),
        でなければ: () => 等しい(事実.主語名 ?? "", 候補.主語名 ?? ""),
      }),
  });
}
