/**
 * kawaiko の長期記憶の形と，それを変えるときの規則．
 *
 * 純粋な核．保存もバインディングも知らない．永続化は記憶庫ポート
 * (振る舞い/接続口.ts) の向こう側で，SQLite にどう書くかは 外界/D1/記憶庫.ts の
 * 都合でしかない．
 *
 * 記憶は Discord のサーバー (guild) 単位で，追記専用ログの形をしている．だから
 * 「それは忘れて」が上書きではなく新しい出来事になる．出来事を「今の信念」へ
 * 畳み込む SQL は 移行/0001_記憶ログ.sql にある．
 */
import type { 真偽, 数値, 文字列 } from "../共通/型";
import type { 読み取り専用配列 } from "../共通/型";
import { 反復度 } from "./反復";

export type 主語の種別 = "user" | "topic" | "channel" | "server";

/** 実際に流れた発言そのまま．解釈も編集もしない． */
export interface 観測の入力 {
  サーバーid: 文字列;

  チャンネルid: 文字列;

  発言id: 文字列;

  発言者id: 文字列;

  発言者名: 文字列;

  kawaikoの発言か: 真偽;

  本文: 文字列;

  時刻: 数値;
}

export interface 観測 {
  連番: 数値;

  チャンネルid: 文字列;

  発言者id: 文字列;

  発言者名: 文字列;

  kawaikoの発言か: 真偽;

  本文: 文字列;

  時刻: 数値;
}

/** kawaiko がいま信じている，このサーバーについての事柄． */
export interface 事実 {
  連番: 数値;

  主語の種別: 主語の種別;

  主語id: 文字列 | null;

  主語名: 文字列 | null;

  本文: 文字列;

  時刻: 数値;
}

/** まだ既知の事実と突き合わせていない，事実の候補． */
export interface 学習した事実 {
  主語の種別: 主語の種別;

  主語id?: 文字列;

  主語名?: 文字列;

  本文: 文字列;

  出典チャンネルid?: 文字列;

  出典発言id?: 文字列;
}

export interface 取り込み結果 {
  学習: 数値;

  更新: 数値;

  却下: 数値;
}

/** 学習 1 回分．何を取り消すか選ぶときに見せる単位． */
export interface 学習の回 {
  識別子: 文字列;

  時刻: 数値;

  事実の数: 数値;

  読んだ位置: 数値 | null;

  生きている数: 数値;
}

/** ここまで似ていれば言い直しでしかない．捨てる． */
export const 重複とみなす点数 = 0.85;

/** ここまで似ていれば「同じことをより良く言った」．改訂として残す． */
export const 改訂とみなす点数 = 0.55;

/** 事実は文脈であって作文ではない． */
export const 事実の最大長 = 120;

/** 覚えたことが会話そのものを押し出さないように． */
export const 指示文に載せる事実の数 = 10;

/** この候補を追記するとログがどうなるか． */
export type 取り込み方 =
  | { 種別: "却下" }
  | { 種別: "学習" }
  | { 種別: "改訂"; 置き換える連番: 数値 };

/** 保存する価値のある形に整える．空になったら価値がなかったということ． */
export function 事実本文を整える(本文: 文字列): 文字列 {
  return 本文.trim().slice(0, 事実の最大長);
}

/**
 * 候補の事実を，既知の信念と突き合わせる．
 *
 * 比べるのは同じ主語についての事実だけ．同じ文が二人について同時に真であることは
 * あるし，そこを潰すと片方の性質がもう片方に静かに付け替わってしまう．
 */
export function 取り込み方を決める(候補: 学習した事実, 既知: 読み取り専用配列<事実>): 取り込み方 {
  const 本文 = 事実本文を整える(候補.本文);
  if (!本文) return { 種別: "却下" };

  let 最も近い: 事実 | undefined;
  let 最高点 = 0;
  for (const 事実 of 既知) {
    if (!同じ主語か(事実, 候補)) continue;
    const 点数 = 反復度(本文, [事実.本文]);
    if (点数 > 最高点) {
      最も近い = 事実;
      最高点 = 点数;
    }
  }

  if (最高点 >= 重複とみなす点数) return { 種別: "却下" };
  if (最高点 >= 改訂とみなす点数 && 最も近い) {
    return { 種別: "改訂", 置き換える連番: 最も近い.連番 };
  }
  return { 種別: "学習" };
}

function 同じ主語か(事実: 事実, 候補: 学習した事実): 真偽 {
  if (事実.主語の種別 !== 候補.主語の種別) return false;
  // Discord の id が付いていればそれが正．id を持たない主語 (話題・サーバー
  // 自身) のときだけ，表示名で突き合わせる．
  if (事実.主語id !== null || 候補.主語id !== undefined) {
    return 事実.主語id === (候補.主語id ?? null);
  }
  return (事実.主語名 ?? "") === (候補.主語名 ?? "");
}
