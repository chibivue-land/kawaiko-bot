/**
 * その発言は，何かを訊いているのか．訊いているなら，何について．
 *
 * 純粋な判定．ここが真を返した回だけ，外界が web を引きにいく — 雑談のたびに
 * 検索していたら，速さも枠も持たない．
 */
import { 文字列, 新しい型, 未定義, 真偽 } from "../共通/型";
import { もし } from "../共通/構文";
import { 以上, 等しい, 等しくない } from "../共通/演算";
import { 前後の空白を落とす, 繋ぐ, 置き換える, 長さ } from "../共通/関数";

/** ただの雑談ではなく，何かを訊いている合図． */
const 問いかけの合図 = [
  "[?？]",
  "とは",
  "教えて",
  "どう(いう|やって|なる|思)",
  "何(が|を|で|の)",
  "なに",
  "最新",
  "最近",
  "リリース",
  "バージョン",
  "いつ",
  "どこ",
  "誰",
  "だれ",
  "何者",
  "調べ",
  "比較",
  "おすすめ",
  "どんな",
];

const 問いかけの型 = 新しい型(繋ぐ(問いかけの合図, "|"));

/** この発言は問いかけ / 情報を求める形か． */
export function 調べる価値があるか(本文: 文字列): 真偽 {
  return 問いかけの型.test(本文);
}

/**
 * 問いかけを検索語に絞る．
 *
 * 生の問いかけは検索語として最悪で，主語だけ («ryoppippi») ならそこそこ効く．
 * 実際「ryoppippi について教えて」をそのまま投げて，どの検索先にも当たらず
 * 「知らない」と答えた．
 *
 * 頼み方の言い回しを後ろから削るだけ．削れなければ元のまま返す — 下手に
 * 切り詰めて別のものを引くより，当たらないほうがまし．
 */
const 敬称 = "(?:さん|氏|くん|ちゃん|様)?";

/** 「〜について教えて」「〜とは」など，頼み方の側の言い回し． */
const 頼み方 = [
  // 〜のこと知ってる / 〜って知ってる
  "(?:のこと|の話)?(?:を|って|は)?(?:知って|しって)(?:る|ますか|います)?",
  // 〜について教えて / 〜を調べて / 〜が知りたい
  "(?:について|のこと|の|を|が)?(?:教えて|調べて|知りたい|聞きたい|解説して)(?:ください|下さい|くれ)?",
  // 〜って何 / 〜ってどんな人
  "って(?:何|なに|どんな|どういう|誰|だれ|何者)(?:ですか|なの|の|人|もの)?",
  // 〜とは / 〜は誰
  "(?:とは|は|というのは)(?:何|なに|誰|だれ|何者)?(?:ですか|なの)?",
  // 〜の最新情報
  "の(?:最新|最近)(?:情報|の話)?",
  "について",
];

const 頼み方の型 = 新しい型(`^(.+?)${敬称}(?:${繋ぐ(頼み方, "|")})[\\s。．、，!！?？…]*$`, "u");

/** 末尾に残りやすい助詞． */
const 末尾の助詞 = /[はがのをもとにで]\s*$/u;

export function 検索語を取り出す(問いかけ: 文字列): 文字列 {
  const 素 = 前後の空白を落とす(問いかけ);
  const 主語 = 頼み方の型.exec(素)?.[1];
  const 削った = 等しい(主語, 未定義)
    ? 未定義
    : 前後の空白を落とす(置き換える(主語!, 末尾の助詞, ""));

  return もし(等しくない(削った, 未定義) && 以上(長さ(削った!), 2), {
    であれば: () => 削った!,
    でなければ: () => 素,
  });
}
