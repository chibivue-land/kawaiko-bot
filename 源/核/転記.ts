/**
 * 直近のチャンネルの発言を、kawaiko に見せる会話ログへ起こす。単発のメッセージ
 * ではなく会話に返事をさせるため。
 *
 * 入力はチャット API が返すのと同じ「新しい順」。
 */
import type { 文字列, 数値, 配列, 読み取り専用配列 } from "../共通/型";
import type { 発言 } from "./発言";
import { 反復しているか } from "./反復";
import { エポックミリ秒 } from "./時刻";

/**
 * 会話ログを組み立てる (出力は古い順)。
 *
 * kawaiko 自身のよく似た発言は最新の 1 件だけ残す。同じ形の自分の発言が並んで
 * いる状態はモデルにとって few-shot のお手本そのもので、チャンネルが 1 つの
 * 決め台詞に固着する原因がまさにこれだった。
 */
export function 会話ログを組み立てる(
  発言一覧: readonly 発言[],
  設定: { 自分のid: 文字列; 除外するid?: 文字列; 上限?: 数値 },
): 文字列 {
  const 上限 = 設定.上限 ?? 12;
  const 残した自分の発言: 文字列[] = [];
  return 発言一覧
    .filter((発言) => 発言.id !== 設定.除外するid && 発言.本文.trim().length > 0)
    .filter((発言) => {
      if (発言.発言者id !== 設定.自分のid) return true;
      // 新しい順に見ているので、生き残るのは常に最新のものになる。
      if (反復しているか(発言.本文, 残した自分の発言)) return false;
      残した自分の発言.push(発言.本文);
      return true;
    })
    .slice(0, 上限)
    .reverse()
    .map((発言) => {
      const 名前 = 発言.発言者id === 設定.自分のid ? "kawaiko" : 発言.発言者名;
      return `${名前}: ${発言.本文.replace(/\s+/g, " ").slice(0, 150)}`;
    })
    .join("\n");
}

/**
 * kawaiko 自身の直近の発言 (新しい順)。プロンプトにも出力側の反復チェックにも
 * 使う「これは繰り返すな」の一覧。
 */
export function 自分の直近発言を集める(
  発言一覧: readonly 発言[],
  自分のid: 文字列,
  上限 = 6,
): 文字列[] {
  return 発言一覧
    .filter((発言) => 発言.発言者id === 自分のid && 発言.本文.trim().length > 0)
    .slice(0, 上限)
    .map((発言) => 発言.本文.replace(/\s+/g, " ").trim());
}

/**
 * チャンネルのリセット印より前の発言を落とす (0 は「まだリセットしていない」)。
 * 印はチャンネル単位なので、ここでの適用が他のチャンネルへ漏れることはない。
 */
export function リセット後に絞る<発言 extends { 時刻: 文字列 }>(
  発言一覧: 読み取り専用配列<発言>,
  リセット時刻: 数値,
): 配列<発言> {
  if (!リセット時刻) return [...発言一覧];
  return 発言一覧.filter((発言) => (エポックミリ秒(発言.時刻) ?? 0) > リセット時刻);
}
