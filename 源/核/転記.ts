/**
 * 直近のチャンネルの発言を，kawaiko に見せる会話ログへ起こす．単発のメッセージ
 * ではなく会話に返事をさせるため．
 *
 * 入力はチャット API が返すのと同じ「新しい順」．
 */
import { 反復しているか } from "./反復";
import { エポックミリ秒 } from "./時刻";
import { 添付の印 } from "./添付";
import type { 発言 } from "./発言";

import { 偽, 数値, 文字列, 真 } from "../共通/型";
import type { 読み取り専用配列, 配列 } from "../共通/型";
import { 改行 } from "../共通/文字";
import { もし } from "../共通/構文";
import { 否定, 等しい, 等しくない } from "../共通/演算";
import {
  写す,
  切り出す,
  前後の空白を落とす,
  取り出す,
  末尾に足す,
  空か,
  絞る,
  繋ぐ,
  置き換える,
  逆順にする,
} from "../共通/関数";

/**
 * 会話ログを組み立てる (出力は古い順)．
 *
 * kawaiko 自身のよく似た発言は最新の 1 件だけ残す．同じ形の自分の発言が並んで
 * いる状態はモデルにとって few-shot のお手本そのもので，チャンネルが 1 つの
 * 決め台詞に固着する原因がまさにこれだった．
 */
export function 会話ログを組み立てる(
  発言一覧: 読み取り専用配列<発言>,
  設定: { 自分のid: 文字列; 除外するid?: 文字列; 上限?: 数値 },
): 文字列 {
  const 中身のある発言 = 絞る(
    発言一覧,
    (発言) =>
      等しくない(発言.id, 設定.除外するid) &&
      (否定(空か(前後の空白を落とす(発言.本文))) || 否定(空か(発言.添付一覧))),
  );

  const 残った = 自分の重複を畳む(中身のある発言, 設定.自分のid);

  return 繋ぐ(
    写す(逆順にする(取り出す(残った, 0, 設定.上限 ?? 12)), (発言) =>
      一行にする(発言, 設定.自分のid),
    ),
    改行,
  );
}

/**
 * kawaiko 自身のよく似た発言を，最新の 1 件だけにする．
 * 新しい順に見ているので，生き残るのは常に最新のもの．
 */
function 自分の重複を畳む(発言一覧: 読み取り専用配列<発言>, 自分のid: 文字列): 配列<発言> {
  const 残した自分の発言: 配列<文字列> = [];

  return 絞る(発言一覧, (発言) =>
    もし(等しくない(発言.発言者id, 自分のid), {
      であれば: () => 真,
      でなければ: () =>
        もし(反復しているか(発言.本文, 残した自分の発言), {
          であれば: () => 偽,
          でなければ: () => {
            末尾に足す(残した自分の発言, 発言.本文);

            return 真;
          },
        }),
    }),
  );
}

/**
 * 返信を親まで遡る通数の上限．
 *
 * 1 通遡るごとに REST を 1 往復払う．長いスレッドの奥は直近の会話ログと
 * 重なっていることも多いので，深追いしない．
 */
export const 返信を辿る上限 = 5;

/**
 * 返信の連なり (古い順) を，指示文へ載せる形にする．
 *
 * 行の形は会話ログと同じ — 同じ発言が両方に出たとき，別のものに見えないように．
 */
export function 返信の連なりを書き出す(発言一覧: 読み取り専用配列<発言>, 自分のid: 文字列): 文字列 {
  return 繋ぐ(
    写す(発言一覧, (発言) => 一行にする(発言, 自分のid)),
    改行,
  );
}

function 一行にする(発言: 発言, 自分のid: 文字列): 文字列 {
  const 名前 = もし(等しい(発言.発言者id, 自分のid), {
    であれば: () => "kawaiko",
    でなければ: () => 発言.発言者名,
  });

  // 本文が空でも「何か貼った」ことは流れとして残す．
  const 印 = 添付の印(発言.添付一覧);
  const 本文 = 切り出す(置き換える(発言.本文, /\s+/g, " "), 0, 150);

  return 繋ぐ(
    絞る([`${名前}: ${本文}`, 印], (かけら) => 否定(空か(かけら))),
    " ",
  );
}

/**
 * kawaiko 自身の直近の発言 (新しい順)．指示文にも出力側の反復チェックにも使う
 * 「これは繰り返すな」の一覧．
 */
export function 自分の直近発言を集める(
  発言一覧: 読み取り専用配列<発言>,
  自分のid: 文字列,
  上限: 数値 = 6,
): 配列<文字列> {
  const 自分の発言 = 絞る(
    発言一覧,
    (発言) => 等しい(発言.発言者id, 自分のid) && 前後の空白を落とす(発言.本文).length > 0,
  );

  return 写す(取り出す(自分の発言, 0, 上限), (発言) =>
    前後の空白を落とす(置き換える(発言.本文, /\s+/g, " ")),
  );
}

/**
 * チャンネルのリセット印より前の発言を落とす (0 は「まだリセットしていない」)．
 * 印はチャンネル単位なので，ここでの適用が他のチャンネルへ漏れることはない．
 */
export function リセット後に絞る<記録 extends { 時刻: 文字列 }>(
  発言一覧: 読み取り専用配列<記録>,
  リセット時刻: 数値,
): 配列<記録> {
  return もし(等しい(リセット時刻, 0), {
    であれば: () => [...発言一覧],
    でなければ: () => 絞る(発言一覧, (記録) => (エポックミリ秒(記録.時刻) ?? 0) > リセット時刻),
  });
}
