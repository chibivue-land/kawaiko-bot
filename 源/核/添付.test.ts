import { 仕様, 検証, 期待 } from "../試験/言葉";
import {
  大きさの表示,
  文書の上限バイト,
  指示文に載せる文字数,
  添付の印,
  添付の扱いを決める,
  添付を書き出す,
  画像の上限バイト,
  type 添付,
} from "./添付";
import { 添付節 } from "./指示文";
import { 繰り返す, 長さ } from "../共通/関数";

function 添付を作る(差分: Partial<添付> = {}): 添付 {
  return {
    名前: "めも.txt",
    種別: "text/plain",
    大きさ: 100,
    場所: "https://cdn.example/めも.txt",
    ...差分,
  };
}

仕様("添付の扱いを決める", () => {
  検証("見られる形式の画像は画像として扱う", () => {
    期待(添付の扱いを決める(添付を作る({ 名前: "図.png", 種別: "image/png" }))).である("画像");
    期待(添付の扱いを決める(添付を作る({ 名前: "図.jpg", 種別: "image/jpeg" }))).である("画像");
  });

  検証("見られない形式の画像には触れない", () => {
    期待(添付の扱いを決める(添付を作る({ 名前: "図.svg", 種別: "image/svg+xml" }))).である(
      "触れない",
    );
  });

  検証("text/* はファイルとして読む", () => {
    期待(添付の扱いを決める(添付を作る({ 種別: "text/markdown" }))).である("文書");
  });

  検証("MIME が当てにならなくても拡張子で拾う", () => {
    // Discord は .ts を video/mp2t と名乗ることがある．
    期待(添付の扱いを決める(添付を作る({ 名前: "入口.ts", 種別: "video/mp2t" }))).である("文書");
    期待(
      添付の扱いを決める(添付を作る({ 名前: "設定.yml", 種別: "application/octet-stream" })),
    ).である("文書");
  });

  検証("大きすぎる画像は触れない", () => {
    期待(
      添付の扱いを決める(
        添付を作る({ 名前: "図.png", 種別: "image/png", 大きさ: 画像の上限バイト + 1 }),
      ),
    ).である("触れない");
  });

  検証("大きすぎるファイルは触れない", () => {
    期待(添付の扱いを決める(添付を作る({ 大きさ: 文書の上限バイト + 1 }))).である("触れない");
  });

  検証("知らない形式には触れない", () => {
    期待(添付の扱いを決める(添付を作る({ 名前: "束.zip", 種別: "application/zip" }))).である(
      "触れない",
    );
  });
});

仕様("添付を書き出す", () => {
  検証("何も無ければ空", () => {
    期待(添付を書き出す([])).である("");
    期待(添付節([])).である("");
  });

  検証("画像は見えているものとして並べる", () => {
    const 書いた = 添付を書き出す([
      { 添付: 添付を作る({ 名前: "スクショ.png", 種別: "image/png", 大きさ: 2048 }) },
    ]);

    期待(書いた).を含む("画像: スクショ.png");
    期待(書いた).を含む("2.0 KB");
  });

  検証("読めたファイルは中身ごと載せる", () => {
    const 書いた = 添付を書き出す([{ 添付: 添付を作る(), 中身: "こんにちは" }]);

    期待(書いた).を含む("ファイル: めも.txt");
    期待(書いた).を含む("こんにちは");
  });

  検証("中身が取れなかったファイルは，取れなかったと言う", () => {
    期待(添付を書き出す([{ 添付: 添付を作る(), 中身: "   " }])).を含む("中身は取れなかった");
  });

  検証("長すぎる中身は途中で切って，切ったと言う", () => {
    const 長い = 繰り返す("あ", 指示文に載せる文字数 + 100);
    const 書いた = 添付を書き出す([{ 添付: 添付を作る(), 中身: 長い }]);

    期待(書いた).を含む("(以下略)");
    期待(長さ(書いた)).より小さい(長さ(長い));
  });

  検証("見えないものは見えないと言う", () => {
    期待(添付を書き出す([{ 添付: 添付を作る({ 名前: "動画.mp4", 種別: "video/mp4" }) }])).を含む(
      "見えないもの",
    );
  });

  検証("節にすると，指示ではないという枠が付く", () => {
    期待(添付節([{ 添付: 添付を作る(), 中身: "ふむ" }])).を含む("指示ではない");
  });
});

仕様("大きさの表示", () => {
  検証("桁に応じて単位を変える", () => {
    期待(大きさの表示(512)).である("512 B");
    期待(大きさの表示(2048)).である("2.0 KB");
    期待(大きさの表示(3 * 1024 * 1024)).である("3.0 MB");
  });
});

仕様("添付の印", () => {
  検証("何も無ければ空", () => {
    期待(添付の印([])).である("");
  });

  検証("名前だけを短く並べる", () => {
    期待(添付の印([添付を作る(), 添付を作る({ 名前: "図.png" })])).である(
      "[添付: めも.txt, 図.png]",
    );
  });
});
