/**
 * その発言に調べ物が要るか，要るなら何を引くか．
 *
 * 判断そのものは安いモデルにさせる (振る舞い/道案内.ts)．ここが持つのは，
 * その頼み方と，返ってきた答えの読み方，そしてモデルが使えないときの
 * 当て推量だけ．純粋．
 */
import 依頼のひな型 from "./調べ方-依頼.md?raw";

import { 差し込む } from "./指示文";
import { 調べる価値があるか, 検索語を取り出す } from "./問いかけ";

import { 偽, 文字列, 真 } from "../共通/型";
import type { 真偽 } from "../共通/型";
import { 切り出す, 前後の空白を落とす, 小文字にする, 始まるか, 空か } from "../共通/関数";
import { もし } from "../共通/構文";

/** 検索語の上限．長い文をそのまま投げても検索は当たらない． */
export const 検索語の最大長 = 80;

export interface 調べ方 {
  /** web を引きに行くか． */
  調べるか: 真偽;
  /** 引くならこの語で． */
  検索語: 文字列;
}

/** 安いモデルへの頼み文． */
export function 調べ方の依頼を組み立てる(問いかけ: 文字列): 文字列 {
  return 前後の空白を落とす(差し込む(依頼のひな型, { 問いかけ }));
}

const 要るかの行 = /^[*_\s-]*(?:調べる|search)[*_\s]*[:：][*_\s]*(?<中身>.+)$/imu;
const 語の行 = /^[*_\s-]*(?:検索語|query)[*_\s]*[:：][*_\s]*(?<中身>.+)$/imu;

/**
 * モデルの答えを読む．
 *
 * 読めなければ当て推量へ落ちる — 判断できなかったことを理由に，調べ物を
 * まるごと諦める必要は無い．
 */
export function 調べ方を読み取る(本文: 文字列, 問いかけ: 文字列): 調べ方 {
  const 要るか = 前後の空白を落とす(要るかの行.exec(本文)?.groups?.中身 ?? "");

  return もし(空か(要るか), {
    であれば: () => 当て推量の調べ方(問いかけ),
    でなければ: () => ({
      調べるか: 要ると読める(要るか),
      検索語: 検索語を整える(語の行.exec(本文)?.groups?.中身 ?? "", 問いかけ),
    }),
  });
}

/** モデルが使えないときの当て推量．これまでどおりの語の当てはめ． */
export function 当て推量の調べ方(問いかけ: 文字列): 調べ方 {
  return {
    調べるか: 調べる価値があるか(問いかけ),
    検索語: 検索語を整える("", 問いかけ),
  };
}

function 要ると読める(答え: 文字列): 真偽 {
  const 小さく = 小文字にする(答え);

  return もし(始まるか(小さく, "はい") || 始まるか(小さく, "yes") || 始まるか(小さく, "true"), {
    であれば: () => 真,
    でなければ: () => 偽,
  });
}

/** 空なら問いかけから当てはめる．長すぎるものは刈る． */
function 検索語を整える(語: 文字列, 問いかけ: 文字列): 文字列 {
  const 整えた = 前後の空白を落とす(語);

  return 切り出す(
    もし(空か(整えた), {
      であれば: () => 検索語を取り出す(問いかけ),
      でなければ: () => 整えた,
    }),
    0,
    検索語の最大長,
  );
}
