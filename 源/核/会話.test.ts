import { 横槍の指示文を組み立てる, 横槍を見送る返事か } from "./会話";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 偽, 真 } from "../共通/型";

仕様("横槍を見送る返事か", () => {
  検証("「見送り」とだけ返ってきたら見送る", () => {
    期待(横槍を見送る返事か("見送り")).である(真);
    期待(横槍を見送る返事か(" 「見送り」． ")).である(真);
    期待(横槍を見送る返事か("(見送ります)")).である(真);
  });

  検証("見送りという語を含むだけの返事は見送らない", () => {
    期待(横槍を見送る返事か("その PR は見送りでいいと思います")).である(偽);
    期待(横槍を見送る返事か("")).である(偽);
  });
});

仕様("横槍の指示文を組み立てる", () => {
  検証("茶化してはいけない流れなら見送れと頼む", () => {
    const 指示文 = 横槍の指示文を組み立てる({
      時刻の表示: "10月28日(水) 13:07",
      時: 13,
      相手の名前: "ubugeeei",
      対象の発言: "コンパイラ書いてた",
      会話ログ: "",
      事実一覧: [],
      自分の直近発言: [],
      乱数: () => 0,
    });

    期待(指示文).を含む("「見送り」とだけ返して");
    期待(指示文).を含む("持ちネタ");
  });
});
