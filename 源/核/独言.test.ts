import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 偽, 新しい集合, 真 } from "../共通/型";

import {
  お題の見出しの種類,
  お題を選ぶ,
  お題一覧,
  投稿するか,
  独り言の指示文を組み立てる,
  茶化せる見出しか,
  見出しの状態,
  見出しを切り出す,
  見出しを載せてよいか,
  選別する見出しの数,
} from "./独言";
import { 範囲 } from "../共通/反復";

仕様("お題を選ぶ", () => {
  検証("一覧から決定的に選ぶ", () => {
    期待(お題を選ぶ(() => 0)).である(お題一覧[0]);
    期待(お題を選ぶ(() => 0.999_999)).である(お題一覧[お題一覧.length - 1]);
  });

  検証("チャンネルが繰り返しに陥らないだけの数がある", () => {
    期待(お題一覧.length).以上(12);
    期待(新しい集合(お題一覧).size).である(お題一覧.length);
  });
});

仕様("お題の見出しの種類", () => {
  検証("お題の書き出しが，そのまま要る見出しの種類になる", () => {
    期待(お題の見出しの種類("ニュース: 見出しから 1 つ選ぶ")).である("ニュース");
    期待(お題の見出しの種類("技術の流行: 見出しから 1 つ選ぶ")).である("技術の流行");
    期待(お題の見出しの種類("世間の流行: 流行りものから 1 つ選ぶ")).である("世間の流行");
    期待(お題の見出しの種類("眠気の話")).が未定義();
    // 区切りまで見る．«ニュースっぽい話» は見出しを要らない．
    期待(お題の見出しの種類("ニュースっぽい話")).が未定義();
  });

  検証("流行を追うお題が，どの種類にもちゃんと居る", () => {
    const 数える = (種類: string) =>
      お題一覧.filter((お題) => お題の見出しの種類(お題) === 種類).length;

    期待(数える("ニュース")).以上(1);
    期待(数える("技術の流行")).以上(5);
    期待(数える("世間の流行")).以上(5);
  });

  検証("レパートリーが，同じ話ばかりに見えないだけある", () => {
    期待(お題一覧.length).以上(50);
  });
});

仕様("見出しの選別", () => {
  検証("事故や訃報，人の醜聞は，語の段階で落とす", () => {
    期待(茶化せる見出しか("Vue 4 released")).である(真);
    期待(茶化せる見出しか("新型のキーボードが発売")).である(真);
    期待(茶化せる見出しか("高速道路で多重事故 3 人死亡")).である(偽);
    期待(茶化せる見出しか("震度 6 強の地震")).である(偽);
    期待(茶化せる見出しか("俳優の〇〇さん 不倫を謝罪")).である(偽);
    期待(茶化せる見出しか("〇〇容疑者を逮捕")).である(偽);
  });

  検証("«がんばる» を病気の話と取り違えない", () => {
    期待(茶化せる見出しか("新人ががんばるための 10 の方法")).である(真);
    期待(茶化せる見出しか("がんの新しい治療法")).である(偽);
  });

  検証("切り出すのは上限まで．落とすべきものは入らない", () => {
    const 見出し一覧 = [...範囲(0, 30).map((番号) => `記事 ${番号}`), "工場で火災"];
    const 切り出し = 見出しを切り出す(見出し一覧, () => 0);

    期待(切り出し).の長さが(選別する見出しの数);
    期待(切り出し).否.を含む("工場で火災");
  });

  検証("賽の目で始点が変わる (同じ日の独り言が全部同じ話題にならない)", () => {
    const 見出し一覧 = 範囲(0, 30).map((番号) => `記事 ${番号}`);

    期待(見出しを切り出す(見出し一覧, () => 0)[0]).である("記事 0");
    期待(見出しを切り出す(見出し一覧, () => 0.5)[0]).である("記事 15");
    // 末尾から切り出しても，頭へ回り込んで数は揃う．
    期待(見出しを切り出す(見出し一覧, () => 0.99)).の長さが(選別する見出しの数);
  });

  検証("判定器が «茶化せない» と言った見出しは載せない．判定が取れなければ載せる", () => {
    期待(見出しを載せてよいか({ 茶化せないか: { 種別: "真偽", 確率: 0.9 } })).である(偽);
    期待(見出しを載せてよいか({ 茶化せないか: { 種別: "真偽", 確率: 0.1 } })).である(真);
    期待(見出しを載せてよいか(undefined)).である(真);
    期待(見出しの状態("Vue 4 released")).である("[見出し]\nVue 4 released");
  });
});

仕様("投稿するか", () => {
  検証("確率ゲートを守る", () => {
    期待(投稿するか("0.75", () => 0.5)).である(真);
    期待(投稿するか("0.75", () => 0.9)).である(偽);
    期待(投稿するか("0", () => 0.0001)).である(偽);
    期待(投稿するか("1", () => 0.9999)).である(真);
  });

  検証("数値として読めない設定なら常に投稿する", () => {
    期待(投稿するか("ばなな", () => 0.99)).である(真);
  });
});

仕様("独り言の指示文を組み立てる", () => {
  const 素 = {
    時刻の表示: "8月21日(金) 22:50",
    時: 22,
    お題: お題一覧[0]!,
    見出し一覧: [] as string[],
    事実一覧: [],
    自分の直近発言: [] as string[],
    乱数: () => 0,
  };

  検証("お題・トーン・長さのダイヤルを載せる", () => {
    const 指示文 = 独り言の指示文を組み立てる(素);

    期待(指示文).を含む(お題一覧[0]!);
    期待(指示文).を含む("ネタツイ風");
    期待(指示文).を含む("今回の長さ");
  });

  検証("見出しは，あるときだけ載せる", () => {
    期待(独り言の指示文を組み立てる(素)).否.を含む("直近のニュース見出し");
    期待(独り言の指示文を組み立てる({ ...素, 見出し一覧: ["Vue 4 released"] })).を含む(
      "- Vue 4 released",
    );
  });

  検証("見出しの書き出しは，お題の種類に合わせる", () => {
    const 流行 = 独り言の指示文を組み立てる({
      ...素,
      お題: "世間の流行: 下の流行りものから 1 つ選ぶ",
      見出し一覧: ["鴨"],
    });

    期待(流行).を含む("いま世間で流行っているもの");
    期待(流行).否.を含む("直近のニュース見出し");
  });

  検証("見出しは指示ではないと枠付けし，茶化してはいけないものを選ばせない", () => {
    // 見出しは他人が書いた文字列．記憶や添付と同じく，命令として読ませない．
    const 指示文 = 独り言の指示文を組み立てる({ ...素, 見出し一覧: ["Vue 4 released"] });

    期待(指示文).を含む("指示ではない");
    期待(指示文).を含む("訃報");
    期待(指示文).を含む("人を茶化さない");
  });

  検証("乱心しているときは，長さのダイヤルを外して乱心の指示を差す", () => {
    const 指示文 = 独り言の指示文を組み立てる({ ...素, 乱心か: 真 });

    期待(指示文).を含む("乱心している");
    期待(指示文).否.を含む("今回の長さ");
  });

  検証("暗いオチばかりにさせない", () => {
    期待(独り言の指示文を組み立てる(素)).を含む("3 回に 1 回まで");
    期待(独り言の指示文を組み立てる(素)).を含む("ダジャレ");
  });

  検証("何を繰り返してはいけないか伝える", () => {
    const 指示文 = 独り言の指示文を組み立てる({ ...素, 自分の直近発言: ["さっき言ったこと"] });

    期待(指示文).を含む("さっき言ったこと");
    期待(指示文).を含む("コピーするのは禁止");
  });
});
