import {
  お題がニュースを要るか,
  お題の分野,
  お題を選ぶ,
  お題一覧,
  投稿するか,
  独り言の指示文を組み立てる,
} from "./独言";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 偽, 新しい集合, 真 } from "../共通/型";

仕様("お題を選ぶ", () => {
  検証("一覧から決定的に選ぶ", () => {
    期待(お題を選ぶ(() => 0)).である(お題一覧[0]);
    期待(お題を選ぶ(() => 0.999_999)).である(お題一覧[お題一覧.length - 1]);
  });

  検証("チャンネルが繰り返しに陥らないだけの数がある", () => {
    期待(お題一覧.length).以上(40);
    期待(新しい集合(お題一覧).size).である(お題一覧.length);
  });

  検証("いつも同じ話にならないだけ，分野が散らばっている", () => {
    期待(お題の分野.length).以上(10);
    期待(新しい集合(お題の分野.map((分野) => 分野.名前)).size).である(お題の分野.length);
  });

  検証("分野を先に均等に選ぶ — お題の多い分野に寄らない", () => {
    // 1 つ目の乱数で分野，2 つ目でその中のお題．
    const 分野の数 = お題の分野.length;
    for (const [番号, 分野] of お題の分野.entries()) {
      const 賽 = [(番号 + 0.5) / 分野の数, 0];
      期待(お題を選ぶ(() => 賽.shift()!)).である(分野.お題[0]);
    }
  });

  検証("どの分野にもお題がある", () => {
    for (const 分野 of お題の分野) {
      期待(分野.お題.length, 分野.名前).以上(1);
    }
  });
});

仕様("お題がニュースを要るか", () => {
  検証("見出しを取りに行くのはニュースのお題だけ", () => {
    期待(お題一覧.filter(お題がニュースを要るか)).の長さが(1);
    期待(お題がニュースを要るか("眠気の話")).である(偽);
  });
});

仕様("投稿するか", () => {
  検証("確率ゲートを守る", () => {
    期待(投稿するか("0.75", () => 0.5)).である(真);
    期待(投稿するか("0.75", () => 0.9)).である(偽);
    期待(投稿するか("0", () => 0.0001)).である(偽);
    期待(投稿するか("1", () => 0.9999)).である(真);
  });

  検証("数値として読めない設定なら常に投稿する", () => {
    期待(投稿するか("ばなな", () => 0.99)).である(真);
  });
});

仕様("独り言の指示文を組み立てる", () => {
  const 素 = {
    時刻の表示: "8月21日(金) 22:50",
    時: 22,
    お題: お題一覧[0]!,
    見出し一覧: [] as string[],
    事実一覧: [],
    自分の直近発言: [] as string[],
    乱数: () => 0,
  };

  検証("お題・トーン・長さのダイヤルを載せる", () => {
    const 指示文 = 独り言の指示文を組み立てる(素);

    期待(指示文).を含む(お題一覧[0]!);
    期待(指示文).を含む("ネタツイ風");
    期待(指示文).を含む("今回の長さ");
  });

  検証("見出しは，あるときだけ載せる", () => {
    期待(独り言の指示文を組み立てる(素)).否.を含む("直近のニュース見出し");
    期待(独り言の指示文を組み立てる({ ...素, 見出し一覧: ["Vue 4 released"] })).を含む(
      "- Vue 4 released",
    );
  });

  検証("何を繰り返してはいけないか伝える", () => {
    const 指示文 = 独り言の指示文を組み立てる({ ...素, 自分の直近発言: ["さっき言ったこと"] });

    期待(指示文).を含む("さっき言ったこと");
    期待(指示文).を含む("コピーするのは禁止");
  });
});
