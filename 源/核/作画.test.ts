import {
  作画の指示書を組み立てる,
  作画の返事を読み取る,
  作画依頼を組み立てる,
  描く頼みか,
  絵の指示の最大長,
} from "./作画";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 各要素に } from "../共通/反復";
import { 未定義 } from "../共通/型";
import { 繰り返す, 長さ } from "../共通/関数";

仕様("描く頼みか", () => {
  検証("末尾の「描いて」を頼みとして読む", () => {
    期待(描く頼みか("猫を描いて")).と等しい({ お題: "猫" });
    期待(描く頼みか("鴨鍋の絵を描いて")).と等しい({ お題: "鴨鍋" });
    期待(描く頼みか("滋賀の郷土料理をイラストにして描いてください")).の形をしている({});
  });

  検証("先頭の「描いて 〜」も読む", () => {
    期待(描く頼みか("描いて 湖の朝")).と等しい({ お題: "湖の朝" });
    期待(描く頼みか("draw a cyberpunk duck")).と等しい({ お題: "a cyberpunk duck" });
  });

  検証("お題が無くても頼みは頼み", () => {
    期待(描く頼みか("描いて")).と等しい({ お題: "" });
    期待(描く頼みか("なんか描いて")).と等しい({ お題: "なんか" });
  });

  検証("命令が末尾に無いものは頼みではない", () => {
    // ここで誤爆すると，普通の雑談が全部お絵かきになる．
    各要素に(
      [
        "README に描いてあった手順どおりにやった",
        "そう書いてあったけど本当？",
        "昨日の絵を描いていた人だれ",
        "設計を書いて共有しますね",
      ],
      (本文) => {
        期待(描く頼みか(本文)).である(未定義);
      },
    );
  });

  検証("絵と関係ない普通の発言は頼みではない", () => {
    各要素に(["おはよう", "Vapor Mode ってどうなんですか", ""], (本文) => {
      期待(描く頼みか(本文)).である(未定義);
    });
  });

  検証("末尾の句読点や飾りは落とす", () => {
    期待(描く頼みか("猫を描いて！！！")).と等しい({ お題: "猫" });
    期待(描く頼みか("猫を描いてくださいね")).と等しい({ お題: "猫" });
  });
});

仕様("作画依頼を組み立てる", () => {
  検証("お題と相手の名前を差し込む", () => {
    const 依頼 = 作画依頼を組み立てる({ お題: "鴨鍋", 相手の名前: "ubugeeei" });

    期待(依頼).を含む("鴨鍋");
    期待(依頼).を含む("ubugeeei");
    期待(依頼).を含む("絵:");
    期待(依頼).を含む("一言:");
  });

  検証("お題が無いときは，勝手に決めてよいと伝える", () => {
    期待(作画依頼を組み立てる({ お題: "", 相手の名前: "誰か" })).を含む("勝手に決める");
  });
});

仕様("作画の返事を読み取る", () => {
  検証("2 行を拾う", () => {
    期待(作画の返事を読み取る("絵: a duck hotpot, warm light\n一言: 鍋にした")).と等しい({
      絵の指示: "a duck hotpot, warm light",
      一言: "鍋にした",
    });
  });

  検証("前置きが付いていても拾う", () => {
    期待(
      作画の返事を読み取る("はい。\n\n絵: a quiet lake at dawn\n一言: 朝は静かでいいね"),
    ).の形をしている({ 絵の指示: "a quiet lake at dawn" });
  });

  検証("一言が無くても絵の指示があれば通す", () => {
    期待(作画の返事を読み取る("絵: a cat")).と等しい({ 絵の指示: "a cat", 一言: "" });
  });

  検証("絵の指示が読めなければ諦める", () => {
    // 空のプロンプトで真っ白な絵を出すより，描けなかったと言うほうがまし．
    期待(作画の返事を読み取る("一言: めんどい")).である(未定義);
    期待(作画の返事を読み取る("よくわかりません")).である(未定義);
  });

  検証("長すぎる指示は刈る", () => {
    const 読んだ = 作画の返事を読み取る(`絵: ${繰り返す("cat ", 300)}`);

    期待(長さ(読んだ!.絵の指示)).である(絵の指示の最大長);
  });
});

仕様("作画の指示書を組み立てる", () => {
  検証("書式の指示を最優先で載せる", () => {
    const 指示書 = 作画の指示書を組み立てる();

    期待(指示書).を含む("絵:");
    期待(指示書).を含む("一言:");
    期待(指示書).を含む("2 行");
  });

  検証("kawaiko の口調は残す", () => {
    期待(作画の指示書を組み立てる()).を含む("kawaiko");
  });

  検証("人格指示書の会話向けの縛りは入れない", () => {
    // 「見出しも箇条書きも使うな」「いきなり本文だけ返せ」は，ラベル付き 2 行と
    // 真っ向から喧嘩する．本番でこれのせいで 1 度も読めなかった．
    期待(作画の指示書を組み立てる()).否.を含む("いきなり本文だけ");
  });
});

仕様("作画の返事を読み取る: 書式が崩れていても", () => {
  検証("太字のラベルでも拾う", () => {
    期待(作画の返事を読み取る("**絵:** a duck hotpot\n**一言:** 鍋にした")).と等しい({
      絵の指示: "a duck hotpot",
      一言: "鍋にした",
    });
  });

  検証("箇条書きのラベルでも拾う", () => {
    期待(作画の返事を読み取る("- 絵: a quiet lake\n- 一言: 静かだね")).の形をしている({
      絵の指示: "a quiet lake",
      一言: "静かだね",
    });
  });

  検証("英語のラベルでも拾う", () => {
    期待(作画の返事を読み取る("prompt: a cyberpunk duck\ncaption: 未来的だね")).と等しい({
      絵の指示: "a cyberpunk duck",
      一言: "未来的だね",
    });
  });

  検証("ラベルが無くても，英語の行が 1 つあれば拾う", () => {
    // 書式を守らせるのは指示書の仕事．読む側は守られなかった場合に備える．
    期待(作画の返事を読み取る("a duck hotpot on a portable stove, warm light")).の形をしている({
      絵の指示: "a duck hotpot on a portable stove, warm light",
    });
  });

  検証("日本語だけの返事は，絵の指示として拾わない", () => {
    期待(作画の返事を読み取る("すみませんが描けません")).である(未定義);
  });

  検証("短すぎる英語は拾わない", () => {
    期待(作画の返事を読み取る("OK")).である(未定義);
  });
});
