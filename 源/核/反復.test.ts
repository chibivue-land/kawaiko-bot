import { describe, expect, it } from "vitest";
import { 反復しているか, 反復度, 発言を正規化する } from "./反復";

describe("発言を正規化する", () => {
  it("先頭の「〇〇さん」を落として型を揃える", () => {
    expect(発言を正規化する("ubugeeei さん，それはあまりに雑です")).toBe("それはあまりに雑です");
    expect(発言を正規化する("kazupon さん、それはあまりに雑です")).toBe("それはあまりに雑です");
  });

  it("たまたま「さん」で始まる語は食わない", () => {
    expect(発言を正規化する("さんまが好きです")).toBe("さんまが好きです");
  });

  it("メンション・リンク・句読点を落とす", () => {
    expect(発言を正規化する("<@123> はい．https://example.com 🦆")).toBe("はい");
  });
});

describe("反復度", () => {
  // チャンネルが実際に固着した形: 骨格は同じで、名前だけが回る。
  const 固着した発言 = [
    "ubugeeei さん，それはあまりに雑な質問ですね",
    "kazupon さん，それはあまりに筋が悪いです",
  ];

  it("名前と語尾が違っても同じ骨格なら検出する", () => {
    expect(反復しているか("yamanoku さん，それはあまりに浅いです", 固着した発言)).toBe(true);
  });

  it("丸写しは 1 点になる", () => {
    expect(反復度("kazupon さん，それはあまりに筋が悪いです", 固着した発言)).toBe(1);
  });

  it("本当に違う返事は通す", () => {
    expect(
      反復しているか("Vapor Mode の話なら朝まで喋れます (誰も聞いていない)", 固着した発言),
    ).toBe(false);
    expect(反復しているか("眠いです．レッドブルが切れました．", 固着した発言)).toBe(false);
  });

  it("短すぎる発言は偶然の一致で騒がない", () => {
    expect(反復しているか("はい．", ["すごい"])).toBe(false);
  });

  it("比べる相手が無ければ 0", () => {
    expect(反復度("なんでもよい", [])).toBe(0);
  });
});
