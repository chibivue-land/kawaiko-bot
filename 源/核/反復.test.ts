import { 仕様, 検証, 期待 } from "../試験/言葉";
import { 反復しているか, 反復度, 発言を正規化する } from "./反復";
import { 偽, 真 } from "../共通/型";

仕様("発言を正規化する", () => {
  検証("先頭の「〇〇さん」を落として型を揃える", () => {
    期待(発言を正規化する("ubugeeei さん，それはあまりに雑です")).である("それはあまりに雑です");
    期待(発言を正規化する("kazupon さん、それはあまりに雑です")).である("それはあまりに雑です");
  });

  検証("たまたま「さん」で始まる語は食わない", () => {
    期待(発言を正規化する("さんまが好きです")).である("さんまが好きです");
  });

  検証("メンション・リンク・句読点を落とす", () => {
    期待(発言を正規化する("<@123> はい．https://example.com 🦆")).である("はい");
  });
});

仕様("反復度", () => {
  // チャンネルが実際に固着した形: 骨格は同じで，名前だけが回る．
  const 固着した発言 = [
    "ubugeeei さん，それはあまりに雑な質問ですね",
    "kazupon さん，それはあまりに筋が悪いです",
  ];

  検証("名前と語尾が違っても同じ骨格なら検出する", () => {
    期待(反復しているか("yamanoku さん，それはあまりに浅いです", 固着した発言)).である(真);
  });

  検証("丸写しは 1 点になる", () => {
    期待(反復度("kazupon さん，それはあまりに筋が悪いです", 固着した発言)).である(1);
  });

  検証("本当に違う返事は通す", () => {
    期待(
      反復しているか("Vapor Mode の話なら朝まで喋れます (誰も聞いていない)", 固着した発言),
    ).である(偽);
    期待(反復しているか("眠いです．レッドブルが切れました．", 固着した発言)).である(偽);
  });

  検証("短すぎる発言は偶然の一致で騒がない", () => {
    期待(反復しているか("はい．", ["すごい"])).である(偽);
  });

  検証("比べる相手が無ければ 0", () => {
    期待(反復度("なんでもよい", [])).である(0);
  });
});
