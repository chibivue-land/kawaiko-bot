import { 避けるチャンネルか, 避ける語, 避ける話題か } from "./避ける話題";

import { 仕様, 検証, 期待 } from "../試験/言葉";

import { 偽, 新しい集合, 真 } from "../共通/型";

仕様("避ける話題か", () => {
  検証("心や体の調子の話は避ける", () => {
    期待(避ける話題か("最近ずっとしんどくて眠れない")).である(真);
    期待(避ける話題か("メンタルやられてて休職することになった")).である(真);
    期待(避ける話題か("祖父が亡くなったので数日いません")).である(真);
  });

  検証("活用していても避ける", () => {
    期待(避ける話題か("最近しんどくて")).である(真);
    期待(避ける話題か("つらすぎる")).である(真);
    期待(避ける話題か("寂しくなった")).である(真);
  });

  検証("英語でも，大文字でも避ける", () => {
    期待(避ける話題か("Dealing with Burnout lately")).である(真);
  });

  検証("ふつうの雑談は避けない", () => {
    期待(避ける話題か("Vapor Mode のベンチ回したら速かった")).である(偽);
    期待(避ける話題か("眠い")).である(偽);
    期待(避ける話題か("がんばって型パズル解いた")).である(偽);
  });

  検証("語は小文字で，重なりが無い", () => {
    for (const 語 of 避ける語) {
      期待(語, 語).である(語.toLowerCase());
    }
    期待(新しい集合(避ける語).size).である(避ける語.length);
  });
});

仕様("避けるチャンネルか", () => {
  検証("相談や吐き出しの場所に見えるチャンネルは避ける", () => {
    期待(避けるチャンネルか("お悩み相談")).である(真);
    期待(避けるチャンネルか("Mental-Health")).である(真);
  });

  検証("ふつうのチャンネルは避けない", () => {
    期待(避けるチャンネルか("雑談")).である(偽);
    期待(避けるチャンネルか("初心者質問")).である(偽);
    期待(避けるチャンネルか("events")).である(偽);
    期待(避けるチャンネルか("chibivue-support")).である(偽);
  });
});
